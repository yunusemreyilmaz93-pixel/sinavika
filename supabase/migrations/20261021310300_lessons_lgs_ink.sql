## 3. Hukuk alanındaki inkılaplar

- **Medeni Kanun (17 Şubat 1926):** Din kurallarına dayalı hukuk yerine **çağdaş ve laik** hukuk getirildi. Kadın ve erkek arasında eşitlik sağlandı: Çok eşlilik kaldırıldı, evlilik resmî nikâha bağlandı, kadınlara miras ve boşanma haklarında eşitlik tanındı.
- **Mahkemelerin birleştirilmesi:** Şer’i mahkemeler kaldırıldı, hukuk birliği sağlandı.
- **Kadınlara siyasi haklar:** 1930’da belediye seçimlerinde, 1934’te milletvekili seçme ve seçilme hakkı tanındı. Böylece Türk kadını birçok Avrupa ülkesinden önce bu haklara kavuştu.

