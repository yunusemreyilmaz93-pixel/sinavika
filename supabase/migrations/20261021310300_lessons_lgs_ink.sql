## 5. Toplumsal alandaki inkılaplar

- **Şapka Kanunu (25 Kasım 1925):** Kıyafette çağdaşlaşma, “fes” yerine şapka.
- **Tekke, zaviye ve türbelerin kapatılması (30 Kasım 1925):** Din ve devlet işlerinin ayrılması, laiklik yönünde bir adım.
- **Uluslararası takvim, saat ve ölçülerin kabulü:** Takvim (1926), saat (1925) ve ölçü birimleri (metre-kilogram, 1931) Avrupa ile uyumlu hâle getirildi.
- **Soyadı Kanunu (21 Haziran 1934):** Herkes soyadı almak zorunda kaldı. Bu, **sınıf ayrımını ve unvanları** kaldırdı. Mustafa Kemal’e TBMM tarafından **“Atatürk” soyadı** verildi (24 Kasım 1934).
- **Lakap ve unvanların kaldırılması (1934):** Efendi, bey, paşa gibi unvanlar kaldırıldı.
- **Kadın haklarının genişlemesi:** Medeni Kanun ve siyasi haklarla.

