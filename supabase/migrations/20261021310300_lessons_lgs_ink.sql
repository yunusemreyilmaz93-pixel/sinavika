## 1. Atatürk ilkeleri

Atatürk ilkeleri, Türkiye Cumhuriyeti’nin yönetim ve toplum anlayışının temelidir. 1937’de anayasaya girmiştir.

| İlke | Anlamı |
| --- | --- |
| Cumhuriyetçilik | Devletin başında halk tarafından seçilmiş cumhurbaşkanı bulunur. Yönetim milletin elindedir. |
| Milliyetçilik | Türk milletinin birlik ve bütünlüğünü korumak, milli bağımsızlığı savunmak. Irkçılığa dayanmaz, milli birlik ve beraberliğe dayanır. |
| Halkçılık | Millet içinde sınıf ayrılığı yoktur, bütün yurttaşlar hukuk önünde eşittir. |
| Devletçilik | Özel girişimin yetersiz kaldığı alanlarda devlet ekonomiye müdahale eder. |
| Laiklik | Din ve devlet işlerinin ayrılması, devlet yönetiminin dinî kurallara değil akla ve bilime dayanması. |
| İnkılapçılık | Toplumun çağdaşlaşması için yeniliklerin sürekli yapılması ve korunması. |

:::baglanti
**Laiklik, dinsizlik değildir.** Her yurttaş, dinini ve inancını özgürce yaşayabilir. Laiklikte devlet hiçbir dine ya da inanca **öncelik tanımaz**. Devlet işleri ise dinî kurallara göre yürütülmez.
:::

