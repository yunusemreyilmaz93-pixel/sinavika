## 1. Atatürk’ün hastalığı ve ölümü

Atatürk, 1930’ların sonunda **karaciğer rahatsızlığı** (siroz) nedeniyle hastalandı. Yurt gezileri ve yoğun çalışması bu rahatsızlığı ağırlaştırdı. Tedavi için İstanbul’a geldi ve **Dolmabahçe Sarayı**’nda kaldı. Hastalığı giderek ağırlaştı.

**10 Kasım 1938 günü saat 09.05’te Dolmabahçe Sarayı’nda yaşama veda etti.** Ölümü, Türkiye’de büyük bir yasa yol açtı. Halk, sokaklara döküldü, radyolar yas yayını yaptı.

- Ülke genelinde **yas** ilan edildi.
- Atatürk’ün naaşı, Dolmabahçe Sarayı’nda halkın ziyaretine açıldı. Milyonlarca kişi saygı duruşunda bulundu.
- Cenaze töreni, **19 Kasım 1938’de** İstanbul’dan Ankara’ya taşındı. **21 Kasım 1938’de Ankara’da** devlet töreni yapıldı. Atatürk’ün naaşı **geçici olarak Etnografya Müzesi’ne** konuldu.
- **10 Kasım 1953’te**, 15 yıl sonra, **Anıtkabir’e** nakledildi.

:::baglanti
Atatürk’ün naaşı Anıtkabir tamamlanana kadar **Etnografya Müzesi**’nde kaldı. Bu yüzden Anıtkabir’e nakil, onun ölümünden 15 yıl sonra, **aynı tarihte (10 Kasım)** gerçekleşti. Tarih ve nakil süreci sorularda sıkça sorulur.
:::

## 2. İsmet İnönü dönemi

Atatürk’ün ölümü üzerine TBMM, **11 Kasım 1938’de** **İsmet İnönü**’yü Türkiye Cumhuriyeti’nin ikinci Cumhurbaşkanı seçti. İnönü, Kurtuluş Savaşı’nda Batı Cephesi komutanı, Lozan’da Türk heyetinin başkanı ve Başbakan olarak devlet deneyimine sahipti.

İnönü’ye “**Millî Şef**” unvanı verildi. Cumhuriyet Halk Partisi, 1938-1950 döneminde yönetimde kaldı.

## 3. II. Dünya Savaşı ve Türkiye

**1 Eylül 1939’da** Almanya’nın Polonya’ya saldırısıyla **II. Dünya Savaşı** başladı. Türkiye savaşın büyük bölümünde **tarafsız** kaldı.

- Türkiye, “Yurtta sulh, cihanda sulh” ilkesine bağlı kalarak savaşa **doğrudan girmedi**.
- 1939’da İngiltere ve Fransa ile **Üçlü İttifak Antlaşması** imzaladı.
- 1941’de Almanya ile **Saldırmazlık Antlaşması** yaptı.
- Savaş döneminde ekonomik sıkıntılar arttı. **Varlık Vergisi (1942)** ve **Milli Korunma Kanunu (1940)** gibi önlemler alındı.
- **Şubat 1945’te** Almanya ve Japonya’ya savaş ilan etti. Bunun amacı, Birleşmiş Milletler’in kurucu üyesi olabilmekti.

**Türkiye, 1945’te Birleşmiş Milletler’in kurucu üyelerinden biri oldu.** Savaştan sonra dünya iki kutba (ABD ve SSCB) ayrıldı. Türkiye Batı bloğuyla ilişkilerini güçlendirdi.

:::neden-sonuc
- II. Dünya Savaşı başlar => Türkiye, tarafsızlık politikasıyla savaşa girmemeye çalışır.
- Savaşın bitmesine yakın savaş ilan edilir (1945) => Türkiye BM’nin kurucu üyesi olur.
- Savaş sonrası dünya iki kutba ayrılır => Türkiye Batı bloğuna yakınlaşır (Marshall Planı 1947, NATO üyeliği 1952).
:::

## 4. Atatürk’ün vasiyeti ve mirası

Atatürk, **5 Eylül 1938’de** vasiyetnamesini yazdı. Vasiyetnamesinde şunlar yer alır.

- Mal varlığının önemli bir bölümünü **Türk Dil Kurumu** ve **Türk Tarih Kurumu**’na bıraktı. Böylece Türk dilinin ve tarihinin araştırılmasına katkıda bulunmak istedi.
- Aile bireylerine ve manevi çocuklarına belli paylar ayırdı.
- Çocukların öğrenimi için de pay bıraktı.

Atatürk’ün **manevi mirası** ise çok daha geniştir.

- **Milli egemenlik:** Egemenliğin kayıtsız şartsız millette olması.
- **Cumhuriyet:** Atatürk’ün en büyük eseri.
- **Bilim ve akıl:** “Hayatta en hakiki mürşit ilimdir, fendir.” sözü onun yaklaşımının özetidir.
- **Gençlik:** Gençlere duyduğu güven. **Gençliğe Hitabe** (1927), Nutuk’un sonunda yer alır ve gençlere cumhuriyeti koruma görevi verir.
- **Çocuklar:** 23 Nisan’ı çocuklara armağan etti. 23 Nisan Ulusal Egemenlik ve Çocuk Bayramı, dünyada çocuklara armağan edilen ilk bayramdır.

:::cizelge{baslik="Atatürk’ün hayatından kesitler"}
- 1881 | Selanik’te doğdu
- 1919 | Samsun’a çıktı
- 1923 | Cumhuriyet’i ilan etti
- 1927 | Nutuk’u okudu
- 1934 | “Atatürk” soyadını aldı
- 1938 | Vefat etti
- 1953 | Anıtkabir’e nakledildi
:::

## 5. Atatürk nasıl anılır?

- **10 Kasım, saat 09.05:** Atatürk’ü anma günü. Ülke genelinde saygı duruşu yapılır, sirenler çalar.
- **Anıtkabir:** Ankara’da Atatürk’ün anıt mezarı. Her gün binlerce ziyaretçi gelir.
- **Bayramlar:** 19 Mayıs Atatürk’ü Anma, Gençlik ve Spor Bayramı, 23 Nisan, 30 Ağustos Zafer Bayramı, 29 Ekim Cumhuriyet Bayramı. Hepsi onun gençlik, bağımsızlık ve cumhuriyet düşüncesini yansıtır.
- **Atatürk ilke ve inkılapları:** Eğitimde, hukukta ve toplumda bugünkü hayatın temelleri.

