## 1. Mondros Ateşkesi ve işgaller

Osmanlı Devleti I. Dünya Savaşı’nı **Almanya’nın yanında** yaşadı ve kaybetti. **30 Ekim 1918’de Mondros Ateşkes Antlaşması** imzalandı. Antlaşmanın bazı maddeleri Anadolu’nun işgal edilmesinin önünü açtı.

- Boğazlar itilaf devletlerine açıldı, istihkâmlar işgal edildi.
- Osmanlı ordusu terhis edildi, silahlar teslim edildi.
- İtilaf devletleri, “güvenliklerini tehdit eden durum çıkarsa” herhangi bir stratejik noktayı işgal edebilecekti (7. madde).
- Ermeni vilayetleri adı altındaki altı ilde bir düzenlemeye gidilebilecekti (24. madde).

Mondros’tan sonra İtilaf devletleri ve onların desteklediği devletler Anadolu’yu işgal etmeye başladı.

| İşgal | Tarih | İşgalci |
| --- | --- | --- |
| Antep, Maraş, Urfa | 1919 | Önce İngiltere, sonra Fransa |
| Adana, Mersin | 1918 sonu ve 1919 | Fransa |
| İzmir | 15 Mayıs 1919 | Yunanistan |
| İstanbul | Resmen 16 Mart 1920 | İtilaf devletleri |

**15 Mayıs 1919’da İzmir’in Yunanistan tarafından işgali** Anadolu’da büyük bir tepkiyle karşılandı. Halk, işgale karşı protesto mitingleri düzenledi. İşgale ilk tepki gösteren ve ilk kurşunu atan kişi olarak gazeteci **Hasan Tahsin** anılır.

:::neden-sonuc
- Osmanlı ordusu terhis edildi, silahlar teslim edildi => Anadolu savunmasız kaldı ve işgaller kolaylaştı.
- İzmir’in Yunanlılarca işgali => Halkta büyük tepki doğdu ve milli direniş hareketleri hızlandı.
- İstanbul Hükümeti işgallere karşı etkisiz kaldı => Halk, kendi örgütlenmesini kurmak zorunda kaldı.
:::

## 2. Milli cemiyetler ve Kuva-yi Milliye

İşgallere karşı halk, devletten bağımsız olarak **cemiyetler** kurdu. Cemiyetler bölgesel savunma ve direniş amaçlıydı.

- **Trakya-Paşaeli Müdafaa-i Hukuk Cemiyeti:** Doğu Trakya’nın savunması.
- **Redd-i İlhak Cemiyeti:** İzmir ve çevresinin Yunanistan’a bağlanmasına karşı.
- **Kilikyalılar Cemiyeti:** Çukurova’nın işgaline karşı.
- **Doğu Anadolu Müdafaa-i Hukuk Cemiyeti:** Doğu illerinin bir Ermeni devletine verilmemesi için.

Ayrıca halkın silahlı direnişi olan **Kuva-yi Milliye** (Milli Kuvvetler) doğdu. Başlangıçta düzensiz, gönüllülerden oluşan çeteler hâlindeydi. Bu birlikler ilk günlerde düşmanı oyalayarak zaman kazandırdı, ancak düzenli ordu kurulana kadar bir geçiş dönemi görevi gördü.

:::baglanti
Cemiyetler **bölgesel** düşünüyordu. Her cemiyet kendi bölgesini savunmak istiyordu. Mustafa Kemal ise sonraki kongrelerle bu cemiyetleri **tek bir çatı altında birleştirmeyi** başaracaktı. Bu, mücadelenin başarısındaki en önemli adımlardan biridir.
:::

## 3. Mustafa Kemal Samsun’a çıkıyor

İstanbul Hükümeti, Anadolu’daki karışıklığı yatıştırmak için **9. Ordu Müfettişi** olarak Mustafa Kemal’i görevlendirdi. Ancak Mustafa Kemal bu görevi, **milli bir direniş başlatmak için bir fırsat** olarak gördü.

**19 Mayıs 1919’da Samsun’a çıktı.** Bu tarih, milli mücadelenin başlangıcı kabul edilir.

Samsun’dan sonra yaşananlar:

| Tarih | Olay | Önemi |
| --- | --- | --- |
| 19 Mayıs 1919 | Samsun’a çıkış | Milli mücadelenin başlangıcı |
| 28 Mayıs 1919 | Havza Genelgesi | Mitingler ve protestolar yoluyla işgalleri halka duyurmak |
| 22 Haziran 1919 | Amasya Genelgesi | Milli mücadelenin gerekçesi ve amacı ilk kez ilan edildi |
| 8 Temmuz 1919 | Askerlikten ayrılma | Mustafa Kemal’in görevinden istifası |

**Amasya Genelgesi (22 Haziran 1919)** çok önemlidir. İlk kez şu ifadeler kullanıldı:

- “Vatanın bütünlüğü, milletin istiklali tehlikededir.”
- “Milletin istiklalini yine milletin azim ve kararı kurtaracaktır.”
- Sivas’ta ulusal bir kongre toplanacağı bildirildi.

Bu belge, milli mücadelenin **gerekçesini, amacını ve yöntemini** ortaya koyar. Bu yüzden “ihtilal bildirisi” olarak da anılır.

## 4. Erzurum ve Sivas Kongreleri

### Erzurum Kongresi (23 Temmuz - 7 Ağustos 1919)

Doğu illerinin temsilcilerinin katıldığı **bölgesel** bir kongredir. Kararları şunlardır:

- Milli sınırlar içinde vatan bir bütündür, parçalanamaz.
- Her türlü işgale ve müdahaleye karşı millet topyekûn direnecektir.
- İstanbul Hükümeti vatanı savunamazsa geçici bir hükümet kurulacaktır.
- **Manda ve himaye** kabul edilemez.
- Milli iradeyi hâkim kılmak esastır.

### Sivas Kongresi (4-11 Eylül 1919)

Tüm yurdun temsilcilerinin katıldığı **ulusal** bir kongredir. Erzurum’un kararları bütün yurda yayıldı.

- Bütün cemiyetler **Anadolu ve Rumeli Müdafaa-i Hukuk Cemiyeti** adı altında birleştirildi.
- Mustafa Kemal başkan seçildi, yürütme kurulu olarak **Heyet-i Temsiliye** oluşturuldu.
- Manda ve himaye bir kez daha reddedildi.
- Milli iradeyi hâkim kılma ilkesi tüm yurda mal edildi.

| Özellik | Erzurum Kongresi | Sivas Kongresi |
| --- | --- | --- |
| Niteliği | Bölgesel | Ulusal |
| Katılım | Doğu illeri | Bütün yurt |
| Özel sonucu | Manda ve himaye reddedildi | Heyet-i Temsiliye kuruldu, cemiyetler birleşti |
| Başkan | Mustafa Kemal | Mustafa Kemal |

## 5. Amasya Görüşmeleri, Misak-ı Milli ve TBMM

**Amasya Görüşmeleri (20-22 Ekim 1919):** İstanbul Hükümeti ile Heyet-i Temsiliye arasında yapıldı. İstanbul Hükümeti ilk kez Mustafa Kemal ve arkadaşlarını **muhatap aldı**, böylece milli hareketi resmen tanımış oldu.

**Misak-ı Milli (28 Ocak 1920):** Son Osmanlı Mebusan Meclisi’nde kabul edilen, milli sınırları belirleyen karardır. Milli sınırlar içinde vatan bir bütündür ve parçalanamaz.

**İstanbul’un işgali (16 Mart 1920):** Misak-ı Milli kararlarına tepki gösteren İtilaf devletleri İstanbul’u resmen işgal etti, mebusanı bastı. Meclis-i Mebusan dağıldı.

**TBMM’nin açılışı (23 Nisan 1920):** Ankara’da **Türkiye Büyük Millet Meclisi** açıldı. Mustafa Kemal meclisin başkanı seçildi. Meclis, milletin kendi kaderine kendisi sahip çıkmasının sembolü oldu. Başkent Ankara oldu ve kısa süre sonra Ankara Hükümeti fiilen kurulmuş oldu.

TBMM’nin özellikleri:

- Milli egemenliğe dayanır. Yasama ve yürütme yetkisi tek bir mecliste toplanmıştır.
- Milletin her kesiminden gelen temsilcilerden oluşur.
- Hem savaş yürüten hem de devlet yönetimi kuran bir meclistir.

:::ipucu
“Hangi olay hangi olayın sonucu?” sorularında şu zinciri aklında tut: **İşgaller → cemiyetler ve Kuva-yi Milliye → Samsun’a çıkış → Amasya Genelgesi → Erzurum ve Sivas Kongreleri → Misak-ı Milli → İstanbul’un işgali → TBMM’nin açılışı.**
:::

