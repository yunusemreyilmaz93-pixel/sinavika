## 1. Dış politikanın temel ilkeleri

Atatürk dönemi dış politikası şu ilkelere dayanır.

- **Yurtta sulh, cihanda sulh:** İç barış ve dünya barışı. Türkiye barışçı bir politika izler.
- **Tam bağımsızlık:** Hiçbir devletin Türkiye’nin içişlerine karışmasına izin verilmez.
- **Gerçekçilik:** Güç dengeleri ve Türkiye’nin imkânları göz önünde bulundurulur.
- **Komşularla dostluk:** Komşu ülkelerle sorunlar barışçı yoldan çözülür.
- **Uluslararası iş birliği:** Barışı koruyan uluslararası kuruluşlara katılım.
- **Milli çıkarların korunması:** Barış arayışı, milli menfaatlerden ödün vermek anlamına gelmez.

:::baglanti
Dış politikada “barış” ve “güçlü olmak” aynı anda hedeflenmiştir. Türkiye, savaşı istemiyordu ama **haklarını savunmaya da hazırdı**. Atatürk’ün sorunları çoğu zaman **diplomasi ile çözmesi**, bu anlayışın bir yansımasıdır.
:::

## 2. Lozan sonrası çözülmemiş sorunlar

Lozan Barış Antlaşması (1923) bazı konuları çözmüştü, ancak bazıları **açık** kalmıştı. Başlıcaları şunlardır:

- **Musul sorunu:** Lozan’da çözülememişti.
- **Boğazlar rejimi:** Lozan’da Boğazlar’ın askerden arındırılmasına dair düzenlemeler vardı. Türkiye bu durumdan memnun değildi.
- **Hatay sorunu:** Fransız mandası altındaki Suriye sınırları içinde kalmıştı.

## 3. Musul sorunu ve 1926 Ankara Antlaşması

Musul, Lozan’da çözülemeyince sorun Milletler Cemiyeti’ne taşındı. Türkiye, İngiltere ve Irak arasında **5 Haziran 1926’da Ankara Antlaşması** imzalandı. Antlaşma ile **Musul, Irak’a bırakıldı**. Türkiye, Musul petrollerinden belli bir süre pay aldı. Bu durumda Türkiye barış yolunu seçmiş ve bir savaşa girmemiştir.

## 4. Milletler Cemiyeti’ne giriş (1932)

**18 Temmuz 1932’de Türkiye**, I. Dünya Savaşı sonrası kurulan ve barışı korumayı amaçlayan **Milletler Cemiyeti’ne üye oldu**. Türkiye, bu kuruluşta uluslararası barışı destekleyen bir politika izledi. Bu üyelik, Türkiye’nin **uluslararası alanda tanındığının ve güvenilir bir devlet olarak kabul edildiğinin** göstergesidir.

## 5. Balkan Antantı (1934)

1930’lara gelindiğinde dünyada **gerginlik artmıştı**. Almanya’da Hitler’in iktidara gelmesi (1933), İtalya’nın saldırgan tutumu Avrupa’yı tehdit ediyordu. Balkanların güvenliği için **9 Şubat 1934’te Balkan Antantı** imzalandı.

- **Üyeler:** Türkiye, Yunanistan, Romanya, Yugoslavya.
- **Amaç:** Balkanlardaki sınırları karşılıklı olarak güvence altına almak, bölgeye dışarıdan bir saldırıya karşı birlikte hareket etmek.

Bu antlaşma Türkiye’nin **Yunanistan ile ilişkilerinin düzeldiğini** de gösterir. (Daha önce **1930 Atina Antlaşması** ile ilişkiler iyileşmişti.)

## 6. Montrö Boğazlar Sözleşmesi (1936)

Lozan’da Boğazlar, yabancı savaş gemilerinin geçişine açıktı ve **askerden arındırılmıştı**. İtalya ve Almanya’nın tehditkâr politikaları Boğazlar’ın güvenliğini tehlikeye atıyordu.

Türkiye, Boğazlar rejiminin değiştirilmesi için Lozan’a imza atan devletlere başvurdu. İsviçre’nin Montrö şehrinde yapılan konferans sonunda **20 Temmuz 1936’da Montrö Boğazlar Sözleşmesi** imzalandı.

Sözleşmenin önemli sonuçları:

- Türkiye, **Boğazlar’da askerî güç bulundurma ve tahkimat yapma** hakkına kavuştu.
- Savaş zamanında Türkiye’nin **geçişi kontrol etme** yetkisi arttı.
- Ticaret gemilerinin geçişinde serbestlik korundu.

Montrö, Türkiye’nin **egemenlik haklarını diplomasi ile geri aldığı** bir antlaşmadır. Savaşsız elde edilmiş büyük bir başarıdır.

:::neden-sonuc
- İtalya ve Almanya’nın tehditkâr politikaları artar => Boğazlar’ın güvenliği tehlikeye girer.
- Türkiye, Boğazlar rejiminin değişmesini ister => Montrö Konferansı toplanır, 1936’da sözleşme imzalanır.
- Montrö Sözleşmesi imzalanır => Türkiye Boğazlar üzerinde egemenlik haklarını geri alır.
:::

## 7. Sadabat Paktı (1937)

Doğu sınırındaki güvenliği sağlamak için **8 Temmuz 1937’de Tahran’daki Sadabat Sarayı’nda Sadabat Paktı** imzalandı.

- **Üyeler:** Türkiye, İran, Irak, Afganistan.
- **Amaç:** Doğu komşuları arasında güvenliği ve dostluğu sağlamak, birbirlerinin işlerine karışmamak.

Bu pakt, Türkiye’nin **doğuda barış ortamı** oluşturma çabasının sonucudur.

## 8. Hatay sorunu

Hatay (İskenderun Sancağı), Lozan’dan sonra Fransız mandasındaki Suriye sınırları içinde kalmıştı. Halkının büyük bölümü Türk’tü. Atatürk, Hatay’ın Türkiye’ye katılması için **diplomatik yolları** kullandı.

- **1936:** Fransa, Suriye’ye bağımsızlık verme kararı alınca Hatay’ın durumu gündeme geldi. Türkiye, Milletler Cemiyeti’ne başvurdu.
- **1937-1938:** Hatay’a özel bir statü verildi. Hatay Devleti kuruldu (1938).
- **23 Temmuz 1939:** Hatay Meclisi, **Türkiye’ye katılma kararı aldı**. Böylece Hatay anavatana katıldı.

Hatay, Atatürk’ün **ölümünden sonra** katılmıştır, ama çalışmalar ve süreç onun döneminde başlamıştır.

