Savaşı kazanmak bir devleti kurmak için yeterli değildi. Yeni Türk devletinin siyasi, hukuki, eğitim, toplumsal ve ekonomik alanlarda da **çağdaş bir yapıya** kavuşması gerekiyordu. Mustafa Kemal Atatürk ve arkadaşları bu amaçla birçok **inkılap** gerçekleştirdi. Bu konuda Atatürk ilkelerini, inkılapları ve bu inkılapların hangi ilkeye dayandığını öğreneceksin. LGS’de en çok “hangi inkılap hangi ilkeyle ilgilidir?” ve “hangi inkılap hangi alanda yapılmıştır?” soruları çıkar.

