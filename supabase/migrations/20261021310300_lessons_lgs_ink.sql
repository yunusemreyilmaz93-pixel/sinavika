“Hattı müdafaa yoktur, sathı müdafaa vardır. O satıh bütün vatandır.” Bu söz Sakarya Meydan Muharebesi öncesinde söylendi. Kurtuluş Savaşı, bir milletin yok olma tehlikesine karşı verdiği **destansı bir mücadeledir**. Bu konuda savaşın hangi cephelerde, nasıl bir sırayla yürütüldüğünü, hangi muharebelerin neden önemli olduğunu ve savaşın nasıl sona erdiğini öğreneceksin.

:::hedefler
1. Kurtuluş Savaşı’nın cephelerini (doğu, güney, batı) ve oralarda olan gelişmeleri açıklamak.
2. Kuva-yi Milliye’den düzenli orduya geçişin sebep ve sonuçlarını yorumlamak.
3. İnönü, Sakarya ve Büyük Taarruz muharebelerini sırayla ve önemiyle söylemek.
4. Mudanya Ateşkesi ve Lozan Barış Antlaşması’nın sonuçlarını açıklamak.
:::

:::ipucu
Cephe soruları iki şeyi karıştırır: **hangi cephe** ve **hangi sonuç**. Her cepheyi bir cümleyle özetle. Doğu: Ermenilere karşı Gümrü Antlaşması. Güney: Fransızlara karşı Ankara Antlaşması. Batı: Yunanlara karşı İnönü, Sakarya, Büyük Taarruz.
:::

## 1. Savaşın cepheleri

TBMM açıldıktan sonra Anadolu’yu işgal eden devletlere karşı üç ana cephede savaş verildi.

| Cephe | Düşman | Sonuç |
| --- | --- | --- |
| Doğu | Ermeniler | Gümrü Antlaşması (3 Aralık 1920) |
| Güney | Fransızlar | Ankara Antlaşması (20 Ekim 1921) |
| Batı | Yunanlılar | İnönü, Sakarya ve Büyük Taarruz sonucu zafer |

### Doğu Cephesi

Doğu’da Ermeni birliklerine karşı **Kâzım Karabekir** komutasındaki Doğu Ordusu savaştı. Ermenilerin yenilgisiyle **Gümrü Antlaşması (3 Aralık 1920)** imzalandı. Bu, **TBMM’nin imzaladığı ilk uluslararası antlaşmadır**. Doğu sınırımız güvence altına alındı.

### Güney Cephesi

Güneyde Fransızlara karşı halkın kahramanca direnişi öne çıktı. Antep, Maraş ve Urfa’da halk, Kuva-yi Milliye ile birlikte savaştı. Bu direniş sonunda şehirlere **gazilik ve şehitlik** unvanları verildi: Gaziantep, Kahramanmaraş, Şanlıurfa. Savaşın ilerlemesiyle Fransa, **Ankara Antlaşması (20 Ekim 1921)** ile Güney Cephesi’nden çekildi ve Türkiye’yi fiilen tanıdı.

### Batı Cephesi

Batı Cephesi’nde Yunan ordusuna karşı ilk zamanlarda **Kuva-yi Milliye birlikleri** ve düzensiz birlikler savaştı. Ancak Yunan ordusunun düzenli saldırıları karşısında düzenli bir orduya ihtiyaç doğdu.

:::baglanti
Düzenli ordunun kurulması, Kuva-yi Milliye’nin **görevini tamamladığı** anlamına gelir. Kuva-yi Milliye düzenli ordu kurulana kadar düşmanı oyaladı, halkta direniş ruhu yarattı. Düzenli ordu ise **merkezden yönetilen, disiplinli ve planlı** savaş yapabilen bir yapıya sahipti.
:::

## 2. Düzenli ordunun kuruluşu

TBMM, 1920 sonunda düzenli ordu kurmaya karar verdi. Bu karara muhalefet eden **Çerkez Ethem** ve çevresindeki Kuva-yi Milliye birlikleri, Meclis’e karşı çıktı. Bu isyan bastırıldı ve düzenli ordu güçlendi.

## 3. Batıdaki ana muharebeler

### Birinci İnönü Muharebesi (6-10 Ocak 1921)

Düzenli ordunun **ilk zaferidir**. Yunan ordusunun Eskişehir yönündeki ilerleyişi durduruldu. Batı Cephesi komutanı **İsmet Bey** idi. Bu zafer sayesinde **Moskova Antlaşması (16 Mart 1921)** imzalandı ve TBMM’nin uluslararası itibarı arttı. Ayrıca **Teşkilat-ı Esasiye Kanunu (20 Ocak 1921)** ile ilk anayasa kabul edildi.

Birinci ve İkinci İnönü muharebeleri arasında, **12 Mart 1921’de İstiklal Marşı** TBMM’de kabul edildi.

### İkinci İnönü Muharebesi (23 Mart - 1 Nisan 1921)

Yunan ordusunun yeniden saldırısı sonucu verilen muharebedir. İsmet Bey yine zafer kazandı. Mustafa Kemal, İsmet Bey’e gönderdiği tebrik telgrafında şöyle dedi: **“Siz orada yalnız düşmanı değil, milletin makûs talihini de yendiniz.”**

### Kütahya-Eskişehir Savaşları (10-24 Temmuz 1921)

Yunan ordusu bu savaşlarda üstünlük sağladı. Türk ordusu **Sakarya Nehri’nin doğusuna çekildi**. Eskişehir ve Kütahya kaybedildi, Meclis’te kaygı arttı.

:::neden-sonuc
- Kütahya-Eskişehir’de geri çekilme => Meclis’te Mustafa Kemal’e **Başkomutanlık yetkisi** verilmesi talebi güçlendi.
- Mustafa Kemal Başkomutan olur (5 Ağustos 1921) => Ordunun tüm yetkisi tek elde toplanır, savaş planlı yürütülür.
- “Tekâlif-i Milliye Emirleri” yayımlanır => Halktan ordunun ihtiyacı için erzak, giyecek ve hayvan toplanır.
:::

### Sakarya Meydan Muharebesi (23 Ağustos - 13 Eylül 1921)

Ankara’yı tehdit eden Yunan ordusunu durdurmak için verilen **22 gün 22 gece süren** muharebedir. Mustafa Kemal şu sözle stratejiyi açıkladı: **“Hattı müdafaa yoktur, sathı müdafaa vardır. O satıh bütün vatandır. Vatanın her karış toprağı vatandaşın kanıyla sulanmadıkça terk olunamaz.”**

- Türk ordusu, savunma yapıp saldırıya geçerek **Yunan ordusunu geri attı**.
- Sakarya’nın ardından Türk ordusu savunmadan **taarruza** geçti.
- **19 Eylül 1921’de** TBMM, Mustafa Kemal’e **Mareşal** rütbesi ve **Gazi** unvanını verdi.

Sakarya Muharebesi’nin sonucu savaşın **dönüm noktasıdır**. Türk ordusu bundan sonra taarruz için hazırlık yaptı.

### Büyük Taarruz ve Başkomutanlık Meydan Muharebesi

Büyük Taarruz, **26 Ağustos 1922’de Kocatepe’den** başladı. Başkomutan Mustafa Kemal ordunun başındaydı. Muharebe **26 Ağustos - 18 Eylül 1922** arasında sürdü.

| Tarih | Olay |
| --- | --- |
| 26 Ağustos 1922 | Büyük Taarruz başladı (Kocatepe) |
| 30 Ağustos 1922 | Dumlupınar’da Yunan ordusu kuşatıldı (Başkomutanlık Meydan Muharebesi) |
| 1 Eylül 1922 | “Ordular! İlk hedefiniz Akdeniz’dir, ileri!” emri verildi |
| 9 Eylül 1922 | İzmir kurtuldu |
| 18 Eylül 1922 | Batı Anadolu’nun tamamı kurtuldu |

**30 Ağustos** bugün **Zafer Bayramı** olarak kutlanır. Dumlupınar zaferi, Yunan ordusunun büyük kısmının esir alınması ve komutanlarının yakalanmasıyla sonuçlandı.

## 4. Mudanya Ateşkesi ve Lozan

### Mudanya Ateşkes Antlaşması (11 Ekim 1922)

Büyük Taarruz’un ardından **ateşkes** imzalandı. Doğu Trakya ve İstanbul’un Türklere geri verilmesi kabul edildi. Bu antlaşma, **Kurtuluş Savaşı’nın askerî olarak sona erdiğini** gösterir. TBMM de bundan sonra **saltanatı kaldırdı** (1 Kasım 1922).

### Lozan Barış Antlaşması (24 Temmuz 1923)

Savaş bittiğinde yeni Türk devletinin uluslararası alanda tanınması gerekiyordu. **Lozan Konferansı**’nda Türk heyetine **İsmet Paşa** başkanlık etti. **24 Temmuz 1923’te Lozan Barış Antlaşması** imzalandı.

Antlaşmanın önemli sonuçları:

- **Misak-ı Milli** büyük ölçüde gerçekleştirildi. Türkiye’nin bugünkü sınırlarına büyük ölçüde ulaşıldı (Musul ve Hatay hariç).
- **Kapitülasyonlar kaldırıldı.** Yabancılara tanınan ayrıcalıklar sona erdi.
- **Azınlıkların haklarına** dair düzenlemeler yapıldı.
- Boğazlar için bir rejim belirlendi (daha sonra 1936’da Montrö ile değişecektir).
- Osmanlı borçları meselesi çözüme bağlandı.
- Türkiye bağımsız ve egemen bir devlet olarak tanındı.

:::baglanti
Lozan, Türk Milleti’nin **savaş meydanındaki zaferini diplomasi masasına taşıdığı** antlaşmadır. Sevr, Osmanlı’yı bitirmeye çalışan bir belgeydi. Lozan ise Sevr’i **geçersiz kılan**, Türkiye’yi uluslararası alanda tanıtan belgedir.
:::

## 5. Kurtuluş Savaşı’nda halkın rolü

Savaş yalnızca ordunun değil, **bütün milletin** mücadelesidir.

- **Kadınlar:** Cephane taşıdı, yaralı baktı, köylerde üretimi sürdürdü. Nene Hatun, Kara Fatma (Fatma Seher Erden), Halime Çavuş gibi kadınlar savaşta fiilen yer aldı.
- **Köylüler:** Kağnılarla cepheye mühimmat taşıdı.
- **Tekâlif-i Milliye Emirleri:** Halktan ordu için erzak, giyecek ve hayvan toplandı.
- **Yurt dışı destek:** Bazı İslam ülkeleri ve Sovyetler Birliği maddi destek verdi.

