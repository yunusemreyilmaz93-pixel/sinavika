## 1. Demokrasinin ilk adımları

Cumhuriyet ilan edildiğinde yönetim anlayışı şu ilkelere dayanıyordu:

- **Milli egemenlik:** Egemenlik bir kişinin ya da hanedanın değil, milletindir.
- **Seçimle gelen yönetim:** Yasama yetkisi, halkın seçtiği temsilcilerden oluşan TBMM’dedir.
- **Hukukun üstünlüğü:** Herkes yasalar karşısında eşittir.

1921 Anayasası (Teşkilat-ı Esasiye) “Hâkimiyet, kayıtsız şartsız milletindir.” ilkesini koydu. 1924 Anayasası ise Cumhuriyet’i ve milli egemenliği anayasal güvenceye aldı.

**Cumhuriyet Halk Fırkası (CHF)**, Mustafa Kemal’in öncülüğünde kuruldu (9 Eylül 1923’te kuruldu, 1924’te Cumhuriyet Halk Fırkası adını aldı). Parti, ülkeyi yönetirken aynı zamanda inkılapları gerçekleştiren ana siyasi güç oldu.

## 2. Çok partili hayata geçiş denemeleri

Atatürk, demokrasinin gelişmesi için **muhalefet partilerinin** de önemli olduğunu düşünüyordu. Bu nedenle iki kez çok partili hayata geçiş denendi.

### Terakkiperver Cumhuriyet Fırkası (1924)

**17 Kasım 1924’te** Kâzım Karabekir ve arkadaşları tarafından kuruldu. Cumhuriyet’i ve laikliği benimseyen bir muhalefet partisiydi. Ancak parti programında dinî duyguların ve geleneklerin saygıyla karşılanmasına dair maddeler vardı. Bazı çevreler partiyi ve bu maddeleri **inkılaplara karşı çıkmak için** kullanmak istedi.

**Şeyh Said İsyanı (Şubat 1925)** patlak verdi. Bu isyan, **Cumhuriyet ve laiklik karşıtı** bir ayaklanmadır. Hükümet, isyanı bastırmak için **Takrir-i Sükûn Kanunu**nu (4 Mart 1925) çıkardı. Bu kanun, hükümete olağanüstü yetkiler verdi ve **İstiklal Mahkemeleri** yeniden kuruldu. İsyanın ardından **Terakkiperver Cumhuriyet Fırkası kapatıldı** (Haziran 1925).

:::neden-sonuc
- Şeyh Said İsyanı çıktı => Hükümet, Takrir-i Sükûn Kanunu ile olağanüstü yetkiler aldı.
- İsyanda Terakkiperver Cumhuriyet Fırkası’nın bazı maddeleri çevrelerce kullanıldı => Parti, isyandan sonra kapatıldı.
- Muhalefet partisi kapanınca => Çok partili hayat denemesi sonuçsuz kaldı. Cumhuriyet Halk Fırkası tek parti olarak yoluna devam etti.
:::

### Serbest Cumhuriyet Fırkası (1930)

1929 Dünya Ekonomik Bunalımı Türkiye’yi de etkiledi. Halkta ekonomik sıkıntı arttı. Atatürk, bu sıkıntıları hükümete **eleştiri yoluyla** dile getirecek bir muhalefet partisinin kurulmasını istedi. Bunun üzerine **12 Ağustos 1930’da** Atatürk’ün yakın arkadaşlarından **Fethi Okyar** önderliğinde **Serbest Cumhuriyet Fırkası** kuruldu.

Partiye halk büyük ilgi gösterdi. Ancak bazı çevreler partiyi **Cumhuriyet’e ve inkılaplara karşı** bir platform olarak kullanmaya çalıştı, gösteriler gerginlik çıkardı. Bunun üzerine **Fethi Okyar**, partisini **17 Kasım 1930’da** kendisi feshetti.

Kısa süre sonra yaşanan **Menemen Olayı (23 Aralık 1930)**, gericiliğin tehlikesini göstermiştir. Derviş Mehmet adlı bir kişi ve yandaşları Menemen’de ayaklandı ve Yedek Subay Öğretmen **Mustafa Fehmi Kubilay**’ı şehit etti. Olay, rejimin inkılaplara yönelik tehdit algısını güçlendirdi.

| | Terakkiperver Cumhuriyet Fırkası | Serbest Cumhuriyet Fırkası |
| --- | --- | --- |
| Kuruluş | 17 Kasım 1924 | 12 Ağustos 1930 |
| Kurucu | Kâzım Karabekir ve arkadaşları | Fethi Okyar |
| Kuruluş sebebi | Demokratik muhalefet | Ekonomik sıkıntılara eleştirel yaklaşım |
| Kapanış | Şeyh Said İsyanı sonrası (Haziran 1925) | Fethi Okyar’ın kendini feshetmesi (Kasım 1930) |
| İlgili olay | Şeyh Said İsyanı | Gerici eylemler, fesihten kısa süre sonra Menemen Olayı |

:::baglanti
İki partinin ortak kaderi şudur: İkisi de **demokratik muhalefet** için kuruldu ama **gericiliğin ve inkılap karşıtlarının** kullanma çabasına yakalandı. Atatürk’ün demokrasi niyeti ciddiydi. Ancak toplumun henüz hazır olmadığı ve yeni rejimin tehdit altında bulunduğu bir dönemdi.
:::

## 3. Kadınlara siyasi haklar

Cumhuriyet döneminde kadınların toplumdaki yeri güçlendi. Siyasi haklar basamak basamak verildi.

| Hak | Tarih |
| --- | --- |
| Belediye seçimlerinde seçme ve seçilme | 3 Nisan 1930 |
| Köy muhtarlığı ve ihtiyar heyeti seçimleri | 26 Ekim 1933 |
| Milletvekili seçme ve seçilme hakkı | 5 Aralık 1934 |

**1935 seçimlerinde 18 kadın milletvekili** TBMM’ye girdi. Türkiye, bu hakkı birçok Avrupa ülkesinden **önce** tanımıştır. Bu gelişme **halkçılık** ve **demokratikleşme** açısından önemlidir. Kadınlar siyasete katıldı, kamu görevlerinde ve eğitimde yer aldı.

## 4. Atatürk’ten sonra çok partili hayat

Atatürk’ün ölümünden sonra, **II. Dünya Savaşı’nın** sonunda Türkiye çok partili hayata geçişi yeniden gündeme aldı.

- **7 Ocak 1946’da Demokrat Parti** kuruldu. Parti, tek partili yönetimden çok partili yönetime geçişin önemli adımı oldu.
- **1946 seçimlerinde** çok partili hayatın ilk seçimi yapıldı.
- **14 Mayıs 1950 seçimlerinde** Demokrat Parti büyük bir çoğunlukla iktidara geldi. Bu seçim, Türkiye’de **ilk kez iktidarın seçimle el değiştirdiği** seçimdir.

Böylece Atatürk’ün planladığı demokratik rejim, uzun bir süreç sonunda gerçekleşti.

