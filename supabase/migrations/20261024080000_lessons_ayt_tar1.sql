## 1. I. Meşrutiyet (1876)

- **Neden:** Tanzimat'ın yetersizliği, mali kriz, Balkanlardaki isyanlar, **Jön Türkler** ve **Yeni Osmanlılar** (Namık Kemal, Ziya Paşa) hareketi, Mithat Paşa'nın liderliği.
- **1876'da** V. Murat'ın akıl hastalığı nedeniyle tahttan indirilmesinin ardından **II. Abdülhamit** tahta çıktı ve **Kanun-ı Esasi**'yi ilan etti (23 Aralık 1876). **Osmanlı Devleti'nin ilk anayasası**dır. **Meclis-i Mebusan** (halkın seçtiği) ve **Ayan Meclisi** (padişahın seçtiği) açıldı.
- **93 Harbi (1877-78):** Osmanlı-Rus Savaşı. Ayastefanos, sonra **Berlin Antlaşması** (1878). **Abdülhamit Meclisi kapattı** (1878) ve Kanun-ı Esasi'yi askıya aldı. **Istibdat dönemi** başladı.

## 2. II. Abdülhamit dönemi (1878-1908)

- **Yönetim:** Sansür, jurnal (ihbar), siyasi baskı. **İttihad-ı İslam (Panislamizm)** siyaseti. **Halifelik** vurgusu.
- **Eğitim ve ulaşım:** Okullar (idadi, rüşdiye), **Darülfünun** (üniversite), **Hicaz Demiryolu**, **Bağdat Demiryolu** (Almanya ile).
- **Dış politika:** Almanya'ya yakınlık. **Düyun-u Umumiye** (1881): Osmanlı borçlarının yönetimi yabancılara bırakıldı.
- **Muhalefet:** **Jön Türkler**: **İttihat ve Terakki Cemiyeti** (1889 İstanbul'da askerî tıbbiyede, Paris'te Ahmet Rıza) ve diğer cemiyetler.

## 3. II. Meşrutiyet (1908) ve sonrası

- **1908:** İttihat ve Terakki'nin baskısıyla II. Abdülhamit **Kanun-ı Esasi'yi yeniden yürürlüğe koydu**.
- **31 Mart Vakası (13 Nisan 1909):** İstanbul'da çıkan gerici ayaklanma. **Hareket Ordusu** (Mahmut Şevket Paşa, Mustafa Kemal'in de görev yaptığı) bastırdı. **II. Abdülhamit tahttan indirildi**, V. Mehmet Reşat tahta çıktı.
- **1913 Bab-ı Ali Baskını:** İttihat ve Terakki yönetimi tek parti idaresine yöneldi.

**Siyasi akımlar:** **Osmanlıcılık** (tüm tebaanın eşitliği), **İslamcılık** (İslam birliği), **Türkçülük** (Ziya Gökalp, Yusuf Akçura), **Batıcılık** (Abdullah Cevdet, Kılıçzade Hakkı). **Adem-i merkeziyetçilik** (Prens Sabahattin).

## 4. Savaşlar

- **Trablusgarp Savaşı (1911-1912):** İtalya saldırdı. **Uşi (Ouchy) Antlaşması**: Osmanlı Libya'yı fiilen kaybetti. Mustafa Kemal ve Enver Bey direniş.
- **Balkan Savaşları (1912-1913):** Sırbistan, Bulgaristan, Yunanistan ve Karadağ **Balkan Birliği** kurdu. **I. Balkan Savaşı** (1912): Osmanlı yenildi. **Londra Antlaşması** (1913). **II. Balkan Savaşı** (1913): Bulgaristan, müttefikleriyle savaştı. **Bükreş Antlaşması**. Osmanlı Edirne'yi geri aldı: **İstanbul Antlaşması** (Bulgaristan, 1913). Rumeli'deki topraklar büyük ölçüde kaybedildi.

## 5. I. Dünya Savaşı (1914-1918)

- **Nedenler:** Sömürge rekabeti, silahlanma, bloklaşma (**Üçlü İttifak** ve **Üçlü İtilaf**), Balkanlar sorunu. **Saraybosna Suikastı (28 Haziran 1914).**
- **Osmanlı'nın girişi:** **2 Ağustos 1914** gizli Alman-Osmanlı ittifakı. **Ekim 1914**'te Karadeniz'de Rus limanlarının bombalanmasıyla savaşa girdi.
- **Cepheler:**
  - **Çanakkale (1915):** İtilaf Devletleri'nin Boğazları geçerek İstanbul'u alma ve Rusya'ya yardım ulaştırma girişimi. **Deniz Savaşı (18 Mart 1915)** Osmanlı zaferi. **Kara savaşları:** Anafartalar, Conkbayırı, Arıburnu (Mustafa Kemal'in başarıları). **Sonuç:** Osmanlı zaferi. **Rusya'ya yardım yolu kapandı**, Rusya zayıfladı, **1917 Bolşevik Devrimi** hızlandı.
  - **Kafkas Cephesi:** **Sarıkamış** (1914-15, Osmanlı ağır kayıp), **Ardahan, Kars, Batum** (Brest-Litovsk 1918).
  - **Irak:** **Kut'ül Amare** (1916, Osmanlı zaferi).
  - **Filistin-Sina** ve **Hicaz**: Arap isyanı (Şerif Hüseyin, İngiliz desteği).
- **Savaşın sonu:** **1917'de ABD** İtilaf yanında, **Rusya** savaştan çıkma. **1918'de** **Wilson ilkeleri**. Bulgaristan'ın teslimiyetiyle (Eylül 1918) Osmanlı yalnız kaldı.

## 6. Mondros Ateşkes Antlaşması (30 Ekim 1918)

**Mondros Mütarekesi**, Osmanlı Devleti ile İtilaf Devletleri arasında Limni Adası'ndaki Mondros Limanı'nda **Agamemnon** zırhlısında imzalandı.

**Hükümleri:** Osmanlı ordusu terhis edilecek. Boğazlar İtilaf Devletleri'nin kontrolüne verilecek. **7. madde:** İtilaf Devletleri **güvenliklerini tehdit eden** her stratejik noktayı işgal edebilecek. **24. madde:** Doğu Anadolu'da karışıklık çıkarsa **altı vilayeti** işgal edebilecek. Limanlar ve demiryolları İtilaf Devletleri'nin kontrolüne verilecek.

**Sonuç:** Osmanlı fiilen **savaştan çekildi**. İtilaf Devletleri **bu maddelere dayanarak işgalleri** başlattı (Ocak 1919'dan itibaren). Ardından **İstanbul'un işgali**, **Sevr Antlaşması** (1920) gelir. **Milli Mücadele'nin** başlamasına zemin hazırlar.

## 7. Sık yapılan hatalar

- Kanun-ı Esasi'yi II. Meşrutiyet sırasında hazırlandı sanmak. 1876'dır.
- İstanbul Antlaşması'nı Londra ile karıştırmak. Bulgaristan'la 1913 İstanbul Antlaşması Edirne'yi geri verdi.
- Çanakkale'yi Osmanlı yenilgisi sanmak. Zaferdir.
- Sarıkamış'ı Rus yenilgisi sanmak. Osmanlı ağır kayıp verdi.
- Mondros'u Sevr ile karıştırmak. Mondros ateşkes, Sevr barış antlaşması.

