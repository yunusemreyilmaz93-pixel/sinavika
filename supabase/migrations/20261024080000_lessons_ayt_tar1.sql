## 1. Merkez teşkilatı

- **Padişah:** Devletin başı, hem hükümdar hem **halife** (1517'den sonra). Yetkileri **örfî hukukla** (kanun) ve **şer'i hukukla** (şeriat) sınırlıdır.
- **Divan-ı Hümayun:** Devletin en yüksek **danışma ve yürütme kurulu**. Başkanı **sadrazam** (vezir-i azam). Üyeler: **kubbealtı vezirleri**, **kazaskerler** (adalet), **defterdarlar** (maliye), **nişancı** (tuğra ve fermanlar), **reisülküttap**.
- **Saray:** **Enderun** (devşirmelerin yetiştirildiği saray okulu), **Birun** (dış hizmetler), **Harem**.
- **Şeyhülislam:** Dinî işlerin başı, fetva makamı. Padişahın kararlarını şeriata uygunluk açısından onaylar.

## 2. Taşra teşkilatı

**Eyalet** (beylerbeyi) $\rightarrow$ **Sancak** (sancak beyi) $\rightarrow$ **Kaza** (kadı) $\rightarrow$ **Nahiye** $\rightarrow$ **Köy**. **Kadı**, hem hâkim hem belediye hizmetlerinin başı. Sancak beyi askerî-idari yönetici, kadı yargı organıdır. Bu ikili yapı denge sağlar.

## 3. Askerî teşkilat

- **Kapıkulu askerleri:** Devşirmeden ve ücretli. **Yeniçeri ocağı**, cebeci, topçu, sipahi. Başkent ve sınır kalelerinde.
- **Eyalet askerleri:** **Timarlı sipahi**. Taşrada toprak geliriyle beslenen atlı savaşçılar.
- **Donanma:** Kaptan-ı Derya. **Barbaros Hayrettin Paşa**, **Piri Reis**.
- **Devşirme sistemi:** Gayrimüslim ailelerden çocuklar alınır, İslam ve Türk terbiyesi içinde yetiştirilir, saray ve ordu hizmetinde çalıştırılır. Devşirmeler yetenek sayesinde vezir ve sadrazam olabilirdi.

## 4. Timar sistemi

**Timar:** Devletin **toprak gelirini** hizmet karşılığı **sipahiye** vermesi (iktâ benzeri). Sipahi, bölgesinde **asker besler**, güvenliği ve vergi toplamayı sağlar, savaşta **cebelü** (atlı asker) götürür. **Toprağın mülkiyeti devlete** aittir (**miri arazi**), sipahi yalnızca gelirini alır. **Çiftbozan** vergisi.

Bu sistem hem **maaş ödemesini** (nakit gereksiniminden kurtulma), hem **taşra yönetimini**, hem **askeri gücü** sağlar.

## 5. Toplum yapısı

**Askerîler:** Vergi vermeyen yönetici sınıf (padişah ailesi, vezirler, kadılar, sipahiler, yeniçeriler, ulema).

**Reaya:** Vergi veren halk (çiftçi, esnaf, tüccar, hayvancılık yapanlar). Gayrimüslim reaya da vardı.

**Millet sistemi:** Gayrimüslim cemaatler (Rum Ortodoks, Ermeni, Yahudi) **kendi dinî ve hukuki işlerinde** özerkti. Cemaat önderleri (patrik, hahambaşı) sorumluydu. **Cizye** vergisi ödenir, askerlik yapılmazdı. Bu hoşgörülü yapı toplumsal barışı sağladı.

## 6. Ekonomi

- **Tarım:** Temel gelir. **Miri arazi**, vakıf arazisi, mülk arazi. **Çift-hane sistemi.**
- **Ticaret ve esnaf:** **Lonca** (Ahilik temelli), **narh** (fiyat denetimi), **bedesten**, **han**. **İpek Yolu**, Baharat Yolu.
- **Maliye:** Öşür, cizye, avarız, gümrük. **İltizam** sonra yaygınlaştı.
- **Vakıf:** Gelirini hayır işlerine ayıran kurum. Cami, medrese, hastane, çeşme, kervansaray. Toplumsal dayanışma ve kamu hizmeti.
- **Kapitülasyonlar:** Önce 1535 Fransa'ya verilen ticaret ayrıcalıkları (hukuki bağlama sonra).

## 7. Eğitim, bilim, sanat ve mimari

- **Eğitim:** **Sıbyan mektebi** (ilkokul), **medrese** (yüksek). **Sahn-ı Seman** (Fatih) ve **Süleymaniye Medreseleri**. **Enderun** (saray okulu).
- **Bilim:** **Ali Kuşçu** (astronomi), **Piri Reis** (Kitab-ı Bahriye, 1513 dünya haritası), **Takiyüddin** (İstanbul Rasathanesi), **Katip Çelebi** (Cihannüma, Keşfüzzünun), **Evliya Çelebi** (Seyahatname), **Matrakçı Nasuh**.
- **Mimari:** **Mimar Sinan**: **Şehzade Camii** (çıraklık), **Süleymaniye** (kalfalık), **Edirne Selimiye** (ustalık). **Mimar Mehmet Ağa:** Sultanahmet Camii. Külliye, cami, medrese, imaret.
- **Edebiyat:** Divan edebiyatı (Fuzuli, Baki, Nedim), halk edebiyatı, tekke edebiyatı.
- **Sanat:** Çini (İznik), minyatür (Nakkaş Osman, Levni), hat, ebru, tezhip.
- **Matbaa:** **İbrahim Müteferrika** 1727'de ilk Türk matbaasını kurdu.

## 8. Sık yapılan hatalar

- Devşirmeyi yalnızca ordu için sanmak. Saray ve devlet yönetimini de besledi.
- Timar sahibinin toprağın mülkiyetini aldığını sanmak. Toprak devletindi.
- Millet sistemini ayrımcılık olarak yorumlamak. Cemaat özerkliğidir.
- Mimar Sinan'ın ustalık eserinin Süleymaniye olduğunu sanmak. Selimiye'dir.
- Divan-ı Hümayun'u yalnızca yargı organı sanmak. Danışma ve yürütme kuruludur.

