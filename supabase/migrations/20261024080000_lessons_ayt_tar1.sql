## 1. Kuruluş

**Malazgirt'ten (1071)** sonra Türkmen akınları arttı. **Kutalmışoğlu Süleyman Şah**, Büyük Selçuklu sultanına bağlı kalmayarak **1075'te İznik**'te **Anadolu Selçuklu Devleti**'ni kurdu.

- **I. Kılıç Arslan (1092-1107):** İznik merkezli. **I. Haçlı Seferi** sırasında (1097) Haçlılar İznik'i aldı. Selçuklular **Dorylaion'da** yenildi. **Başkent Konya'ya taşındı.**
- **II. Kılıç Arslan (1156-1192):** **1176 Miryokefalon Savaşı'nda** Bizans'ı yendi. **Anadolu'nun Türk yurdu olduğu** kesinleşti. Bizans'ın Anadolu'yu geri alma umudu sona erdi.

## 2. Yükseliş ve en parlak dönem

- **I. Gıyaseddin Keyhüsrev:** **1207 Antalya** fethi. Akdeniz'e çıkış.
- **I. İzzeddin Keykâvus:** **1214 Sinop** fethi, Karadeniz'e çıkış. Önemli limanlar ve ticaret.
- **I. Alaaddin Keykubat (1220-1237):** **Devletin en parlak dönemi.** **Alanya** fethi (1221, Alaiye) ve Akdeniz hâkimiyeti. **Kubadabad Sarayı.** Konya'da imar. Moğol tehlikesine karşı Harezmşah ve Eyyubi ilişkileri. **Kervansaraylar** ve **hanlar** yapıldı. Ticaret yolları güvenliği.

## 3. Gerileme ve Moğol hâkimiyeti

- **Babailer isyanı (1240):** Baba İlyas önderliğinde, vergi ve yönetimden hoşnutsuz Türkmenler. Bastırıldı ama devlet zayıfladı.
- **Kösedağ Savaşı (1243):** **II. Gıyaseddin Keyhüsrev**, Moğol komutanı **Baycu Noyan**'a yenildi. **Anadolu Selçuklu Devleti Moğol hâkimiyetine girdi**, vergi vermek zorunda kaldı. Selçuklu sultanları Moğollara bağlı hükümdar oldu.
- **Parçalanma:** Moğol baskısı ve iç çekişmeler. Selçuklu otoritesi azaldı, **Türkmen beylikleri** güçlendi. **1277'de Karamanoğlu Mehmet Bey Türkçeyi resmî dil ilan etti.** **1308 civarında** devlet sona erdi.
- **Beylikler:** Osmanlı, Karamanoğulları, Germiyanoğulları, Aydınoğulları, Saruhanoğulları, Menteşeoğulları, Candaroğulları gibi beylikler ortaya çıktı.

## 4. Devlet teşkilatı

- **Sultan:** Devletin başı. **Divan:** Vezir, **Sahib-i Divan** (maliye), **Pervane** (tuğra ve fermanlar).
- **Atabeylik, iktâ sistemi** (toprak gelirinin askerlere tahsisi), **Uç beylikleri** (sınır).
- **Ordu:** Atlı birlikler, Türkmen askerleri, ücretli askerler. **Merkez ordusu** (hassa) ve iktâ sahibi atlılar.
- **Hukuk:** İslam hukuku ve Türk töresi.

## 5. Ekonomi, sanat ve kültür

- **Ticaret:** İpek Yolu ve Baharat Yolu'nun Anadolu geçişi. **Kervansaraylar** (Sultanhanı, Ağzıkarahan, Alarahan) yol boyunca yaklaşık bir günlük yürüyüş mesafesine yapıldı ve güvenli konaklama, ticaretin güvenliği sağladı. **Gümrük** ve vergi gelirleri.
- **Mimari:** **Medreseler** (Karatay Medresesi, İnce Minareli Medrese, Çifte Minareli Medrese), **camiler** (Alâeddin Camii, Konya), **darüşşifalar** (hastaneler, Divriği Ulu Cami ve Şifahanesi), **kümbetler**, **çini** süslemeler. Taç kapı, çini, alçı süsleme.
- **Dil:** Resmî dil Farsça, ilim dili Arapça, halk dili Türkçe. **Mevlana (Farsça Mesnevi)**, **Yunus Emre** (sade Türkçe), **Hacı Bektaş Veli** (Vilayetname), **Ahi Evran**.
- **Tasavvuf:** Mevleviliğin merkezi Konya. Türkmen kitlelerin İslamlaşmasında dervişler önemli rol oynadı.

## 6. Ahilik ve sosyal yapı

**Ahilik:** Ahi Evran (Kırşehir) ile ilişkilendirilen, **esnaf ve sanatkârları örgütleyen**, ahlaki ve ekonomik düzen kuran teşkilattır. Üretimde kalite, fiyat denetimi, usta-çırak yetiştirme, iş ahlakı. Ahiler Moğol baskısı döneminde **kentlerin yönetiminde** etkili oldu. **Bacıyan-ı Rum** kadın teşkilatıdır. Osmanlı'da **lonca sistemi** Ahilik temelindedir.

**Yerleşme:** Türkmenler Anadolu'ya **göçebe boylar** hâlinde yerleşti, **uç bölgelerde** gaza geleneği. Kırsalda **zaviyeler**, şehirlerde medrese ve ahi birlikleri.

