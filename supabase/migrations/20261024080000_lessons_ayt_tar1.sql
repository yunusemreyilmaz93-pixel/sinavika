## 1. Asya Hun Devleti (M.Ö. 209-MS 48)

- **Bilinen ilk Türk devletidir.** Kurucusu **Teoman**, devleti güçlendiren **Mete Han**'dır (M.Ö. 209'da başa geçti).
- **Mete Han:**
  - Orduyu **onlu sisteme** (onluk, yüzlük, binlik, onbinlik) göre düzenledi. Bu sistem sonraki Türk devletlerine örnek oldu.
  - Doğuda Tunguzları, batıda Yüeçileri yendi. Çin'i vergiye bağladı.
  - **Çin Seddi** Çin'in Hun akınlarına karşı yaptığı savunmadır.
  - Devleti "ikili yönetim" (doğu-batı) ile yönetti.
- **Parçalanma:** M.S. 48'de **Kuzey ve Güney Hunları** olarak ikiye ayrıldı. Çin baskısı, iç çekişme ve doğal afetler nedeniyle zayıfladı.
- **Sosyal ve kültürel:** Hayvancılık, savaşçılık, ticaret. Hayvan üslubu (geyik, kurt) sanatı. Gök Tanrı inancı.

## 2. Avrupa Hun Devleti

Hunların bir kısmı batıya göç etti. **375'te Balamir** komutasında Karadeniz'in kuzeyine gelmeleriyle **Kavimler Göçü** başladı.

- **Kavimler Göçü:** Hunlar Germen ve Slav kavimlerini batıya sürdü, Roma sınırları zorlandı. **Roma 395'te ikiye ayrıldı, 476'da Batı Roma yıkıldı.** Böylece Orta Çağ'ın başlamasında dolaylı rol oynadı.
- **Attila (434-453):** Avrupa Hun Devleti'nin en güçlü hükümdarı. **Katalon Ovası Savaşı** (451) sonunda Roma ve Cermenlerle yapılan savaşta çekilmek zorunda kaldı. Attila'nın ölümüyle (453) devlet dağıldı.

## 3. Göktürk Devleti (552-744)

- **Bumin Kağan** 552'de kurdu. **"Türk" adını taşıyan ilk Türk devletidir.** İlk kez "Türk" adıyla anılan devlet. Batıdaki kardeşi **İstemi Yabgu**.
- **582'de** Doğu ve Batı Göktürk olarak ikiye ayrıldı. Çin baskısı ve iç çekişmeler.
- **II. Göktürk Devleti (682-744):** **Kutluk (İlteriş) Kağan** kurdu. **Kapgan, Bilge Kağan, Kül Tigin, Tonyukuk** dönemde öne çıkar. **Orhun Yazıtları**: Kül Tigin (732) ve Bilge Kağan (735) yazıtları Türk tarihinin ve Türkçenin en eski yazılı belgeleridir.
- **744'te** Uygurlar, Basmıllar ve Karluklar'ın saldırısıyla yıkıldı.
- **Din:** Gök Tanrı. **Alfabe:** Göktürk (Orhun) alfabesi.
- **Ekonomi:** Hayvancılık ve ticaret. **İpek Yolu** önemli.

## 4. Uygur Devleti (744-840)

- **Kutluk Bilge Kül Kağan** kurdu. Orhun Nehri kıyısında Karabalgasun'u kurdu.
- **Yerleşik hayata** geçen ilk Türk devletlerindendir. Tarım, ticaret, şehirleşme (Karabalgasun, Koço).
- **Din:** **Maniheizm** (762'de Bögü Kağan kabul etti) ve **Budizm**. Hristiyanlık da yaşadı.
- **Alfabe:** **Uygur alfabesi** (Soğd kökenli). Sonraki Türk devletleri ve Moğollar da bu alfabeyi kullandı.
- **Sanat ve bilim:** Duvar resimleri (Bezeklik), minyatür, **kâğıt ve matbaa** (tahta kalıp baskı), tıp ve takvim.
- **840'ta** Kırgızlar Karabalgasun'u yıktı. Uygurlar Doğu Türkistan'a (Turfan) ve Çin içlerine dağıldı.

## 5. Diğer Türk toplulukları

- **Avarlar:** Kavimler Göçü sonrası Orta Avrupa'da devlet kurdu.
- **Hazarlar:** Hazar Denizi'nin kuzeyi. **Yahudiliği** kabul eden Türk devleti.
- **Bulgarlar, Macarlar, Peçenekler.**

## 6. Devlet ve toplum yapısı

- **Kağan (Hakan):** Devletin başı. **Kut** anlayışıyla yönetme yetkisi Tanrı'dan gelir. Hükümdar halkın hukukuna uyar.
- **Töre:** Yazılı olmayan hukuk kurallarıdır. Hükümdarı da bağlar.
- **Kurultay (toy):** Devlet işlerinin görüşüldüğü danışma meclisi. Seçimler, savaş, barış kararları.
- **Yabgu, tigin, tarkan, beg, tudun:** Yönetici ve unvan adları.
- **Tuğ:** Hükümdarlık sembolü, sancak.
- **Ordu:** Atlı, okçu. **Hun'da onlu sistem.** Ordu-millet anlayışı: Her Türk bir askerdir.
- **Devlet anlayışı:** Hanedanın ortak malı. Ülke hanedan üyeleri arasında paylaşılabilirdi. Bu iç savaşlara ve bölünmelere yol açtı.
- **Ekonomi:** Hayvancılık, ticaret (İpek Yolu), savaş ganimeti. Göçebe ve yerleşik yaşam.

## 7. Sık yapılan hatalar

