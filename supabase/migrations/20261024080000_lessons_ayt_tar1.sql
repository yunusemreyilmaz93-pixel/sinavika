- Epigrafya (yazıt) ile nümizmatiği (para) karıştırmak.
- Olayla olguyu karıştırmak. Olay tek ve tekrarlanmaz, olgu uzun süreli ve tekrarlanabilir.
- Hicri takvimin güneş yılı esaslı olduğunu sanmak.
- Orta Çağ'ın başlangıcını 476 sanmak. Sınav ölçütü 395.

