## 1. Tarih nedir?

**Tarih**, geçmişte yaşanmış olayları **zaman ve yer göstererek**, **neden-sonuç ilişkisi** içinde, **belgelere dayanarak** inceleyen bilimdir.

- **Tarihî olay:** Belirli bir zamanda ve yerde gerçekleşen, bir kez yaşanan durumdur ve tekrarlanmaz (İstanbul'un fethi).
- **Tarihî olgu:** Birçok olayın sonucunda ortaya çıkan, uzun sürelere yayılan durumdur (Orta Çağ'daki feodalite, Sanayi Devrimi).
- **Kronoloji:** Olayları zaman sırasına dizen bilimdir.
- **Tarihî çevre:** Olayın geçtiği coğrafya ve toplumsal ortam.

Tarih **geçmişi anlatır**, ama **deney yapılamaz**. Tarihçi, belgeleri ve kaynakları inceler, karşılaştırır, çıkarım yapar. Tarihin diğer bilimlerden farkı olayların **tekrar edilemez ve tek olmasıdır**. Tarihçi **nesnel** davranmak zorundadır, ama yorumlar tarihçinin bakış açısına göre değişebilir.

## 2. Tarihî kaynaklar

| Tür | Örnek |
| --- | --- |
| **Yazılı** | Yazıtlar, kitabeler, fermanlar, yıllıklar, mektuplar, kanunlar, anılar, gazeteler |
| **Sözlü** | Destan, efsane, atasözü, türkü, masal, ninni |
| **Görsel** | Resim, fotoğraf, harita, minyatür, film |
| **Arkeolojik (kalıntı)** | Kazılarda bulunan eşya, yapı, silah, çanak çömlek |
| **Mimari** | Cami, kale, köprü, saray |

Kaynaklar **birincil** (olayı yaşayanın bıraktığı) ve **ikincil** (sonradan yazılan) olabilir. Birincil kaynaklar daha güvenilirdir ama yine de karşılaştırılarak kullanılır.

## 3. Tarihin yardımcı bilimleri

| Bilim | İncelediği alan |
| --- | --- |
| **Arkeoloji** | Kazı ve kalıntılar, eski yaşam izleri |
| **Epigrafya** | Taş, maden, ağaç üzerindeki yazıtlar (kitabeler) |
| **Paleografya** | Eski yazıları okuma ve çözme |
| **Nümizmatik** | Para ve madalyalar |
| **Sfragistik** | Mühür ve damgalar |
| **Diplomatik** | Resmî belgeler, ahitnameler, fermanlar |
| **Heraldik** | Arma ve flamalar |
| **Antropoloji** | İnsanın biyolojik ve kültürel yapısı |
| **Etnografya** | Halkların yaşam ve kültürleri |
| **Filoloji** | Dil ve yazı çalışması |
| **Kronoloji** | Olayların zamansal sıralanışı |
| **Coğrafya, jeoloji, sosyoloji, ekonomi** | Çevre, yer, toplum ve ekonomi |

## 4. Zaman ve takvim

- **Miladi takvim:** Hz. İsa'nın doğumu (MS 1). Güneş yılı esaslı. Bugünün evrensel takvimi.
- **Hicri takvim:** Başlangıcı Hz. Muhammed'in Mekke'den Medine'ye **hicretidir** (622). **Ay yılı** esaslıdır ve yaklaşık 354 gündür. Dinî günler için kullanılır.
- **Rumi takvim:** Osmanlı'da **mali yıl** için kullanılan, başlangıcı hicret olan ama güneş yılına dayanan takvim.
- **Cumhuriyet dönemi:** 1925'te Miladi takvime geçiş kararı alındı ve 1 Ocak 1926'dan itibaren uygulandı.

**Zaman ölçüleri:** Yıl, asır (yüzyıl), bin yıl, dönem. **Çağ:** Önemli bir olayla başlayıp önemli bir olayla biten, uzun tarih dilimi.

## 5. Tarih dönemleri

**Tarih Öncesi (Prehistorya):** Yazının bulunuşundan (M.Ö. 3200 civarı) öncesidir. Taş Devri (Paleolitik, Mezolitik, Neolitik), Maden Devri (Kalkolitik, Bronz, Demir) olarak ayrılır. Ateşin bulunması, tarıma geçiş (Neolitik), yerleşik hayat, tekerlek.

**Tarih Çağları:**

| Çağ | Başlangıç | Bitiş |
| --- | --- | --- |
| **İlk Çağ** | Yazının bulunuşu (M.Ö. 3200 civarı) | Roma'nın ikiye ayrılması (395) |
| **Orta Çağ** | 395 | İstanbul'un fethi (1453) |
| **Yeni Çağ** | 1453 | Fransız İhtilali (1789) |
| **Yakın Çağ** | 1789 | Günümüz |

Bu dönemlendirme **Avrupa merkezlidir**. Türk tarihinde Orta Çağ'ın başlangıcı için farklı olaylar tartışılır, ama sınav ölçütü 395'tir.

## 6. Sık yapılan hatalar

