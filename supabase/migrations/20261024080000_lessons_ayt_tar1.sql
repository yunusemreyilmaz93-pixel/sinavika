## 1. Mezopotamya

Dicle ve Fırat arasındaki bölgede kurulan uygarlıklar:

- **Sümerler (M.Ö. 3200 civarı):** **Çivi yazısını** buldular. Şehir devletleri (site) kurdular, tekerleği, 60'lık sayı sistemini, takvimi geliştirdiler. **Ziggurat** denen tapınak kuleleri yaptılar.
- **Akadlar:** Sargon önderliğinde Sümerleri birleştirdi. İlk imparatorluk.
- **Babiller:** **Hammurabi** (M.Ö. 1750 civarı) **Hammurabi Kanunları**'nı yazdırdı. **Bilinen ilk yazılı kanunlardan biridir.** "Göze göz, dişe diş" ilkesi.
- **Asurlar:** Güçlü ordu ve demir silahlar. Ninova başkentti. Kütüphane (Asurbanipal).

## 2. Mısır

- **Nil Nehri**'nin taşkınları tarımı belirledi. Güneş takvimi ve geometri geliştirildi. **Hiyeroglif** yazısı, papirüs.
- **Firavun** hem siyasi hem dinî lider. Ölümden sonraki yaşam inancı: **mumyalama**, **piramitler** (Keops, Kefren, Mikerinos).
- Tıp, matematik ve mimaride ilerleme. **Kadeş Savaşı** (M.Ö. 1274): II. Ramses ile Hititler. Savaşın sonunda **Kadeş Antlaşması** yapıldı. Bu antlaşma, bilinen ilk yazılı barış antlaşmasıdır.

## 3. Anadolu uygarlıkları

Anadolu, jeopolitik konumu ve verimli toprakları nedeniyle **uygarlıkların beşiğidir**.

- **Hititler (M.Ö. 17.-12. yüzyıl):** Başkent Hattuşaş (Boğazkale). Kızılırmak çevresinde. **Çivi yazısı** kullandılar. **Kral ve Panku (meclis)**. İlk yazılı antlaşmalardan biri olan Kadeş Antlaşması. **Hititler'de kanunlar** Hammurabi'ye göre daha insancıldır (ölüm cezası sınırlı).
- **Frigler:** Başkent Gordion. Kral Midas. Hititlerin ardından.
- **Lidyalılar:** Başkent Sart. **İlk parayı bastılar** (M.Ö. 7. yüzyıl). **Kral Yolu** (Sart-Susa) ticareti geliştirdi.
- **Urartular:** Van çevresinde. Kale ve sulama kanalları, demir işçiliği.
- **İyonlar:** Batı Anadolu'da Efes, Milet. Felsefe ve bilimin doğduğu yer (Thales, Anaksimandros). Sistemli düşünce, doğaya akılcı bakış.

## 4. Yunan uygarlığı

- **Polis (site):** Bağımsız şehir devletleri (Atina, Sparta, Teb, Korint). **Atina** demokrasinin, **Sparta** askerî rejimin örneğidir. Halk meclisi (Ekklesia).
- **Pers Savaşları (M.Ö. 5. yüzyıl):** Maraton (M.Ö. 490), Termopil, Salamis. Yunanlar kazandı.
- **Makedonya Kralı İskender (M.Ö. 334):** Doğu seferi ve **Helenistik dönem**. Yunan kültürü Asya'ya yayıldı.
- **Katkıları:** Felsefe (Sokrates, Platon, Aristoteles), tarih (Herodot), tıp (Hipokrat), matematik (Pisagor, Öklid), tiyatro, **Olimpiyat oyunları**, demokrasi, alfabe (Fenike alfabesinden).

## 5. Roma

- **Cumhuriyet (M.Ö. 509-27):** Senato, konsüller. Akdeniz'e hâkimiyet.
- **İmparatorluk (M.Ö. 27'den itibaren):** Augustus. Geniş topraklar, sağlam yollar (Via Appia), su kemerleri.
- **Roma hukuku:** "Hukuk önünde eşitlik"in temeli, günümüz hukukunu etkiledi.
- **Hristiyanlığın yayılışı:** 313 Milano Fermanı ile serbest, 380'de resmî din.
- **395:** Theodosius'un ölümüyle Roma, **Doğu (Bizans)** ve **Batı** olarak ikiye bölündü. **476'da** Batı Roma yıkıldı.

## 6. Çin ve Hint

- **Çin:** İpek, barut, pusula, kâğıt ve matbaa. **Çin Seddi** (Türk akınlarına karşı).
- **Hint:** Kast sistemi, Budizm ve Hinduizm, sıfırın ve ondalık sistemin gelişimi.

