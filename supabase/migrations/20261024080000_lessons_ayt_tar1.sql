- Medine Vesikası'nı Veda Hutbesi sanmak.
- Kur'an'ın çoğaltılmasını Hz. Ebubekir'e vermek. Hz. Osman dönemindedir.
- Başkent Şam'ı Abbasilere, Bağdat'ı Emevilere vermek.
- Talas Savaşı'nı Emevi dönemine koymak. 751, Abbasiler dönemindedir.

