## 1. Türklerin İslamiyet'i kabulü

Türkler, **Talas Savaşı'ndan (751)** sonra Araplarla yakınlaştı. İslamiyet, Orta Asya'da 9-10. yüzyıllarda yayıldı. Türklerin eski inançlarıyla (Gök Tanrı, tek Tanrı fikri) İslamiyet'in benzerliği, Türklerin savaşçı karakterine uygun olması, Abbasi ordusunda görev almaları, tüccar ve dervişlerin etkisi, kabulü kolaylaştırdı. **Müslüman olan ilk Türk devleti Karahanlılar**'dır (Satuk Buğra Han, 10. yüzyıl).

## 2. Karahanlılar (840-1212)

- **Kuruluş:** Karluk, Yağma ve Çiğil boylarından oluşan Karahanlı Devleti. **Satuk Buğra Han (Abdülkerim)** İslamiyet'i kabul etti.
- **Başkent:** Balasagun, Kaşgar.
- **Özellikleri:** **Müslüman olan ilk Türk devleti.** Hanedan üyeleri arasında bölünmüş (ikili yönetim), **Tamgaç Buğra Han** döneminde güçlendi. **Samanoğulları'nı yıktı** (999).
- **Kültür:** **Yusuf Has Hacip: Kutadgu Bilig** (devlet yönetimi), **Kaşgarlı Mahmud: Divanü Lügati't-Türk**, **Edip Ahmet Yüknekî: Atabetü'l-Hakayık**, **Ahmed Yesevi: Divan-ı Hikmet**. **Medreseler** ve Türkçenin gelişimi.
- **Sonu:** Karahıtaylar ve Harezmşahlar tarafından yıkıldı.

## 3. Gazneliler (962-1187)

- **Kurucu:** **Alptigin** (Samanoğulları'nın komutanı) 962'de Gazne'de kurdu. **Sebük Tigin** devleti güçlendirdi.
- **Sultan Mahmut (998-1030):** Devletin en parlak dönemi. **Hindistan'a 17 sefer** düzenledi (İslamiyet'i yaymak ve ganimet). **"Sultan" unvanını** ilk kez kullanan hükümdardır (halife tarafından).
- **Kültür:** **Firdevsi** (Şehname, Farsça), **Biruni**. Fars kültürü ağırlıklıdır. Divan dili Farsçadır.
- **Sonu:** **1040 Dandanakan Savaşı**'nda Selçuklulara yenildi. Batı toprakları Selçuklulara geçti. 1187'de Gurlular yıktı.

## 4. Büyük Selçuklu Devleti (1040-1157)

- **Kuruluş:** Oğuzların Kınık boyundan **Selçuk Bey**'in torunları **Tuğrul** ve **Çağrı** Beyler. **1040 Dandanakan Savaşı** ile Gazneliler yenildi, Büyük Selçuklu Devleti kuruldu.
- **Tuğrul Bey (1040-1063):** **1055'te Bağdat'a girdi**. Abbasi halifesi Tuğrul'a "Doğunun ve Batının hükümdarı" unvanını verdi, Selçuklu halifenin koruyucusu oldu. Şii Büveyhoğulları'nı sona erdirdi.
- **Alparslan (1063-1072):** **Malazgirt Savaşı (1071)**'nda Bizans İmparatoru **Romen Diyojen**'i yendi. **Anadolu'nun kapıları Türklere açıldı.** Veziri **Nizamülmülk**.
- **Melikşah (1072-1092):** Devletin zirvesi. **Celali takvimi** (Ömer Hayyam ve arkadaşları), İsfahan'da rasathane. **Nizamülmülk** Nizamiye Medreselerini kurdu ve **Siyasetname**'yi yazdı. Melikşah ve Nizamülmülk'ün ölümüyle (1092) devlet zayıfladı.
- **Sencer (1118-1157):** **1141 Katvan Savaşı**'nda Karahıtaylara yenildi. **1157'de** ölümüyle devlet sona erdi.

**Nizamiye Medreseleri:** Bağdat, Nişabur, İsfahan, Basra gibi şehirlerde açılan, **Sünni** düşünceyi yaymak ve **Şii (İsmaili) propagandaya karşı** devlet adamı ve âlim yetiştirmek için kurulan okullar. Önemli düşünür **Gazali**. **Hasan Sabbah** ve **Haşhaşiler** (İsmaili) devlet adamlarına suikastlar düzenledi.

**Devlet yönetimi:** Sultan, vezir, divan. **İktâ sistemi** (toprak gelirinin askerlere verilmesi). **Atabeylik** (şehzadelerin eğitimi). Türk-İran idari geleneği.

## 5. Harezmşahlar (1077-1231)

- **Anuştigin** temelini attı, **Alaaddin Tekiş** ve **Alaaddin Muhammed** döneminde Büyük Selçukluların mirasını aldı.
- **Cengiz Han'ın** elçilerinin Otrar'da öldürülmesi (1218) üzerine Moğol istilası başladı.
- **Celaleddin Mengüberti:** Moğollara karşı direndi, Anadolu Selçuklularıyla Yassıçemen (1230) mücadelesi. 1231'de öldü, devlet sona erdi.

## 6. Eyyubiler ve Memlükler

- **Eyyubiler (1171-1250):** **Selahaddin Eyyubi** kurdu. **1187 Hıttin Savaşı** ile Kudüs'ü Haçlılardan aldı.
- **Memlükler (1250-1517):** **Kölemen** Türk komutanlar tarafından kuruldu. **Ayn Calut Savaşı (1260)**'nda Moğolları durdurdu. **Baybars** önemli sultandır. Abbasi halifeliğini Kahire'de sürdürdü. **1517'de Osmanlı (Yavuz Selim, Ridaniye)** tarafından yıkıldı.

## 7. Sık yapılan hatalar

- Müslüman ilk Türk devletinin Gazneliler olduğunu sanmak. Karahanlılardır.
- Dandanakan ile Malazgirt'i karıştırmak. Dandanakan (1040) Gazneli, Malazgirt (1071) Bizans karşısındadır.
- Nizamülmülk'ü Gaznelilerin veziri sanmak. Selçuklu veziridir.
- Kutadgu Bilig'i Selçuklu dönemine koymak. Karahanlıdır.
- "Sultan" unvanının ilk kez Selçuklular tarafından kullanıldığını sanmak. Gazneli Mahmut kullandı.

