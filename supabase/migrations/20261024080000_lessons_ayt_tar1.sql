- **Saltanatın kaldırılması (1 Kasım 1922):** Osmanlı Devleti sona erdi.
- **Lozan Barış Antlaşması (24 Temmuz 1923):** Heyet başkanı **İsmet İnönü.** **Türkiye'nin bağımsızlığı** uluslararası alanda tanındı. **Kapitülasyonlar kaldırıldı.** Sınırlar (Doğu Trakya, Boğazlar) belirlendi. **Musul** ve **Hatay** sorunu sonraya bırakıldı (Musul 1926, Hatay 1939). Azınlıklar, nüfus mübadelesi. **Sevr geçersiz oldu.**
- **29 Ekim 1923: Cumhuriyet'in ilanı.** İlk cumhurbaşkanı Mustafa Kemal.

