## 1. İşgaller ve cemiyetler

- **Mondros sonrası işgaller:** İzmir (15 Mayıs 1919, Yunan), Antalya, Konya (İtalya), Güney Anadolu (Fransa ve İngiltere), İstanbul (13 Kasım 1918'de İtilaf donanması). **Pontus** ve **Ermeni** faaliyetleri.
- **Müdafaa-i Hukuk (Hukuku Savunma) cemiyetleri:** Yerel direniş örgütleri. **Redd-i İlhak**, **Trakya-Paşaeli**, **Kilikyalılar**, **Doğu Anadolu**, **İzmir** cemiyetleri.
- **Kuvayı Milliye:** Düzenli ordu kurulana kadar halkın kendiliğinden direniş birlikleri.
- **Wilson ilkeleri:** Ulusal self-determinasyon (kendi kaderini tayin hakkı) fikri direnişi destekledi.

## 2. Mustafa Kemal ve kongreler

- **19 Mayıs 1919: Samsun'a çıkış.** Mustafa Kemal Paşa **9. Ordu Müfettişi** olarak Samsun'a çıktı. Milli Mücadele'nin başlangıcı kabul edilir.
- **Havza Genelgesi (28 Mayıs):** Mitingler.
- **Amasya Genelgesi (22 Haziran 1919):** "Vatanın bütünlüğü, milletin istiklali tehlikededir. **Milletin istiklalini yine milletin azim ve kararı kurtaracaktır.**" İlk kez **ulusal bağımsızlık** ve **milli egemenlik** ilkesi. Sivas'ta kongre toplanması kararı.
- **Erzurum Kongresi (23 Temmuz-7 Ağustos 1919):** Doğu illeri adına. **Milli sınırlar** belirlendi. **Manda ve himaye reddedildi.** **Vatanın bütünlüğü** vurgulandı. **Temsil Heyeti** seçildi. Heyet-i Temsiliye (Mustafa Kemal başkan).
- **Sivas Kongresi (4-11 Eylül 1919):** Bütün yurdu temsil eden kongre. **Anadolu ve Rumeli Müdafaa-i Hukuk Cemiyeti** kuruldu (cemiyetler birleşti). **Manda ve himaye kesin olarak reddedildi.** **Heyet-i Temsiliye** tüm yurdu temsil eder hâle getirildi. **İradei Milliye** gazetesi.
- **Amasya Görüşmeleri (Ekim 1919):** İstanbul hükümeti ile Heyet-i Temsiliye ilk kez tanındı. **Son Osmanlı Mebusan Meclisi** seçimleri.
- **Misak-ı Milli (28 Ocak 1920):** Son Osmanlı Mebusan Meclisi'nde kabul edilen **milli sınırlar** kararı. **İstanbul'un işgali (16 Mart 1920):** Meclis dağıtıldı, mebuslar Malta'ya sürüldü.

## 3. TBMM'nin açılışı (23 Nisan 1920)

Ankara'da **Türkiye Büyük Millet Meclisi** açıldı. Başkan **Mustafa Kemal**. **Millî egemenlik** ilkesi, **meclis hükümeti sistemi.**

- **Teşkilat-ı Esasiye Kanunu (20 Ocak 1921):** İlk anayasa. "Egemenlik kayıtsız şartsız milletindir."
- **Şeyhülislam fetvası** ve **Hıyanet-i Vataniye Kanunu**. **Ayaklanmalar** (Düzce, Yozgat vb.) bastırıldı.
- **Düzenli ordu:** Kuvayı Milliye'den düzenli orduya geçiş.
- **Sevr Antlaşması (10 Ağustos 1920):** Osmanlı ile İtilaf. TBMM tanımadı. Milli Mücadele'yi güçlendirdi.

## 4. Cepheler

**Doğu Cephesi:** **Kazım Karabekir.** Ermenilere karşı. **Sarıkamış**, Kars. **Gümrü Antlaşması (3 Aralık 1920):** TBMM'nin imzaladığı **ilk uluslararası antlaşma.** **Moskova Antlaşması (Mart 1921):** SSCB ile.

**Güney Cephesi:** Fransızlara karşı **Maraş, Antep, Urfa** (Kahraman unvanları). **Ankara Antlaşması (Ekim 1921):** Fransa ile. Fransa Güney'den çekildi.

**Batı Cephesi:**

- **I. İnönü (Ocak 1921):** Düzenli ordunun ilk büyük başarısı. Komutan **İsmet Paşa.**
- **II. İnönü (Mart 1921):** Yunanlara karşı ikinci başarı. Zaferin ardından **Moskova Antlaşması** (16 Mart 1921) imzalandı ve TBMM'nin uluslararası itibarı arttı.
- **Kütahya-Eskişehir Muharebeleri (Temmuz 1921):** Yunan ilerleyişi, Türk ordusu Sakarya'ya çekildi.
- **Sakarya Meydan Muharebesi (23 Ağustos-13 Eylül 1921):** **Mustafa Kemal Başkomutan**. "**Hattı müdafaa yoktur, sathı müdafaa vardır.** O satıh bütün vatandır." **Savunmadan taarruza geçiş.** 22 gün 22 gece. **Mustafa Kemal'e Gazi ve Mareşal** unvanları verildi.
- **Büyük Taarruz (26 Ağustos 1922):** **Başkomutanlık Meydan Muharebesi (30 Ağustos)**, Dumlupınar. **9 Eylül 1922 İzmir'in kurtuluşu.** Yunan ordusu Anadolu'dan çıkarıldı.

## 5. Mudanya, Lozan ve Cumhuriyet

