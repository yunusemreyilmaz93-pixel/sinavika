## 1. Atatürk ilkeleri

- **Cumhuriyetçilik:** Egemenlik millete aittir. Halkın seçtiği temsilcilerle yönetim.
- **Milliyetçilik:** Ortak tarih, dil, kültür ve ülkü birliğine dayalı **Türk milleti**. Irkçılık değil, ulusal bağımsızlık ve birlik.
- **Halkçılık:** Kanun önünde eşitlik. Sınıf ve ayrıcalık yok.
- **Devletçilik:** Ekonomide **devletin planlayıcı ve yönlendirici** rolü. Özel girişim korunur, ama büyük sanayi devlet eliyle yapılır (1930'lar, dünya ekonomik bunalımı).
- **Laiklik:** Din ve devlet işlerinin ayrılması. Din vicdan özgürlüğüdür. Hukuk, eğitim ve yönetimde dinî kuralların etkisi sona erer.
- **İnkılapçılık:** Çağdaşlaşmayı sürekli kılmak. Yeniliklere açık olmak, **kazanımları korumak.**

## 2. Siyasi alanda inkılaplar

- **Saltanatın kaldırılması (1 Kasım 1922).**
- **Cumhuriyet'in ilanı (29 Ekim 1923).**
- **Halifeliğin kaldırılması (3 Mart 1924)** ve **Hanedanın yurt dışına çıkarılması.**
- **1924 Anayasası (20 Nisan 1924):** Tek meclisli parlamenter sistem.
- **Çok partili hayat denemeleri:** Terakkiperver Cumhuriyet Fırkası (1924, kapatıldı). **Serbest Cumhuriyet Fırkası (1930)** kısa sürede kapandı. **Şeyh Said İsyanı (1925)**, Takrir-i Sükun Kanunu. **Menemen Olayı (1930).**

## 3. Hukuk alanında inkılaplar

- **Medeni Kanun (17 Şubat 1926):** İsviçre'den uyarlandı. **Kadın-erkek eşitliği** (miras, evlilik, boşanma), **resmî nikâh**, **tek eşlilik**. Laik hukuk sisteminin temeli.
- Ceza Kanunu, Ticaret Kanunu, Borçlar Kanunu (İtalya, Almanya'dan uyarlama).
- **Mecelle**'nin kaldırılması. Şer'i mahkemelerin kapatılması (1924).

## 4. Eğitim ve kültür inkılapları

- **Tevhid-i Tedrisat Kanunu (3 Mart 1924):** Bütün eğitim kurumları **Milli Eğitim Bakanlığı**'na bağlandı. Medreseler kapandı. **Eğitimde birlik**.
- **Harf Devrimi (1 Kasım 1928):** **Latin harfleri** (Türk alfabesi) kabul edildi. **Millet Mektepleri** (halka okuma-yazma). Okuma-yazma yaygınlaştı.
- **Türk Tarih Kurumu (1931), Türk Dil Kurumu (1932)** kuruldu. **Güneş Dil Teorisi** ve **Türk Tarih Tezi.**
- **Üniversite Reformu (1933):** Darülfünun kapatıldı, **İstanbul Üniversitesi** açıldı. **Halkevleri (1932)**, **Köy Enstitüleri (1940).**
- **Sanat:** Güzel Sanatlar Akademisi, Devlet Konservatuvarı, Cumhuriyet'in resmî sanat politikası.

## 5. Toplumsal alanda inkılaplar

- **Şapka Kanunu (25 Kasım 1925)**, **tekke ve zaviyelerin kapatılması (30 Kasım 1925)**.
- **Takvim, saat ve ölçü birimleri:** Miladi takvim (1925-1926), uluslararası saat ve rakamlar (1928), metre-kilogram (1931).
- **Soyadı Kanunu (21 Haziran 1934).** "Atatürk" soyadı 1934'te TBMM tarafından verildi. **Lakap ve unvanların kaldırılması** (1934).
- **Kadın hakları:** **Medeni Kanun (1926)** eşitliği sağladı. **1930'da belediye seçimlerinde**, **1933'te muhtar seçimlerinde**, **5 Aralık 1934'te milletvekili seçme ve seçilme** hakkı tanındı (Fransa ve İtalya'dan önce).

## 6. Ekonomik alanda gelişmeler

- **İzmir İktisat Kongresi (1923):** Ekonomik bağımsızlığın temeli, **milli ekonomi** hedefi. Aşar vergisi 1925'te kaldırıldı. **Çiftçilere** destek.
- **İş Bankası (1924)**, **Sanayi ve Maadin Bankası.**
- **Teşvik-i Sanayi Kanunu (1927):** Özel girişimi destekler.
- **Devletçilik dönemi (1930'lar):** **Sümerbank (1933)**, **Etibank**, **I. Beş Yıllık Sanayi Planı (1934)**, **II. Beş Yıllık Plan (1936).** Dünya ekonomik bunalımına karşı devlet eliyle sanayileşme.
- **Tarım:** Ziraat Bankası, model çiftlikler (Atatürk Orman Çiftliği).

## 7. Atatürk dönemi dış politikası

- **Musul sorunu:** **1926 Ankara Antlaşması** ile Irak'a bırakıldı (İngiltere ile).
- **Milletler Cemiyeti'ne giriş (1932)**, **Balkan Antantı (1934)**, **Sadabat Paktı (1937).**
- **Montrö Boğazlar Sözleşmesi (1936):** Türkiye **Boğazlar'da egemenlik ve askerî güvenlik** kazandı. Lozan'dan sonraki önemli diplomatik başarı.
- **Hatay (1939):** Atatürk'ün ölümünden sonra, ama onun politikalarının sonucu olarak Hatay Türkiye'ye katıldı.
- **İlke:** "Yurtta sulh, cihanda sulh."

