## 1. Kuruluş dönemi (1299-1402)

**Osmanlı Beyliği**, Selçuklu ve Bizans arasındaki sınırda (**uç bölgesi**) kuruldu. Söğüt ve Domaniç yöresinde **Kayı boyu** Ertuğrul Gazi'nin liderliğinde. **Osman Bey** (1299 gelenekle) bağımsızlığını ilan etti. Başarı nedenleri: **Bizans'ın zayıflığı**, Selçuklu'nun Moğol baskısı altında çökmesi, **gaza ve cihat ruhu**, **Ahiler ve dervişlerin desteği**, Anadolu'dan gelen Türkmenlerin akını, **uç bölgesinde** hareketlilik.

- **Osman Bey:** **1302 Koyunhisar Savaşı** (Bizans'a karşı ilk büyük zafer), Eskişehir ve çevresi.
- **Orhan Bey (1324-1362):** **1326'da Bursa'yı** aldı ve başkent yaptı. **1331 İznik**, **1337 İzmit**. **İlk medrese** İznik'te açıldı. **İlk Osmanlı parası** bastırıldı. **Yaya ve müsellem** adlı ilk düzenli ordu kuruldu. **Karesi Beyliği (1345)** ele geçirildi ve Çanakkale Boğazı'na ulaşıldı. **1352'de Çimpe Kalesi** (Süleyman Paşa): **Rumeli'ye ilk geçiş.**
- **I. Murat (1362-1389):** **1361-62 Edirne**, **1365'te başkent** yapıldı. **Sırpsındığı Savaşı (1364)**, **Çirmen (1371)**. **Beylerbeyilik** (Lala Şahin Paşa), **devşirme** ve **yeniçeri ocağı** kuruldu. **Timar** sistemi geliştirildi. **1389 I. Kosova Savaşı**: Sırp ve müttefikleri yenildi, ama Murat şehit düştü.
- **Yıldırım Bayezid (1389-1402):** **Anadolu Türk birliğini** sağlamaya çalıştı. **1396 Niğbolu Savaşı:** Haçlı ordusu yenildi. **İstanbul kuşatması** (Anadolu Hisarı). **1402 Ankara Savaşı:** **Timur**'a yenildi. Bayezid esir düştü ve öldü.

## 2. Fetret Devri ve toparlanma (1402-1451)

**Ankara Savaşı'nın sonuçları:** Osmanlı **Fetret Devri**ne girdi (1402-1413): Bayezid'in oğulları (Süleyman, İsa, Musa, Mehmet) arasında **taht mücadelesi**. Anadolu beylikleri bağımsızlığını geri aldı. Bizans nefes aldı.

- **Çelebi Mehmet (1413-1421):** Kardeşlerini yenerek devleti yeniden birleştirdi. **II. Kuruluş** kabul edilir.
- **II. Murat (1421-1451):** **1444 Varna Savaşı**'nda Haçlı ordusunu yendi. **1448 II. Kosova Savaşı** ile Balkanlar'daki Osmanlı hâkimiyeti kesinleşti.

## 3. Yükselme dönemi (1451-1566)

**Fatih Sultan Mehmet (1451-1481):**

- **29 Mayıs 1453 İstanbul'un fethi:** **Orta Çağ kapandı, Yeni Çağ başladı.** Bizans yıkıldı. İstanbul başkent oldu. **Rumeli Hisarı**, **büyük toplar (Şahi)** ve gemilerin karadan yürütülmesi.
- **Fetihler:** Mora, Sırbistan, Bosna, Arnavutluk, **1461 Trabzon (Trabzon Rum İmparatorluğu)**, **Amasra**, **Kırım (1475)**, **Otlukbeli (1473):** Akkoyunlu Uzun Hasan yenildi, Doğu Anadolu güvence altına alındı.
- **Kanunname-i Âli Osman**, **Sahn-ı Seman Medreseleri**, **Ayasofya Camii**'ne çevrildi. **Kardeş katli** kanunlaşmıştır.

**II. Bayezid (1481-1512):** Dengeli politika. **Cem Sultan** meselesi, Memlüklerle savaş, **Endülüs Müslümanlarını** donanmayla kurtardı (Kemal Reis).

**Yavuz Sultan Selim (1512-1520):**

- **1514 Çaldıran Savaşı:** **Safevi Şah İsmail**'e karşı. Doğu Anadolu'nun alınması.
- **1516 Mercidabık** ve **1517 Ridaniye Savaşları:** **Memlük Devleti** yıkıldı. **Mısır, Suriye, Filistin, Hicaz** Osmanlı'ya geçti. **Halifelik** Osmanlı'ya geçti ve **Kutsal Emanetler** İstanbul'a getirildi. Osmanlı **İslam dünyasının lideri** oldu.

**Kanuni Sultan Süleyman (1520-1566):**

- **1521 Belgrad**, **1522 Rodos**, **1526 Mohaç Meydan Muharebesi** (Macar Kralı II. Lajos yenildi, Macaristan Osmanlı etkisine girdi), **1529 I. Viyana Kuşatması** (başarısız), **1538 Preveze Deniz Savaşı:** **Barbaros Hayrettin Paşa**, Haçlı donanmasını yendi. **Akdeniz'de Osmanlı üstünlüğü.**
- **Kanuni** döneminde hukuk ve teşkilat düzenlemeleri, **Mimar Sinan**, **Baki**. Osmanlı üç kıtaya yayıldı.
- **Kanuni sonrası:** **II. Selim (1566-1574):** **1570 Kıbrıs'ın fethi**, **1571 İnebahtı** (donanma yenildi ama kısa sürede yenilendi, Sokollu Mehmet Paşa'nın tedbiriyle). **Don-Volga kanalı** projesi (1569) başarısız oldu.

