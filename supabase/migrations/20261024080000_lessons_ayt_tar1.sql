Atatürk ilke ve inkılapları, **Milli Mücadele'nin** devamıdır. **Tarih-2'deki İki Savaş Arasındaki Dönem** ve **II. Dünya Savaşı** konuları dış politikayı tamamlar. **Edebiyat** dersinde Cumhuriyet dönemi edebiyatı bu inkılapların çevresinde gelişir. **Felsefe** dersinde Aydınlanma ve laiklik, **Din Kültürü**'nde din-devlet ilişkisi bu ilkelerle bağlanır.
:::

