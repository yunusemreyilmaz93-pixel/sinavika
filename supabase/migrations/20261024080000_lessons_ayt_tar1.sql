## 1. İslamiyet'ten önce Arabistan

Arap Yarımadası'nda yarı göçebe kabileler (bedeviler) ve ticaret şehirleri (Mekke, Taif, Yesrib) vardı. Kabile bağları (asabiyet) güçlüydü. **Mekke**, Kâbe ve ticaret yolları üzerinde önemli bir merkezdi. **Cahiliye** (bilgisizlik) dönemi olarak adlandırılan bu dönemde putperestlik yaygındı, ama Hanif gibi tek Tanrı'ya inananlar da vardı. Bazı bölgelerde Yahudilik ve Hristiyanlık da yaşıyordu.

## 2. Hz. Muhammed dönemi

**Mekke dönemi (610-622):**

- **570**'te Mekke'de doğdu. **610**'da Hira Mağarası'nda ilk vahiy geldi.
- İlk üç yıl **gizli**, sonra **açık** davet. Mekkeli müşriklerin baskısı arttı.
- **Habeşistan'a hicretler.** **Akabe biatları** (621-622), Medine'ye hicretin zemini.

**Medine dönemi (622-632):**

- **622 Hicret:** Mekke'den Medine'ye göç. **Hicri takvimin başlangıcı.** Medine'de İslam devleti kuruldu.
- **Mescid-i Nebevi**, **muahat** (Muhacir-Ensar kardeşliği) ve **Medine Vesikası**. Medine Vesikası, farklı din ve kabileleri bir arada yaşatan **ilk yazılı anayasa** kabul edilir.
- **Savaşlar:** **Bedir** (624, Müslümanlar kazandı), **Uhud** (625), **Hendek** (627, savunma savaşı).
- **628 Hudeybiye Barışı:** Mekke ile on yıllık barış. Müslümanların varlığı tanındı.
- **630 Mekke'nin fethi:** Savaşsız fethedildi, Kâbe putlardan temizlendi. **Veda Hutbesi (632):** İnsan hakları, eşitlik, kan davasının kaldırılması. **632'de vefat.**

## 3. Dört Halife dönemi (632-661)

Halife, "vekil" demektir ve seçimle belirlenir (ilk dört halife için danışma esastır).

| Halife | Dönem | Önemli gelişmeler |
| --- | --- | --- |
| **Hz. Ebubekir** | 632-634 | Ridde savaşları (dinden dönenler), Kur'an'ın bir araya toplanması |
| **Hz. Ömer** | 634-644 | Fetihler hızlandı (Yermuk, Kadisiye, Kudüs 638, Mısır), divan teşkilatı, Hicri takvimin kabulü |
| **Hz. Osman** | 644-656 | Kur'an'ın çoğaltılıp merkezlere gönderilmesi, ilk İslam donanması (Kıbrıs) |
| **Hz. Ali** | 656-661 | Cemel (656) ve Sıffin (657) savaşları, Hariciler, devlet merkezi Kufe |

Bu dönemde İslam devleti Suriye, Irak, İran ve Mısır'ı kapsayacak şekilde yayıldı.

## 4. Emeviler (661-750)

- **Kurucu:** Muaviye. **Başkent: Şam.** **Halifelik babadan oğula geçti** (saltanata dönüştü).
- **Arap milliyetçiliği:** Arap olmayan (mevali) Müslümanlar ikinci sınıf sayıldı. Bu yönetime karşı hoşnutsuzluk yarattı.
- **Abdülmelik:** **Arapçayı resmî dil** yaptı, ilk İslam parasını bastırdı. **Kubbetüs-Sahra** (Kudüs) yapıldı.
- **Kerbela (680):** Hz. Hüseyin'in şehit edilmesi, Şiilik'in doğuşunda etkili.
- **Fetihler:** Kuzey Afrika, **Endülüs (711, Tarık bin Ziyad)**, Orta Asya (Türklerle temas). **732 Tours-Poitiers Savaşı**'nda Franklara karşı durdu.
- **Çöküş:** Arap olmayanlara yönelik politikalar ve iç isyanlar. **750'de Abbasilerle yıkıldı.**

## 5. Abbasiler (750-1258)

- **Kurucu:** **Ebu'l Abbas Abdullah (Seffah).** 750'de Zap Suyu Savaşı'yla Emevileri yıktı. **Ebu Müslim Horasani** ve Horasan Türklerinin desteği önemlidir.
- **Başkent Bağdat** (762, Mansur). **Arap olmayan** Müslümanlara eşit yaklaşıldı (Fars ve Türk etkisi).
- **751 Talas Savaşı:** Abbasiler ve Karluk Türkleri, Çin'i yendi. **Sonuçları:** Orta Asya'da Çin etkisi sona erdi, Türklerin İslamiyet'e yaklaşması hızlandı, kâğıt yapımı Müslümanlar eliyle Batı'ya yayıldı.
- **Harun Reşid** ve **Me'mun** dönemleri en parlak dönemlerdir. **Beyt'ül-Hikme** (Bilgelik Evi) ve çeviri hareketi.
- **Türklerin rolü:** Halifeler Türk askerlerden muhafız birlikleri kurdu. Sonradan Türk komutanlar yönetimde etkili oldu (Tolunoğulları, İhşidiler).
- **Çöküş:** Merkezî otoritenin zayıflaması, bağımsız emirlikler. **1258'de Hülagü** Bağdat'ı yıktı.

## 6. İslam medeniyeti ve bilim

- **Harezmi:** Cebir, algoritma. **İbn-i Sina:** Tıp (El-Kanun fi't-Tıb), felsefe. **Farabi:** Felsefe, "İkinci Muallim". **Biruni:** Astronomi, coğrafya, matematik. **İbn-i Heysem:** Optik. **Cabir bin Hayyan:** Kimya. **Zehravi:** Cerrahi. **Ömer Hayyam:** Matematik, astronomi, takvim.
- **Mimari:** Camiler, medreseler (Nizamiye), hastaneler (bimarhane), kervansaraylar. Kubbetüs-Sahra, Kurtuba Camii.
- **Kurumlar:** Medrese, rasathane, kütüphane, vakıf.
- **Etkisi:** İslam medeniyeti bilgiyi Avrupa'ya aktardı ve Rönesans'ın zeminini hazırladı.

