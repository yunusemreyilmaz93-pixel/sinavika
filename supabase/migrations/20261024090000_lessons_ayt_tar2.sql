## 1. Kapitalizm, liberalizm, sosyalizm

- **Kapitalizm:** Özel mülkiyet, serbest piyasa ve kâr amacına dayanan ekonomi sistemi. **Sermaye sahibi (burjuva)** ile **işçi (proletarya)** arasında ilişki.
- **Liberalizm:** Bireysel özgürlük, serbest ticaret, devletin ekonomiye sınırlı müdahalesi. **Adam Smith** (Ulusların Zenginliği, "görünmez el").
- **Sosyalizm:** Eşitlik ve ortak mülkiyet. **Karl Marx ve Friedrich Engels, Komünist Manifesto (1848).** İşçi sınıfının sömürüsüne tepki. **Sendika** ve **işçi partileri.**
- **Emperyalizm:** Sanayileşmiş devletlerin hammadde ve pazar için sömürge edinme politikası.

## 2. İşçi hareketleri

Sanayi Devrimi'nden sonra fabrikalarda işçiler uzun çalışma saatleri (12-16 saat), düşük ücret, çocuk ve kadın işçiliği, kötü yaşam koşulları yaşadı.

- **Makine kırıcılığı (Luddizm).** Daha sonra **sendikalar** ve grevler.
- **1886 Chicago:** 8 saatlik iş günü grevi. **1 Mayıs** İşçi Bayramı olarak anıldı.
- **Sonuçları:** İş yasaları, sendika hakkı, sosyal güvenlik, **sosyal devlet** anlayışı. **1864 Birinci Enternasyonal.**
- **Osmanlı'da:** **1909 Tatil-i Eşgal Kanunu:** Grev yasağı. **İşçi sınıfı** küçük ama oluşuyordu (Selanik, İstanbul, Zonguldak).

## 3. Osmanlı ekonomisi ve kapitülasyonlar

**Kapitülasyonlar:** Osmanlı'nın bazı devletlerin tüccarlarına tanıdığı ticari ayrıcalıklar. **1535 Fransa**. Başlangıçta ayrıcalık ve iyi niyet, sonra **hukuki ve ekonomik bağımlılığa** dönüştü. **Konsolosluk mahkemeleri**, düşük gümrük.

- **1838 Balta Limanı Ticaret Antlaşması (İngiltere):** **Yed-i vahid** (tekel) sistemi kaldırıldı, yabancı tüccara **serbest ticaret.** İç ticarette yabancı tüccarın **ayrıcalıkları arttı**. **Gümrük vergisi çok düşük** (%3). **Yerli üretim zayıfladı**, Osmanlı Avrupa için **hammadde sağlayıcısı** ve **mamul madde pazarı** oldu. Diğer devletlerle de benzer antlaşmalar yapıldı.
- Osmanlı'nın **sanayi** ve **zanaat** üretimi (dokuma) çöktü.

## 4. Dış borçlar ve mali bağımsızlık

- **1854:** Kırım Savaşı sırasında **ilk dış borç.** Fransa ve İngiltere'den.
- **1860-1875:** Borç sarmalı. Savaş ve saray masrafları, borçların borçla ödenmesi.
- **1875 Ramazan Kararnamesi:** Osmanlı **iflas** etti (borçların faizinin yarısı). 
- **1881 Muharrem Kararnamesi: Düyun-ı Umumiye İdaresi.** Osmanlı'nın dış borçlarının **tahsili** için yabancı alacaklıların yönettiği kurum. **Tuz, tütün, damga** gelirlerine el kondu. **Mali bağımsızlık fiilen kaybedildi.**
- **Osmanlı Bankası (1856):** Başlangıçta İngiliz-Fransız sermayesi. Merkez bankası işlevi, **ilk kâğıt para (Kaime, 1840).**
- **Yabancı sermaye yatırımları:** **Demiryolları** (İzmir-Aydın İngiliz, **Bağdat Demiryolu** Alman, 1903), liman, tramvay, elektrik, tütün (Reji). **Hammadde** ihracatı ve limanlara bağlanma.
- **Tarım:** Pamuk, tütün, kuru yemiş ihracatı. **Çiftlik** sistemi.

## 5. Osmanlı'da sanayi ve ticaret

- **Sanayi:** **Hereke Fabrikası**, **Feshane (fes)**, **Bakırköy Bez Fabrikası**, **Zeytinburnu Demir**. Devlet eliyle sanayileşme çabaları, ancak sınırlı.
- **Ticaret:** **Gayrimüslim tüccar** (Rum, Ermeni, Yahudi) aracılık rolü. Müslüman tüccar azdı. **Millî iktisat** fikri (II. Meşrutiyet sonrası: **Ziya Gökalp, Millî İktisat**).
