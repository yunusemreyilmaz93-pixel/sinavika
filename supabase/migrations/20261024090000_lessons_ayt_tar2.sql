## 1. Rönesans ve Reform

**Rönesans (14.-16. yüzyıl, İtalya):** "Yeniden doğuş". Antik Yunan-Roma kültürüne dönüş. **Hümanizm** (insan merkezli düşünce), akıl ve bilim. **Sanat:** Leonardo da Vinci, Michelangelo, Raffaello. **Edebiyat:** Dante, Petrarca. **Neden İtalya?** Zengin ticaret şehirleri (Venedik, Floransa), Bizans âlimlerinin gelişi (1453), **matbaa** (Gutenberg, 1450 civarı).

**Reform (16. yüzyıl):** Katolik Kilisesi'ne tepki. **Martin Luther (1517)** 95 tez. **Protestanlık** doğdu. **Kalvin** (İsviçre). Katolik Kilisesi'nin mutlak otoritesi sarsıldı, **Karşı Reform**. **Augsburg Barışı (1555):** Prenslerin dinini seçme hakkı. Ulusal diller ve dinî metinlerin yerel dillere çevrilmesi.

## 2. Coğrafi Keşifler (15.-16. yüzyıl)

**Nedenler:**

- **Osmanlı'nın** doğu ticaret yollarını (Baharat ve İpek Yolu) kontrol etmesi ve yüksek vergiler.
- **Pusula, usturlap, kadırga yerine karaka ve kervel** gibi gemi ve **harita** teknolojisi.
- **Merkantilizm** (altın ve gümüşün zenginlik sayılması), yeni pazar ve hammadde arayışı.
- Rönesans'ın merak ve bilimi, **Hristiyanlığı yayma** isteği.

**Önemli keşifler:**

- **Bartolomeo Diaz (1488):** Ümit Burnu. **Vasco da Gama (1498):** Hindistan'a deniz yolu. **Kristof Kolomb (1492):** Amerika. **Magellan (1519-1522):** Dünya turu, Dünya'nın yuvarlaklığı kanıtlandı.

**Sonuçları:** Ticaret merkezi **Akdeniz'den Atlantik'e** kaydı. **Sömürgecilik** başladı. **Altın ve gümüş** akışı, **fiyat devrimi**. **Burjuvazinin** gücü arttı. Osmanlı ve İtalyan şehirleri zayıfladı. Avrupa zenginleşti.

## 3. Bilimsel Devrim ve Aydınlanma

- **Bilimsel Devrim:** **Kopernik** (Güneş merkezli sistem), **Galile** (teleskop), **Kepler**, **Newton** (evrensel çekim, 17. yüzyıl). Gözlem ve deneye dayalı bilim.
- **Aydınlanma Çağı (18. yüzyıl):** Aklın ve bilimin egemenliği. **Locke** (doğal haklar), **Montesquieu** (**kuvvetler ayrılığı**, Kanunların Ruhu), **Rousseau** (**toplum sözleşmesi**, halk egemenliği), **Voltaire** (düşünce ve din özgürlüğü). **Ansiklopedi** (Diderot).

## 4. Fransız İhtilali (1789)

- **Nedenler:** Mutlak monarşi, sınıfsal eşitsizlik (soylular, din adamları ayrıcalıklı, burjuva ve köylü yük altında), mali kriz, Aydınlanma fikirleri.
- **1789:** Bastille baskını. **İnsan ve Yurttaş Hakları Bildirisi.** "**Özgürlük, eşitlik, kardeşlik.**"
- **Sonuçları:** **Milliyetçilik** ve **ulus devlet** fikri yayıldı. **Halk egemenliği**, hukuk eşitliği, anayasal rejim. Çok uluslu imparatorluklarda (Osmanlı, Avusturya, Rusya) **azınlık isyanlarını** tetikledi (Sırp, Yunan). **Napolyon** savaşları Avrupa'yı karıştırdı.

## 5. Sanayi Devrimi (18. yüzyıl sonu, İngiltere)

- **Nedenler:** Sömürgelerden gelen hammadde ve sermaye, zengin kömür ve demir, **bilimsel buluşlar**, tarım devrimi (nüfus artışı, iş gücü), siyasi istikrar.
- **Buluşlar:** **James Watt (buhar makinesi)**, dokuma tezgâhları, **demiryolu, buharlı gemi**.
- **Sonuçları:** **Fabrikalar ve şehirleşme**, **işçi sınıfı** (proletarya), **kapitalizm ve burjuvazi**. **Sömürgecilik ve emperyalizm** (hammadde ve pazar). **Sosyalizm** ve **işçi hareketleri**. Çevre kirliliği.

## 6. Osmanlı ve değişim

- **Tepki:** Osmanlı Avrupa'yı başlangıçta "geri" olarak gördü. **Ordu ve askerî teknoloji** alanında yenilgilerle ıslahatlar başladı.
- **III. Selim (1789-1807):** **Nizam-ı Cedid** (yeni düzen), Avrupa tarzı ordu, **ilk daimi elçilikler** (Londra, Paris, Berlin, Viyana). Yeniçeri ve ulema tepkisi ile **Kabakçı Mustafa İsyanı (1807)** ile tahttan indirildi.
- **Fransız İhtilali'nin etkisi:** Milliyetçilik fikri Balkanlar'a ulaştı. Sırp (1804) ve Yunan (1821) isyanları.
- **Napolyon'un Mısır seferi (1798):** Avrupa devleti doğrudan Osmanlı toprağına girdi.

## 7. Sık yapılan hatalar

- Coğrafi Keşifleri yalnızca merak sonucu sanmak. Osmanlı hâkimiyeti ve ticaret yolları da nedendir.
- Reform'u Rönesans ile karıştırmak. Reform dinîdir.
- Montesquieu'yu toplum sözleşmesi ile, Rousseau'yu kuvvetler ayrılığı ile eşleştirmek.
- Sanayi Devrimi'ni Fransa'da başlamış sanmak. İngiltere'de başladı.
- Fransız İhtilali'nin etkisini yalnızca Fransa'ya özgü sanmak. Milliyetçilik akımını yaydı.

