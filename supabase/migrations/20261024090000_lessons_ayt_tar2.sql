## 1. Yumuşama (Détente) nedenleri

- **Nükleer tehlike:** Küba Krizi'nde nükleer savaşın eşiği. İki tarafın **karşılıklı caydırıcılığı.**
- **Ekonomik yük:** Silahlanma yarışının maliyeti.
- **Çin-SSCB ayrılığı:** Komünist dünyada çatlak. ABD Çin'e yaklaştı (Nixon'un 1972 Pekin ziyareti).
- **Avrupa'da gerilimin azalması.**
- **Vietnam'da ABD'nin zorlanması.**

## 2. Yumuşama uygulamaları

- **Sıcak Hat (1963):** ABD ve SSCB liderleri arasında doğrudan iletişim hattı.
- **Kısmi Nükleer Deneme Yasağı Anlaşması (1963)**, **Nükleer Silahların Yayılmasını Önleme Anlaşması (1968).**
- **SALT I (1972)** ve **SALT II (1979):** Stratejik silahların sınırlandırılması görüşmeleri.
- **Batı Almanya'nın Doğu Politikası** (Willy Brandt): Doğu Bloğu ile ilişkileri düzeltme. 1972 İki Almanya Temel Antlaşması.
- **Helsinki Nihai Senedi (1975):** Avrupa Güvenlik ve İş Birliği Konferansı. **35 devlet.** Sınırların dokunulmazlığı, insan hakları, iş birliği. **AGİT'in temeli.**

## 3. Yeni gerginlik (1979-1985)

- **1979 Sovyetler'in Afganistan'ı işgali.** ABD tepkisi: 1980 Moskova Olimpiyatları boykotu.
- **Reagan'ın sert politikası** ("Kötülük İmparatorluğu", Yıldız Savaşları projesi). **Silahlanma yarışı** yeniden hızlandı.
- **Polonya'da Dayanışma (Solidarność)** hareketi (1980).
- **İran Devrimi (1979)** ve Orta Doğu'da değişen dengeler.

## 4. Gorbaçov dönemi ve Soğuk Savaş'ın sonu

- **Mihail Gorbaçov (1985):** SSCB lideri. **Glasnost (açıklık)** ve **Perestroyka (yeniden yapılanma).** Siyasi ve ekonomik reform.
- **Reagan-Gorbaçov zirveleri:** **INF Anlaşması (1987):** Orta menzilli füzelerin imhası.
- **Afganistan'dan çekilme (1989).**
- **1989 Doğu Avrupa devrimleri:** Polonya, Macaristan, Çekoslovakya, Romanya, Bulgaristan'da komünist yönetimler çöktü.
- **9 Kasım 1989: Berlin Duvarı yıkıldı.** **3 Ekim 1990: Almanya birleşti.**
- **Varşova Paktı** 1991'de dağıldı.

## 5. SSCB'nin dağılması (1991)

- **Nedenler:** Ekonomik durgunluk, silahlanma maliyeti, Afganistan, milliyetçi hareketler (Baltık cumhuriyetleri), reformların kontrol dışına çıkması. **Ağustos 1991 darbe girişimi.**
- **25 Aralık 1991:** Gorbaçov istifa etti. **SSCB dağıldı.** **BDT** (Bağımsız Devletler Topluluğu) kuruldu.
- **Sonuçları:** **Soğuk Savaş sona erdi, iki kutuplu düzen çöktü.** ABD tek süper güç. **Orta Asya ve Kafkas Türk cumhuriyetleri** (Azerbaycan, Kazakistan, Özbekistan, Türkmenistan, Kırgızistan) bağımsızlığını kazandı. **Yugoslavya** parçalandı (Bosna, Kosova savaşları).
- **Türkiye için etkileri:** **Türk dünyasıyla yeni ilişkiler**, Karadeniz Ekonomik İş Birliği (1992), **Jeopolitik önem artışı.** Orta Doğu ve Balkan sorunları. Güvenlik tehdidi (SSCB) azaldı.

## 6. Türkiye ve Yumuşama

- **Johnson Mektubu (1964)** sonrası ABD'ye güven azaldı. **Çok yönlü dış politika:** SSCB, Orta Doğu ve Afrika ile ilişkiler.
- **1974 Kıbrıs Barış Harekâtı.** **ABD silah ambargosu (1975-78).**
- **1980 askerî müdahale.**
- **Özal dönemi:** Liberal ekonomi, ABD ve Batı'ya yakınlık. **Körfez Savaşı (1991).**
- **1987 AB'ye tam üyelik başvurusu.**

## 7. Sık yapılan hatalar

- Yumuşama dönemini Soğuk Savaş'ın bitişi sanmak. 1985 sonrası bitiş.
- Berlin Duvarı'nın 1961'de yıkıldığını sanmak. 1961'de yapıldı, 1989'da yıkıldı.
- Glasnost ile perestroykayı karıştırmak. Glasnost açıklık, perestroyka yeniden yapılanma.
- SSCB'nin 1989'da dağıldığını sanmak. 1991'de.
- Helsinki Nihai Senedi'ni Yalta ile karıştırmak.

