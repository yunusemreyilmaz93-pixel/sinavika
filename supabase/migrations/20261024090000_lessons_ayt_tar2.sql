## 1. Devlet anlayışı

- **Kut:** Hakanın yönetme yetkisinin **Gök Tanrı tarafından verildiği** inancıdır. Hakan Tanrı adına yönetir ama "kutsal" sayılsa da halka karşı sorumludur.
- **Töre:** Yazısız **hukuk ve gelenek kuralları.** Hakan dahil herkes için bağlayıcıdır. Devletin düzenini sağlar.
- **Kurultay (Toy):** Hakan, hanedan üyeleri, bey ve komutanların toplandığı **danışma meclisi.** Savaş ve barış, hakan seçimi, ülkenin yönetimi gibi konular görüşülür.
- **İl / el:** Devlet. **Hakan (kağan):** Hükümdar. **Hatun:** Hükümdarın eşi.
- **Hakanın görevleri:** Ülkenin güvenliği, halkın refahı ve töreye uyum.

## 2. Yönetim şekli

- **İkili teşkilat:** Ülke **doğu ve batı** olmak üzere iki kola ayrılır. Doğuyu hakan, batıyı ona bağlı yabgu yönetir. Hunlarda sol (doğu) kol ve sağ (batı) kol vardı.
- **Ülüş (pay) sistemi:** Devletin hanedan üyeleri arasında paylaşılması anlayışıdır. Bu, **egemenliğin ailenin ortak malı sayılmasından** doğar. Taht kavgalarına ve devletin parçalanmasına yol açtı.
- **Yargu:** Mahkeme ve yargılama. **Tuğ:** Egemenlik sembolü (sancak).
- **Başkent anlayışı:** Hakanın yaşadığı yer (ordu-balık). Göçebe hayatın etkisi.

## 3. Toplum yapısı

Toplum **aile (oba)**, **boy** ve **budun** (halk) kademelerinden oluşur. Topluluğun tamamı **il** (devlet) çatısı altında toplanır. Toplum içinde **bey (aristokrat)** ve **halk** ayrımı vardı. Ancak sınıf ayrımı keskin değildi.

- **Boy:** Soy bağıyla birleşmiş topluluk.
- **Budun:** Halk.
- **Bey:** Üst yönetici, komutan.

## 4. Ordu

Ordu **hakanın başında olduğu**, tüm erkeklerin asker olduğu bir yapıdır. **Onlu sistem:** Ordu onluk, yüzlük, binlik, onbinlik birimlere ayrılırdı. **Okçuluk ve atlı birlikler** ön plandaydı. Ordu-millet anlayışı vardı. Savaş, sürekli bir yaşam biçimiydi.

## 5. Ekonomi

- **Hayvancılık** (at, koyun, sığır) temel geçim kaynağıdır. **Göçebe** ve **yarı göçebe** yaşam.
- **Tarım** sınırlı, daha çok Orta Asya'nın uygun bölgelerinde.
- **Ticaret:** İpek Yolu üzerindeki konum, Çin ve Bizans ile ticaret ve vergi geliri.
- **Çin'den alınan ipek** için at satımı gibi ilişkiler.

## 6. Kadının konumu

Türk toplumunda **kadın erkekle birlikte toplumsal hayatın içindeydi.** Hatun, hakanla birlikte **devlet işlerinde söz sahibiydi**, elçileri kabul eder, kurultaya katılırdı. Kadın savaşlara da katılabilir, mal sahibi olabilirdi. Bu durum, Türk toplumunda **eşitlikçi** bir anlayışın göstergesidir. Hakanın eşi için "hatun", hanedan kadınları için "han kızı" gibi unvanlar kullanılırdı.

## 7. Kaynaklar

- **Orhun Yazıtları (Göktürk, 8. yüzyıl):** Kül Tigin, Bilge Kağan ve Tonyukuk anıtları. Türkçe'nin bilinen en eski yazılı belgeleridir. Devlet anlayışı, töre ve toplum hakkında bilgi verir.
- Çin kaynakları.
- Sonraki dönemde **Kutadgu Bilig** (Karahanlılar) ve **Divanü Lügati't-Türk**.

## 8. Sık yapılan hatalar

- Kut'u töre ile karıştırmak. Kut yetkinin kaynağı, töre hukuk kurallarıdır.
- Ülüş sistemini ikili teşkilat sanmak. İkili teşkilat bölgesel, ülüş mülkiyet anlayışıdır.
- Kurultayı hakanın tek karar organı sanmak. Kurultay danışma meclisidir.
- Türk kadınını yönetimin dışında sanmak.
- Orhun Yazıtları'nı Karahanlı eseri sanmak. Göktürk dönemine aittir.

