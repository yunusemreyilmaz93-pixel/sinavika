## 1. Nedenler

- **Versay Antlaşması'nın ağır şartları** Almanya'da intikam duygusu.
- **Büyük Buhran** ve ekonomik kriz. **Totaliter rejimlerin yükselişi** (Nazizm, Faşizm). **Hitler'in** yayılmacı politikası ("yaşam alanı").
- **Milletler Cemiyeti'nin** etkisizliği.
- **İngiltere ve Fransa'nın yatıştırma politikası** (Münih, 1938).
- **Japonya'nın** Asya'da yayılması.

## 2. Taraflar

- **Mihver Devletleri (Eksen):** **Almanya, İtalya, Japonya** (ve Macaristan, Romanya, Bulgaristan).
- **Müttefik Devletler:** **İngiltere, Fransa, SSCB** (1941'den), **ABD** (1941'den), Çin.

## 3. Savaşın gelişimi

**1939-1941 (Mihver üstünlüğü):**

- **1 Eylül 1939:** Almanya Polonya'ya saldırdı. **II. Dünya Savaşı başladı.** İngiltere ve Fransa savaş ilan etti. SSCB Polonya'yı Almanya ile paylaştı (Molotov-Ribbentrop Paktı).
- **1940:** Almanya Danimarka, Norveç, Hollanda, Belçika, **Fransa'yı** işgal etti (Paris'e girdi). **İngiltere Savaşı:** Alman hava saldırıları başarısız oldu. İtalya Mihver yanında savaşa girdi.
- **22 Haziran 1941:** Almanya SSCB'ye saldırdı (Barbarossa).

**1941-1943 (Dönüm noktası):**

- **7 Aralık 1941: Japonya Pearl Harbor'a saldırdı.** ABD savaşa girdi. Savaş gerçek anlamda **dünya savaşı** oldu.
- **Stalingrad (1942-43):** Sovyetlerin zaferi. Almanya'nın **Doğu Cephesi'nde gerilemeye** başladığı **dönüm noktası.**
- **El Alamein (1942):** İngiliz zaferi (Kuzey Afrika).

**1944-1945 (Müttefik zaferi):**

- **6 Haziran 1944: Normandiya Çıkarması.** Batıda ikinci cephe açıldı.
- **8 Mayıs 1945:** Almanya teslim oldu (Hitler intihar etti).
- **Yalta (Şubat 1945)** ve **Potsdam (Temmuz 1945)** Konferansları: Almanya'nın bölünmesi, savaş sonrası düzen.
- **6 Ağustos 1945 Hiroşima, 9 Ağustos Nagasaki:** ABD atom bombası attı. **2 Eylül 1945:** Japonya teslim oldu. Savaş sona erdi.

## 4. Sonuçlar

- **Milyonlarca ölü** (yaklaşık 60-70 milyon). **Holokost:** Naziler 6 milyon Yahudi'yi soykırımla öldürdü. **Nürnberg Mahkemeleri** (savaş suçluları).
- **Birleşmiş Milletler (24 Ekim 1945):** Milletler Cemiyeti'nin yerine kuruldu. **Güvenlik Konseyi (5 daimi üye: ABD, SSCB, İngiltere, Fransa, Çin).**
- **Avrupa'nın gücünü yitirmesi.** ABD ve SSCB **iki süper güç.** **Soğuk Savaş**, **sömürgelerin bağımsızlığı.**
- **İsrail'in kuruluşu (1948).**
- **Almanya'nın bölünmesi.**
- **Marshall Planı, NATO, Varşova Paktı** gibi yeni yapılar.

## 5. Türkiye ve II. Dünya Savaşı

- **Dış politika:** **Aktif tarafsızlık.** Lozan ve Montrö sonrası barış politikası. **Balkan Antantı** (1934), **Sadabat Paktı** (1937).
- **1939:** İngiltere ve Fransa ile **Üçlü İttifak (Ankara Antlaşması).** Ancak Fransa'nın düşmesiyle (1940) etkisiz kaldı.
- **1941:** Almanya ile **Türk-Alman Dostluk ve Saldırmazlık Antlaşması.**
- **Savaşa girmeme:** Savunma gücünün yetersizliği, her iki bloğun baskısı.
- **1942 Varlık Vergisi:** Savaş ekonomisinde gayrimüslim ve zenginlere ağır vergi (sonra kaldırıldı).
- **1943 Adana Görüşmeleri (Churchill-İnönü), Kahire Konferansı (Aralık 1943).**
- **Şubat 1945:** Türkiye **Almanya ve Japonya'ya savaş ilan etti.** Amaç: **Birleşmiş Milletler'e kurucu üye** olmak (Mart 1945 şartı).
- **Sonrası:** SSCB'nin Montrö'nün değiştirilmesi ve Doğu Anadolu'da toprak talepleri, Türkiye'nin **Batı bloğuna** yönelmesine neden oldu.

## 6. Sık yapılan hatalar

- Savaşın Pearl Harbor ile başladığını sanmak. 1 Eylül 1939 Polonya.
- Stalingrad'ı Normandiya ile karıştırmak. Stalingrad Doğu Cephesi dönüm noktası, Normandiya Batı'da ikinci cephe.
- Türkiye'nin Almanya yanında savaştığını sanmak. Tarafsızdı.
- İkinci Dünya Savaşı'nı Almanya'nın teslimiyle bitmiş sanmak. Japonya Eylül 1945'te teslim oldu.
- Milletler Cemiyeti ile BM'yi karıştırmak.

:::baglanti
Bu konu, **XX. Yüzyıl Başlarında Dünya** konusunun doğrudan sonucudur ve **Soğuk Savaş Dönemi**'nin başlangıcıdır. **Atatürk İlke ve İnkılapları** (Tarih-1) konusundaki Montrö ve Türkiye'nin tarafsızlık politikası burada devam eder. **Felsefe** dersindeki 20. yüzyıl felsefesi (varoluşçuluk) ve **Edebiyat** dersindeki absürt ve varoluşçu eserler savaşın etkisini taşır. **Coğrafya** dersinde sınırlar ve jeopolitik değişimler bu savaşla şekillenir.
