## 1. Emperyalizm ve ittifaklar

**Sanayi Devrimi** sonrası Avrupa devletleri **hammadde, pazar ve yatırım alanı** için sömürge edinme yarışına girdi (**emperyalizm**). Afrika ve Asya paylaşıldı. **Berlin Konferansı (1884-85):** Afrika'nın paylaşımı. **Silahlanma yarışı**, **milliyetçilik** ve **Balkanlar sorunu** gerginlik yarattı.

