## 1. Duraklama Dönemi (1595-1699)

**Neden duraklama?** Fetihlerle gelen gelirler durdu, **sınırlar genişlemesini sürdüremedi**. Ordu, timar ve maliye bozuldu. Avrupa'nın **coğrafi keşiflerle** zenginleşmesi, **Atlantik ticareti** Osmanlı'nın ticaret yollarını önemsizleştirdi. **Altın ve gümüş** akımı ve **fiyat devrimi**. Nüfus artışı, **Celali isyanları**. Saray ve **harem etkisi** (kadınlar saltanatı), **kardeş katli** yerine **kafes sistemi** nedeniyle padişahlar tecrübesiz kaldı.

- **Haçova Savaşı (1596):** III. Mehmet'in komutasında Avusturya'ya karşı.
- **Zitvatorok Antlaşması (1606):** Osmanlı, Avusturya (Habsburg) imparatorunu **ilk kez eşit** tanıdı. "Eşit" kabulü, Osmanlı'nın üstünlüğünün sona erişi kabul edilir.
- **Celali isyanları** (16. yüzyıl sonu-17. yüzyıl başı): Anadolu'da vergi ve asker yetersizliği nedeniyle. Köylüler topraktan koptu (büyük kaçgun).
- **IV. Murat (1623-1640):** **Merkezi otoriteyi** yeniden kurdu. **Bağdat (1638)** ve **Revan (1635)** seferleri. Kahve ve tütünü yasakladı.
- **Köprülüler (1656-1710):** **Köprülü Mehmet Paşa** sadrazamlığı. **Fazıl Ahmet Paşa:** **Uyvar (1663)**, **Girit (1669)** fethi. **Kara Mustafa Paşa:** **1683 II. Viyana Kuşatması.** Başarısız oldu. **Kutsal İttifak** (Avusturya, Lehistan, Venedik, Rusya) kuruldu.

## 2. Karlofça ve gerileme (1699-1774)

- **Karlofça Antlaşması (1699):** **Osmanlı'nın ilk büyük toprak kaybı.** Macaristan, Transilvanya Avusturya'ya, Mora ve Dalmaçya Venedik'e, Podolya Lehistan'a. Azak Rusya'ya (1700). **Gerileme Dönemi'nin başı.** Osmanlı ilk kez "savunma" konumuna geçti.
- **Pasarofça Antlaşması (1718):** Avusturya'ya karşı. Osmanlı Belgrad ve Banat'ı kaybetti. **Lale Devri** barış dönemidir.
- **Belgrad Antlaşması (1739):** **Osmanlı'nın galip sayıldığı** son büyük antlaşmalardan biri. Belgrad'ı Osmanlı geri aldı.
- **1768-1774 Osmanlı-Rus Savaşı:** **Çeşme Baskını (1770)** (Osmanlı donanması yakıldı). **Küçük Kaynarca Antlaşması (1774):** Osmanlı için ağır sonuçlar (aşağıda).

## 3. Lale Devri (1718-1730)

- **Sadrazam Nevşehirli Damat İbrahim Paşa** ve **III. Ahmet.** Barış ve eğlence dönemi. **Lale** merakı, **Nedim** (şair), köşkler, **Sadabad Sarayı**.
- **Avrupa'ya açılma:** **Yirmisekiz Mehmet Çelebi** Fransa'ya elçi (1720-21). Avrupa'daki gelişmeleri ve sosyal hayatı tanıttı.
- **İbrahim Müteferrika (1727):** **İlk Türk matbaası.** Basılan ilk eser **Vankulu Sözlüğü.** Dinî kitaplar basılmadı.
- **Sonu:** Maliye bozuldu, halk üzerindeki baskı arttı. **Patrona Halil İsyanı (1730)** ile Lale Devri sona erdi.

## 4. Küçük Kaynarca Antlaşması (1774)

**Osmanlı ile Rusya** arasında imzalandı. **Sonuçları:**

- **Kırım** bağımsız oldu (1783'te Rusya'ya katıldı).
- Rusya, Karadeniz'de **ticaret gemisi** işletme ve Boğazlardan geçiş hakkı kazandı.
- Rusya, **Ortodoks tebaanın haklarını** koruma bahanesiyle Osmanlı'nın iç işlerine karışma imkânı buldu.
- **Savaş tazminatı** (4,5 milyon kuruş).
- Osmanlı'nın **Türk ve Müslüman** olmayan bir toprağı ilk kez kaybedişi ve **halife-sultan** unvanının Müslüman Kırım'a dayatılması.
- Osmanlı için **kapitülasyonlar** ve Rusya'nın Boğazlara yönelmesi.

## 5. Ekonomik ve toplumsal yapı

- **Timar sistemi bozuldu.** Yerine **iltizam** (mukataa gelirinin ihale ile verilmesi) ve **malikâne** (ömür boyu iltizam, 1695) geçti. **Ayanlar** (yerel eşraf) güçlendi.
- **Yeniçeri ocağı** bozuldu. Ticaretle uğraşmak, maaş için isyan etmek.
- **Avrupa'ya ihracat** için hammadde satışı, mamul alımı. **Kapitülasyonlar** Fransa'ya 1740'ta kalıcı hâle geldi.
- **Islahat çabaları:** Öncelikle **askerî**. **Humbaracı Ocağı** (Comte de Bonneval, Humbaracı Ahmet Paşa), **Mühendishane**. Batı tipi eğitim ve ordu yapılanması.

## 6. Sık yapılan hatalar

- Karlofça'yı Küçük Kaynarca ile karıştırmak. Karlofça 1699 Avusturya-Venedik-Lehistan, Küçük Kaynarca 1774 Rusya.
- Lale Devri'ni Tanzimat ile karıştırmak. Lale Devri 1718-1730.
- Belgrad Antlaşması'nı (1739) kayıp sanmak. Osmanlı Belgrad'ı geri aldı.
- Matbaayı Lale Devri'nde dinî kitaplar için kurulduğunu sanmak. Dinî eserler basılmadı.
- Zitvatorok'u Karlofça ile karıştırmak. Zitvatorok 1606, Karlofça 1699.

