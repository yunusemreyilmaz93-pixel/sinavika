## 1. Şark Meselesi

**Şark Meselesi:** Osmanlı Devleti'nin zayıflaması karşısında büyük devletlerin Osmanlı topraklarını ve miraslarını paylaşma çabası. 1774 Küçük Kaynarca ile başlar, 1923 Lozan ile sona erer.

| Devlet | Çıkarı |
| --- | --- |
| **Rusya** | Sıcak denizlere (Boğazlar) inmek, Ortodoksların koruyuculuğu, Balkanlar'da Slav (Panslavizm) |
| **İngiltere** | Hindistan yolunu korumak, Rusya'nın Akdeniz'e inmesini önlemek, Mısır ve Kıbrıs |
| **Fransa** | Akdeniz'de nüfuz, Katolikleri koruma, Kuzey Afrika |
| **Avusturya** | Balkanlar'da yayılma |
| **Almanya** | Ekonomik ve askerî nüfuz (Bağdat Demiryolu) |

## 2. Napolyon ve Mısır

- **1798 Napolyon'un Mısır'ı işgali.** Osmanlı ilk kez Fransa'ya karşı **İngiltere ve Rusya** ile ittifak etti.
- **Mehmet Ali Paşa (1805-):** Mısır valisi, Napolyon sonrası Mısır'da güç topladı. Osmanlı için **Mısır sorunu** başladı.
- **Mısır Sorunu:** **1831-33** Kavalalı Mehmet Ali Paşa'nın oğlu **İbrahim Paşa** Suriye'ye saldırdı. **Kütahya Antlaşması (1833)** ile Suriye Mısır'a bırakıldı. **Hünkâr İskelesi Antlaşması (1833):** Osmanlı, **Rusya ile savunma ittifakı** yaptı (Rusya yardım istedi). Boğazlar Rusya dışındaki devletlere kapatma anlaşması. **İngiltere ve Fransa** tepki gösterdi.
- **1839 Nizip Savaşı:** Osmanlı ordusu yenildi. Ardından II. Mahmut öldü. **1840-41 Londra Sözleşmeleri:** İngiltere, Rusya, Avusturya, Prusya Osmanlı yanında müdahale etti. Mehmet Ali Paşa Mısır'ın **kalıtsal valisi** oldu.
- **1841 Londra Boğazlar Sözleşmesi:** **Barış zamanında Boğazlar tüm yabancı savaş gemilerine kapatıldı.** Hünkâr İskelesi'nin Rus avantajı sona erdi.

## 3. Balkanlar'da milliyetçilik

- **Sırp İsyanı (1804-1830):** Sırbistan özerk oldu (1830).
- **Yunan İsyanı (1821):** Yunanistan'ın bağımsızlığı. **Navarin (1827)** Osmanlı-Mısır donanması İngiltere-Fransa-Rusya donanmasınca yakıldı. **Edirne Antlaşması (1829):** Rusya ile, Yunan özerkliği. **Londra Protokolü (1830):** Yunanistan bağımsız oldu.
- Fransız İhtilali'nin milliyetçilik fikri Balkan halklarına yayıldı.

## 4. Kırım Savaşı (1853-1856)

- **Nedeni:** Rusya, Kutsal Yerler (Kudüs) sorununu bahane ederek Osmanlı'daki Ortodoksları koruma hakkı istedi. Osmanlı reddedince savaş çıktı. **Osmanlı, İngiltere, Fransa ve Sardinya**, Rusya'ya karşı.
- **Sonuç: Paris Antlaşması (1856):**
  - **Osmanlı Avrupa Devletler Hukuku'na dahil edildi.** Osmanlı'nın **toprak bütünlüğü Avrupa devletlerinin garantisine** alındı.
  - **Karadeniz tarafsız** ilan edildi, savaş gemisi bulundurma yasaklandı.
  - Eflak, Boğdan özerkliği, Sırbistan haklar.
  - **Islahat Fermanı** (1856) gayrimüslim haklarının Avrupa tarafından denetimi.
- **Mali etki:** İlk **dış borç** (1854). **Osmanlı Bankası** (1856).

## 5. 93 Harbi (1877-1878)

- **Nedeni:** Balkan isyanları (Bosna-Hersek 1875, Bulgar 1876), **Panslavizm**. Rusya savaş ilan etti (Nisan 1877).
- **Doğu cephesi:** Gazi Ahmed Muhtar Paşa. **Plevne Savaşı:** Gazi Osman Paşa direnişi.
- **Ayastefanos Antlaşması (3 Mart 1878):** Büyük Bulgaristan kuruldu. Rusya Balkanlar'da ağır. İngiltere ve Avusturya kabul etmedi.
- **Berlin Antlaşması (13 Temmuz 1878):** **Büyük Bulgaristan küçültüldü.** **Kıbrıs İngiltere'ye** (savunma ittifakı karşılığı), **Bosna-Hersek Avusturya-Macaristan'a idare için** bırakıldı. Kars, Ardahan, Batum Rusya'ya. Sırbistan, Karadağ, Romanya bağımsız.

## 6. 1878 sonrası

- **Tunus (1881) Fransa'ya, Mısır (1882) İngiltere'ye** geçti. **Düyun-ı Umumiye** (1881).
- **Almanya'ya yakınlık:** II. Abdülhamit, İngiltere ve Rusya'ya karşı Almanya'yı destekledi. **Bağdat Demiryolu** (Almanya, 1903).
- **1897 Osmanlı-Yunan Savaşı:** Osmanlı kazandı.
- **1908 Bosna Krizi:** Avusturya-Macaristan Bosna-Hersek'i ilhak etti. Bulgaristan bağımsızlığını ilan etti.
- **1911-1913:** Trablusgarp ve Balkan savaşları.

## 7. Sık yapılan hatalar

- Hünkâr İskelesi'ni Londra Boğazlar Sözleşmesi ile karıştırmak. Hünkâr İskelesi Rusya yararınaydı, Londra tersini yaptı.
- Paris Antlaşması'nı Berlin ile karıştırmak. Paris 1856 Kırım Savaşı, Berlin 1878 93 Harbi sonucu.
- Ayastefanos'u Osmanlı lehine sanmak. Rusya lehineydi.
- Kıbrıs'ın Berlin'de Rusya'ya bırakıldığını sanmak. İngiltere'ye geçti.
- Denge politikasını tarafsızlık sanmak. Aktif çıkar yönetimi.

