Eski Türkler devleti nasıl yönetiyordu? Hakanın yetkisi nereden geliyordu? Kadının toplumdaki yeri neydi? Orta Asya'da kurulan ilk Türk devletleri, sonraki İslam dönemi devletlerine de temel oluşturan **devlet ve toplum geleneklerini** geliştirdi. Bu konuda **Eski Türklerde devlet anlayışını** (kut, töre, kurultay), **yönetim şeklini** (ikili teşkilat, ülüş), **toplum yapısını**, **ordu, ekonomi ve hukuku** ile **kadının konumunu** öğreneceksin.

:::hedefler
1. Kut, töre ve kurultay kavramlarını açıklamak.
2. İkili teşkilat ve ülüş sistemini yorumlamak.
3. Boy, budun ve il kademelerini sıralamak.
4. Ordu, ekonomi ve hukuk özelliklerini söylemek.
5. Türk kadınının toplumdaki yerini anlatmak.
6. Orhun Yazıtları gibi kaynakları tanımak.
:::

:::ipucu
Devlet geleneğini üç sütunda düşün: **kut** (yönetme yetkisi Tanrı'dandır), **töre** (yazısız hukuk, hakanı da bağlar), **kurultay** (önemli kararlar ortak alınır). Bu üçlü, hakanın yetkisinin hem kutsal hem sınırlı olduğunu gösterir.
