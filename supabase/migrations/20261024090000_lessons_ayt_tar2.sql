## 1. III. Selim dönemi (1789-1807)

- **Nizam-ı Cedid (Yeni Düzen):** Avrupa tarzında yeni bir ordu ve idari reformlar. **Hazine-i Cedid** ile mali kaynak.
- **Daimi elçilikler:** Londra (1793), Paris, Viyana, Berlin. Avrupa'yı tanımak.
- **Mühendishane** ve basımevi.
- **Tepki:** Yeniçeriler, ulema ve ayanlar. **Kabakçı Mustafa İsyanı (1807)** ile tahttan indirildi.

## 2. II. Mahmut dönemi (1808-1839)

- **Sened-i İttifak (1808):** Padişah ile **ayanlar** arasında imzalandı. Padişah, ayanların haklarını tanıdı, ayanlar padişaha bağlılık ve vergi ödemeyi kabul etti. **Padişahın yetkisinin ilk kez sınırlandığı** belgedir. Ancak ayanlar sözünden döndü, padişah güçlendi.
- **Vaka-i Hayriye (1826):** **Yeniçeri Ocağı kaldırıldı.** Yerine **Asakir-i Mansure-i Muhammediye** (Batı tarzı ordu) kuruldu. Askerî alanda büyük değişim.
- **İdari yenilikler:** **Divan-ı Hümayun yerine nazırlıklar** (bakanlıklar), **Meclis-i Vala-yi Ahkâm-ı Adliye**, **Takvim-i Vekayi (1831)**, **ilk resmî gazete.** **Posta** ve **karantina**, **nüfus sayımı** (1831), **kıyafet inkılabı** (fes, setre-pantolon).
- **Eğitim:** **Mekteb-i Tıbbiye (1827)**, **Mekteb-i Harbiye (1834)**, **zorunlu ilköğretim** denemesi. **Rüştiye** mektepleri.
- **Dış gelişmeler:** Yunan ve Mısır sorunları. **Hünkâr İskelesi** (1833).

## 3. Tanzimat Dönemi (1839-1876)

**Tanzimat Fermanı (Gülhane Hatt-ı Hümayunu, 3 Kasım 1839):** Sadrazam **Mustafa Reşit Paşa** hazırladı. Abdülmecit tarafından Gülhane'de okundu.

**Hükümleri:**

- **Can, mal ve namus güvenliği** (herkesin hayatı güvence altında).
- **Vergide adalet** (herkes gelirine göre vergi ödeyecek).
- **Askerlik** düzenli ve süreli olacak.
- **Yargılama açık** ve herkes mahkemede eşit.
- İltizam kaldırılması hedefi.

Bu ferman **Osmanlı'da ilk anayasal belge** gibi anılır, ama padişahın **kendi isteğiyle** verdiği bir lütuf olarak sunuldu. **Batı'ya Osmanlı'nın uyum mesajı** idi.

**Islahat Fermanı (1856):** Kırım Savaşı sonrası, **Paris Antlaşması öncesinde** ilan edildi. **Gayrimüslimlere eşit haklar:** Din, mezhep ayrımı olmadan **eşit vatandaşlık**, **askerlik hakkı**, devlet memurluğu, mülk edinme, okul açma.

**Diğer yenilikler:**

- **Hukuk:** **Ticaret Kanunu (1850)**, **Ceza Kanunu (1858)**, **Arazi Kanunnamesi (1858)**, **Mecelle (1869-1876)** (şer'i hukukun kanunlaştırılması). **Nizamiye mahkemeleri.**
- **Eğitim:** **Maarif-i Umumiye Nizamnamesi (1869):** Eğitimde kademeler. **Darülfünun** (1863 ve 1900), **Mekteb-i Sultani** (Galatasaray, 1868), **Darülmuallimin** (öğretmen okulu, 1848).
- **Maliye:** **Osmanlı Bankası (1856)**, **Meclis-i Vükelâ**, **ilk kâğıt para (Kaime)**, **ilk dış borç (1854).**
- **Basın:** **Tercüman-ı Ahval (1860)**, **Tasvir-i Efkâr (1862).**
