## 1. Nedenler ve iki blok

- **Savaş sonrası boşluk:** Avrupa yıkıldı. **ABD ve SSCB** iki süper güç oldu.
- **İdeoloji farkı:** **Kapitalizm ve demokrasi** (ABD) karşısında **komünizm ve tek parti** (SSCB).
- **Sovyetlerin Doğu Avrupa'yı** etki alanına alması (**Demir Perde**, Churchill 1946).
- **Batı Bloğu:** ABD, İngiltere, Fransa, Batı Almanya, İtalya, Türkiye. **Doğu Bloğu:** SSCB, Polonya, Doğu Almanya, Çekoslovakya, Macaristan, Romanya, Bulgaristan.

## 2. Batı'nın hamleleri

- **Truman Doktrini (1947):** ABD Başkanı Truman, **komünizm tehdidi altındaki Türkiye ve Yunanistan'a** ekonomik ve askerî yardım yapılacağını açıkladı. Gerekçe: SSCB'nin Boğazlar ve Doğu Anadolu talepleri, Yunan İç Savaşı. **Soğuk Savaş'ın başlangıcı sayılır.**
- **Marshall Planı (1947-48):** ABD'nin **Batı Avrupa'nın ekonomik kalkınması** için yardımı. Amaç: Komünizmin yayılmasını önlemek. **Avrupa Ekonomik İş Birliği Örgütü (OEEC).** Türkiye de yararlandı.
- **NATO (Nisan 1949):** Batı bloğunun **askerî ittifakı.** **Türkiye 1952'de katıldı** (Kore Savaşı'na asker göndermesinin ardından, Yunanistan ile birlikte).
- **Batı Almanya'nın kuruluşu (1949).**

## 3. Doğu Bloğu'nun cevapları

- **Cominform (1947), COMECON (1949).** Ekonomik iş birliği.
- **Berlin Ablukası (1948-1949):** SSCB, Batı Berlin'in kara yollarını kapattı. Batı **hava köprüsüyle** yardım ulaştırdı. Blokaj kalktı. **Almanya ikiye bölündü:** Batı Almanya (FAC) ve Doğu Almanya (DAC).
- **Varşova Paktı (1955):** NATO'ya karşı Doğu bloğunun askerî ittifakı.
- **Macaristan (1956)** ve **Çekoslovakya (1968)** müdahaleleri.
- **Berlin Duvarı (1961):** Doğu Almanya Berlin'i duvarla ikiye böldü.

## 4. Büyük krizler

- **Çin Devrimi (1949):** Mao komünist Çin Halk Cumhuriyeti'ni kurdu.
- **Kore Savaşı (1950-1953):** Kuzey Kore (komünist, SSCB ve Çin destekli) Güney Kore'ye saldırdı. **BM kuvvetleri** (ABD önderliğinde) müdahale etti. **Türkiye** 5.000'den fazla askerle katıldı (Kunuri, Kumyangjang). Savaş **38. paralelde** sona erdi. Türkiye'nin NATO'ya girişinde etkili.
- **Vietnam Savaşı (1955-1975):** Kuzey Vietnam ile ABD destekli Güney Vietnam çatıştı. ABD yenildi.
- **Küba Füze Krizi (1962):** SSCB, Küba'ya nükleer füze yerleştirdi. ABD kuşatma uyguladı. Dünya nükleer savaşın eşiğine geldi. **Kriz diyalogla çözüldü:** SSCB füzeleri çekti, ABD Küba'yı işgal etmeyeceğini taahhüt etti ve **Türkiye'deki Jüpiter füzelerini** gizlice çekti.

**Silahlanma yarışı:** Atom bombası (SSCB 1949), hidrojen bombası, uzay yarışı (**Sputnik 1957, Apollo 11 1969**), balistik füzeler.

## 5. Bağlantısızlar ve Üçüncü Dünya

Sömürge dönemi sona erdi (**dekolonizasyon**). Yeni bağımsız devletler iki bloğa girmek istemedi: **Bandung Konferansı (1955)**, **Bağlantısızlar Hareketi** (Nehru, Nasır, Tito). **Üçüncü Dünya** ülkeleri.

## 6. Türkiye ve Soğuk Savaş

- **SSCB'nin tehdidi:** 1945'te **Türk-Sovyet Dostluk Antlaşması'nı** (1925) uzatmayı reddetti, Boğazlar'da üs ve Doğu Anadolu'da toprak (Kars, Ardahan) istedi.
- **Batı bloğuna yönelim:** **Truman Doktrini (1947), Marshall Planı (1948), Avrupa Konseyi (1949), Kore (1950), NATO (1952).** **Balkan Paktı (1953)**, **Bağdat Paktı (1955, daha sonra CENTO).**
- **Çok partili hayata geçiş** (1946) ve **Demokrat Parti (1950).**
- **Kıbrıs sorunu:** **1960** Kıbrıs Cumhuriyeti. **1963-64 olayları.** **Johnson Mektubu (1964):** ABD, Türkiye'nin Kıbrıs müdahalesine karşı çıktı. Türkiye'nin dış politikasında **çok yönlü** arayışlar.
- **1974 Kıbrıs Barış Harekâtı:** ABD silah ambargosu (1975-78).

## 7. Sık yapılan hatalar

- Truman Doktrini'ni Marshall Planı ile karıştırmak. Truman askerî ve ekonomik yardım (Türkiye, Yunanistan), Marshall ekonomik (Batı Avrupa).
- NATO'ya girişi 1949 sanmak. Türkiye 1952'de üye oldu.
- Kore Savaşı'nı Vietnam ile karıştırmak.
- Küba Krizi'ni savaşa dönüştü sanmak. Diyalogla çözüldü.
- Soğuk Savaş'ı yalnızca askerî çatışma sanmak. İdeolojik ve ekonomik rekabettir.

:::baglanti
Bu konu, **II. Dünya Savaşı**'nın doğrudan devamıdır. **Yumuşama Dönemi ve Sonrası** konusunda bu rekabetin gevşemesi ve sona ermesi işlenir. **Atatürk İlke ve İnkılapları** (Tarih-1) konusunun dış politika başlıkları, Türkiye'nin Batı'ya yönelişini açıklar. **Coğrafya** dersinde Kıbrıs, Boğazlar ve Orta Doğu jeopolitiği bu mücadele ile bağlanır. **Felsefe** dersinde politik felsefe bu çatışmanın düşünsel zeminidir.
