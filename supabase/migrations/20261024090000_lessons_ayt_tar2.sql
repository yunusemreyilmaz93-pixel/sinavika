## 1. Küreselleşme nedir?

**Küreselleşme**, mal, sermaye, bilgi, insan ve kültürün ülke sınırlarını aşarak dolaşması ve dünyanın ekonomik, siyasi ve kültürel olarak birbirine bağlanmasıdır. Soğuk Savaş'ın bitmesiyle hız kazandı. İki kutuplu düzen yıkıldı ve pazarlar yeniden birleşti.

**Küreselleşmeyi hızlandıran etkenler:**

- **İletişim teknolojileri:** İnternet, uydu yayınları, cep telefonu. Haber ve para anında dolaşır.
- **Ulaşım:** Konteyner taşımacılığı, hızlı trenler, ucuz uçak yolculuğu.
- **Serbest ticaret:** Gümrük engellerinin azaltılması.
- **Çok uluslu şirketler:** Üretimi birçok ülkeye yayar, tüketimi de dünya çapında örgütler.
- **Finans piyasaları:** Sermayenin ülkeler arasında hızla hareket etmesi.

## 2. Önemli uluslararası kuruluşlar

- **Birleşmiş Milletler (BM, 1945):** Barış ve güvenliği korumak. Merkezi New York. **Güvenlik Konseyi** (5 daimi üye: ABD, Rusya, Çin, İngiltere, Fransa).
- **IMF ve Dünya Bankası (1944, Bretton Woods):** Uluslararası para sistemi ve kalkınma finansmanı.
- **GATT (1947) $\rightarrow$ DTÖ (1995):** Uluslararası ticaretin kurallarını belirler, ticari anlaşmazlıkları çözer. Merkezi Cenevre.
- **NATO:** Askerî ittifak. Soğuk Savaş sonrası çalışma alanı genişledi.
- **OECD, G20:** Gelişmiş ve büyük ekonomilerin iş birliği.

## 3. Avrupa Birliği

Süreç **Avrupa Kömür ve Çelik Topluluğu (1951)** ile başladı. **Roma Antlaşması (1957)** ile Avrupa Ekonomik Topluluğu kuruldu. **Maastricht Antlaşması (1992)** ile **Avrupa Birliği** adı ve **ortak para birimi (Avro)** hedefi doğdu. Avro 2002'de tedavüle girdi. Üye ülkeler arasında mal, hizmet, sermaye ve insanların serbest dolaşımı hedeflenir. Soğuk Savaş sonrası Orta ve Doğu Avrupa ülkeleri de katıldı.

**Diğer bölgesel bütünleşmeler:** **NAFTA (1994)** ABD, Kanada, Meksika. **ASEAN** Güneydoğu Asya. **Mercosur** Güney Amerika.

## 4. Sonuçları

**Olumlu yanlar:**

- Dünya ticaretinin ve bilgiye erişimin artması.
- Teknoloji ve üretimin yayılması.
- Kültürel etkileşim ve çeşitlilik.

**Olumsuz yanlar:**

- Gelişmiş ve gelişmekte olan ülkeler arasındaki **gelir farkının büyümesi.**
- Yerel kültürlerin ve dillerin zayıflaması, kültürel benzeşme.
- Küresel krizlerin hızla yayılması (**2008 ekonomik krizi**).
- Çevre sorunları ve kaynak tüketimi.
- Ulusal egemenliğin sınırlanması tartışması.

## 5. Küresel sorunlar

- **Terörizm:** 11 Eylül 2001 saldırılarından sonra uluslararası güvenlik düzeni değişti.
- **İklim değişikliği:** Paris İklim Anlaşması (2015).
- **Salgın hastalıklar:** 2020 küresel salgını, sınırların ve ulaşımın dünyayı birbirine nasıl bağladığını gösterdi.
- **Göç ve mülteci sorunları.**
- **Arap Baharı (2010-2011)** ve Orta Doğu'daki çatışmalar.

## 6. Türkiye ve küreselleşme

- **1963 Ankara Antlaşması:** Türkiye ile AET arasında ortaklık.
- **1987:** AB'ye tam üyelik başvurusu.
- **1995:** DTÖ üyeliği ve AB ile **Gümrük Birliği** kararı (**1 Ocak 1996**'da yürürlüğe girdi).
- **1999 Helsinki Zirvesi:** Türkiye'nin AB'ye aday ülke olarak kabulü.
- **2005:** Tam üyelik müzakerelerinin başlaması.
- **Soğuk Savaş sonrası Türk cumhuriyetleriyle ilişkiler:** Ekonomik ve kültürel iş birliği, Türk Devletleri Teşkilatı'na giden süreç.
- G20 üyesi, OECD ve NATO üyesi.

