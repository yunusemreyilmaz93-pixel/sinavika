## 1. Genel özellikler

- **Kuruluş:** 1909'da İstanbul'da, Servet-i Fünun dergisinin sayfalarında yayımlanan bir bildirgeyle **Fecr-i Ati** ("Geleceğin şafağı") topluluğu kuruldu. Topluluğun öne çıkan sanatçıları **Ahmet Haşim** ve **Yakup Kadri** oldu.
- **İlke:** **"Sanat şahsi ve muhteremdir."** Sanatçının kişiliğine, sanatın özgürlüğüne ve saygınlığına vurgu yapar. Sanat başka bir amaca (toplum, politika) hizmet etmez. "Sanat sanat içindir"in yeni bir söyleyişidir.
- **Etki:** Fransız edebiyatı (özellikle **sembolizm**, **parnasizm**).
- **Dil:** Ağır, süslü, Arapça-Farsça tamlamalar, Servet-i Fünun gibi. Ancak Ahmet Haşim, şiir dilini kendine özgü bir müzikaliteye taşıdı.
- **Konular:** Bireysel duygular, yalnızlık, hayal, ölüm, doğa ve lirik atmosfer.
- **Dağılma:** 1912'de, Balkan Savaşı ve Milli Edebiyat akımının güçlenmesiyle dağıldı. Üyelerin çoğu daha sonra başka çizgilere yöneldi (Yakup Kadri ve Refik Halit gerçekçi toplum yazarlığına geçti).

## 2. Servet-i Fünun ile karşılaştırma

