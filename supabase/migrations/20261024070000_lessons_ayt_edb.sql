Aynı kelimeyi iki farklı cümlede kullandığında anlamı neden değişir? Bir paragrafı okuyunca yazarın asıl söylemek istediğini nasıl bulursun? Sınavda Türkçe ve Edebiyat sorularının büyük bölümü **anlam** üzerine kuruludur. Bu konuda **sözcükte anlamı** (gerçek, mecaz, terim, yan anlam), **sözcükler arası anlam ilişkilerini**, **deyim ve atasözlerini**, **cümlede anlam ilişkilerini** (neden-sonuç, amaç-sonuç, koşul, karşılaştırma) ve **paragrafta ana düşünce ile anlatım tekniklerini** öğreneceksin. Edebiyat sorularında verilen parçayı doğru yorumlamak için bu temel şarttır.

:::hedefler
1. Sözcüğün gerçek, mecaz, terim ve yan anlamını ayırt etmek.
2. Eş anlamlı, zıt anlamlı, eş sesli ve yakın anlamlı sözcükleri tanımak.
3. Cümlede neden-sonuç, amaç-sonuç, koşul ve karşılaştırma ilişkilerini bulmak.
4. Öznel ve nesnel yargıları ayırmak.
5. Paragrafta ana düşünceyi, yardımcı düşünceyi ve konuyu belirlemek.
6. Tanımlama, karşılaştırma, örneklendirme, tanık gösterme ve sayısal veri tekniklerini tanımak.
:::

:::ipucu
Paragraf sorusunda önce **soru kökünü** oku, sonra parçayı oku. Ana düşünce çoğunlukla **sonuç cümlesinde** ("bu yüzden", "sonuç olarak", "kısacası") ya da **ilk cümlede** yer alır. Seçeneklerde parçada **geçmeyen** ya da **gereğinden fazla genelleyen** ("her zaman", "yalnızca", "hiçbir") ifadelerden kaçın.
:::

