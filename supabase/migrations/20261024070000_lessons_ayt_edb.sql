## 1. Ortaya çıkış

- **Siyasal zemin:** II. Meşrutiyet (1908), Balkan Savaşları (1912-1913), **Türkçülük** düşüncesinin yükselişi. **Yusuf Akçura** "Üç Tarz-ı Siyaset" (1904) ve **Ziya Gökalp** (Türkçülüğün Esasları, 1923) etkili oldu. **Türk Yurdu** (1911) ve **Türk Ocakları** (1912).
- **Genç Kalemler** (1911, Selanik): **Ömer Seyfettin**, **Ali Canip Yöntem** ve **Ziya Gökalp** tarafından çıkarıldı. Dergide **"Yeni Lisan"** makalesi yayımlandı (Ömer Seyfettin).
- **Yeni Lisan:** İstanbul'da konuşulan sade Türkçenin yazı dili olması. Arapça ve Farsça sözcüklerin ve dil bilgisi kurallarının dilden atılması. Türkçe sözcükleri tercih etme.

## 2. Genel özellikler

- **Dil:** İstanbul Türkçesi, sade, anlaşılır. Arapça ve Farsça tamlamalardan kaçınma.
- **Konu:** Milli konular. Anadolu insanı, Türk tarihi ve destanları, Milli Mücadele, halkın yaşayışı.
- **Şiir:** **Hece ölçüsü** (Halk şiirine dönüş). Hece ölçüsünün **milli ölçü** olduğu düşünüldü. Nazım biçimi olarak **koşma, mani** gibi halk biçimleri.
- **Roman ve öykü:** Gerçekçi, yerel unsurlar, Anadolu. **Öykü**de **olay hikâyesi** (Maupassant tarzı) öne çıktı.
- **Anlayış:** "Sanat toplum içindir" anlayışının yeniden dirilişi.

## 3. Şiir

- **Mehmet Emin Yurdakul (1869-1944):** "Milli şair". Sade Türkçe ve hece ölçüsüyle ilk şiirleri yazdı. **Türkçe Şiirler** (1899), **Turan'a Doğru**, **Ordunun Destanı**. "Ben bir Türküm, dinim, cinsim uludur" dizesi ünlüdür.
- **Ziya Gökalp (1876-1924):** Düşünür ve şair. **Kızıl Elma**, **Yeni Hayat**, **Altın Işık**. Şiirlerinde hece ölçüsü, Türkçülük. Sosyolojik düşünceleri: "Türkleşmek, İslamlaşmak, muasırlaşmak".
- **Beş Hececiler:** Hece ölçüsünü benimseyen, milli konuları şiire taşıyan beş şair: **Faruk Nafiz Çamlıbel**, **Yusuf Ziya Ortaç**, **Orhan Seyfi Orhon**, **Enis Behiç Koryürek**, **Halit Fahri Ozansoy**. En önemli temsilcileri Faruk Nafiz Çamlıbel'dir (**Han Duvarları**, **Sanat**).
- **Rıza Tevfik, Ali Ekrem Bolayır, Mehmet Akif Ersoy:** Aruzu sürdüren ama toplum içindir anlayışıyla ilişkili şairler. **Mehmet Akif** (Safahat, **İstiklal Marşı**) Milli Edebiyat ile aynı dönemde yaşayıp aruzla yazdı, ancak dilin sade olması ve halk için yazma yönünden Milli Edebiyat çizgisine yakındır.

## 4. Roman ve öykü

- **Ömer Seyfettin (1884-1920):** Türk öyküsünün büyük ustası. **Olay hikâyesi** (Maupassant). **Yeni Lisan** hareketinin öncüsü. Eserleri: **Kaşağı**, **Ashab-ı Kehfimiz**, **Pembe İncili Kaftan**, **Bomba**, **Yalnız Efe**, **Primo Türk Çocuğu**, **Başını Vermeyen Şehit**. Romanları: **Efruz Bey**.
- **Halide Edib Adıvar (1884-1964):** **Sinekli Bakkal** (1936), **Ateşten Gömlek** (1922, Milli Mücadele), **Vurun Kahpeye** (1923), **Yeni Turan** (1912), **Türk'ün Ateşle İmtihanı**. Milli Mücadele'ye katıldı.
- **Reşat Nuri Güntekin (1889-1956):** **Çalıkuşu** (1922), **Yaprak Dökümü** (1930), **Acımak**, **Yeşil Gece**, **Dudaktan Kalbe**. Okuyucuya yakın, sade romancı, aile ve yaşam.
- **Yakup Kadri Karaosmanoğlu:** Milli Mücadele dönemi romanları. **Yaban** (1932).
- **Refik Halit Karay:** **Memleket Hikâyeleri**.
- **Falih Rıfkı Atay:** **Zeytindağı**, **Çankaya** (anı).
- **Ali Canip Yöntem:** Öykü ve şiir.

