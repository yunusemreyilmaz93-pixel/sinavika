## 1. Genel özellikler

- **Kuruluş:** Servet-i Fünun dergisi (1891'den beri yayımlanıyordu, Ahmet İhsan Tokgöz) 1896'da **Recaizade Mahmut Ekrem'in** önerisiyle edebiyat dergisi oldu. Genç yazarlar **Edebiyat-ı Cedide** ("Yeni Edebiyat") adı altında toplandı.
- **Dağılma:** 1901'de dergi kapatıldı, topluluk dağıldı.
- **Sanat anlayışı:** **"Sanat sanat içindir."** Toplumdan çok bireye yönelmişlerdir.
- **Etki:** Fransız edebiyatı (Parnasizm, Sembolizm, Realizm).
- **Dil:** Ağır, sanatlı, Arapça-Farsça sözcüklerle ve tamlamalarla dolu. Yeni sözcükler ve imgeler kullanıldı.
- **Konu:** Aşk, ölüm, hastalık, yalnızlık, kaçış, karamsarlık, **bireysel duygular**. Toplumsal konulardan uzak.
- **Şiir:** Aruz ölçüsü, **Fransız şiirinin biçimleri** (sone, **serbest müstezat**). Beyit yerine **bent**. **Şiirde konu bütünlüğü** (bir şiir bir konu). Şiirde imge ve ses uyumu önemli. **Mensur şiir** denendi.
- **Roman ve öykü:** Realizm ve psikolojik çözümleme. Çağdaş İstanbul yaşamı, aile içi dramlar, **kişilerin iç dünyaları**.

## 2. Sanatçılar ve eserleri

**Tevfik Fikret (1867-1915):**

- Dönemin en büyük şairi. **Rübab-ı Şikeste** (1900, sanat sanat içindir döneminin şiirleri), **Haluk'un Defteri** (1911, çocuğuna yönelik), **Rübabın Cevabı** (1911), **Tarih-i Kadim** (1905).
- **Sis** şiiri: İstanbul'un sisini baskıcı yönetime benzetir (toplumsal şiir).
- **Serbest müstezat** biçimini ilk kullanan sanatçıdır.
- Servet-i Fünun'dan sonra toplumsal konulu, **hümanist** şiirlere yöneldi.

**Cenap Şahabettin (1870-1934):**

- Şiirde sembolizmden yararlandı. Eserleri: **Tamât** (şiir), **Evrak-ı Eyyam** (nesir), **Hac Yolunda** (gezi yazısı).

**Halit Ziya Uşaklıgil (1866-1945):**

- Dönemin en büyük romancısı. **Mai ve Siyah** (1897, sanatçı Ahmet Cemil'in hayalleri, romantik ve gerçekçi), **Aşk-ı Memnu** (1900, İstanbul'un aristokrat ailesi, Behlül ve Bihter), **Kırık Hayatlar**, **Sefile**, **Nesl-i Ahir**.
- Dili ağır, anlatımı gerçekçi, ayrıntı ve betimleme zengin.

**Mehmet Rauf (1875-1931):**

- **Eylül** (1901): Türk edebiyatının ilk **psikolojik** romanı kabul edilir (Suat, Necip, Nüzhet üçgeni).

**Hüseyin Cahit Yalçın:**

- **Hayat-ı Muhayyel** (öykü ve düşünce), **Nadide**. Eleştiri ve makale yazarı.

**Diğer:** Ahmet Hikmet Müftüoğlu, Süleyman Nazif (şair, hiciv), Ali Ekrem Bolayır (şair), Safveti Ziya.

