## 1. Öğretici metinler

Amacı bilgi vermek, ikna etmek ve düşünce paylaşmaktır. Dil açık ve anlaşılırdır.

| Tür | Özellikler |
| --- | --- |
| **Makale** | Bir konuyu kanıtlayarak, nesnel biçimde ele alır, resmî dil, giriş-gelişme-sonuç |
| **Fıkra (köşe yazısı)** | Gazetelerde güncel olayları yazarın görüşüyle ele alır, sohbet havası, kısa |
| **Deneme** | Kişisel görüşleri kanıtlama kaygısı gütmeden, içten ve serbest biçimde anlatır |
| **Sohbet (söyleşi)** | Okurla konuşuyormuş gibi, samimi bir dille yazılır |
| **Eleştiri** | Bir eseri değer yargılarıyla yorumlar |
| **Gezi yazısı** | Görülen yerleri ve izlenimleri anlatır |
| **Anı (hatıra)** | Yaşanmış olayları, belli zaman sonra, yazarın anlatması |
| **Günlük** | Olayları günü gününe, tarih atarak yazma |
| **Mektup** | Bir kişiye hitaben yazılan metin |
| **Biyografi** | Bir kişinin hayatının başkası tarafından anlatılması |
| **Otobiyografi** | Yazarın kendi hayatını anlatması |
| **Röportaj** | Soru-cevap yoluyla bir kişi ya da konu hakkında bilgi toplama |
| **Haber yazısı** | Güncel bir olayı kısa ve tarafsız biçimde verir |

**Makale ile deneme farkı:** Makalede kanıtlama ve nesnellik, denemede kişisellik ve içtenlik öne çıkar.

**Anı ile günlük farkı:** Günlük olayın yaşandığı gün tarih atılarak yazılır, anı ise belli bir süre sonra anlatılır. Günlükte kişisel konular olur, anıda toplumsal olaylara tanıklık da yer alabilir.

## 2. Sanatsal (edebî) metinler

Amacı **estetik haz** vermektir. Sözcükler çok anlamlı kullanılır.

- **Öykü (hikâye):** Kısa olay anlatır, kişi sayısı az, zaman ve mekân sınırlı, tek bir olay etrafında. Türkçede ilk örnekler Tanzimat sonrasında görülür.
- **Roman:** Uzun olay örgüsü, çok sayıda kişi, çok mekân, uzun zaman, betimlemelerle zengin.
- **Masal:** Halk anlatısı, olağanüstü, "Bir varmış bir yokmuş".
- **Fabl:** Hayvanların konuşturulduğu, ders veren hikâye.
- **Destan:** Halkın kahramanlıklarını anlatan, olağanüstü unsurlarla dolu uzun şiirsel anlatı.
- **Halk hikâyesi:** Aşk ve kahramanlık temalı, nesir ve nazım karışık (Kerem ile Aslı, Ferhat ile Şirin).

**Olay anlatımının unsurları:** Olay, kişi, yer, zaman, anlatıcı, bakış açısı.

**Bakış açıları:**

- **Kahraman anlatıcı (birinci kişi):** Olayı "ben" diliyle olayın içindeki kişi anlatır.
- **İlahi (hâkim) bakış açısı:** Anlatıcı her şeyi bilir, kişilerin içinden geçenleri bilir.
- **Gözlemci bakış açısı:** Anlatıcı yalnızca dışarıdan gördüklerini aktarır.

## 3. Tiyatro türleri

**Tiyatro (oyun):** Diyaloglar yoluyla sahnede gösterilmek için yazılır. Bölümleri: **perde**, **sahne**, **tablo**. Yazılış amaçlarına göre:

- **Trajedi:** Soylu kişilerin yaşadığı felaketleri anlatan acıklı oyun, seyirciyi acıma ve korku duygusuyla arındırır, ölümle biter (Eski Yunan, Aiskhylos, Sophokles, Euripides).
- **Komedi:** İnsanların gülünç yanlarını ya da toplumun aksayan yönlerini güldürerek eleştirir, mutlu sonla biter (Molière).
- **Dram:** Trajedi ile komedi karışımı, günlük yaşamdan acı ve gülünç unsurlar birlikte (Shakespeare).
- **Fars:** Abartılı, güldürmeyi amaçlayan kısa oyun.
- **Vodvil:** Şarkılı, dansı olan hafif komedi.

**Geleneksel Türk tiyatrosu:** Karagöz (gölge oyunu), meddah (tek kişilik anlatım), kukla, ortaoyunu (halk tiyatrosu, pişekâr, kavuklu).

