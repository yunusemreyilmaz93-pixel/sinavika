Edebiyatın toplumu eğitmek, uyandırmak için kullanıldığı dönemdir.

- **Şinasi (1826-1871):** Dönemin kurucusu. **Tercüman-ı Ahval** ve **Tasvir-i Efkâr** gazetelerini çıkardı. **Şair Evlenmesi** (ilk tiyatro oyunu, tek perdelik komedi, 1859). Fransızcadan şiir çevirisi: **Müntehabat-ı Eş'ar**. **Noktalama işaretlerini** ve **atasözlerini** (Durub-ı Emsal-i Osmaniye) edebiyata soktu. Sade bir dil istedi. Aklı ve bilimi savundu.
- **Namık Kemal (1840-1888):** "Vatan şairi". **Vatan, hürriyet, millet, eşitlik** fikirlerini coşkulu bir dille işledi. Şiirleri: Hürriyet Kasidesi. **İntibah** (ilk edebi roman, 1876), **Cezmi** (ilk tarihi roman, 1880). Tiyatro: **Vatan yahut Silistre** (1873, sahnelendiğinde büyük etki yarattı), **Gülnihal**, **Akif Bey**, **Zavallı Çocuk**. Eleştiri ve inceleme: **Tahrib-i Harabat**, **Takip**, **Renan Müdafaanamesi**. Kemal'in eserlerinde **romantizm** hâkimdir.
- **Ziya Paşa (1829-1880):** Divan şiirini sade dille eleştirdi. **Zafername** (hiciv), **Harabat** (antoloji), **Terkib-i Bend**, **Şiir ve İnşa** makalesi. Halk edebiyatını öne çıkardı.
- **Ahmet Vefik Paşa:** Molière'den tiyatro uyarlamaları yaptı.
- **Şemsettin Sami:** **Taaşuk-ı Talat ve Fitnat** (ilk Türk romanı, 1872).

## 3. II. dönem (1876-1896): "Sanat sanat içindir"a yöneliş

Sanat kaygısı öne çıkmaya başladı. Roman ve öyküde **realizm** ve **natüralizm** etkisi, şiirde bireysel duygular arttı. Sansür ve baskı vardı.

- **Recaizade Mahmut Ekrem (1847-1914):** **Araba Sevdası** (ilk realist roman, 1896), **Talim-i Edebiyat** (edebiyat kuramı), **Zemzeme** (şiir), **Takdir-i Elhan**. Servet-i Fünunculara öğretmenlik yaptı. "Sanat sanat içindir"i savundu.
- **Abdülhak Hamit Tarhan (1852-1937):** "Şair-i Âzam". **Makber** (eşinin ölümü üzerine yazdığı şiir, 1885), **Sahra, Ölü, Hacle, Bunlar O'dur**. Tiyatro oyunları: **Tarık, Finten, İlhan, Tezer, Duhter-i Hindu** (manzum tiyatro). Hayal gücü, ölüm ve metafizik konuları işledi.
- **Samipaşazade Sezai (1859-1936):** **Sergüzeşt** (köle Dilber'in hikâyesi, romantik ve gerçekçi unsurlar, 1888), **Küçük Şeyler** (ilk modern öykü kitabı, 1892). Realizm.
- **Nabizade Nazım (1862-1893):** **Karabibik** (ilk natüralist roman ve ilk köy romanı, 1890), **Zehra** (natüralist roman).
- **Ahmet Mithat Efendi (1844-1912):** Çok yönlü yazar. **Felatun Bey ile Rakım Efendi** (1875), **Paris'te Bir Türk**, **Hüseyin Fellah**, **Letaif-i Rivayat** (öykü). "Eğitici" roman, olaylara yazar sürekli müdahale eder. Yaşadığı çağın sorunlarına, Doğu-Batı çatışmasına yöneldi. Gazete çıkardı (Tercüman-ı Hakikat).

