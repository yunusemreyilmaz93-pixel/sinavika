## 1. Ses bilgisi

**Ünlüler (8):** a, e, ı, i, o, ö, u, ü. **Ünsüzler:** diğerleri. **Sert ünsüzler:** f, s, t, k, ç, ş, h, p ("Fıstıkçı Şahap").

**Büyük ünlü uyumu:** Kelimede kalın ünlüden sonra kalın, ince ünlüden sonra ince ünlü gelir. "okul-lar", "ev-ler". **Küçük ünlü uyumu:** Düz ünlüden (a, e, ı, i) sonra düz, yuvarlak ünlüden (o, ö, u, ü) sonra düz-geniş (a, e) ya da dar yuvarlak (u, ü) ünlü gelir. Uyuma uymayan sözcükler genelde yabancı kökenli ya da birleşik sözcüklerdir ("kitap", "anne").

**Ünsüz benzeşmesi:** Sert ünsüzle biten sözcüğe gelen ekin ilk ünsüzü de sert olur. "kitap-çı", "sokak-ta", "ağaç-ta".

**Ses olayları:**

| Ses olayı | Örnek |
| --- | --- |
| Ünsüz yumuşaması | kitap $\rightarrow$ kitabı, ağaç $\rightarrow$ ağacı, sokak $\rightarrow$ sokağa |
| Ünlü düşmesi | omuz $\rightarrow$ omzum, ağız $\rightarrow$ ağzı, gönül $\rightarrow$ gönlüm |
| Ünsüz düşmesi | küçük $\rightarrow$ küçücük |
| Ses türemesi | az $\rightarrow$ azıcık, his $\rightarrow$ hissi |
| Ünlü daralması | demek $\rightarrow$ diyor, yemek $\rightarrow$ yiyor |
| Kaynaşma | su-y-u, kapı-y-ı (ünlü ile biten sözcüğe ünlüyle başlayan ek gelince) |

## 2. Yapı bilgisi

**Kök:** Sözcüğün anlam taşıyan en küçük parçasıdır ("göz" gözlük). **Ek:** Köke ya da gövdeye eklenen parçadır.

- **Yapım eki:** Yeni sözcük yapar, anlamı ve çoğu zaman türü değiştirir. "göz+lük", "balık+çı", "güzel+leş".
- **Çekim eki:** Sözcüğe yeni anlam katmaz, cümledeki göreviyle ilgilidir. Çoğul, iyelik, hâl (-i, -e, -de, -den, -in), kip, kişi ekleri. "ev+ler", "ev+im", "ev+de".

Önce yapım, sonra çekim eki gelir. "göz+lük+ler+im+den".

**Sözcük yapısına göre:**

- **Basit:** Kök hâlinde, ek almamış ("göz", "kitap"). Çekim ekli de basittir ("kitaplar").
- **Türemiş:** Yapım eki almış ("gözlük", "balıkçı").
- **Birleşik:** İki sözcüğün birleşmesi ("anneanne", "hanımeli", "karabiber", "başöğretmen").

## 3. Sözcük türleri

- **İsim (ad):** Varlıkları adlandırır. Cins (kalem), özel (Ankara), tekil/çoğul, topluluk (sürü).
- **Sıfat:** İsmi niteler ya da belirtir. "güzel çocuk" (niteleme), "bu kitap" (belirtme).
- **Zamir (adıl):** İsmin yerini tutar. Kişi (ben), işaret (bu, şu), belgisiz (kimse), soru (kim), iyelik zamiri.
- **Zarf (belirteç):** Fiili, sıfatı ya da başka bir zarfı belirtir. "hızlı koştu", "çok güzel".
- **Edat:** Tek başına anlamı olmayan, ilgi kuran sözcük. "için, gibi, kadar, ile".
- **Bağlaç:** Eş görevli sözcükleri ve cümleleri bağlar. "ve, ama, fakat, çünkü, ile".
- **Ünlem:** Duygu bildirir. "Aman! Ah!"
- **Fiil (eylem):** İş, oluş, durum bildirir.

## 4. Fiil

**Kip:** Haber kipleri (bildirme): görülen geçmiş (-dı), öğrenilen geçmiş (-mış), şimdiki (-yor), gelecek (-ecek), geniş zaman (-r). **Dilek kipleri:** Gereklilik (-meli), istek (-e), emir (-sin), şart (-se).

**Kişi ekleri:** Ben, sen, o, biz, siz, onlar.

**Fiilimsiler (eylemsiler):** Fiilden türeyen ama fiil gibi çekimlenmeyen sözcüklerdir.

| Tür | Ek | Örnek |
| --- | --- | --- |
| İsim-fiil | -mak, -ma, -ış | Yürümek sağlıklıdır. |
| Sıfat-fiil (ortaç) | -an, -ası, -mış, -ecek, -dık | Çalışan öğrenci başardı. |
| Zarf-fiil (ulaç) | -ıp, -arak, -ınca, -dıkça, -meden | Koşarak geldi. |

**Ek fiil:** İsimleri yüklem yapar. "Hava güzeldi." "O öğretmen-miş."

## 5. Cümle bilgisi

**Öğeler:**

- **Yüklem:** Cümlenin yargı bildiren öğesi, genellikle sondadır.
- **Özne:** Yüklemin bildirdiği işi yapan ya da durumda olan. (Kim? Ne?)
- **Nesne:** İşten etkilenen. Belirtili nesne (Neyi? Kimi?), belirtisiz nesne (Ne?).
- **Dolaylı tümleç:** Yer-yönelme hâlleri (-e, -de, -den) ile. "Çocuk okula gitti."
- **Zarf tümleci:** Yüklemin zaman, durum, yer, miktar anlamını tamamlar.

**Cümle türleri:**

- **Yüklemine göre:** Fiil cümlesi ("Ali geldi."), isim cümlesi ("Hava güzeldi.").
- **Yapısına göre:** Basit (tek yargı), birleşik (fiilimsili, şartlı, ki'li), sıralı, bağlı.
- **Anlamına göre:** Olumlu, olumsuz, soru, ünlem, emir.
- **Yüklemin yerine göre:** Kurallı (yüklem sonda), devrik (yüklem başta ya da ortada).

## 6. Yazım ve noktalama

- **de/da, ki, mi:** Bağlaç olan "de/da" ayrı yazılır ("Ben de geldim"), ek olan bitişik ("evde"). "ki" bağlaç ayrı yazılır ("Dedi ki gel."), sıfat yapan "-ki" bitişik ("evdeki"). "mi" ayrı yazılır ("Geldi mi?").
- **Büyük harf:** Cümle başı, özel adlar, unvanlar (adın başında).
- **Noktalama:** Virgül (sıralama, ara söz), noktalı virgül, iki nokta, üç nokta, tırnak, kesme işareti (özel ada gelen ek).

## 7. Sık yapılan hatalar

- Yapım ekini çekim ekiyle karıştırmak.
- Bağlaç "de" ile ek olan "-de"yi karıştırmak.
- Fiilimsiyle fiili karıştırmak ("gelen" fiilimsidir, "geldi" fiildir).
- Özneyi her zaman cümlenin başında aramak.
- Ünsüz yumuşamasını sert ünsüzlü her sözcükte beklemek. "ot, at, top" gibi tek heceli sözcüklerde olmaz.

:::baglanti
Dil bilgisi, **anlam bilgisiyle** birlikte metin yorumunun temelidir. **Şiirde** sözcüklerin ek ve yapısı ölçü ve uyağı belirler. **Edebi sanatlarda** cümle yapısı, yineleme ve devrik cümle gibi anlatım özelliklerini belirler. **Metin türlerinde** yazarın dilini tanımak için bu bilgiler gerekir.
:::

