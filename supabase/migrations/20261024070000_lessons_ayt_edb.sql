## 1. Benzetme (teşbih)

Aralarında bir ilgi bulunan iki varlıktan **zayıf olanı güçlü olana benzetmek**. Dört öge:

- **Benzeyen:** Zayıf olan.
- **Benzetilen:** Güçlü olan.
- **Benzetme yönü:** Ortak özellik.
- **Benzetme edatı:** gibi, tek, sanki, kadar.

**Örnek:** "Gözleri deniz gibi derindi." Benzeyen: gözleri, benzetilen: deniz, yön: derin, edat: gibi.

Edat ya da yön anılmayabilir. Hem benzeyen hem benzetilen birlikte kullanılırsa **benzetme** (teşbih), yalnızca benzetilen kullanılırsa **istiare** olur.

## 2. İstiare (eğretileme)

Benzetmenin edatı ve benzeyenin ya da benzetilenin söylenmemesiyle olur.

- **Açık istiare:** Yalnızca benzetilen (güçlü) söylenir. "Aslan geldi." (cesur adam).
- **Kapalı istiare:** Yalnızca benzeyen söylenir, benzetilenin özelliği yazılır. "Rüzgâr kapının ardında ağlıyordu." (rüzgâr: insana benzetilmiş).

Kapalı istiare, kişileştirme ve konuşturmayı da kapsar.

## 3. Kişileştirme (teşhis) ve konuşturma (intak)

- **Kişileştirme:** İnsan dışındaki varlıklara insana özgü özellikler vermek. "Ağaçlar fısıldaşıyordu."
- **Konuşturma:** İnsan dışındaki varlıkları konuşturmak. "Dağ dedi ki: Ben yıllardır buradayım."

Konuşturmada kişileştirme de vardır ama kişileştirmede konuşma olmayabilir.

## 4. Abartma (mübalağa)

Bir şeyi olduğundan fazla ya da az göstermek. "O kadar güldüm ki gözlerimden akan yaşlar nehir oldu." "Bu acıyı dağlar bile taşıyamaz."

## 5. Karşıtlık (tezat)

Birbirine zıt kavramları bir arada kullanmak. "Gülerken ağlıyordu." "Aydınlık gecede karanlık düşünceler."

## 6. Ad aktarması (mecaz-ı mürsel)

Bir sözcüğün, ilişkisi olan başka bir sözcük yerine kullanılması. "Bütün şehir ayağa kalktı." (şehir: şehirdekiler). "Bir bardak içtim." (bardak: bardaktaki su). Bu sanatta **benzetme ilgisi değil**, yakınlık ve ilişki vardır.

## 7. Kinaye

Sözcüğün hem gerçek hem de mecaz anlamının aynı anda geçerli olduğu, ama asıl niyetin mecaz olduğu anlatım. "Eli açık biri." (hem eli açık, hem cömert).

## 8. Divan edebiyatında sık geçen sanatlar

- **Tenasüp:** Aralarında anlam ilgisi olan sözcüklerin bir arada kullanılması. (gül, bülbül, diken, bahar).
- **Hüsnütalil:** Bir olayın gerçek nedeni yerine, güzel ve şiirsel bir neden göstermek. "Sabah güneş doğdu, çünkü sevgilim uyandı."
- **Telmih:** Bilinen bir olay ya da kişiye değinmek. "Yusuf'un güzelliği ..."
- **Tevriye:** Bir sözcüğün hem yakın hem uzak anlamıyla kullanılması, uzak anlamının kastedilmesi.
- **Cinas:** Yazılışı ve söylenişi aynı, anlamı farklı sözcükleri aynı dizede kullanmak. "Yüz yüze gelince yüzü kızardı."
- **Leff ü neşr:** Önce birkaç unsuru sıralayıp sonra onlarla ilgili başka unsurları aynı sırayla söylemek.
- **Nida (seslenme):** Bir kişiye ya da varlığa seslenme. "Ey gönül!"
- **Tariz:** Alay, iğneleme (iyi gibi söyleyip kötü anlatma).

## 9. Sık yapılan hatalar

- Benzetme ile istiareyi karıştırmak. Benzetmede iki taraf da vardır.
- Kişileştirme ile konuşturmayı karıştırmak. Konuşturmada konuşma vardır.
- Ad aktarmasını benzetme sanmak. Ad aktarması ilişkiye dayanır.
- Abartmayı yalnızca büyütme sanmak. Küçültme de abartmadır ("Karıncadan küçüktü").
- Karşıtlığı zıt sözcüğün geçtiği her yerde aramak. İki zıt kavramın birlikte anlam kazandığı yerde vardır.

:::baglanti
Edebi sanatlar, **şiir bilgisi** ile birlikte bir şiirin yorumunu oluşturur. **Anlam bilgisindeki** mecaz ve deyimler, bu sanatların temelidir. **Divan edebiyatı** tenasüp, hüsnütalil, telmih gibi sanatlarla zengindir. **Halk edebiyatında** benzetme ve abartma yaygındır. **Tanzimat sonrası** edebiyatında kişileştirme ve imge öne çıkar.
:::

