| Dönem | 1896-1901 | 1909-1912 |
| İlke | Sanat sanat içindir | Sanat şahsi ve muhteremdir |
| Etki | Fransız edebiyatı | Fransız edebiyatı (sembolizm) |
| Dil | Ağır | Ağır |
| Bireysellik | Var | Var |
| Etkisi | Roman, öykü, şiir | Özellikle şiir (Ahmet Haşim) |

