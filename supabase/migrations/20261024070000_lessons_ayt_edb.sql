## 3. Sanatçılar ve eserleri

**Ahmet Haşim (1884-1933):**

- Türk şiirinin **sembolist** şairidir. Şiirde **müzikalite**, imge ve sezgi ön plandadır. Anlam bulanık, ses ve renk öne çıkar. Konuları: Gece, göl, akşam, ölüm, sevgili.
- **Eserleri:** **Göl Saatleri** (1921, şiir), **Piyale** (1926, şiir). Nesir: **Gurebahane-i Laklakan** (1928, fıkra ve denemeler), **Bize Göre**, **Frankfurt Seyahatnamesi**.
- Şiirleri aruz ölçülüdür ama serbest ve ses ağırlıklıdır. Şiirleri kapalıdır.

**Yakup Kadri Karaosmanoğlu (1889-1974):**

- Romancı ve düşünür. Eserleri: **Kiralık Konak** (1922), **Nur Baba** (1922), **Sodom ve Gomore** (1928), **Yaban** (1932, Anadolu'ya ve köylüye yabancılaşan aydın), **Ankara** (1934).
- Fecr-i Ati'den sonra Milli Edebiyat ve Cumhuriyet dönemine geçti.

**Refik Halit Karay (1888-1965):**

- Öykü ve romanda yerli yaşamı, mizahı işledi. **Memleket Hikâyeleri** (1919), **İstanbul'un Bir Yüzü**, **Sürgün**, **Çete**. Sürgün yıllarındaki yaşantıları anlattı.

**Diğerleri:** **Emin Bülent Serdaroğlu**, **Cemil Süleyman Bey**, **Müfide Ferit Tek** (ilk kadın yazarlarımızdan, Aydemir romanı), **Celal Sahir Erozan** (şair), **Tahsin Nahit**.

## 4. Sık yapılan hatalar

- Fecr-i Ati'yi Servet-i Fünun'dan önce sanmak. Fecr-i Ati daha sonradır (1909).
- "Sanat şahsi ve muhteremdir" ilkesini Servet-i Fünun'a vermek.
- Ahmet Haşim'in şiirini sade ve açık sanmak. Haşim kapalı ve sembolisttir.
- Yaban romanını Refik Halit'e vermek. Yakup Kadri'nindir.
- Topluluğun uzun süre var olduğunu sanmak. Üç yıl sürdü.

:::baglanti
Fecr-i Ati, **Servet-i Fünun'un** devamıdır ve **Milli Edebiyat'a** karşı kalmıştır. **Edebi akımlar** konusunda sembolizm Ahmet Haşim'le Türk şiirine girdi. **Cumhuriyet dönemi** romanında Yakup Kadri ve Refik Halit'in eserleri toplumu işledi. **Şiir bilgisi** konusundaki aruz ölçüsü ve imge, Haşim'in şiirini anlamak için gereklidir.
:::

