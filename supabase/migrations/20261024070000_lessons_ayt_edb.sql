## 1. Antik Yunan ve Roma

**Antik Yunan (MÖ 8. yy sonrası):**

- **Homeros:** **İlyada** (Truva Savaşı), **Odysseia** (Odysseus'un dönüş yolculuğu). Epik şiir.
- **Hesiodos:** Tanrıların Doğuşu.
- **Tiyatro (trajedi):** **Aiskhylos** (Zincire Vurulmuş Prometheus), **Sophokles** (Kral Oidipus, Antigone), **Euripides** (Medea).
- **Komedi:** **Aristophanes** (Kuşlar, Kurbağalar).
- **Aristoteles:** **Poetika** (Şiir Sanatı), edebiyat kuramının kaynağı. Trajedi tanımı ve "katharsis" kavramı.

**Roma:** **Vergilius** (Aeneis), **Ovidius** (Dönüşümler), **Horatius** (şiir sanatı), **Plautus** (komedi).

## 2. Orta Çağ ve Rönesans

- **Dante Alighieri (1265-1321):** **İlahi Komedya** (Cehennem, Araf, Cennet). İtalyan Rönesansının habercisi.
- **Petrarca:** **Canzoniere** (Sone biçiminin ustası). **Boccaccio:** **Decameron** (Dekameron, Rönesans'ın ilk öyküleri).
- **Chaucer:** **Canterbury Hikâyeleri** (İngiliz).
- **Rönesans:** **Cervantes** (İspanya): **Don Kişot** (1605, ilk modern roman). **Rabelais** (Gargantua ve Pantagruel). **Shakespeare** (İngiliz, 1564-1616): **Hamlet**, **Macbeth**, **Othello**, **Kral Lear** (trajedi), **Romeo ve Juliet**, **Yaz Gecesi Rüyası**, **Venedik Taciri** (komedi).

## 3. 17. ve 18. yüzyıl

- **Klasisizm (Fransa):** **Molière** (Cimri, Tartuffe, Hastalık Hastası), **Racine** (Phèdre), **Corneille** (Le Cid), **La Fontaine** (Fabllar).
- **Aydınlanma:** **Voltaire** (Candide), **Montesquieu** (Kanunların Ruhu), **Rousseau** (İtiraflar), **Diderot**.
- **Almanya:** **Goethe** (Faust, Genç Werther'in Acıları), **Schiller** (Haydutlar).
- **İngiltere:** **Daniel Defoe** (Robinson Crusoe), **Jonathan Swift** (Gulliver'in Gezileri).

## 4. 19. yüzyıl

**Romantizm:** **Victor Hugo** (Sefiller, Notre Dame'ın Kamburu), **Lamartine**, **Byron**, **Puşkin** (Yevgeni Onegin), **Walter Scott**.

**Realizm:** **Balzac** (İnsanlık Komedyası, Goriot Baba), **Stendhal** (Kırmızı ve Siyah), **Flaubert** (Madame Bovary), **Charles Dickens** (Oliver Twist, Büyük Umutlar), **Tolstoy** (Savaş ve Barış, Anna Karenina), **Dostoyevski** (Suç ve Ceza, Karamazov Kardeşler, Budala), **Gogol** (Ölü Canlar, Palto), **Çehov** (Vişne Bahçesi, öykü).

**Natüralizm:** **Zola** (Germinal, Nana), **Maupassant** (Bir Hayat, öyküler).

**Sembolizm:** **Baudelaire** (Kötülük Çiçekleri), **Verlaine**, **Rimbaud**, **Mallarmé**.

**Tiyatro:** **Ibsen** (Bir Bebek Evi), **Çehov**.

## 5. 20. yüzyıl

- **Franz Kafka:** **Dönüşüm**, **Dava**, **Şato**. Yabancılaşma ve ezilmişlik.
- **Marcel Proust:** **Kayıp Zamanın İzinde**. **James Joyce:** **Ulysses**. Bilinç akışı.
- **Thomas Mann:** **Büyülü Dağ**. **Hermann Hesse:** **Bozkırkurdu**.
- **Albert Camus:** **Yabancı**, **Veba**. **Jean-Paul Sartre:** **Bulantı**. Varoluşçuluk.
- **George Orwell:** **1984**, **Hayvan Çiftliği**. **Aldous Huxley:** **Cesur Yeni Dünya**.
- **Ernest Hemingway:** **Yaşlı Adam ve Deniz**, **Çanlar Kimin İçin Çalıyor**.
- **William Faulkner:** **Ses ve Öfke**. **John Steinbeck:** **Gazap Üzümleri**.
- **Gabriel García Márquez:** **Yüzyıllık Yalnızlık** (büyülü gerçekçilik).
- **Samuel Beckett:** **Godot'yu Beklerken**. **Eugène Ionesco:** **Gergedan** (absürt tiyatro).
- **Maksim Gorki:** **Ana** (sosyalist gerçekçilik). **Mihail Şolohov:** **Don Sessiz Akar**.

## 6. Sık yapılan hatalar

- Cervantes'i İtalyan, Dante'yi İspanyol sanmak.
- Shakespeare'in eserlerini Molière'e vermek.
- Dostoyevski ile Tolstoy'un eserlerini karıştırmak.
- Kafka'yı gerçekçi, Camus'yü romantik sanmak.
- Balzac'ı romantik, Hugo'yu realist sanmak.

