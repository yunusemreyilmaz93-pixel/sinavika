## 1. Sözcükte anlam

- **Gerçek anlam:** Sözcüğün akla gelen ilk, temel anlamıdır. "Taş yola düştü." (taş: gerçek taş)
- **Yan anlam:** Gerçek anlamla ilişkili ikinci anlamdır. "Çocuğun ayağı yaralandı." (gerçek) "Masanın ayağı kırıldı." (yan anlam)
- **Mecaz anlam:** Sözcüğün benzetme ya da ilişkiyle kazandığı anlamdır. "Taş" gibi bir adam. "Ağır" laf etmek.
- **Terim anlam:** Bir bilim, sanat ya da meslek dalına özgü anlamdır ve tek anlamlıdır. "Elmas" (kimya), "fiil" (dil bilgisi), "kök" (matematik).
- **Ad aktarması:** Bir adın başka bir varlığa aktarılmasıdır. "Bütün köy toplandı." (köy: köylüler) "Bir tabak yedi." (tabak: tabaktaki yemek)

Bir sözcüğün mecaz mı yan anlamlı mı olduğunu anlamak için **cümledeki kullanıma** bak. Yan anlam sözlükte ayrı madde olarak yer alır, mecaz ise cümlede o an ortaya çıkar.

## 2. Sözcükler arası anlam ilişkisi

| İlişki | Açıklama | Örnek |
| --- | --- | --- |
| Eş anlamlı | Anlamca aynı, yazılışça farklı | Okul, mektep / Öğretmen, muallim |
| Yakın anlamlı | Anlamları birbirine yakın | Korkmak, ürkmek |
| Zıt anlamlı | Anlamca tersi | Soğuk, sıcak |
| Eş sesli | Yazılış ve okunuş aynı, anlamı farklı | Yüz (sayı, surat, yüzmek) |

**Deyim:** Gerçek anlamından uzaklaşmış kalıplaşmış söz öbeğidir ("göz boyamak", "kulak asmak"). **Atasözü:** Genel doğruları öğüt verir biçimde anlatan kalıplaşmış cümledir ("Damlaya damlaya göl olur"). Atasözleri **yargı bildirir**, deyimler yargı bildirmez.

## 3. Cümlede anlam

**Neden-sonuç:** Bir olayın nedenini ve sonucunu birlikte verir. "Yağmur yağdığı için maç ertelendi."

**Amaç-sonuç:** Bir eylemin amacını ve sonucunu verir. "Sınavı kazanmak için gece gündüz çalıştı."

**Koşul (şart):** Bir olayın gerçekleşmesi başka bir olaya bağlıdır. "Çok çalışırsan sınavı kazanırsın."

**Karşılaştırma:** İki ya da daha çok varlığı benzerlik ya da farklılık açısından ele alır. "Ali, Veli'den daha çalışkandır."

**Örnekleme:** Bir düşünceyi örnekle destekler. **Tanımlama:** Bir kavramı "nedir" sorusuna cevap verecek biçimde açıklar.

**Öznel yargı:** Kişiden kişiye değişir, kanıtlanamaz ("Bu film çok sıkıcı"). **Nesnel yargı:** Herkes için aynıdır, kanıtlanabilir ("Su $100^\circ\text{C}$'de kaynar").

**Dolaylı anlatım:** Bir sözü, söyleyen kişiden sonra aktarma yoludur. "Öğretmen, ödevin yarına verileceğini söyledi."

## 4. Paragrafta anlam

**Paragrafın yapısı:** Giriş (konu tanıtılır), gelişme (düşünce geliştirilir), sonuç (ana düşünce).

- **Konu:** Parçanın "neyi" anlattığı.
- **Ana düşünce (ana fikir):** Yazarın okura vermek istediği temel mesaj.
- **Yardımcı düşünce:** Ana düşünceyi destekleyen ikinci derecede düşünceler.

**Düşünceyi geliştirme yolları:**

- **Tanımlama:** "Bilim insanı, doğadaki olayları gözlemleyen, aralarındaki ilişkiyi araştıran kişidir."
- **Karşılaştırma:** İki şey arasındaki benzerlik ve farklar.
- **Örneklendirme:** "Mesela, Fatih Sultan Mehmet, İstanbul'u fethederek..."
- **Tanık gösterme:** Bilinen birinin sözüne başvurma. "Mevlana'nın dediği gibi..."
- **Sayısal verilerden yararlanma:** "Dünya nüfusunun yaklaşık yüzde yetmişi..."
- **Neden-sonuç, benzetme.**

**Anlatım biçimleri:** Öyküleyici (olay anlatır), betimleyici (görünüş anlatır), açıklayıcı (bilgi verir), tartışmacı (düşünceyi savunur).

## 5. Sık yapılan hatalar

- Mecaz ile yan anlamı karıştırmak.
- Deyimle atasözünü karıştırmak. Atasözü bir yargı bildirir.
- Ana düşünceyi parçadaki bir ayrıntı sanmak.
- "Amaç" ile "neden" farkını atlamak. Amaç ileriye, neden geriye bakar.
- Seçenekte parçanın söylemediği ama doğru olan bir bilgiyi seçmek. Cevap parçadan çıkmalıdır.

:::baglanti
Anlam bilgisi, **dil bilgisi** ve **metin türleri** için temeldir. **Şiir ve edebi sanatlarda** mecaz ve söz sanatları anlamı derinleştirir. **Edebiyat tarihi sorularında** verilen metinden çıkarım yapmak için paragraf yorumu gerekir. Aynı beceri **sosyal bilimler** sorularındaki metinleri anlamak için de kullanılır.
:::

