## 1. Nazım birimleri

- **Dize (mısra):** Şiirin her bir satırı.
- **Beyit:** İki dizelik birim. Divan şiirinin birimi.
- **Bent (kıta, dörtlük):** Dörder dizelik birim. Halk şiiri ve yeni şiirin birimi.
- **Manzume:** Bütün olarak şiir. **Nazım:** Şiirin biçimi, **nesir:** düzyazı.

## 2. Ölçü

**Hece ölçüsü:** Dizelerdeki hece sayısının eşit olmasıdır. Halk şiirinin ölçüsüdür. Dizeler **duraklarla** bölünür.

| Kalıp | Duraklar | Kullanıldığı nazım biçimleri |
| --- | --- | --- |
| 7'li | $4+3$ ya da $3+4$ | Mani, bazı türküler |
| 8'li | $4+4$ | Semai |
| 11'li | $6+5$ ya da $4+4+3$ | Koşma, destan |

Sayarken: "Bir ses gelir uzaklardan" $\rightarrow$ Bir(1) ses(2) ge-lir(4) u-zak-lar-dan(8) $=8$ hece.

::sim{tur="hece"}

**Aruz ölçüsü:** Hecelerin **açık-kapalı** (kısa-uzun) oluşuna dayanır. Açık hece (ünlüyle biten, kısa), kapalı hece (ünsüzle biten, uzun). Kalıplar ("fâilâtün, mefâilün" gibi) Arapçadan gelir. Divan edebiyatının ölçüsüdür. Tanzimat'tan sonra bile bir süre kullanılmıştır.

**Serbest ölçü:** Belirli bir ölçü kuralı yoktur. Dizelerin uzunluğu şaire göre değişir. Yeni şiirde (Garip akımı, serbest nazım) yaygındır.

## 3. Uyak (kafiye) ve redif

**Uyak:** Dize sonlarındaki ses benzerliğidir.

- **Yarım uyak:** Tek ses benzerliği ("göz-yüz").
- **Tam uyak:** Ünlü ve ünsüz benzerliği ("kol-yol", "can-yan").
- **Zengin uyak:** En az üç sesin benzerliği ("bağlı-dağlı").
- **Cinaslı uyak:** Yazılışları aynı, anlamları farklı sözcüklerle ("yüz-yüz": sayı ve surat).

**Redif (ek):** Uyaktan sonra gelen ve aynen tekrarlanan sözcük ya da eklerdir. "Gönül" sözcüğünün her dizede tekrar etmesi gibi.

**Uyak düzenleri:**

| Düzen | Şema | Açıklama |
| --- | --- | --- |
| Düz | aaaa | Hepsi uyaklı |
| Çapraz | abab | 1-3 ve 2-4 |
| Sarmal | abba | 1-4 ve 2-3 |
| Mani | aaba | 1-2-4 |
| Koşma | aaab cccb | Dördüncü dize ortak |

![Uyak düzenleri: düz, çapraz, sarmal, mani ve koşma](/lessons/ayt-edb/uyak-duzenleri.svg "Aynı harf uyaklı dizeleri gösterir")

## 4. Nazım biçimleri

**Halk edebiyatı:**

- **Koşma:** 11'li, genelde üç-beş dörtlük, uyak düzeni aaab cccb ya da abab cccb, son bentte mahlas, saz eşliği, konular aşk, doğa, ayrılık.
- **Semai:** 8'li hece ölçüsü, koşma gibi uyaklı.
- **Mani:** 7'li, tek dörtlük, aaba.
- **Destan:** Olayları anlatır, 11'li.
- **Türkü:** Halkın anonim ürünü, ezgiyle söylenir.

**Divan edebiyatı (beyit esaslı):**

- **Gazel:** 5-15 beyit, aa ba ca da, ilk beyit matla, son beyit makta (şair mahlasını anar), aşk, şarap konulu.
- **Kaside:** 33-99 beyit, aa ba ca, övgü amaçlı.
- **Mesnevi:** Her beyit kendi içinde uyaklı (aa bb cc), uzun hikâye anlatır.
- **Rubai:** Dörtlük, aaxa.
- **Murabba, muhammes, müstezat:** Bentli nazım biçimleri.

**Batı etkisiyle:** Sone (14 dize, 4+4+3+3), serbest müstezat, serbest şiir.

## 5. Şiir türleri

- **Lirik:** Duygu ve coşku (aşk, ölüm, doğa, özlem).
- **Epik:** Kahramanlık, savaş anlatımı (destan).
- **Pastoral:** Çoban ve doğa yaşamı.
- **Didaktik (öğretici):** Bilgi ve öğüt verir.
- **Satirik:** Aksayan yönleri eleştirir.
- **Dramatik:** Tiyatro ve olay merkezli, diyalogla.

## 6. Sık yapılan hatalar

- Hece sayarken ünsüzleri saymak. Yalnızca ünlüler sayılır.
- Redifi uyakla karıştırmak. Redif tekrarlanan sözcüktür.
- Gazel ile kasideyi karıştırmak. Gazelde 5-15, kasidede 33-99 beyit vardır.
- Koşma ile semaiyi karıştırmak. Koşma 11'li, semai 8'lidir.
- Beyiti dörtlük sanmak. Beyit iki dizedir.

:::baglanti
Şiir bilgisi, **edebi sanatlar** ve **edebiyat tarihi** için temeldir. Halk edebiyatında hece ölçüsü ve koşma, **Divan edebiyatında** aruz ölçüsü ve gazel öne çıkar. **Tanzimat** ile birlikte Batı etkisi gelir (sone, serbest nazım). **Dil bilgisinde** hece ve ses olayları, ölçü ve uyak hesaplarını belirler.
:::

