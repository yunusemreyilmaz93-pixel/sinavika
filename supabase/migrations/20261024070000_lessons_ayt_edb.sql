- Anı ile günlüğü karıştırmak. Günlük tarihle yazılır.
- Biyografi ile otobiyografiyi karıştırmak.
- Dram ile trajediyi aynı sanmak. Trajede sonu ölümle biten ciddi bir oyundur.
- Romanla öyküyü yalnızca uzunluğa göre ayırmak. Olay örgüsü, kişi ve mekân çokluğu da farktır.

:::baglanti
Metin türleri, **anlam bilgisi ve dil bilgisiyle** birlikte metin analizinin temelidir. **Edebiyat tarihinde** her dönemin tercih ettiği türler vardır. Tanzimat'ta gazete aracılığıyla makale, fıkra ve gezi yazısı gelişti. Servet-i Fünun'da roman ve öykü gelişti. **Tiyatro** geleneksel Türk tiyatrosundan Batı tarzı tiyatroya geçişle Tanzimat'ta yeni bir yön kazandı.
:::

