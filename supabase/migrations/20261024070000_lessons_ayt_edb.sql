- Yahya Kemal'in serbest nazım kullandığını sanmak. Aruzla yazdı.
- Yaşar Kemal ile Orhan Kemal'i karıştırmak. İnce Memed Yaşar Kemal'in, Bereketli Topraklar Üzerinde Orhan Kemal'in.
- Huzur'u Peyami Safa'ya vermek. Tanpınar'ındır.

