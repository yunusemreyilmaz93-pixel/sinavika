## 1. Genel özellikler

- Cumhuriyetin ilanıyla birlikte **Atatürk ilke ve inkılapları** edebiyatın konusu oldu (Milli Mücadele, Anadolu, köy, kentleşme, modernleşme).
- **Dil:** Sadeleşme, Türkçeleşme. Harf devrimi (1928), Dil Devrimi (1932, Türk Dil Kurumu).
- **Tür:** Roman, öykü, tiyatro, şiir, deneme, eleştiri.
- **Yönelişler:** Milli konular, toplumcu gerçekçilik, bireysel ve psikolojik anlatım, modernizm.

## 2. Şiir

**Milli Edebiyat geleneğini sürdürenler:** **Beş Hececiler** (Faruk Nafiz, Yusuf Ziya, Orhan Seyfi, Enis Behiç, Halit Fahri), **Yahya Kemal Beyatlı**.

**Yahya Kemal Beyatlı (1884-1958):** Aruz ölçüsünü Türkçeye ustalıkla uyguladı. Tarih, İstanbul, Türk kültürü. Parnasizm ve sembolizmden etkilendi. Eserleri: **Kendi Gök Kubbemiz** (1961), **Eski Şiirin Rüzgârıyla** (1962), **Sessiz Gemi** (şiir), **Aziz İstanbul**. "Sanat sanat içindir" anlayışına bağlıdır.

**Yedi Meşaleciler (1928):** **Ziya Osman Saba**, **Sabri Esat Siyavuşgil**, **Muammer Lütfi Bahşi**, **Cevdet Kudret Solok**, **Kenan Hulusi Koray**, **Vasfi Mahir Kocatürk**, **Yaşar Nabi Nayır**. Hece ve serbest ölçü, bireysel şiir, ortak bir akım olmaktan çok bir topluluk.

**Ahmet Haşim, Ahmet Hamdi Tanpınar, Cahit Sıtkı Tarancı, Ahmet Muhip Dıranas:** Bireysel şiir çizgisi. **Cahit Sıtkı:** "Otuz Beş Yaş" şiiri.

**Nâzım Hikmet (1902-1963):** **Serbest nazmın** ve **toplumcu gerçekçi şiirin** öncüsü. Şiirde dize düzenini ve sesi yeniden kurdu. Eserleri: **Simavne Kadısıoğlu Şeyh Bedreddin Destanı**, **Kuvayi Milliye Destanı**, **Memleketimden İnsan Manzaraları**, **Yatar Bursa Kalesinde**.

**Garip Hareketi (1941):** **Orhan Veli Kanık**, **Oktay Rifat**, **Melih Cevdet Anday**. "Garip" kitabı. Şiirden ölçü, uyak ve söz sanatlarını çıkardılar. Konuları gündelik yaşamdan, **sıradan insan**. Dil günlük konuşma dili. Orhan Veli'nin şiirleri: **Garip, Vazgeçemediğim, Destan Gibi, Yenisi, Karşı**.

**İkinci Yeni (1950'ler):** **Cemal Süreya**, **Edip Cansever**, **İlhan Berk**, **Turgut Uyar**, **Sezai Karakoç**, **Ece Ayhan**, **Ülkü Tamer**. Garip'e tepki. Şiirde **imge, ses, kapalılık**. Anlam arka plandadır, söyleyiş ve çağrışım önemlidir. Cemal Süreya'nın **Üvercinka**, Edip Cansever'in **Dirlik Düzenlik**, Turgut Uyar'ın **Dünyanın En Güzel Arabistanı** eserlerindendir.

**Toplumcu gerçekçi şiir:** **Nâzım Hikmet**, **Ahmed Arif** (Hasretinden Prangalar Eskittim, 1968), **Attila İlhan**.

## 3. Roman ve öykü

**Toplumcu gerçekçilik:** Köy ve kent yaşamının sorunlarını, toplumsal adaletsizlikleri işler.

- **Orhan Kemal:** **Bereketli Topraklar Üzerinde** (1954), **Baba Evi**.
- **Yaşar Kemal:** **İnce Memed** (1955), **Yılanı Öldürseler**.
- **Kemal Tahir:** **Devlet Ana**, **Esir Şehrin İnsanları**.
- **Aziz Nesin:** Hiciv ve mizah. **Zübük**, **Yaşar Ne Yaşar Ne Yaşamaz**.
- **Sabahattin Ali:** **Kuyucaklı Yusuf**, **İçimizdeki Şeytan**, **Kürk Mantolu Madonna** (1943).
- **Fakir Baykurt, Talip Apaydın:** Köy Enstitüleri çıkışlı yazarlar. **Yılanların Öcü** (Fakir Baykurt).
- **Memduh Şevket Esendal:** **Ayaşlı ile Kiracıları**.

**Bireysel, psikolojik ve modernist anlatım:**

- **Peyami Safa:** **Dokuzuncu Hariciye Koğuşu**, **Fatih-Harbiye**.
- **Ahmet Hamdi Tanpınar:** **Huzur** (1949), **Saatleri Ayarlama Enstitüsü** (1961), **Beş Şehir**.
- **Sait Faik Abasıyanık:** **Semaver**, **Alemdağ'da Var Bir Yılan**. Olay yerine **an** ve duygu. Çok yönlü öykü.
- **Oğuz Atay:** **Tutunamayanlar** (1971-72), **Bir Bilim Adamının Romanı**. Türk romanının modernist ustası.
- **Yusuf Atılgan:** **Aylak Adam**, **Anayurt Oteli**.
- **Adalet Ağaoğlu:** **Ölmeye Yatmak** (1973).

## 4. Tiyatro

**Haldun Taner**, **Necati Cumalı**, **Orhan Asena** (Hürrem Sultan), **Turgut Özakman** (Şu Çılgın Türkler), **Cevat Fehmi Başkut**. Aziz Nesin'in oyunları da hiciv geleneğini sürdürür.

