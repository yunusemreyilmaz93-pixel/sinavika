## 1. Klasisizm (Kalasizm)

- **17. yüzyıl**, Fransa (XIV. Louis dönemi).
- **Akıl, kural, düzen, denge.** Eski Yunan ve Roma örnek alınır.
- **Üç birlik kuralı** (tiyatroda): Yer birliği, zaman birliği (bir gün), olay birliği.
- Trajedi ve komedi **ayrı** tutulur, karıştırılmaz. Evrensel insan tipi.
- **Temsilciler:** Corneille, Racine (trajedi), Molière (komedi: Cimri, Tartuffe), Boileau (şiir sanatı).
- **Türk edebiyatı:** Klasisizm etkisi görülmez (Divan edebiyatının kuralcılığı benzer).

## 2. Romantizm

- **18. yüzyıl sonu ve 19. yüzyıl**, Almanya ve Fransa. Klasisizme **tepki**.
- **Duygu, hayal, özgürlük, bireysellik**. Doğa sevgisi, geçmişe (ortaçağ) özlem, milliyetçilik.
- Kurallardan kurtulma. Trajedi ile komedi **karıştırılır** (dram). Aşk, ölüm, vatan.
- **Temsilciler:** Victor Hugo (Sefiller, Notre Dame'ın Kamburu), Lamartine, Alfred de Musset, Goethe (Faust, Genç Werther'in Acıları), Schiller, Byron, Puşkin.
- **Türk edebiyatı:** Namık Kemal, Abdülhak Hamit (Tanzimat).

## 3. Realizm (Gerçekçilik)

- **19. yüzyıl ortası**, Fransa. Romantizme tepki.
- **Gerçeği olduğu gibi** yansıtma. Gözlem, sıradan insan, toplum. Nesnellik, ayrıntı, çevre betimlemesi.
- **Temsilciler:** **Balzac** (İnsanlık Komedyası, Goriot Baba), **Stendhal** (Kırmızı ve Siyah), **Flaubert** (Madame Bovary), Dickens (Oliver Twist), Tolstoy (Anna Karenina, Savaş ve Barış), Dostoyevski (Suç ve Ceza).
- **Türk edebiyatı:** Recaizade Mahmut Ekrem (Araba Sevdası), Halit Ziya (Mai ve Siyah), Samipaşazade Sezai.

## 4. Natüralizm (Doğalcılık)

- **19. yüzyıl sonu**. Realizmin ileri biçimi.
- **Bilimsel yöntem**: Deney ve gözlem. **Kalıtım ve çevre** insanı belirler. Çirkin ve acı yönler de işlenir. Edebiyatta "deney romanı".
- **Temsilci:** **Émile Zola** (Germinal, Nana), Maupassant, Daudet.
- **Türk edebiyatı:** Nabizade Nazım (Karabibik, Zehra).

## 5. Parnasizm ve Sembolizm

**Parnasizm:** 19. yüzyıl ortası. **"Sanat sanat içindir."** Biçim, sağlam ve kusursuz dil, nesnellik, duygularını saklama. **Temsilciler:** Théophile Gautier, Leconte de Lisle, Heredia. **Türk edebiyatı:** Servet-i Fünun şiiri (Cenap Şahabettin, Tevfik Fikret).

**Sembolizm:** 19. yüzyıl sonu. Duyguyu ve düşünceyi **doğrudan anlatmak yerine sembollerle, imgelerle ve müzikle** sezdirme. Şiirde **müzikalite**, kapalılık, çağrışım. **Temsilciler:** **Baudelaire** (Kötülük Çiçekleri), Verlaine, Rimbaud, Mallarmé. **Türk edebiyatı:** Ahmet Haşim, Cenap Şahabettin.

## 6. 20. yüzyıl akımları

- **Empresyonizm (izlenimcilik):** Nesneleri olduğu gibi değil, **bırakılan izlenimi** anlatır. Işık ve renk. (Resim kaynaklı, şiire geçti.)
- **Ekspresyonizm (dışavurumculuk):** Duyguların ve iç gerilimin **şiddetle** dışa vurulması. (Kafka, Trakl.)
- **Fütürizm (gelecekçilik):** Geçmişi reddedip makineyi, hızı ve geleceği över. **Marinetti** (İtalya).
- **Dadaizm:** Her türlü kuralı, mantığı, geleneği reddeder. Anlamsızlık, tepki. **Tristan Tzara**.
- **Sürrealizm (gerçeküstücülük):** Bilinçaltı, rüya, otomatik yazı. **André Breton** (Manifesto, 1924), Paul Éluard. **Türk edebiyatı:** Ece Ayhan, İkinci Yeni'nin bir kısmı.
- **Egzistansiyalizm (varoluşçuluk):** Birey özgürdür ve kendi varlığını kendisi yaratır. Sorumluluk, yabancılaşma, kaygı. **Jean-Paul Sartre** (Bulantı), **Albert Camus** (Yabancı, Veba, Sisifos Söyleni), Simone de Beauvoir.
- **Absürdizm (saçmanın tiyatrosu):** Hayatın ve insan durumunun saçmalığı. **Samuel Beckett** (Godot'yu Beklerken), **Eugène Ionesco** (Gergedan).

## 7. Sık yapılan hatalar

- Realizm ile natüralizmi aynı sanmak. Natüralizm bilimsel, deneysel ve kalıtım temellidir.
- Romantizmi klasisizmin devamı sanmak. Tepkidir.
- Parnasizm ile sembolizmi karıştırmak. Parnasizm biçimsel kusursuzluğa, sembolizm sezdirmeye dayanır.
- Sürrealizm ile dadaizmi karıştırmak. Sürrealizm bilinçaltına, dadaizm kuralları reddetmeye dayanır.
- Türk edebiyatındaki örnekleri karıştırmak: Karabibik natüralizm, Araba Sevdası realizm.

:::baglanti
Edebi akımlar, **edebiyat tarihi konularını** (Tanzimat, Servet-i Fünun, Fecr-i Ati) anlamak için temeldir. **Dünya edebiyatı** konusunda her akımın eser ve yazarları ayrıntılı işlenir. **Felsefe** konusundaki akıl, duygu, varoluşçuluk tartışmaları bu akımlarla bağlantılıdır. **Edebi sanatlar** (imge, sembol) sembolizm ve sürrealizmin temel araçlarıdır.
:::

