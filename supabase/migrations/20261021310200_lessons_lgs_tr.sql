LGS Türkçe’de soruların en büyük bölümü paragraf sorusudur. Paragraf okumak, “metni okuyup anlamak” ve **yazarın ne demek istediğini yakalamak** demektir. Bu konuda paragrafın ana düşüncesini, konusunu ve yardımcı düşüncelerini bulmayı, yazarın kullandığı anlatım biçimlerini ve düşünceyi geliştirme yollarını öğreneceksin.

:::hedefler
1. Paragrafın konusunu, ana düşüncesini ve yardımcı düşüncelerini bulmak.
2. Paragrafın yapısını (giriş, gelişme, sonuç) ve cümleler arasındaki bağı yorumlamak.
3. Anlatım biçimlerini (öyküleme, betimleme, açıklama, tartışma) ayırt etmek.
4. Düşünceyi geliştirme yollarını (tanımlama, örnekleme, karşılaştırma, benzetme, tanık gösterme, sayısal veri) tanımak.
:::

:::ipucu
Paragraf sorusuna **önce soruyu, sonra paragrafı** oku. Soru kökü (“ana düşünce”, “anlatım biçimi”, “ulaşılamaz”) paragrafı hangi gözle okuyacağını belirler. Metni bir kere iyi oku, seçeneklere geçmeden önce kendi cümlenle özetle.
:::

## 1. Paragraf nedir?

**Paragraf**, bir düşünceyi ya da duyguyu bütünlük içinde anlatan, birbiriyle bağlantılı cümlelerden oluşan **anlam bütünlüğü olan** yazı parçasıdır. Paragraf satır başı ile başlar.

Bir paragrafta genellikle şu bölümler vardır.

- **Giriş:** Konuyu ya da düşünceyi ortaya koyan cümle ya da cümleler.
- **Gelişme:** Düşüncenin açıklandığı, desteklendiği ve örneklendiği kısım.
- **Sonuç:** Düşüncenin toparlandığı, vurgulandığı kısım.

## 2. Konu, ana düşünce, yardımcı düşünce

**Konu:** Paragrafta **ne anlatıldığıdır**. “Sporun faydaları”, “Ormanların korunması” gibi. Konu kısa bir ad ya da tamlamadır.

**Ana düşünce:** Yazarın **okuyucuya vermek istediği asıl mesajdır**. Bir cümleyle ifade edilir. “Düzenli spor sağlıklı bir yaşamın temelidir.” gibi.

**Yardımcı düşünce:** Ana düşünceyi destekleyen, açıklayan, örnekleyen fikirlerdir. Bir paragrafta birden fazla olabilir.

| Kavram | Soruları | Örnek (spor paragrafı için) |
| --- | --- | --- |
| Konu | Ne anlatılıyor? | Sporun faydaları |
| Ana düşünce | Yazar ne demek istiyor? | Düzenli spor sağlıklı yaşamın temelidir. |
| Yardımcı düşünce | Ana fikri nasıl destekliyor? | Spor kasları güçlendirir, stresi azaltır. |
| Başlık | Paragrafa uygun ad? | “Spor ve Sağlık” |

**Örnek paragraf:**

> Düzenli spor yapmak, vücudu güçlendirmenin yanı sıra zihni de dinç tutar. Bir saatlik yürüyüş bile stresi azaltır, uykuyu düzenler. Bu nedenle sporu yaşamımızın bir parçası hâline getirmeliyiz.

- **Konu:** Sporun faydaları.
- **Ana düşünce:** Spor yaşamın bir parçası olmalıdır (yazar bu sonuca varıyor).
- **Yardımcı düşünceler:** Spor vücudu güçlendirir, zihni dinç tutar, stresi azaltır, uykuyu düzenler.

:::baglanti
Ana düşünce çoğu zaman paragrafın **ilk ya da son cümlesinde** bulunur. “Bu nedenle”, “sonuç olarak”, “kısacası” gibi sözcüklerle başlayan cümleler genellikle ana düşünceyi verir.
:::

## 3. Ana düşünceyi bulma yolları

1. Paragrafı oku ve **“Yazar ne demek istiyor?”** diye sor.
2. Son cümleye bak. Çoğunlukla ana düşünce sonuç cümlesinde vardır.
3. Seçeneklerden, **paragrafın tamamını kapsayan** ve **fazla genelleme yapmayan** yargıyı seç.
4. Yalnızca bir cümleyi ya da örneği anlatan seçenek yardımcı düşüncedir, ana düşünce değildir.

**Tuzak:** Yazar bir örneği ayrıntılı anlatır, ama asıl vermek istediği başka bir şeydir. Örnekten çok, örneğin **sonunda çıkan sonucu** ara.

## 4. Anlatım biçimleri

Yazar, düşüncesini aktarırken dört temel anlatım biçiminden birini ya da birkaçını kullanır.

| Anlatım biçimi | Ne yapar? | Özellik |
| --- | --- | --- |
| Öyküleme | Olay anlatır | Kişi, yer, zaman var. Fiiller çoğunlukla geçmiş zamanlı. |
| Betimleme | Bir şeyi gözümüzün önüne getirir | Duyulara seslenir. Sıfat ve benzetme çok. |
