| --- | --- | --- |
| Anlam | Genellikle mecaz | Gerçek ya da mecaz olabilir |
| Yargı | Yargı bildirmez | Yargı bildirir |
| Cümledeki yeri | Cümlenin bir parçasıdır | Kendi başına cümledir |
| Fiil çekimi | Çekim eki alabilir | Kalıp olduğu için genelde almaz |
