:::

## 4. Özdeyiş ve ona yakın kavramlar

**Özdeyiş (vecize)**, bir yazar ya da düşünürün söylediği, **söyleyeni bilinen** ve genel bir doğruyu içeren sözdür. “Gelecek, bugünden hazırlananlar içindir.” gibi. Atasözü ve özdeyiş birbirine benzer ama özdeyişin söyleyeni bellidir.

## 5. Bağlama uygun atasözü ve deyimi seçmek

Bir durum verilip hangi söze uygun olduğu sorulduğunda şu adımları izle.

1. Durumun **ana fikrini** bul. (Birikim mi, iş birliği mi, acele mi?)
2. Seçeneklerdeki sözlerin **anlamlarını** kendi cümlelerinle yaz.
3. Durumun ana fikriyle aynı olan sözü seç.

**Örnek:** “Her gün kumbarasına küçük bir miktar atan Elif, bir yıl sonra bisiklet alacak kadar para biriktirmişti.”

Bu durumda ana fikir: **küçük birikimlerin büyük sonuç doğurması**. Uygun atasözü: “Damlaya damlaya göl olur.”

:::neden-sonuc
- Bir kişi gelirinden fazla harcıyor => “Ayağını yorganına göre uzat.” atasözü uygundur.
- İş birliği yapınca iş kolaylaşıyor => “Bir elin nesi var, iki elin sesi var.” atasözü uygundur.
- Çevresindeki kötü arkadaşlar kişiyi etkiliyor => “Üzüm üzüme baka baka kararır.” atasözü uygundur.
- Zorlukları göze alıp amacına ulaşıyor => “Gülü seven dikenine katlanır.” atasözü uygundur.
:::

