## 1. Özneye göre çatı

### Etken çatı

Özne işi **kendisi yapar**. Eylem bir nesneye yönelebilir ya da yönelmeyebilir.

- Ali kapıyı **açtı**. (Özne işi yapıyor)
- Çocuklar parkta **oynadı**.
- Kuş ağaçtan **uçtu**.

Etken fiillere **özel bir ek gerekmez**, fiil kökü ya da yalın hâlidir.

### Edilgen çatı

Özne işi **yapmaz, işten etkilenir**. İşi yapan belli değildir ya da önemli değildir. Fiil kökünün sonuna **-ıl, -il, -ul, -ül** ya da **-ın, -in, -un, -ün (sessizle biten köklerde -ıl, ünlüyle bitenlerde -n)** ekleri gelir.

- Kapı **açıldı**. (Kapıyı kimin açtığı belli değil)
- Ödevler **yapıldı**.
- Yazı tahtaya **yazıldı**.
- Mektup **gönderildi**.

Edilgen çatılı cümlelerde özneye **sözde özne** denir.

### Dönüşlü çatı

Özne işi **hem yapar hem de kendisi bundan etkilenir**. İş, öznenin **kendi üzerinde** gerçekleşir. Fiil kökünün sonuna **-ın, -in, -un, -ün** (ünlüyle biten köklerde **-n**) ekleri gelir.

- Ali **yıkandı**. (Ali kendini yıkadı)
- Elif **giyindi**. (Kendini giydirdi)
- Çocuk **süslendi**. (Kendini süsledi)

### İşteş çatı

İş, **birden fazla özne tarafından karşılıklı ya da birlikte** yapılır. Fiil kökünün sonuna **-ış, -iş, -uş, -üş** (ünlüyle biten köklerde **-ş**) eki gelir.

- Ali ile Ayşe **selamlaştı**. (Karşılıklı)
- İki çocuk **kavga etti**. (Karşılıklı)
- Öğrenciler sınıfta **toplaştı**. (Birlikte)
- Arkadaşlar **buluştu**.

| Çatı | Özne | Ek | Örnek |
| --- | --- | --- | --- |
| Etken | İşi yapar | Yok | Kapıyı açtı. |
| Edilgen | İşten etkilenir | -ıl, -n | Kapı açıldı. |
| Dönüşlü | Hem yapar hem etkilenir | -ın, -n | Ali yıkandı. |
| İşteş | Birden fazla, karşılıklı | -ış | Selamlaştılar. |

:::baglanti
**-n eki** hem edilgen hem dönüşlü fiil yapar. Ayırt etmek için şu soruyu sor: **İşi yapan kim?** İş kişinin **kendi üzerinde** gerçekleşiyorsa dönüşlüdür (Ali yıkandı: kendini yıkadı). İşi başka biri yapmış ya da belli değilse edilgendir (Çamaşırlar yıkandı: biri yıkadı).
:::

## 2. Nesneye göre çatı

### Geçişli fiil

**Nesne alabilen** fiillerdir. Yüklemine **“Neyi?”, “Kimi?”** sorusu sorulduğunda cevap bulunur.

- Ali **kitabı okudu**. (Neyi okudu? Kitabı)
- Anne **yemeği pişirdi**.
- Öğretmen **öğrenciyi uyardı**.

### Geçişsiz fiil

**Nesne alamayan** fiillerdir. “Neyi?” sorusuna cevap verilemez.

- Çocuklar **koştu**.
- Güneş **doğdu**.
- Kuşlar **uçtu**.

### Ettirgen fiil

İşin **başka birine yaptırıldığını** gösteren fiillerdir. Fiil köküne **-t, -dır, -dir, -tır, -tir, -ır, -ir** gibi ekler eklenir.

- Anne çocuğa yemek **yedirdi**. (Çocuk yedi, anne yedirdi)
- Öğretmen öğrencilere şiir **okuttu**.
- Berber saçını **kestirdi**.

Ettirgen fiil, geçişsiz bir fiili geçişli yapabilir. “Çocuk **uyudu**” cümlesi geçişsizdir. “Anne çocuğu **uyuttu**” cümlesi geçişlidir.

:::neden-sonuc
- Özne işi kendisi yapıyorsa => Etken çatı.
- Özne işten etkileniyorsa, işi yapan belli değilse => Edilgen çatı.
- Özne hem işi yapıp hem kendisi etkileniyorsa => Dönüşlü çatı.
- Birden çok özne karşılıklı ya da birlikte yapıyorsa => İşteş çatı.
- Yüklem “neyi, kimi” sorusuna cevap alıyorsa => Geçişli fiil.
:::

## 3. Çatı soruları nasıl çözülür?

1. Cümlenin **yüklemini** bul.
2. Yüklemin **kökünü ve eklerini** ayır.
3. **Özne** kim, bu özne işi yapıyor mu, işten etkileniyor mu, kendini mi etkiliyor?
4. Gerekirse **“Neyi, kimi?”** sorusunu sorarak geçişliliği kontrol et.

**Örnekler:**

- “Çocuklar yazın deniz kenarında **oynaştı**.” (-ş eki, birden çok özne: işteş)
- “Misafirler kapıda **karşılandı**.” (Misafirleri biri karşıladı: edilgen)
- “Sabah erkenden **kalkıp** yüzünü **yıkadı**.” (Etken, kendi yüzünü yıkadı, nesne var)
- “Kız, aynanın karşısında **süslendi**.” (Kendini süsledi: dönüşlü)

