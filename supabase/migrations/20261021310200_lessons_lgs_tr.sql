“Gözleri yıldız gibi parlıyordu.” “Rüzgâr kulağıma fısıldadı.” “Sana bin kere söyledim!” Bu cümlelerde sözcükler gerçek anlamlarıyla değil, **anlatımı güçlendirmek için özel biçimlerde** kullanılmıştır. Bu biçimlere **söz sanatları** denir. Bu konuda başlıca söz sanatlarını, ayırt edici ipuçlarını ve sık yapılan karışıklıkları öğreneceksin.

:::hedefler
1. Benzetme, kişileştirme, konuşturma ve abartmayı tanımak.
2. Karşıtlık ve ad aktarmasını örneklerle açıklamak.
3. Birbirine karışan söz sanatlarını ayırt etmek.
4. Bir cümledeki söz sanatını bulmak ve cümleye katkısını yorumlamak.
:::

:::ipucu
Söz sanatı sorusunda cümleyi **gerçek anlamıyla** düşün. Gerçekte olamayacak ya da mecaza dayanan bir durum varsa söz sanatı vardır. Sonra “Hangi sanat?” diye ipuçlarına bak: “gibi” (benzetme), insan özelliği (kişileştirme), konuşma (konuşturma), aşırılık (abartma).
:::

## 1. Benzetme (teşbih)

Aralarında **ortak bir özellik** bulunan iki şeyden **zayıf olanı güçlü olana benzetmektir**. Anlatıma canlılık, güzellik ve açıklık katar.

Benzetmenin dört öğesi vardır.

- **Benzeyen:** Benzetilen, zayıf olan şey.
- **Kendisine benzetilen:** Güçlü olan şey.
- **Benzetme yönü:** İkisinin ortak özelliği.
- **Benzetme edatı:** Gibi, sanki, kadar, benzer, tıpkı.

**Örnek:** “Gözleri yıldız gibi parlıyordu.”

- Benzeyen: Gözler
- Kendisine benzetilen: Yıldız
- Benzetme yönü: Parlaklık
- Benzetme edatı: Gibi

Benzetmenin “gibi” gibi edatı her zaman açıkça yazılmayabilir. “Kalbi taş” ifadesinde benzetme vardır, “gibi” yoktur: Kalbi taş gibi sert.

:::dene
1. “Çocuğun gülüşü bahar sabahı kadar tazeydi.” cümlesindeki benzeyen ve kendisine benzetileni bul. => Benzeyen: Gülüş, kendisine benzetilen: Bahar sabahı. Edat: kadar.
2. “Koca bir ağaç gibi dimdik duruyordu.” cümlesindeki benzetme yönü nedir? => Dimdik duruş, sağlamlık.
:::

## 2. Kişileştirme (teşhis)

**İnsan olmayan varlıklara (hayvan, bitki, eşya, doğa olayı) insana özgü özellikler, davranışlar ya da duygular yüklemektir.** Canlandırmak için kullanılır.

- “Rüzgâr ağaçları **okşadı**.”
- “Güneş **gülümsedi**.”
- “Ay **utandı**, bulutların arkasına saklandı.”
- “Deniz **öfkelendi**, dalgalar kıyıya vurdu.”

Kişileştirme, insana özgü olan fiilleri (gülmek, utanmak, öfkelenmek, uyumak, ağlamak) başka varlıklara yükler.

## 3. Konuşturma (intak)

Kişileştirilen varlığa **konuşma özelliği vermektir**. İnsan dışı bir varlığın ağzından söz söylenir.

- “Ağaç, yaprağına dedi ki: ‘Hadi uyan artık.’”
- Tilki karga ya: “Sesin ne kadar güzel!” dedi.
- Bulut yere seslendi: “Ben geliyorum.”

**Önemli:** Her konuşturma **aynı zamanda kişileştirmedir** (çünkü konuşmak insana özgüdür), ama her kişileştirme konuşturma değildir. Varlık **konuşuyorsa** konuşturma, yalnızca insan gibi davranıyorsa kişileştirmedir.

:::baglanti
Konuşturma soruları “Hangisinde konuşturma yapılmıştır?” biçiminde gelir. Seçenekte **tırnak içinde bir söz** ya da “dedi, seslendi, fısıldadı” gibi bir fiil varsa ve konuşan şey insan değilse konuşturma vardır. Fabllar konuşturma açısından çok örnek içerir.
:::

## 4. Abartma (mübalağa)

Bir durumu, özelliği ya da olayı **gerçekte olduğundan çok daha fazla ya da çok daha az** göstermektir. Etkiyi artırmak için kullanılır.

- “Sana **bin kere** söyledim.”
- “Açlıktan **ölüyorum**.”
- “Bütün dünya seni arıyor.”
- “Gözyaşları **sel oldu**.”

Abartmanın ipuçları: **Bin, milyon, her zaman, asla, bütün dünya, kıyamet, ölmek, uçmak** gibi aşırılık bildiren sözcükler.

## 5. Karşıtlık (tezat)

**Birbirinin zıddı iki kavramı, durumu ya da duyguyu** bir arada kullanmaktır. Çatışma, vurgu ve çarpıcılık sağlar.

- “**Gülmek** için **ağlayanlar** vardır.”
- “**Küçük** bir adım, **büyük** bir sıçramadır.”
- “**Ak** ile **karayı** ayırt edemez.”
- “Gündüzün **aydınlığı** ile gecenin **karanlığı** bir arada.”

Karşıtlıkta **zıt anlamlı sözcükler** ya da **zıt durumlar** aynı cümlede yer alır.

## 6. Ad aktarması (mecaz-ı mürsel)

Bir sözcüğün, **gerçek anlamı dışında, onunla ilgisi olan başka bir kavramın yerine** kullanılmasıdır.

- “Bütün **salon** ayağa kalktı.” (Salon yerine salondaki insanlar)
- “**Mehmet Akif**’i okudum.” (Yazarın kendisi yerine eseri)
- “Sofraya **bir tabak** geldi.” (Tabağın içindeki yemek yerine)
- “Şu **kafa** hiç ders çalışmıyor.” (Kişi yerine bir parçası)

Dikkat: Ad aktarmasında **benzerlik yoktur**, **bağlantı** (kap-içindeki, yazar-eser, yer-orada yaşayanlar) vardır. Benzerlik varsa benzetme ya da mecazdır.

## 7. Söz sanatları karışıyor mu?

| Cümle | Söz sanatı | Neden? |
| --- | --- | --- |
| “Çocuk, kuş gibi hafif.” | Benzetme | “Gibi” edatı var |
| “Kuş, çocuğa selam verdi.” | Kişileştirme | Kuş selam veriyor (insan davranışı) |
| “Kuş çocuğa dedi ki: ‘Bana yem ver.’” | Konuşturma | Kuş konuşuyor |
| “Sana bin kere söylemiştim.” | Abartma | Aşırı sayı |
| “Küçük adam, büyük işler yaptı.” | Karşıtlık | Küçük, büyük zıt |
| “Bütün köy toplandı.” | Ad aktarması | Köy, orada yaşayanlar yerine |

:::neden-sonuc
- Cümlede “gibi, sanki, kadar” var => Benzetme olma ihtimali yüksektir.
- İnsan olmayan varlık insan gibi davranıyor => Kişileştirme vardır.
- İnsan olmayan varlık konuşuyorsa => Konuşturma (ve kişileştirme) vardır.
- Aşırı sayı ya da ifade kullanılmışsa => Abartma vardır.
:::

## 8. Konuyu toparla

| Söz sanatı | Özet |
| --- | --- |
| Benzetme | Zayıf olanı güçlüye benzetmek, “gibi” |
| Kişileştirme | İnsan dışı varlığa insan özelliği vermek |
| Konuşturma | Kişileştirilen varlığı konuşturmak |
| Abartma | Gerçekten fazla ya da az göstermek |
| Karşıtlık | Zıt kavramları bir arada kullanmak |
| Ad aktarması | Bir sözcüğü ilgili başka bir şey yerine kullanmak |

