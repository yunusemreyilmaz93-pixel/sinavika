:::hedefler
1. Anlama dayalı anlatım bozukluklarını (gereksiz sözcük, anlam belirsizliği, mantık hatası) tanımak.
2. Yapıya dayalı anlatım bozukluklarını (özne-yüklem uyumsuzluğu, çatı, öge uyumsuzluğu) tanımak.
3. Bozuk bir cümlenin neden bozuk olduğunu açıklamak.
4. Bozuk cümleleri düzeltmek.
:::

:::ipucu
Anlatım bozukluğu sorusunda cümleyi **sesli oku** (içinden). Kulağına takılan yeri işaretle, sonra “Bu hata anlamdan mı yoksa dil bilgisi kurallarından mı?” diye sor. Cevabın hangi gruba girdiğini bilirsen düzeltmesi kolaylaşır.
:::

## 1. Anlama dayalı anlatım bozuklukları

### Gereksiz sözcük kullanımı

Aynı anlamı veren ya da zaten cümlede olan bir bilgiyi tekrar eden sözcükler cümleye **fazla yük** olur.

- Yanlış: **Geri** dönmek zorunda kaldı. Doğrusu: Dönmek zorunda kaldı. (“Dönmek” zaten geri gelmek demek.)
- Yanlış: **Yaklaşık** 50 **kadar** öğrenci katıldı. Doğrusu: Yaklaşık 50 öğrenci katıldı.
- Yanlış: Sürekli **hep** gecikiyor. Doğrusu: Sürekli gecikiyor.
- Yanlış: **Tekrar yeniden** denedi. Doğrusu: Yeniden denedi.
- Yanlış: **Karşılıklı** birbirine baktılar. Doğrusu: Birbirine baktılar.

Bu hatalar, “yaklaşık … kadar”, “tekrar yeniden”, “geri dönmek, içeri girmek, yukarı çıkmak” gibi kalıplarda görülür.

### Anlam belirsizliği

Cümle **birden çok anlama** gelebiliyorsa belirsizlik vardır.

- Yanlış: **Ali, Ahmet ve Ayşe’nin arkadaşını gördü.** Ahmet ve Ayşe’nin ortak arkadaşı mı, yoksa Ahmet ile Ayşe’nin arkadaşı mı?
- Yanlış: Öğretmen öğrencisiyle babasını çağırdı. Kimin babası?
- Doğru: Ali, Ahmet’i ve Ayşe’nin arkadaşını gördü. (Anlam netleşti.)

### Mantık hatası ve anlamca çelişki

Cümlenin parçaları birbirinin **tersini** söylüyor ya da **akla uygun olmayan** bir ilişki kuruyorsa bozukluk vardır.

- Yanlış: **Hastalığını** duyunca çok **sevindi**. (Hastalığa sevinilmez)
- Yanlış: Yağmur yağdığı için sokaklar **kuruydu**. (Yağmur yağınca sokaklar ıslanır)
- Yanlış: Hiç tanımadığım birini **iyi tanırım**. (Çelişki)
- Doğru: Hastalığını duyunca çok üzüldü.

### Deyim ve atasözlerinin yanlış kullanımı

Deyimin içindeki sözcüğü değiştirmek, deyimi **bozar**.

- Yanlış: Sonucu duyunca **ağzı kulaklarına ulaştı**. Doğrusu: Sonucu duyunca ağzı kulaklarına vardı.

## 2. Yapıya dayalı anlatım bozuklukları

### Özne-yüklem uyumsuzluğu

Özne ile yüklemin **kişi ve sayı bakımından** uyumlu olması gerekir.

- Yanlış: **Ben ve arkadaşım** parka **gidiyorsunuz**. Doğrusu: Ben ve arkadaşım parka gidiyoruz.
- Yanlış: **Çocuklar** bahçede oynuyor, **eğleniyorsun**. Doğrusu: Çocuklar bahçede oynuyor, eğleniyorlar.
- Yanlış: **Sen ve ben** tiyatroya **gidiyorsunuz**. Doğrusu: Sen ve ben tiyatroya gidiyoruz.

**Not:** Birden çok özne olduğunda yüklem, **kişi bakımından** ilk kişiye göre çekimlenir. “Ben ve sen” → “biz”.

### Çatı uyuşmazlığı

Aynı özneye bağlı fiiller **aynı çatıda** olmalıdır. Biri etken, diğeri edilgen olursa bozukluk çıkar.

- Yanlış: Yemek **hazırlanıp** masaya **koydu**. (Edilgen + etken)
- Doğru: Yemek hazırlanıp masaya konuldu. (Edilgen + edilgen)
- Doğru: Anne yemeği hazırlayıp masaya koydu. (Etken + etken)

### Öge uyumsuzluğu (ortak yüklem hatası)

Aynı yükleme bağlı ögelerin, **aynı eki** alması gerekir. Nesne ile dolaylı tümleç, ortak yüklemle çelişemez.

- Yanlış: **Kitap okumayı** ve **müzik dinlemek** severim. Doğrusu: Kitap okumayı ve müzik dinlemeyi severim. (İkisi de belirtme hâlinde)
- Yanlış: **Okula** ve **parkı** gitti. Doğrusu: Okula ve parka gitti.
- Yanlış: Ödevlerini **bitirip** ve **dinlendi**. Doğrusu: Ödevlerini bitirip dinlendi.

:::baglanti
Bu hatalarda genel ilke şudur: **Ortak yükleme bağlanan ögeler aynı türde ve aynı biçimde olmalıdır.** “Ve” ile bağlanan iki öğeye bak ve ikisinin de yükleme bağlanabildiğinden emin ol.
:::

### Zaman uyuşmazlığı

Cümledeki zaman belirteçleri ile fiilin zamanı **birbirine uymalıdır**.

- Yanlış: **Dün** akşam sinemaya **gideceğiz**. Doğrusu: Dün akşam sinemaya gittik.
- Yanlış: **Yarın** erkenden **kalktım**. Doğrusu: Yarın erkenden kalkacağım.

