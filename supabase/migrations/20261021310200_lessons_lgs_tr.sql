“Hava kararmadan eve dön, çünkü yollar tehlikeli.” Bu cümlede bir sebep ve bir sonuç var. “Çok çalışırsan başarılı olursun.” cümlesinde ise bir koşul var. LGS’de sana verilen cümlenin **ne anlattığını, neye dayandığını ve hangi anlam ilişkisini kurduğunu** bulman beklenir. Bu konuda cümlelerin anlam özelliklerini ve cümle yorumlama yöntemini öğreneceksin.

:::hedefler
1. Cümledeki anlam ilişkilerini (neden-sonuç, amaç-sonuç, koşul, karşılaştırma, tanım, örnekleme) belirlemek.
2. Öznel ve nesnel yargıları ayırt etmek.
3. Kesin ve olasılık bildiren ifadeleri tanımak.
4. Cümleden çıkarılabilecek ve çıkarılamayacak yargıları ayırt etmek.
:::

:::ipucu
Cümle soruları genellikle **bağlaçlara ve eklere** dayanır. “Çünkü”, “bu yüzden”, “eğer”, “-sa”, “için”, “-dikçe” gibi ipuçlarını bulduğunda cümlenin anlam ilişkisini bulmuş olursun.
:::

## 1. Neden-sonuç cümleleri

Bir olayın **sebebini** ve **sonucunu** birlikte anlatan cümlelerdir.

- Çok yorulduğu **için** erkenden uyudu. (Sebep: yorulma, sonuç: uyuma)
- Yağmur yağdı**ğından** maç ertelendi.
- Sınavda başarısız oldu, **çünkü** yeterince çalışmamıştı.
- Hava çok soğuktu, **bu yüzden** dışarı çıkmadık.

Ayırt edici sözcükler: Çünkü, için, -dığından, -diği için, bu yüzden, bu nedenle, sonucunda, yüzünden, -den dolayı.

**Dikkat:** “Çünkü” ile başlayan kısım **sebep**tir. “Bu yüzden” ile başlayan kısım **sonuç**tur.

## 2. Amaç-sonuç cümleleri

Bir eylemin **amacını** bildiren cümlelerdir. Amaç henüz gerçekleşmemiştir. Bir şey yapılır, çünkü ileride bir şey olması istenir.

- Sınavı kazanmak **için** her gün çalışıyor.
- Sağlıklı kalmak **amacıyla** spor yapıyor.
- Trene yetişmek **üzere** erkenden evden çıktı.

Ayırt edici sözcükler: İçin, amacıyla, -mak üzere, -mek için, diye.

:::baglanti
Neden-sonuç ile amaç-sonuç arasındaki fark **zamandır**. Neden-sonuçta sebep **olmuştur** (yorulduğu için uyudu). Amaç-sonuçta amaç **henüz gerçekleşmemiştir** (kazanmak için çalışıyor). “İçin” sözcüğü ikisinde de görünebilir, bu yüzden anlama bakmalısın.
:::

## 3. Koşul-sonuç (şart) cümleleri

Bir olayın gerçekleşmesinin **bir koşula bağlı** olduğunu anlatır.

- **Erken kalkarsan** otobüse yetişirsin.
- Çok **çalışırsa** başarılı olur.
- Hava **güzel olursa** pikniğe gideceğiz.
- Bütün sorulara **doğru cevap verirsen** tam puan alırsın.

Ayırt edici ekler ve sözcükler: -sa, -se, eğer, ise, takdirde, -ırsa.

## 4. Karşılaştırma

İki varlık ya da durum arasında **benzerlik veya farklılık** kurulur.

- Ali, kardeşinden **daha** çalışkandır.
- Bu kitap, ötekisi **kadar** ilgi çekici değil.
- İstanbul, Ankara’ya **göre** daha kalabalıktır.
- Bu soru, diğerleri **gibi** kolaydı.

Ayırt edici sözcükler: Daha, en, -den, -e göre, kadar, gibi, oranla, -dır/-dir (yargı).

## 5. Tanımlama ve örnekleme

**Tanımlama**, bir kavramın ne olduğunu açıklar.

- **Fotosentez**, bitkilerin ışık enerjisini kullanarak besin üretmesidir.
- Kitap, bilginin en eski ve en kalıcı taşıyıcısıdır.

**Örnekleme**, bir düşüncenin somut örnekle desteklenmesidir.

- Yararlı alışkanlıklar vardır, **örneğin** düzenli kitap okumak.
- Bazı hayvanlar kış uykusuna yatar. **Mesela** ayılar ve yarasalar.

Ayırt edici sözcükler: Örneğin, mesela, söz gelimi, yani, demek ki (ek açıklama).

## 6. Öznel ve nesnel yargılar

**Nesnel yargı**, herkes için aynı olan, **kanıtlanabilir ya da denenebilir** yargıdır. Kişiden kişiye değişmez.

- Su, 100°C’de kaynar. (Ölçülebilir)
- Türkiye’nin başkenti Ankara’dır. (Doğrulanabilir)
- Ay, Dünya’nın uydusudur.

**Öznel yargı**, kişisel duygu, düşünce ve beğeniyi yansıtır. Kişiden kişiye değişir, kanıtlanamaz.

- Bu film çok sıkıcıydı. (Kişisel beğeni)
- Bence en güzel mevsim ilkbahardır.
- Çikolatalı pasta en lezzetli tatlıdır.

Öznel yargıların ipuçları: **Bence, sanırım, galiba, çok güzel, harika, sıkıcı** gibi değer bildiren sözcükler.

:::neden-sonuc
- Cümlede ölçülebilir ya da denenebilir bilgi var => Nesnel yargıdır. “Bir yıl 12 aydır.”
- Cümlede beğeni, duygu ve kişisel yorum var => Öznel yargıdır. “Bu şarkı çok hüzünlü.”
- Cümlede “bence, sanırım” ifadeleri var => Büyük olasılıkla öznel yargıdır.
:::

## 7. Kesinlik ve olasılık

Cümle bir şeyi **kesin** olarak bildirebilir ya da **olasılık, tahmin** belirtebilir.

| Anlam | Örnek | İpucu sözcük |
| --- | --- | --- |
| Kesinlik | Yarın sınav olacak. | Mutlaka, kesinlikle, hiç, her zaman |
| Olasılık | Yarın yağmur yağabilir. | Belki, galiba, sanırım, -ebilir |
| Tahmin | Muhtemelen geç kalacaklar. | Muhtemelen, herhalde |

## 8. Cümleden çıkarılabilecek yargılar

Yeni nesil sorular “bu cümleden **hangisine ulaşılabilir**?” ya da “**ulaşılamaz**?” diye sorar. Çözüm yolu şudur.

1. Cümleyi dikkatle oku ve **kesin söylenenleri** not et.
2. Seçenekleri tek tek cümleyle karşılaştır.
3. Cümlede **söylenmeyen** ya da **tersi söylenen** bilgiyi içeren seçeneği ele.

**Örnek:** “Kitap okumayı alışkanlık hâline getirenler, farklı bakış açıları kazanır.”

- “Kitap okuyanların bakış açıları gelişir.” (Çıkarılabilir)
- “Kitap okumayanlar başarısız olur.” (**Çıkarılamaz**, cümlede böyle bir bilgi yok.)

:::ipucu
“Hiçbir”, “her zaman”, “mutlaka”, “yalnızca” gibi **kesin** ifadeler içeren seçenekler, genellikle cümlede açıkça yazılmadığı için **yanlış** olur. Çıkarım sorularında bu seçeneklere dikkat et.
:::

