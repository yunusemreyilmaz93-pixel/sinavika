## 1. Nokta (.)

- **Cümlenin sonuna** konur: “Okula gittim.”
- **Kısaltmaların sonuna** konur: “Dr. Ali, Prof. Ayşe.” (Bazı kısaltmalarda nokta konmaz: cm, kg)
- **Sıra sayılarından sonra** konur: “1. sınıf, 5. gün.”
- **Tarihlerin yazımında** gün, ay, yıl arasına konabilir: “23.04.2024”.
- **Başlıkların sonuna** konmaz.

## 2. Virgül (,)

Virgül en çok sorulan işarettir. Kullanım yerleri şunlardır.

- **Eş görevli sözcükleri ayırırken:** “Elma, armut, kiraz aldım.”
- **Sıralı cümleleri ayırırken:** “Geldi, oturdu, bekledi.”
- **Hitap sözcüklerinden sonra:** “Ahmet, kapıyı aç.” “Sevgili arkadaşım, mektubun elime ulaştı.”
- **Cümle başındaki “evet, hayır, tamam” gibi sözcüklerden sonra:** “Evet, haklısın.”
- **Ara sözleri ve ara cümleleri ayırırken:** “Ali, tüm arkadaşlarının aksine, derse gecikmedi.”
- **Ögelerin yer değiştirmesi (devrik cümlede) durumunda:** “Seni, ben sevmiştim.”
- **Uzun cümlelerde anlam kolaylığı için:** “Yağmur yağmaya başladığında, herkes eve koştu.”
- **Sayılarda ondalık ayırıcı olarak:** “3,5”.

**Virgül konmaz:** Özne ile yüklem arasında, nesne ile yüklem arasında gereksiz yere konmaz. “Kitabı, okudum.” yanlıştır.

## 3. Noktalı virgül (`;`)

- **Öğelerinin içinde virgül bulunan cümleleri** ayırırken kullanılır. Örnek: `Çocuklar, bahçede top oynarken; anneleri, bir köşede sohbet ediyordu.`
- **Sıralı cümleleri** birbirinden ayırırken kullanılır. Örnek: `Yağmur çok şiddetliydi; yollar kapandı.`
- **Her biri virgül içeren uzun sıralamalarda**, öğeleri birbirinden ayırmak için kullanılır.

Noktalı virgül, virgülden **daha güçlü bir duraklama**, noktadan **daha hafif bir duraklama** bildirir.

## 4. İki nokta (:)

- **Açıklama yapılacaksa, kendisinden sonra söylenecek sözlerden önce** kullanılır: “Şunu unutma: Zaman en değerli varlıktır.”
- **Örnek verilecekse:** “Mevsimler dörttür: ilkbahar, yaz, sonbahar, kış.”
- **Sıralama yapılacaksa:** “Alışveriş listem: elma, süt, ekmek.”
- **Konuşmaların başında** kişi adından sonra: “Ali: Yarın gelecek misin?”
- **Saat ve oranlarda:** “14:30”, “2:1”.

## 5. Üç nokta (...)

- **Yarım bırakılan cümlelerde:** “Keşke daha erken gelseydim...”
- **Sözün devamının anlaşılacağı durumlarda:** “Hepimiz bildik... Sen bilirsin!”
- **Duraksamayı ya da düşünceyi belirtmek için:** “Şey... aslında... bilmiyorum.”
- **Alıntıda atlanan bölümü göstermek için.**

## 6. Soru işareti (?) ve ünlem (!)

**Soru işareti**, soru bildiren cümlelerin sonuna konur: “Ne zaman geleceksin?” Soru sözcüğü ya da soru eki taşıyan cümlelerde kullanılır. **Soru işaretini** bir sözcüğün sonuna kuşkuyu belirtmek için de koyabiliriz: “Çok güzel (?) bir film.”

**Ünlem işareti**, **şaşma, sevinç, korku, öfke** gibi güçlü duyguları bildiren cümlelerin ve **seslenme sözcüklerinin** sonuna konur: “Yaşasın, kazandık!”, “Hey, burada mısın!”

## 7. Tırnak, kesme, parantez, eğik çizgi, kısa çizgi

### Tırnak işareti (“ ”)

- **Başkasından yapılan alıntıların** başına ve sonuna konur: Atatürk, “Yurtta sulh, cihanda sulh.” demiştir.
- **Özel anlam yüklenen sözcükleri** belirtmek için: “Kapıdaki levhada ‘Giriş yasak’ yazıyordu.”
- **Eser adlarında:** “Çalıkuşu” romanını okudum.

### Kesme işareti (’)

- **Özel adlara gelen çekim eklerini** ayırır: “Ankara’ya gittik.” “Ali’nin kitabı.”
- **Ek, sözcüğün asıl sesini bozmuyorsa kullanılır.** Genel adlara getirilen eklerde kullanılmaz: “okulda”.

### Parantez

- **Açıklama ya da ek bilgi** vermek için: “Kitap (Türkçe baskısı) rafta duruyor.”
- **Tiyatro eserlerinde sahne yönergelerini** göstermek için: “(Kapıyı çalar.)”

### Eğik çizgi (/)

- **“Veya” anlamında** ya da seçenek bildirmek için: “Gidecek/gitmeyecek.”
- **Tarihlerde:** “12/05/2024”.

### Kısa çizgi (-)

- **Satır sonunda bölünen sözcüklerin** hecesini belirtmek için.
- **İki sözcük arasında “ile, ve” anlamıyla:** “Türkçe-İngilizce sözlük.”
- **Sayılarda “arasında” anlamıyla:** “10-12 yaş grubu.”

