## 1. “de, da” ayrı mı bitişik mi?

**“De, da” bağlacı:** Cümleye “ben de, sen de” gibi **katılma** anlamı verir. Ayrı yazılır, ünsüz benzeşmesine uğramaz (hep “de/da”, asla “te/ta” olmaz). Cümleden çıkarılınca cümle anlamını korur.

- Sen **de** bizimle gel.
- Ali **de** geldi, Ayşe **de**.
- Kitap **da** aldım, defter **de**.

**“-de, -da” hâl eki:** Bulunma hâli ekidir. Bitişik yazılır. Ünsüz benzeşmesiyle “-te, -ta” biçimine dönüşebilir.

- Okul**da** ders yaptık.
- Kitap**ta** önemli bilgiler var.
- Ev**de** kimse yoktu.

| | Bağlaç “de, da” | Hâl eki “-de, -da” |
| --- | --- | --- |
| Yazılış | Ayrı | Bitişik |
| Çıkarılırsa | Cümle anlamını korur | Anlam bozulur |
| Örnek | Sen **de** gel. | Okul**da** kal. |

**Bende / ben de karışıklığı:** “Bende kitap var” (bende = bende bulunuyor) ile “Ben de kitap aldım” (ben dahil) farklı anlamlardır.

## 2. “ki” ayrı mı bitişik mi?

**“Ki” bağlacı:** İki cümleyi bağlar. **Ayrı yazılır.**

- Biliyorum **ki** sen başaracaksın.
- O kadar yoruldum **ki** oturur oturmaz uyudum.

**“-ki” eki:** Bir sözcüğü sıfat ya da zamir yapar. **Bitişik yazılır.**

- Bahçe**deki** çiçekler soldu.
- Dün**kü** ders çok eğlenceliydi.
- Evdeki saat bozuldu.

**Bitişik yazılan “ki”li sözcükler (kalıplaşmıştır):** Sanki, belki, mademki, halbuki, oysaki, çünkü, meğerki, hâlbuki.

:::baglanti
“Ki” bağlacından **önce virgül** koyup cümleyi bölebiliyorsan bağlaçtır. “Biliyorum ki gelecek” cümlesini “Biliyorum, gelecek” biçiminde söyleyebilirsin, bu yüzden ayrı yazılır. “Evdeki” sözcüğünde bu mümkün değildir.
:::

## 3. “mi” soru eki

**Soru eki “mi, mı, mu, mü”** her zaman **ayrı** yazılır.

- Ödevini bitirdin **mi**?
- Sen de geliyor **musun**?
- Yarın gidiyor **muyuz**?

“Mi” ek-fiil olarak **bitişik** yazılabilir: “Güzel**miş**”, “Geliyor**muş**”. Ama bu soru eki değildir.

**Yaygın hata:** “Geliyormusun?” yanlış, “Geliyor musun?” doğrudur.

## 4. Büyük harflerin kullanımı

Büyük harfle yazılan sözcükler:

- **Cümlenin ilk sözcüğü** ve tırnak içindeki cümlenin başı.
- **Özel adlar:** Kişi, ülke, şehir, dağ, nehir, deniz adları. (Ali, Türkiye, Ankara, Erciyes, Kızılırmak)
- **Unvan ve rütbeler**, kişi adından önce ya da yerine gelirse: Ahmet Bey, Doktor Mehmet, Kaymakam Bey.
- **Kurum, kuruluş, bayram adları:** Türkiye Büyük Millet Meclisi, Milli Eğitim Bakanlığı, Cumhuriyet Bayramı.
- **Bölge ve yer adları:** Güneydoğu Anadolu Bölgesi, Karadeniz.
- **Ulus ve dil adları:** Türk, Türkçe, Almanca.

Küçük harfle yazılan sözcükler:

- **Ay ve gün adları:** ocak, nisan, pazartesi, cuma.
- **Yön adları** (bölge adı olmadıkça): kuzey, güney, doğu, batı.
- **Mevsim adları:** ilkbahar, yaz, kış.
- Kişi ve unvan adı **genel** anlamda kullanılırsa: “Bu şehrin valisi toplantıya katıldı.”

**Özel ad, tamlama ise:** “Ankara Üniversitesi”, “Atatürk Orman Çiftliği” gibi her sözcüğün ilk harfi büyük yazılır. Ama “Atatürk’ün mezarı” gibi tamlamada ikinci sözcük küçüktür.

## 5. Kesme işareti ve ek yazımı

Özel adlara gelen **çekim ekleri kesme işaretiyle** ayrılır.

- Ankara’ya gittik. İstanbul’da yaşıyoruz. Ali’nin kitabı.
- Atatürk’ün sözleri.

Özel adlardan **yeni sözcük türeten yapım ekleri** kesme işareti almaz: İstanbullu, Ankaralı, Türkçe, Atatürkçü. Genel adlara gelen ekler de kesme almaz: okulda, kitabın.

Kısaltmalar büyük harfle yazılır (TBMM, TDK, MEB). Ölçü birimi kısaltmaları küçük harfle yazılır ve sonlarına nokta konmaz (cm, kg, km).

## 6. Birleşik sözcüklerin yazımı

Bazı birleşik sözcükler **bitişik**, bazıları **ayrı** yazılır.

| Bitişik yazılanlar | Ayrı yazılanlar |
| --- | --- |
| Hiçbir, birçok, birkaç | Her şey, her zaman, her gün |
| Herkes, herhangi | Hiç kimse, hiçbir şey |
| Kahvaltı, başkent | Ya da, bir de |
| Pazartesi, cumartesi | Bir şey, bir kez |

Dikkat edilecek birkaç örnek:

- **Hiçbir şey** yapmadı. (Hiçbir bitişik, şey ayrı)
- **Her şey** çok güzeldi. (Ayrı)
- **Birkaç** arkadaşım geldi. (Bitişik)
- **Birçok** kişi katıldı. (Bitişik)

### “gibi, için, kadar, ile” ayrı yazılır

- Çiçek **gibi** koktu. Bu soru **için** çalıştım. Dün **kadar** soğuk.
- **İle** ek olarak bitişik de yazılır: Ali**yle** gittim.

