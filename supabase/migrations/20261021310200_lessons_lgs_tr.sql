## 1. Öyküleyici metinler

Öyküleyici metinlerde **olay, kişi, yer, zaman** unsurları bulunur. Yazar bir olayı anlatır.

### Hikâye (öykü)

Kısa bir zaman diliminde **tek bir olayı** anlatan, kişi sayısı az, yazılış amacı **okuyucuyu etkilemek** olan metindir. Olay örgüsü kısadır (giriş, gelişme, sonuç).

### Roman

Hikâyeden **uzun**, birden çok olayın ve çok sayıda kişinin yer aldığı, uzun bir zaman diliminin anlatıldığı metindir.

### Masal

**Olağanüstü olayların** anlatıldığı, “Evvel zaman içinde, kalbur saman içinde…” gibi kalıplarla başlayan halk anlatısıdır. Zaman ve yer belirsizdir. İyiler ödüllendirilir, kötüler cezalandırılır.

### Fabl

**Hayvanların, bitkilerin ya da eşyaların konuşturulduğu** ve sonunda bir ders verildiği kısa anlatıdır. Kahramanlar insan özelliklerini taşır (konuşturma ve kişileştirme). Örnek: Tilki ile Karga.

### Destan

Bir milletin yaşadığı **büyük olayları** (savaş, göç, kuruluş) anlatan, **olağanüstü kahramanları** olan uzun anlatılardır. Örnek: Oğuz Kağan Destanı, Dede Korkut hikâyeleri destansı özellik taşır.

### Efsane

Gerçek bir olaya, kişiye ya da doğa olayına dair **halk tarafından olağanüstü şekilde anlatılan** hikâyelerdir. Yer ve kişi çoğunlukla bellidir. Örnek: Kız Kulesi efsanesi.

| Tür | Uzunluk | Ayırt edici özellik |
| --- | --- | --- |
| Hikâye | Kısa | Tek olay, az kişi |
| Roman | Uzun | Çok olay, çok kişi, uzun zaman |
| Masal | Kısa-orta | Olağanüstü, “bir varmış bir yokmuş” |
| Fabl | Kısa | Hayvanlar konuşur, ders verir |
| Destan | Uzun | Milletin büyük olayları, olağanüstü kahraman |
| Efsane | Kısa | Gerçek yer ya da kişiye bağlı olağanüstü anlatı |

## 2. Bilgilendirici metinler

### Haber metni

Güncel bir olayı **“ne, kim, nerede, ne zaman, neden, nasıl”** sorularına cevap vererek bildirir. Dil açık ve nesneldir. Başlık ve spot bulunur.

### Makale

Bir konuyu **bilimsel ve kanıtlı biçimde** ele alan, okuyucuyu bilgilendirmeyi ya da ikna etmeyi amaçlayan yazıdır. Dil ağırbaşlıdır, kanıtlar kullanılır.

### Söyleşi (röportaj)

Bir kişiyle yapılan **soru-cevap biçiminde** yazıdır. Sorular ve cevaplar belirgindir.

### Biyografi ve otobiyografi

- **Biyografi:** Bir kişinin hayatının **başka biri tarafından** anlatıldığı metindir. Üçüncü kişi ağzıyla yazılır (“O doğdu, okula gitti”).
- **Otobiyografi:** Kişinin **kendi hayatını kendisinin** anlattığı metindir. Birinci kişi ağzıyla yazılır (“Doğdum, okula gittim”).

### Anı (hatıra)

Yazarın **yaşadığı ya da tanık olduğu** olayları, **geçmişe dönerek** anlattığı metindir. Birinci kişi ağzıyla yazılır, ama **olaya ve çevreye** odaklıdır. Otobiyografiden farkı, bütün hayatı değil belli bir dönemi ya da olayı anlatmasıdır.

### Günlük

Kişinin **her gün başından geçenleri** tarih belirterek yazdığı metindir. Birinci kişidedir, içten ve samimidir. “Sevgili günlük” gibi hitaplar görülebilir. Tarih başlığı önemlidir.

### Mektup

Bir kişinin **belirli birine** yazdığı yazıdır. **Hitap** (“Sevgili Ayşe,”), **gelişme** ve **imza** bölümleri vardır. Konu serbesttir.

### Gezi yazısı

Bir yerin görülenlerini, gözlemlerini ve izlenimlerini anlatan yazıdır. Yer adları, betimlemeler ve yazarın izlenimi önemlidir.

### Deneme ve fıkra

- **Deneme:** Yazarın bir konuda **kendi düşüncelerini** serbest ve samimi bir dille anlattığı yazıdır, kesin hükümler vermez.
- **Fıkra (köşe yazısı):** Güncel bir konuda **gazetelerde yazarın görüşünü** kısa ve sohbet havasında aktardığı yazıdır.

:::baglanti
Anı, günlük ve otobiyografi üçü de “ben” diliyle yazılır, bu yüzden karıştırılır. Ayırt etmek için şu soruları sor: **Tarih başlığı var mı?** (günlük). **Tüm hayat mı anlatılıyor?** (otobiyografi). **Geçmişte yaşanan bir olay ya da dönem mi anlatılıyor?** (anı).
:::

## 3. Şiir ve tiyatro

### Şiir

Duygu ve düşünceleri **ahenk, ritim, ölçü, uyak ve imgelerle** anlatan metindir. **Dize** (mısra) ve **bent** (kıta) gibi birimleri vardır. Dil, çoğunlukla mecaz ve söz sanatlarıyla zenginleşir.

### Tiyatro (oyun)

**Sahnede oynanmak** için yazılan metindir. **Diyaloglardan** oluşur, kişilerin adları sol tarafa yazılır. Yazar, sahne yönergelerini parantez içinde verir (kapıyı çalar, gülümser). Bölümlerine **perde** (ya da sahne) denir.

| Tür | İpucu |
| --- | --- |
| Şiir | Dize, bent, ahenk |
| Tiyatro | Diyalog, sahne yönergesi, perde |

