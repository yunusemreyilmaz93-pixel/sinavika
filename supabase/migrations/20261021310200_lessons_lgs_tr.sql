## 6. Paragraf tamamlama, akışı bozan cümle, ikiye bölme

**Paragraf tamamlama:** Boşluğa gelen cümle, paragrafın **konusuna ve akışına** uymalıdır. Hem öncesiyle hem sonrasıyla **bağ kurmalıdır**.

**Akışı bozan cümle:** Paragrafın ana düşüncesinden **uzaklaşan, konuyu değiştiren** cümledir. Seçeneklerden bulurken önce paragrafın genel konusunu belirle, sonra bu konuya uymayan cümleyi seç.

**Paragrafı ikiye bölme:** İkinci paragraf **yeni bir düşünceyle** başlamalıdır. Konu ya da bakış açısı değişen cümle yeni paragrafın başıdır. “Ancak”, “ama”, “diğer yandan” gibi zıtlık bildiren sözcükler çoğu zaman yeni paragraf işareti verir.

