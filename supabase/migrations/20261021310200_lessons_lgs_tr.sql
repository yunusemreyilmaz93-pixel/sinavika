## 1. Sözel mantık: sıralama

Verilen karşılaştırmaları (uzun, kısa, önce, sonra, ağır, hafif) **tek bir sıraya** yerleştirmek gerekir.

**Örnek:** Ali, Berk, Cem, Deniz ve Ece’nin boyları hakkında şu bilgiler veriliyor.

- Ali, Berk’ten uzundur.
- Cem, Ali’den uzundur.
- Deniz, Berk’ten kısadır.
- Ece, Cem’den kısadır ama Ali’den uzundur.

Bu bilgileri en uzundan en kısaya doğru dizelim.

1. **Cem > Ali** ve **Ali > Berk** olduğundan Cem > Ali > Berk.
2. Ece, Cem’den kısa ama Ali’den uzun: Cem > Ece > Ali.
3. Deniz, Berk’ten kısa: Berk > Deniz.

Birleştirince:

$$\text{Cem} > \text{Ece} > \text{Ali} > \text{Berk} > \text{Deniz}$$

Bu sıradan şu yargılar **kesin** olarak söylenebilir: Cem en uzundur, Deniz en kısadır, Ece, Ali’den uzundur.

:::dene
1. Yukarıdaki sıralamaya göre Berk’in tam olarak kaçıncı uzun olduğunu söyle. => Dördüncü. Cem, Ece, Ali, Berk, Deniz sırasındadır.
2. “Ali, Ece’den kısadır.” yargısı doğru mudur? => Doğrudur. Ece, Ali’den uzundur.
:::

## 2. Sözel mantık: eşleştirme

Kişi, nesne ve özellik eşleştirmeleri bir **tablo** ile çözülür. Doğru bilgileri “evet”, elenen bilgileri “hayır” yazarak ilerle.

**Örnek:** Ayşe, Burak ve Cansu’nun hobileri resim, müzik ve satranç olarak farklıdır.

- Ayşe, müzik ve resimle ilgilenmiyor.
- Burak, resimle ilgilenmiyor.

Çözüm:

| | Resim | Müzik | Satranç |
| --- | --- | --- | --- |
| Ayşe | Hayır | Hayır | **Evet** |
| Burak | Hayır | **Evet** | Hayır |
| Cansu | **Evet** | Hayır | Hayır |

1. Ayşe, müzik ve resimle ilgilenmediği için hobisi **satranç**.
2. Burak, resimle ve (Ayşe satranç olduğu için) satrançla ilgilenmiyor. Hobisi **müzik**.
3. Kalan hobi **resim**, Cansu’ya aittir.

## 3. Kesin doğru, kesin yanlış, belirlenemez

Soru şunu sorar: “Hangisi **kesin olarak** doğrudur?” O zaman:

- **Kesin doğru:** Verilen bilgilerden zorunlu olarak çıkar.
- **Kesin yanlış:** Verilen bilgilerle çelişir.
- **Belirlenemez:** Verilen bilgilerle ne doğrulanır ne yanlışlanır.

**Örnek:** “Bütün kediler hayvandır. Pamuk bir kedidir.”

- “Pamuk hayvandır.” → **Kesin doğru.**
- “Pamuk bir köpektir.” → **Kesin yanlış** (kedi köpek olamaz).
- “Pamuk beyazdır.” → **Belirlenemez.**

:::baglanti
“Bazı”, “hepsi”, “hiçbiri” gibi niceleyiciler çok önemlidir. “**Bazı** kuşlar uçar” bilgisinden “**Bütün** kuşlar uçar” sonucu **çıkmaz**. Kesinlik ifadeleri taşıyan sonuçlar, çoğunlukla verilen bilgilerden doğrudan çıkarılamaz.
:::

## 4. Görsel okuma: tablo ve grafik

Tablo ve grafiklerde çözüm yolu şudur.

1. **Başlığı ve etiketleri oku.** Neyi gösteriyor, birim ne?
2. **Soruda sorulan bilgiyi** tabloda ya da grafikte bul.
3. Gerekirse **işlem** yap (toplam, fark, oran).
4. **Seçeneklerle** karşılaştır.

**Örnek:** Bir okul kütüphanesinde bir hafta boyunca ödünç verilen kitap sayıları şöyledir: pazartesi 40, salı 55, çarşamba 35, perşembe 60, cuma 50.

| Gün | Ödünç verilen kitap |
| --- | --- |
| Pazartesi | 40 |
| Salı | 55 |
| Çarşamba | 35 |
| Perşembe | 60 |
| Cuma | 50 |

- En çok ödünç verilen gün **perşembedir** (60).
- En az ödünç verilen gün **çarşambadır** (35).
- En çok ile en az arasındaki fark $60 - 35 = 25$ kitaptır.
- Haftalık toplam $40 + 55 + 35 + 60 + 50 = 240$ kitaptır.

Grafik sorularında dikkat: **Eksenlerin neyi gösterdiğine** ve **birimin** ne olduğuna bak. Bir sütun grafiğinde sütun yüksekliği değeri, çizgi grafiğinde çizginin yükselişi artışı, daire grafiğinde dilimin büyüklüğü oranı gösterir.

## 5. Görsel okuma: afiş ve karikatür

### Afiş

Afiş, bir mesajı **görsel ve kısa yazıyla** vermeye çalışan reklam ya da bilgilendirme çalışmasıdır. Okurken şunlara bak.

- **Görsel:** Ne gösteriyor?
- **Slogan:** Ne söylüyor?
- **Amaç:** Kimi, neye çağırıyor? (Satış, bilinçlendirme, davet, uyarı)
- **Hedef kitle:** Kime hitap ediyor?

**Örnek:** Bir afişte, doğada atılmış bir plastik şişe çizilmiş ve altında “Doğa çöp kutusu değildir.” yazıyor.

- Görsel: Doğada atık.
- Slogan: Doğa çöp kutusu değil.
- Amaç: **Çevre bilinci** kazandırmak, çevreyi kirletmemeye çağırmak.
- Hedef kitle: Toplumun tamamı.

### Karikatür

Karikatür, **olayları ya da durumları abartarak, eleştirel ve esprili biçimde** anlatan çizimdir. Okurken şunlara dikkat et.

- Çizimde **ne gösteriliyor**? (Kişiler, nesneler, ortam)
- **Konuşma balonu** ya da yazı ne diyor?
- **Neyi eleştiriyor?** (Bir davranışı, bir aksaklığı, bir toplumsal sorunu)
- **Mizahi öğe** nedir? (Abartma, zıtlık, beklenmedik durum)

:::neden-sonuc
- Görselde bir tehlike ya da uyarı varsa => Afiş uyarı amaçlı olabilir.
- Çizimde abartı ve espri varsa, bir davranış eleştiriliyorsa => Karikatür olabilir.
- Tabloda bir değer sorulmuşsa => İlgili hücreyi bulup gerekiyorsa işlem yap.
- “Kesin olarak” deniyorsa => Yalnızca verilenlerden zorunlu çıkan sonuca güven.
:::

