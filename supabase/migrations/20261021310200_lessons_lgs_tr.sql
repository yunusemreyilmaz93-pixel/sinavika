## 1. Deyim

**Deyim**, sözcüklerin gerçek anlamlarından uzaklaşıp **kalıplaşarak kazandığı özel anlamla** kullanılan söz öbeğidir.

Özellikleri:

- **Kalıplaşmıştır.** İçindeki sözcükler değiştirilemez ve eş anlamlısıyla yer değiştiremez. “Göz atmak” yerine “bakış atmak” denmez.
- **Genellikle mecaz anlamlıdır.** “Ağzı kulaklarına varmak” gerçekten ağzın kulağa ulaşması değil, çok sevinmektir.
- **Cümlenin içinde kullanılır** ve fiil çekimi alabilir. “Sınavdan sonra **içi rahatladı**.”
- **Bir yargı bildirmez.** Bir durumu, davranışı ya da hâli anlatır.

| Deyim | Anlamı |
| --- | --- |
| Göz atmak | Hızlıca bakmak |
| Kulak vermek | Dikkatle dinlemek |
| Gönül koymak | Küsmek, kırılmak |
| El atmak | Bir işe başlamak ya da müdahale etmek |
| Eli açık olmak | Cömert olmak |
| Eli sıkı olmak | Cimri olmak |
| Gözden düşmek | Değerini ve saygınlığını yitirmek |
| Ağzı kulaklarında olmak | Çok sevinmek |
| Burnu havada olmak | Kibirli olmak |
| Yüzü gülmek | Mutlu olmak, işleri yolunda gitmek |
| Baş göz etmek | Evlendirmek |
| Göz yummak | Görmezden gelmek |

Deyimler cümleye **canlılık, kısalık ve anlam zenginliği** katar. “Çok sevindi” yerine “ağzı kulaklarına vardı” dediğimizde anlatım görsel ve etkili olur.

:::dene
1. “Bu konuya hiç **kulak asmadı**, hata yaptı.” cümlesinde “kulak asmak” ne demektir? => Aldırış etmemek, önemsememek.
2. “Yeni arabasını alınca **burnu havaya kalktı**.” cümlesindeki deyim ne anlatır? => Kibirlenmeyi, kendini beğenmeyi.
:::

## 2. Atasözü

**Atasözü**, uzun deneyimlerin ve gözlemlerin sonucunda ortaya çıkmış, **öğüt veren ya da genel bir doğruyu bildiren, kalıplaşmış** sözlerdir. Atasözlerinin söyleyeni belli değildir, **toplumun ortak ürünüdür**.

Özellikleri:

- **Yargı bildirir.** Kendi başına bir cümledir.
- **Genel bir doğruyu ya da öğüdü** anlatır.
- **Kalıplaşmıştır.** Sözcükleri değiştirilemez.
- **Çoğu zaman benzetme, karşılaştırma ve ses uyumu** içerir (“Damlaya damlaya göl olur”).
- Hem **gerçek hem mecaz** anlamlı olabilir. “Ateş düştüğü yeri yakar” gerçekten ateşin yaktığı bir yeri anlatır, ama genelde “acıyı yaşayan bilir” demektir.

| Atasözü | Anlattığı |
| --- | --- |
| Damlaya damlaya göl olur. | Küçük birikimler zamanla büyür |
| Sakla samanı, gelir zamanı. | Tutumlu davranmak ileride işe yarar |
| Ayağını yorganına göre uzat. | Gelirine göre harca |
| Bir elin nesi var, iki elin sesi var. | İş birliği ile iş daha kolay yapılır |
| Üzüm üzüme baka baka kararır. | Çevre insanı etkiler |
| Acele işe şeytan karışır. | Acele edersen hata yaparsın |
| Sabreden derviş muradına ermiş. | Sabreden sonunda istediğine ulaşır |
| Gülü seven dikenine katlanır. | Bir şeyi istiyorsan zorluklarına da katlanırsın |
| Ak akçe kara gün içindir. | Para kötü gün için biriktirilmelidir |
| Komşu komşunun külüne muhtaçtır. | Komşular birbirine ihtiyaç duyar, yardımlaşma önemlidir |

