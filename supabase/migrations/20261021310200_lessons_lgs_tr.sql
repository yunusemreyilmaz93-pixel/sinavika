“Göz” sözcüğü bir yerde yüzündeki organı, başka yerde “çekmecenin gözü”nü, bir başkasında “gözü pek” kişiyi anlatır. Aynı sözcük farklı cümlelerde farklı anlamlar kazanır. Bu konuda sözcüğün anlam katmanlarını ve sözcükler arasındaki anlam ilişkilerini öğreneceksin. LGS Türkçe’de her sınavda karşına çıkan bu konu, paragraf sorularının da temelidir.

:::hedefler
1. Sözcüğün gerçek, yan, mecaz ve terim anlamını ayırt etmek.
2. Eş anlamlı, zıt anlamlı ve eş sesli sözcükleri tanımak.
3. Somut ve soyut, genel ve özel anlamlı sözcükleri ayırt etmek.
4. Bir sözcüğün cümledeki anlamını bağlama bakarak belirlemek.
:::

:::ipucu
Bir sözcüğün anlamını **tek başına değil, cümlenin içinde** belirlersin. Soruda altı çizili sözcüğü gördüğünde önce cümlenin tamamını oku, sonra “Bu cümlede bu sözcük ne demek istiyor?” diye sor.
:::

## 1. Gerçek, yan, mecaz ve terim anlam

### Gerçek anlam

Sözcüğün akla gelen ilk, temel anlamıdır. Sözlükte ilk sırada yazılı olan anlamdır.

- **Taş** duvarı çok sağlamdı. (Sert, katı madde)
- Sabah erkenden **yola** çıktık. (Gidilen yol)

### Yan anlam

Sözcüğün temel anlamıyla bağlantılı kalan, ama farklı bir şeyi gösteren anlamlarıdır.

- Ali’nin **ayağı** burkuldu. (Temel anlam: Organ)
- Masanın **ayağı** kırıldı. (Yan anlam: Altta duran, taşıyan parça)
- Dağın **ayağında** küçük bir köy var. (Yan anlam: En alt kısım)

Yan anlamlar, temel anlamdan **benzerlik ya da kullanım ilişkisiyle** türemiştir. Sözlükte genellikle 2., 3. sırada yer alırlar.

### Mecaz anlam

Sözcüğün gerçek anlamından **tamamen uzaklaşıp**, bir benzetme ya da çağrışımla kazandığı anlamdır.

- **Tatlı** bir gülüşü vardı. (Hoş, sevimli)
- Sınavdan sonra **dünya başıma yıkıldı**. (Çok üzüldüm)
- **Soğuk** bir bakışla karşılandık. (Sevgisiz, ilgisiz)

### Terim anlam

Bir bilim, sanat ya da meslek dalına ait özel anlamdır. Yalnızca o alanda kullanıldığında bu anlama gelir.

- **Üçgen**in iç açıları toplamı 180°’dir. (Matematik)
- **Kök** hücre tedavisi gelişiyor. (Biyoloji)
- Bu şiirdeki **ölçü** hece ölçüsüdür. (Edebiyat)

:::neden-sonuc
- Sözcük temel anlamıyla kullanılır => Gerçek anlam. “Kuşlar **uçuyor**.”
- Temel anlamla bağı sürer ama farklı bir şeyi gösterir => Yan anlam. “Kalemin **ucu** kırıldı.”
- Anlam benzetmeyle uzaklaşır => Mecaz anlam. “Zaman **uçtu** gitti.”
- Bir bilim ya da meslek alanına özgüdür => Terim anlam. “Uçak **rüzgâr** tünelinde test edildi.”
:::

:::dene
1. “Eli açık biri olduğu için herkes onu severdi.” cümlesinde “eli açık” hangi anlamdadır? => Mecaz. “Cömert” anlamına gelir.
2. “Çaydanlığın **ağzı** kırıldı.” cümlesindeki “ağız” hangi anlamdadır? => Yan anlam. Temel anlamla (insan ağzı) bağı var, ama başka bir şeyi (çaydanlığın boşalan kısmı) gösterir.
:::

## 2. Sözcükler arasındaki anlam ilişkileri

### Eş anlamlı sözcükler

Yazılışı farklı, **anlamı aynı ya da çok yakın** sözcüklerdir.

| Sözcük | Eş anlamlısı |
| --- | --- |
| Okul | Mektep |
| Güzel | Hoş, endamlı |
| Hızlı | Çabuk, süratli |
| Başlamak | Girişmek |
| Cevap | Yanıt |

Eş anlamlı sözcükler her cümlede birbirinin yerine **kullanılamayabilir**. “Sıcak bir yemek” yerine “ılık bir yemek” dersen anlam değişir.

### Zıt (karşıt) anlamlı sözcükler

Anlamca birbirinin **tersi** olan sözcüklerdir: Uzun - kısa, açmak - kapamak, doğru - yanlış.

Dikkat: Bir sözcüğün zıt anlamlısı, **kullanıldığı anlama** göre değişir. “Açık hava” için zıt anlamlı “kapalı hava”, “açık renk” için ise “koyu renk” olur. Aynı sözcüğün her cümlede aynı zıt anlamlıya sahip olmadığına dikkat et.

### Eş sesli (sesteş) sözcükler

**Yazılışı ve okunuşu aynı, anlamları farklı ve aralarında anlam bağı olmayan** sözcüklerdir.

| Sözcük | Anlam 1 | Anlam 2 |
| --- | --- | --- |
| Yüz | Sayı (100) | Yüzü yıkamak |
| Çay | Bir içecek | Küçük akarsu |
| Al | Kırmızı | Almak fiili |
| Ben | Zamir | Ciltteki leke |

:::baglanti
**Eş sesli ile çok anlamlı (yan anlamlı) sözcüğü karıştırma.** Çok anlamlı sözcükte anlamlar arasında bir bağ vardır (ağaç gövdesi, masa gövdesi). Eş seslilerde bağ yoktur (yüz sayısı ile yüz organı). Bağ var mı yok mu, ayırt etmenin anahtarıdır.
:::

## 3. Somut ve soyut anlam

- **Somut anlamlı:** Beş duyu organımızla algılanan sözcükler. Masa, ses, koku, tuz, rüzgâr.
- **Soyut anlamlı:** Beş duyuyla algılanamayan, düşünce ve duygularımızla kavradığımız sözcükler. Sevgi, adalet, mutluluk, umut, cesaret.

Bazı sözcükler **hem somut hem soyut** anlamla kullanılabilir. “Ses” (duyulabilen şey) somuttur, “sesini duyurmak” (düşüncelerini bildirmek) mecazdır ve soyuttur.

## 4. Genel ve özel anlam

- **Genel anlamlı:** Bir grubun tamamını kapsayan sözcükler. Meyve, hayvan, taşıt.
- **Özel anlamlı:** Grubun içindeki tek bir türü gösteren sözcükler. Elma, kedi, otobüs.

“Çiçek” genel, “papatya” özeldir. Aynı sözcük bir ilişkide genel, başka bir ilişkide özel olabilir: “Hayvan”, “kedi”ye göre geneldir, “canlı”ya göre özeldir.

## 5. Sözcük soruları nasıl çözülür?

1. Altı çizili sözcüğü **cümlenin içinde** oku.
2. Seçeneklerdeki cümlelerde sözcüğün **aynı anlamda** kullanılıp kullanılmadığına bak.
3. Önce sözcüğün yerine **eş anlamlısını** koy. Cümle anlam bütünlüğünü koruyorsa anlam doğrudur.
4. “Hangisinde mecaz anlam vardır?” sorusunda, gerçek anlamla yorumlanamayan cümleyi ara.

