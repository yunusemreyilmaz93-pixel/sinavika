“Ali dün akşam arkadaşına mektup yazdı.” cümlesinde kim yazdı? Ne yazdı? Kime yazdı? Ne zaman yazdı? Bu soruların her biri cümlenin **bir ögesini** bulur. Cümlenin ögeleri, bir cümlenin yapı taşlarıdır. Bu konuda yüklemi, özneyi, nesneyi, dolaylı tümleci ve zarf tümlecini bulmayı öğreneceksin.

:::hedefler
1. Cümlede yüklemi ve özneyi bulmak.
2. Belirtili ve belirtisiz nesneyi ayırt etmek.
3. Dolaylı tümleci ve zarf tümlecini bulmak.
4. Özne türlerini (gerçek, gizli, sözde, ortak) tanımak.
:::

:::ipucu
Her cümle için **ilk adım yüklemi bulmaktır**. Cümlenin sonundaki ya da bütün işi bildiren sözcüğü yüklem olarak işaretle. Diğer ögeleri **yükleme sorular sorarak** bulacaksın.
:::

## 1. Yüklem

**Yüklem**, cümlede **yapılan işi, oluşu, durumu ya da kimliği** bildiren öğedir. Cümlenin temel ögesidir. Yüklem olmadan cümle olmaz.

- Ali okula **gitti**. (iş: gitmek)
- Hava çok **soğuk**. (durum: soğuk, ek-fiil “-dır” gizli)
- Bu kitap çok **ilginç**.

Yüklem çoğu zaman cümlenin sonundadır (kurallı cümle), ama başta ya da ortada olabilir (devrik cümle): “**Geldi** Ali.”

Yüklemi bulmak için: **“Ne yapıyor?”**, **“Ne oluyor?”**, **“Nasıl?”**, **“Nedir?”** sorularını sor.

## 2. Özne

**Özne**, yüklemde bildirilen işi **yapan ya da durumu yaşayan** öğedir. Yükleme **“Kim?”** ya da **“Ne?”** sorusu sorularak bulunur.

- **Ali** okula gitti. (Kim gitti? Ali)
- **Rüzgâr** kapıyı çarptı. (Ne çarptı? Rüzgâr)

### Özne türleri

| Özne türü | Özelliği | Örnek |
| --- | --- | --- |
| Gerçek özne | İşi gerçekten yapan, cümlede açıkça belirtilen | **Çocuk** kitabı okudu. |
| Gizli özne | Cümlede yazılı değil, yüklemin kişi ekinden anlaşılır | (Ben) Yarın geleceğim. |
| Sözde özne | Edilgen yüklemin öznesi, işi yapan değil işten etkilenen | **Kapı** açıldı. |
| Ortak özne | Birden fazla yüklem aynı özneyi paylaşır | **Ali** eve geldi, ellerini yıkadı, yemek yedi. |

:::baglanti
**Sözde özne**yi gerçek özneden ayırmak için yüklemin çatısına bak. “Kapı açıldı” cümlesinde kapıyı kim açtı bilinmez. Kapı açma işini yapmamıştır, **işten etkilenmiştir**. Yüklem edilgen olduğu için “kapı” sözde öznedir.
:::

## 3. Nesne

**Nesne**, öznenin yaptığı işten **doğrudan etkilenen** öğedir. Yükleme **“Neyi?”**, **“Kimi?”** sorusu sorularak bulunur. Nesne **yalnızca geçişli fiillerle** kullanılır.

### Belirtili nesne

Yükleme sorulan soruya cevap, **belirtme hâli eki (-ı, -i, -u, -ü)** alırsa belirtili nesnedir.

- Ali **kitabı** okudu. (Neyi okudu? Kitabı)
- Anne **çocuğu** uyandırdı. (Kimi uyandırdı? Çocuğu)

### Belirtisiz nesne

Ek almadan, çıplak biçimde kullanılırsa belirtisiz nesnedir.

- Ali **kitap** okudu. (Ne okudu? Kitap)
- Anne **yemek** yaptı. (Ne yaptı? Yemek)

| Özellik | Belirtili nesne | Belirtisiz nesne |
| --- | --- | --- |
| Ek | Belirtme hâli eki (-ı, -i) alır | Ek almaz |
| Soru | Neyi? Kimi? | Ne? |
| Anlam | Belli, bilinen bir varlık | Genel, belirsiz |
| Örnek | Kitabı okudu. | Kitap okudu. |

## 4. Dolaylı tümleç

**Dolaylı tümleç**, yüklemi **yönelme (-e), bulunma (-de) ve ayrılma (-den)** hâllerinde tamamlayan, yer ve yön bildiren öğedir. Yükleme **“Kime?”, “Neye?”, “Nereye?”, “Nerede?”, “Nereden?”, “Kimden?”** sorularıyla bulunur.

- Ali **okula** gitti. (Nereye gitti? Okula)
- Elif **arkadaşına** mektup yazdı. (Kime yazdı? Arkadaşına)
- Kitap **masada** duruyor. (Nerede duruyor? Masada)
- Çocuk **ağaçtan** düştü. (Nereden düştü? Ağaçtan)

:::neden-sonuc
- Yükleme “Neyi, kimi” diye soruyorsun => Nesne. “Kitabı okudu.”
- Yükleme “Kime, neye, nerede, nereden” diye soruyorsun => Dolaylı tümleç. “Okula gitti.”
- Yükleme “Nasıl, ne zaman, ne kadar, niçin” diye soruyorsun => Zarf tümleci. “Hızlı koştu.”
:::

## 5. Zarf tümleci

**Zarf tümleci**, yüklemi **zaman, durum, miktar, yer-yön, neden ve amaç** bakımından tamamlayan öğedir. Yükleme **“Nasıl?”, “Ne zaman?”, “Ne kadar?”, “Niçin?”** sorularıyla bulunur.

| Tür | Soru | Örnek |
| --- | --- | --- |
| Zaman | Ne zaman? | Ali **dün** geldi. |
| Durum | Nasıl? | Çocuk **hızlı** koştu. |
| Miktar | Ne kadar? | **Çok** yoruldum. |
| Yer-yön | Nereye? (ek almadan) | Çocuk **dışarı** çıktı. |
| Neden | Niçin? | Hasta **olduğu için** gelmedi. |
| Amaç | Ne için? | Başarmak **için** çalıştı. |

**Dikkat:** “Okula gitti” cümlesinde “okula” dolaylı tümleçtir (-e hâli eki var). “Dışarı çıktı” cümlesinde “dışarı” zarf tümlecidir (ek yok, yer-yön bildiren sözcük). İkisini karıştırma.

## 6. Örnek çözümleme

“Ali dün akşam arkadaşına mektup yazdı.”

1. **Yüklem:** yazdı (Ne yaptı?)
2. **Özne:** Ali (Kim yazdı?)
3. **Nesne:** mektup (Ne yazdı?) → belirtisiz nesne
4. **Dolaylı tümleç:** arkadaşına (Kime yazdı?)
5. **Zarf tümleci:** dün akşam (Ne zaman yazdı?)

| Öge | Sözcük |
| --- | --- |
| Özne | Ali |
| Zarf tümleci | dün akşam |
| Dolaylı tümleç | arkadaşına |
| Nesne | mektup |
| Yüklem | yazdı |

Sıra sabit değildir. Türkçede genellikle özne başta, yüklem sonda olur, diğer ögeler arada yer alır. Ancak vurgulanmak istenen öğe yüklemin önüne getirilebilir.

## 7. Konuyu toparla

| Öge | Soru | Örnek |
| --- | --- | --- |
| Yüklem | Ne yaptı? Nedir? | yazdı |
| Özne | Kim? Ne? | Ali |
| Nesne | Neyi? Kimi? Ne? | kitabı, kitap |
| Dolaylı tümleç | Kime? Nereye? Nerede? Nereden? | okula |
| Zarf tümleci | Nasıl? Ne zaman? Ne kadar? Niçin? | hızlı, dün |

