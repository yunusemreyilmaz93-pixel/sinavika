## 1. Yapısına göre cümleler

### Basit cümle

**Tek yargı** bildiren, tek yüklemi olan ve **yan cümlecik içermeyen** cümledir.

- Çocuklar bahçede oynuyor.
- Elif kitap okudu.
- Bugün hava çok güzel.

### Birleşik cümle

Bir **temel cümle** ile ona bağlı bir **yan cümle** (fiilimsi, şart ya da “ki”) içerir. Yan cümlenin kendi yüklemi yoktur ya da tamlayan bir yargı sunar.

- **Fiilimsili:** Eve **gelince** ödevini yaptı. (gelince: zarf-fiil)
- **Şartlı:** Yarın hava **güzel olursa** pikniğe gideceğiz.
- **“Ki” ile kurulan:** Biliyorum **ki** bu işi başaracaksın.

Birleşik cümlede **yan cümle, temel cümlenin bir ögesi** olur. “Eve gelince” yan cümleciği, temel cümlenin zarf tümlecidir.

### Sıralı cümle

Birden fazla **bağımsız cümlenin**, yan yana ve çoğunlukla **virgülle** dizilmesinden oluşur. Cümleler **bağlaç olmadan** art arda sıralanır. Her cümle kendi başına anlamlıdır.

- Ali geldi, Ayşe gitti.
- Güneş doğdu, kuşlar öttü, köy uyandı.
- Sabah erkenden kalktım, kahvaltı yaptım, okula gittim.

### Bağlı cümle

**Bağlaçla (ve, ama, fakat, çünkü, ancak, yoksa, ya da, hem…hem, ne…ne gibi) birbirine bağlanmış** bağımsız cümlelerden oluşur.

- Yağmur yağıyordu, **ama** biz yine de dışarı çıktık.
- Hava soğuktu, **çünkü** kış gelmişti.
- Hem çalıştı **hem** eğlendi.

| Tür | Özelliği | Örnek |
| --- | --- | --- |
| Basit | Tek yargı, yan cümle yok | Elif kitap okudu. |
| Birleşik | Temel cümle + yan cümle | Eve gelince yemek yedi. |
| Sıralı | Virgülle art arda bağımsız cümleler | Geldi, oturdu, bekledi. |
| Bağlı | Bağlaçla bağlanmış bağımsız cümleler | Yağmur yağdı ama çıktık. |

:::baglanti
Birleşik cümlede **tek bir temel yargı** vardır ve yan cümle ona bağlıdır. Sıralı ve bağlı cümlede ise **birden fazla bağımsız yargı** vardır. Fark şu: Sıralı ve bağlı cümlelerde, parçalardan her biri **tek başına cümle** olabilir. “Eve gelince” tek başına cümle olamaz, “Ali geldi” olabilir.
:::

## 2. Yüklemin türüne göre cümleler

### Fiil cümlesi

Yüklemi **fiil** (eylem bildiren sözcük) olan cümledir.

- Çocuklar parkta **oynuyor**. (Yüklem: oynuyor)
- Ayşe kitabı masaya **bıraktı**.

### İsim cümlesi

Yüklemi **isim, sıfat ya da zamir** (ek-fiil almış) olan cümledir.

- Hava çok **soğuk**. (Yüklem: soğuk, isim soylu)
- Bu kitap **benim**.
- Ali **hasta**.

İsim cümlelerinde yüklem “-dır, -dir, -tı, -ti” gibi ek-fiil alabilir ya da gizli ek-fiil ile kullanılır.

| Fiil cümlesi | İsim cümlesi |
| --- | --- |
| Çocuk **koştu**. | Çocuk **hızlı**. |
| Kitap **okuyorum**. | Bu kitap **ilginç**. |

## 3. Yüklemin yerine göre cümleler

### Kurallı cümle

Yüklemi **cümlenin sonunda** olan cümledir.

- Çocuklar bahçede **oynuyor**.
- Dün akşam sinemaya **gittim**.

### Devrik cümle

Yüklemi **cümlenin sonunda olmayan**, başta ya da ortada bulunan cümledir. Genellikle şiirde ve konuşma dilinde duygu vurgusu için kullanılır.

- **Gitti** Ali dün akşam.
- Eve **geldi** yorgun argın.
- **Seviyorum** seni.

## 4. Anlamına göre cümleler

| Tür | Özelliği | Örnek |
| --- | --- | --- |
| Olumlu | Bir işin yapıldığını ya da bir durumun var olduğunu bildirir | Çocuk okula gitti. |
| Olumsuz | Yapılmadığını ya da olmadığını bildirir. Fiile “-ma, -me” eki gelir | Çocuk okula gitmedi. |
| Soru | Soru bildirir, “mı, mi, mu, mü” ya da soru sözcükleri var | Okula gidecek misin? |
| Ünlem | Şaşkınlık, sevinç, korku gibi güçlü duygu bildirir | Ne kadar güzel bir gün! |

**Olumsuz cümle** yalnızca “-ma, -me” ekiyle değil “değil”, “yok” sözcükleriyle de kurulabilir: “Bu soru kolay **değil**.” “Evde kimse **yok**.”

**Dikkat:** Bir cümlenin biçimi ile anlamı farklı olabilir. “Hiç mi çalışmadım ben?” cümlesi soru biçimindedir ama “Çok çalıştım” anlamı taşır. Bu nedenle bağlama bak.

:::neden-sonuc
- Cümlede tek bir yüklem ve tek yargı var => Basit cümle.
- Cümlede fiilimsi ya da şart eki taşıyan bir yan cümle var => Birleşik cümle.
- Bağımsız cümleler virgülle sıralanmış => Sıralı cümle.
- Bağımsız cümleler “ama, çünkü, ve” ile bağlanmış => Bağlı cümle.
:::

