-- Plana dinlenme etkinliği eklenebilir. Film, dizi ve belgesel önerileri için katalog.
-- Kaynak Wikidata (CC0): Türkçe Vikipedi maddesi olan yapımlar, yaş sınırı FSK, MPA ya da RARS sınıflandırmasından.
-- Yalnızca 12 yaş ve altı için uygun bulunanlar alındı, uygun olmayan konulu yapımlar elle çıkarıldı. Belgesel dizilerinde yaş bilgisi yoksa min_age boştur.
alter type public.task_kind add value if not exists 'rest';

create table public.catalog_media (
  id integer generated always as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  year smallint check (year between 1890 and 2100),
  kind text not null check (kind in ('film', 'dizi', 'belgesel')),
  origin text not null check (origin in ('yerli', 'yabanci')),
  min_age smallint check (min_age in (0, 6, 12)),
  popularity smallint not null default 0,
  search text generated always as (public.fold_tr(title)) stored
);
create unique index catalog_media_unique on public.catalog_media (public.fold_tr(title), kind);

alter table public.catalog_media enable row level security;
create policy "media catalog read" on public.catalog_media for select to authenticated using (true);
revoke all on public.catalog_media from anon, authenticated;
grant select on public.catalog_media to authenticated;

-- Boş aramada en bilinen yapımlar döner
create or replace function public.search_catalog_media(p_query text, p_kind text)
returns table (id integer, title text, year smallint, kind text, origin text, min_age smallint)
language sql stable security invoker set search_path = ''
as $$
  with q as (select public.fold_tr(left(coalesce(p_query, ''), 80)) as v),
  p as (select v, replace(replace(replace(v, '\', '\\'), '%', '\%'), '_', '\_') as pattern from q)
  select m.id, m.title, m.year, m.kind, m.origin, m.min_age
  from public.catalog_media m, p
  where m.kind = p_kind
    and (char_length(p.v) < 2 or m.search like '%' || p.pattern || '%' or extensions.word_similarity(p.v, m.search) >= 0.45)
  order by (char_length(p.v) >= 2 and m.search like p.pattern || '%') desc, m.popularity desc, m.title
  limit 12
$$;
grant execute on function public.search_catalog_media(text, text) to authenticated;
revoke execute on function public.search_catalog_media(text, text) from anon, public;

