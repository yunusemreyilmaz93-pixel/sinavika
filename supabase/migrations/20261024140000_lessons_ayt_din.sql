- **Bimarhaneler (hastaneler):** Selçuklu ve Osmanlı şifahaneleri. Tıp eğitimi de verirdi (Edirne Sultan II. Bayezid Külliyesi, Divriği Darüşşifası).
- **Kütüphaneler ve vakıflar:** Bilim ve eğitim vakıflarla finanse edildi.

## 6. Bilim ve ahlak

Bilim değerlerden bağımsız değildir. İslam, bilginin **insanlığa yararlı** olmasını ve **ahlaki sınırlar** içinde kullanılmasını ister. Hadislerde yararsız ilimden Allah'a sığınılır. Tıpta hasta hakkı, doğaya zarar vermeme, israf etmeme, zararlı silahlar ve genetik müdahalelerde sorumluluk bu çerçevede tartışılır.

