## 1. Peygamber ve vahiy

- Hz. Muhammed'e vahiy yaklaşık **23 yıl** boyunca indirildi. İlk ayetler Hira Mağarası'nda "Oku" emriyle başladı.
- Kur'an, onun bir **beşer** olduğunu vurgular. "De ki: Ben ancak sizin gibi bir insanım. Bana ilahınızın tek bir ilah olduğu vahyolunuyor." (Kehf suresi, 110. ayet).
- Vahiy dışında kendi isteğiyle konuşmaz. Peygamberin görevi vahyi iletmek, açıklamak ve uygulamaktır.

::sim{tur="hzmuhammed"}

## 2. Kur'an'da Hz. Muhammed'in nitelikleri

- **Resul ve nebi:** Allah'ın elçisi ve peygamberi.
- **Üsve-i hasene (güzel örnek):** "Andolsun, Allah'ın Resulü'nde sizin için güzel bir örnek vardır." (Ahzab suresi, 21. ayet). Müminlerin ahlak ve davranışta model alacağı kişi.
- **Âlemlere rahmet:** "Biz seni ancak âlemlere rahmet olarak gönderdik." (Enbiya suresi, 107. ayet). Şefkat ve merhameti bütün insanlığı ve canlıları kapsar.
- **Şahit, müjdeci ve uyarıcı:** Doğru yolu gösteren, iman edenleri müjdeleyen ve inkâr edenleri uyaran. (Ahzab suresi, 45. ayet).
- **Yüce ahlak sahibi:** "Sen elbette büyük bir ahlak üzerindesin." (Kalem suresi, 4. ayet).
- **Ümmî:** Okuma yazması olmayan, yani vahyi öğrenmişlikle değil doğrudan Allah'tan aldığı vurgulanır.
- **Hâtemü'n-nebiyyîn (peygamberlerin sonuncusu):** "Muhammed, sizin erkeklerinizden hiçbirinin babası değildir. Fakat O, Allah'ın Resulü ve peygamberlerin sonuncusudur." (Ahzab suresi, 40. ayet).
- **Şefkatli ve yumuşak huylu:** "Allah'ın rahmeti sayesinde sen onlara yumuşak davrandın. Eğer kaba ve katı yürekli olsaydın, etrafından dağılıp giderlerdi." (Âl-i İmran suresi, 159. ayet).

## 3. Peygamberin görevleri

- **Tebliğ:** Vahyi insanlara eksiksiz iletmek.
- **Beyan (açıklama):** Kur'an'ı sözü ve davranışıyla açıklamak. Sünnet bu açıklamanın kaynağıdır.
- **Tezkiye:** İnsanları arındırmak, ahlaken yetiştirmek.
- **Örnek olmak:** Hayatıyla Kur'an'ın uygulanabilir olduğunu göstermek.
- **Hüküm vermek:** Toplumsal anlaşmazlıklarda adaletle hükmetmek.

## 4. Peygambere itaat ve sevgi

- Kur'an, Hz. Muhammed'e itaati **Allah'a itaatin** parçası sayar: "Kim Resul'e itaat ederse Allah'a itaat etmiş olur." (Nisa suresi, 80. ayet).
- Müminlerin Peygamber'e saygı göstermesi, onun sünnetine uyması ve ona **salavat getirmesi** istenir.
- Ancak ona **kul olma** vurgusu da vardır. Peygamber, ibadet edilen değil ibadette örnek olan kişidir.

## 5. Hz. Muhammed'in örnekliği

Hz. Muhammed her alanda insanlığa örnek olmuştur:

- **Dürüstlük:** Peygamberlikten önce de **el-Emin** (güvenilir) diye anılırdı.
- **Adalet:** Toplumda herkesi eşit kabul etti.
- **Merhamet:** Düşmanlarına bile affedici davrandı. Mekke'nin fethinde genel af ilan etti.
- **Alçakgönüllülük:** Sade yaşadı, yoksullarla birlikte oldu.
- **Hoşgörü:** Farklı inançlara saygı gösterdi. Medine Vesikası bunun örneğidir.
- **İlme ve akla önem verme.**

## 6. Hâtemü'n-nebiyyîn

Hz. Muhammed'in son peygamber olması, onun getirdiği dinin ve Kur'an'ın **kıyamete kadar** geçerli olduğunu gösterir. Kendisinden sonra yeni bir peygamber ya da yeni bir kitap gelmeyecektir. Kur'an'ın korunmuş olması bu inancı destekler.

## 7. Sık yapılan hatalar

- Hz. Muhammed'i bir ilah gibi görmek. Kur'an onun beşer ve kul olduğunu vurgular.
- "Üsve-i hasene" ile "rahmet" kavramlarını karıştırmak. Birincisi örnek olması, ikincisi şefkati ifade eder.
- "Hâtemü'n-nebiyyîn" ifadesini ilk peygamber sanmak. Son peygamber anlamındadır.
- Sünneti Kur'an'dan bağımsız bir kaynak sanmak. Sünnet Kur'an'ı açıklar.
- İlk vahyin Medine'de geldiğini sanmak. Mekke'de, Hira Mağarası'nda gelmiştir.

