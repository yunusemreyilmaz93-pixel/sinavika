## 1. Tasavvuf nedir

**Tasavvuf**, İslam'ın ahlaki ve manevi yönünü öne çıkaran, nefsi terbiye ederek **Allah sevgisine** ve **manevi olgunluğa** ulaşmayı amaçlayan bir anlayıştır. Tasavvufla uğraşan kişiye **mutasavvıf**, **sûfi** ya da **derviş** denir.

**Amacı:** Kalbi arındırmak, ahlakı güzelleştirmek, ibadetlerde derinlik kazanmak, Allah'a yakınlığı artırmak.

## 2. Gelişimi

- **Hz. Peygamber ve sahabe dönemi:** İbadet, takva ve zühd hayatı. Tasavvuf adı henüz yoktu.
- **Emevi ve Abbasi dönemi (8. ve 9. yüzyıl):** **Zühd hareketi** (Hasan Basri, Rabia el-Adeviyye). Dünya nimetlerinden uzak durma, ibadete yönelme.
- **9. ve 10. yüzyıl:** Tasavvuf sistemleşti. **Cüneyd-i Bağdadi, Hallac-ı Mansur.**
- **11. ve 12. yüzyıl:** **Gazali** tasavvufu şeriatla uzlaştırdı. **İhya-u Ulumi'd-Din.** Tarikatlar kurumsallaştı.
- **13. yüzyıl ve sonrası:** **İbn Arabi** (vahdet-i vücud), **Mevlana** ve **Yunus Emre.** Tarikatlar dünyaya yayıldı.

## 3. Temel kavramlar

- **Zühd:** Dünyaya aşırı bağlanmamak. Dünyayı terk etmek değil, onun kölesi olmamak.
- **Takva:** Allah bilincini koruyarak yasaklardan sakınmak.
- **Tevekkül:** Gerekli tedbiri aldıktan sonra sonucu Allah'a bırakmak.
- **İhlas:** Amelleri yalnızca Allah rızası için yapmak.
- **Aşk (muhabbet):** Allah'a karşı derin sevgi.
- **Marifet:** Allah'ı kalp gözüyle, derinlemesine tanımak.
- **Makam:** Kişinin çabasıyla ulaştığı kalıcı manevi derece (tevbe, zühd, sabır, tevekkül, rıza).
- **Hal:** Allah'ın lütfuyla gelen geçici manevi hâl (korku, ümit, aşk).
- **Nefis terbiyesi (mücahede):** Nefsin kötü isteklerine karşı çaba.
- **Seyr ü sülûk:** Manevi yolculuk.

## 4. Tarikatlar ve kurumlar

- **Tarikat:** Tasavvufi eğitimi belli bir usul ve şeyhin rehberliğinde sürdüren yol.
- **Şeyh (mürşid):** Rehberlik eden manevi önder. **Mürit:** Yola giren kişi.
- **Tekke, dergâh ve zaviye:** Zikir, sohbet ve eğitim yapılan, misafirlerin ağırlandığı yerler.
- **Zikir:** Allah'ı anma.
- **Sema:** Mevlevilerin müzik eşliğinde dönerek yaptığı manevi ayin.
- **Başlıca tarikatlar:** Kadirilik (Abdülkadir Geylani), Rifailik, Yesevilik, Mevlevilik, Nakşibendilik, Halvetilik, Bektaşilik.

## 5. Önemli mutasavvıflar

- **Hasan Basri (öl. 728):** İlk zahitlerden. Kalp temizliği.
- **Rabia el-Adeviyye (öl. 801):** İlahi aşk anlayışı.
- **Cüneyd-i Bağdadi (öl. 910):** Ayık tasavvuf anlayışı.
- **Gazali (1058-1111):** Tasavvufu şeriatla bağdaştırdı. İhya-u Ulumi'd-Din.
- **Abdülkadir Geylani (1077-1166):** Kadirilik.
- **Ahmed Yesevi (12. yüzyıl):** Türkistan, Divan-ı Hikmet.
- **İbn Arabi (1165-1240):** **Vahdet-i vücud** (varlığın birliği) görüşüyle bilinir. Füsusü'l-Hikem, Fütuhat-ı Mekkiyye.
- **Mevlana (1207-1273):** Aşk ve hoşgörü. Mesnevi.
- **Yunus Emre (13. yüzyıl):** Sade Türkçeyle ilahi aşk ve insan sevgisi.

## 6. Tasavvuf hakkındaki değerlendirmeler

- **Olumlu yönleri:** Ahlak eğitimi, ruhsal derinlik, sevgi ve hoşgörü kültürü, sanat ve edebiyata (musiki, hat, şiir) katkı.
- **Eleştiriler:** Kur'an ve sünnete aykırı uygulamalar, bid'at, kadere aşırı bağlılık nedeniyle pasiflik, şeyhe aşırı bağlılık, hurafeler.
- **Dengeli yaklaşım:** Tasavvuf Kur'an ve sünnetin ölçüleri içinde kalmalıdır. Gazali'nin yaklaşımı örnektir: Şeriat ile tasavvuf birbirini tamamlar.

