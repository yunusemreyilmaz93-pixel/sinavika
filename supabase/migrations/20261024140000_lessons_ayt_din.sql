## 1. Din ve bilim

- İslam'a göre **din ve bilim çatışmaz.** Her ikisi de aynı Yaratıcı'nın âlemdeki işaretleridir. Kur'an (okunan kitap) ve kâinat (okunan âlem) birbirini tamamlar.
- Kur'an, insanı **düşünmeye, gözlemlemeye ve araştırmaya** çağırır: "Hiç akletmiyor musunuz?", "Düşünmüyor musunuz?"
- **Bilimin amacı** doğayı anlamak, **dinin amacı** insanı doğru inanca ve ahlaka ulaştırmaktır. Bilimsel bilgi evrenin işleyişini, din varoluşun anlamını ve değerleri konu alır.
- Din bilimsel gelişmenin önünü açan değerler sunar: Merak, araştırma, dürüstlük, toplum yararı.

## 2. Kur'an ve hadislerde ilim

- İlk ayet: "Yaratan Rabbinin adıyla oku!" (Alak suresi, 1. ayet).
- "De ki: Hiç bilenlerle bilmeyenler bir olur mu?" (Zümer suresi, 9. ayet).
- "Rabbim, ilmimi artır." (Taha suresi, 114. ayet).
- Hadis: "İlim öğrenmek her Müslüman'a farzdır." (İbn Mâce).
- Kur'an'ın gökyüzünü, yeryüzünü, canlıları ve insanı **ayet (işaret)** olarak sunması gözlem ve araştırmayı teşvik etti.

## 3. İslam dünyasında bilimin gelişimi

- **8. ve 9. yüzyıl:** **Çeviri hareketi.** Yunan, Hint ve Fars eserleri Arapçaya çevrildi. Bağdat'ta **Beytülhikme** (Abbasiler) araştırma ve çeviri merkezi oldu.
- **Altın çağ (9. ile 13. yüzyıl):** Matematik, astronomi, tıp, kimya, coğrafya ve felsefede önemli ilerleme.
- Medreseler, rasathaneler, hastaneler (bimarhaneler), kütüphaneler ve vakıflar bilimi destekledi.
- **Batı'ya etkisi:** Endülüs ve Sicilya yoluyla Latinceye çeviriler (Toledo çeviri okulu). 12. yüzyıldan itibaren Avrupa üniversitelerinde İbn Sina, Razi ve İbn Rüşd eserleri okutuldu.

