## 1. Hinduizm

- **Kökeni:** Hindistan'da MÖ 1500 civarından itibaren gelişen, kurucusu belli olmayan bir dinî gelenektir.
- **Kutsal metinler:** **Vedalar**, **Upanişadlar**, **Bhagavad Gita**, **Mahabharata** ve **Ramayana.**
- **Tanrı anlayışı:** **Brahman**, her şeyin kaynağı olan en yüksek gerçekliktir. Çok sayıda tanrı bu gerçekliğin tezahürü sayılır. Ana tanrılar: **Brahma** (yaratıcı), **Vişnu** (koruyucu), **Şiva** (yok edici ve yenileyici). Bu üçlüye **Trimurti** denir.
- **Atman:** Bireysel ruh, Brahman'ın bir yansıması.
- **Karma:** Eylemlerin sonuçları. İyi eylemin iyi, kötü eylemin kötü karşılığı olur.
- **Samsara:** Ruhun ölümden sonra karmaya göre yeniden doğma döngüsü (reenkarnasyon).
- **Moksha:** Samsaradan kurtuluş, Brahman'la birleşme. Hinduizmin nihai hedefidir.
- **Kast sistemi:** Toplumsal tabakalar (Brahmanlar, Kşatriyalar, Vaişyalar, Şudralar). Modern Hindistan'da kast ayrımcılığı yasaktır.
- **İbadet:** Tapınaklarda ve evde. Kutsal şehirler (Varanasi) ve Ganj Nehri kutsal sayılır.

## 2. Budizm

- **Kurucusu:** **Siddhartha Gautama (Buda).** MÖ 6. ve 5. yüzyılda Kuzey Hindistan'da yaşadı. Saray hayatını bırakıp ıstırabın nedenini aradı ve aydınlanmaya ulaştı. "Buda" aydınlanmış kişi demektir.
- **Dört asil gerçek:**
  1. Hayat ıstıraptır (dukkha).
  2. Istırabın nedeni arzu ve bağlanmadır.
  3. Istırap sona erdirilebilir.
  4. Istırabın sonuna giden yol vardır.
- **Sekiz katlı yol:** Doğru görüş, düşünce, söz, eylem, geçim, çaba, dikkat ve odaklanma.
- **Nirvana:** Arzulardan kurtulup ıstıraptan arınma, samsara döngüsünün sona ermesi.
- **Ahlak:** Öldürmemek, çalmamak, yalan söylememek, zararlı maddelerden kaçınmak.
- **Mezhepler:** **Theravada** (Güneydoğu Asya) ve **Mahayana** (Çin, Japonya, Kore) ile **Vajrayana** (Tibet).
- **Aşoka** (MÖ 3. yüzyıl) Budizmin yayılmasını destekledi.
- Budizm tek bir yaratıcı tanrı inancına dayanmaz. İnsan kendi çabasıyla kurtuluşa erer.

::sim{tur="hintcin"}

## 3. Caynizm

- **Kurucusu:** **Mahavira** (MÖ 6. yüzyıl).
- **Ahimsa:** Hiçbir canlıya zarar vermeme ilkesi. Vejetaryenlik, bazı mensuplarda aşırı hassasiyet.
- Evrenin ezelî olduğuna ve ruhun karmadan arınarak kurtulabileceğine inanılır.
- Hindistan'da küçük ama etkili bir topluluktur.

## 4. Sihizm

- **Kurucusu:** **Guru Nanak** (15. yüzyıl, Pencap). Hinduizm ve İslam arasında bir uzlaşma arayışından doğdu.
- Tek tanrı inancı, kast sistemine karşı çıkış, eşitlik.
- Kutsal kitabı **Guru Granth Sahib.** İbadet yeri **Gurdvara.**

## 5. Konfüçyüsçülük

- **Konfüçyüs** (MÖ 551-479, Çin). Bir din olmaktan çok **ahlak ve toplum felsefesidir.**
- **Kutsal kitap benzeri eser:** **Analekt (Lun Yu)**, öğrencilerinin derlediği sözler.
- **Temel kavramlar:** **Ren** (insanlık, iyilik), **li** (davranış kuralları, ritüeller), **saygı** (özellikle ana-baba ve atalara), **toplumsal düzen.**
- Beş temel ilişki: Yönetici-tebaa, baba-oğul, ağabey-kardeş, koca-karı, arkadaşlar. Eğitime ve erdemli yöneticiliğe önem verilir.

## 6. Taoizm

- **Lao Tzu** (MÖ 6. yüzyıl) ile anılır. **Tao Te Ching** (Dao De Jing).
- **Tao:** Evrenin ve doğanın değişmez yasası, akışı. Tarif edilemez.
- **Wu wei:** Doğal akışa müdahale etmeme, zorlamamak.
- **Yin ve yang:** Karşıt ama birbirini tamamlayan güçler.
- Sadelik, doğallık ve doğayla uyum esastır.

## 7. Şintoizm

- **Japonya'nın yerli dini.** "Tanrıların yolu."
- **Kami:** Doğadaki ve atalardaki kutsal ruhlar. Dağlar, nehirler, ağaçlar kami taşıyabilir.
- Kurucusu ve tek bir kutsal kitabı yoktur. İbadet yeri **türbe ve tapınaklardır.** Arınma ve temizlik önemlidir. Budizmle birlikte yaşar.

## 8. İbrahimî dinlerle karşılaştırma

| | Hint ve Çin dinleri | İbrahimî dinler |
| --- | --- | --- |
| Tanrı | Çoğu zaman çok tanrılı ya da kişisel olmayan ilke | Tek, kişisel Tanrı |
| Ruh | Yeniden doğuş (Hint) | Tek hayat, ahiret |
| Kurtuluş | Moksha, nirvana | Cennet |
| Kurucu | Çoğu insan ya da bilge | Peygamber |
| Vahiy | Genel olarak yok | Vardır |

İslam diğer dinlere saygıyı emreder. Bu dinleri tanımak, onların takipçilerine ön yargısız yaklaşmamızı sağlar.

## 9. Sık yapılan hatalar

- Hinduizmin kurucusunu Buda sanmak. Budizm Buda'ya aittir, Hinduizmin kurucusu yoktur.
- Karma ile samsarayı karıştırmak. Karma eylem ve sonucu, samsara yeniden doğuş döngüsüdür.
- Konfüçyüsçülüğü Taoizmle karıştırmak. Birincisi toplumsal düzen, ikincisi doğaya uyum odaklıdır.
- Budizmi ibadet ettiği bir tanrı olan din sanmak. Merkezde kişisel çaba ve aydınlanma vardır.
- Şintoizmi Çin kökenli sanmak. Japonya'ya aittir.

