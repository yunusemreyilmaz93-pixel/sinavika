## 4. Din eğitimi ve vakıf kurumları

- **Medreseler:** Selçuklu ve Osmanlı döneminde din ve fen bilimlerinin okutulduğu eğitim kurumları. **Nizamiye Medreseleri**, **Fatih** ve **Süleymaniye Medreseleri.**
- **Vakıflar:** Mal ve mülkün hayır amacıyla bağışlanması. Cami, medrese, hastane, kervansaray, çeşme ve yollar vakıflarla yapıldı ve işletildi.
- **Külliyeler:** Cami, medrese, aşevi, hastane ve kütüphaneyi bir arada barındıran yapı toplulukları.
