## 1. İtikadi mezheplerin doğuşu

Hz. Peygamber döneminde inanç konularında ayrılık yoktu. Sonraki dönemde **siyasi olaylar** (halifelik tartışması, Sıffin Savaşı), **farklı kültürlerle temas** ve **Yunan felsefesinin çevirisi** sonucu inançla ilgili meseleler tartışıldı. **İtikadi (kelami) mezhepler** ortaya çıktı.

## 2. İman, amel ve büyük günah

- **Haricîler:** Büyük günah işleyen kişi imandan çıkar, kâfir olur.
- **Mürcie:** İman kalp ile tasdiktir, amel imanın parçası değildir. Büyük günah işleyenin durumunu Allah'a bırakırlar.
- **Mu'tezile:** Büyük günah işleyen ne mümin ne kâfirdir, **fasık**tır (el-menzile beyne'l-menzileteyn, iki konum arasındaki yer). Ahirette kalıcı cezayı hak eder.
- **Ehl-i sünnet:** Büyük günah işleyen **mümindir** ama günahkârdır. Allah dilerse bağışlar, dilerse cezalandırır. Amel imanın kemalidir ama aslî parçası değildir.

## 3. Kader ve insan iradesi

- **Cebriye:** İnsan hiçbir iradeye sahip değildir, bütün fiilleri Allah yapar. İnsan zorunlu (mecbur) varlıktır.
- **Kaderiye (Mu'tezile'ye yakın):** İnsan fiillerini tamamen kendisi yaratır ve özgürdür. Allah'ın ilmi onun fiillerini önceden belirlemez.
- **Ehl-i sünnet:** **Cüz'i irade.** Allah her şeyi bilir ve takdir eder (kader), insan da seçme gücüne sahiptir ve fiillerinden sorumludur. Allah yaratır, insan kesbeder (kazanır).
- Kader Allah'ın ilminin ve takdirinin ifadesidir. Kader cebir (mecburiyet) anlamına gelmez.

## 4. Akıl ve nakil (vahiy) ilişkisi

- **Mu'tezile:** Akla büyük önem verir. Akıl iyi ve kötüyü bağımsız olarak bilebilir. Çatışma durumunda akıl esas alınır ve nakil yorumlanır.
- **Eş'arilik:** Nakli esas alır. İyi ve kötü vahiyle belirlenir. Aklı kullanır ama naklin altında tutar.
- **Matüridilik:** Akıl ve nakli uyumlu görür. İyi ve kötünün büyük bölümünü akıl bilebilir, vahiy bunu tamamlar.
- **Selefiyye:** Ayetleri ve hadisleri yorumlamadan olduğu gibi kabul etmeyi önceler.

## 5. Ehl-i sünnet itikadi mezhepleri

- **Matüridilik:** **Ebu Mansur el-Matüridi** (öl. 944, Semerkant) tarafından kuruldu. Eseri **Kitabü't-Tevhid.** Türkler arasında yaygındır, Hanefi fıkhıyla uyumludur. Osmanlı ve Türkiye'de itikadi olarak kabul görür.
- **Eş'arilik:** **Ebu'l-Hasan el-Eş'ari** (öl. 935, Basra-Bağdat) tarafından kuruldu. Şafii ve Maliki mezhepleri arasında yaygındır.
- İkisi de **Ehl-i sünnet** çatısı altındadır. Aralarındaki farklar ayrıntıdadır.

**Matüridilik ve Eş'arilik farkı (örnek):**
- Matüridilik insan iradesine daha geniş yer verir.
- Matüridilik akla Eş'ariliğe göre daha fazla yetki tanır.
- Matüridiliğe göre iman tasdik, Eş'ariliğe göre de tasdiktir. Ancak Matüridi'de iman artıp eksilmez, Eş'ari'de artıp eksilebileceği görüşü bulunur.

## 6. Mezheplerin ortak noktası

Bütün mezhepler Allah'ın varlığına ve birliğine, Kur'an'a ve peygamberliğe inanır. Farklılıklar **yorum** düzeyindedir. Müslümanlar arasında iman esaslarında temel birlik vardır. Mezhep farklılıkları bir zenginlik ve yorum çeşitliliği olarak görülebilir. Birbirini tekfir etmek (kâfir ilan etmek) İslam'ın ruhuna aykırıdır.

