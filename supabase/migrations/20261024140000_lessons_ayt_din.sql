## 1. İman, küfür, nifak ve şirk

- **İman:** Allah'ın varlığına, birliğine ve Hz. Muhammed'in getirdiklerine kalbiyle inanıp dille söylemek (tasdik ve ikrar). İmanın şartları: Allah'a, meleklere, kitaplara, peygamberlere, ahirete ve kadere inanmak.
- **Küfür:** Sözlükte "örtmek." İslam'da Allah'a ve iman esaslarına inanmamak, onları inkâr etmek.
- **Nifak (münafıklık):** Dışarıdan inanmış gibi görünüp kalbinde inanmamak. Kur'an münafıkları ağır biçimde uyarır.
- **Şirk:** Allah'a ortak koşmak. Allah'ın zatında, sıfatlarında ya da fiillerinde bir başkasını O'na eş saymak. Kur'an'a göre en ağır günahlardandır. Tevhidin zıddıdır.
- **Tevhid:** Allah'ın bir ve eşsiz olduğuna inanmak.

## 2. Takva ve ihsan

- **Takva:** Allah'a karşı sorumluluk bilinciyle yasaklardan sakınıp emirlerine uymak. Kur'an'a göre Allah katında üstünlük **takva** iledir (Hucurat suresi, 13. ayet).
- **İhsan:** "Allah'ı görüyormuşçasına ibadet etmek, sen onu görmesen de O seni görmektedir." İşi en güzel biçimde yapmak ve iyilik yapmak.
- **Salih amel:** Allah'ın rızasına uygun, topluma ve kişiye yararlı davranış.
- **İhlas:** Yapılan işi yalnızca Allah rızası için yapmak.

## 3. Sabır, şükür ve tövbe

- **Sabır:** Zorluklar, musibetler ve nefsin arzuları karşısında dayanmak ve doğru yolda kalmak. Pasiflik değil, kararlılıktır.
- **Şükür:** Nimetlerin Allah'tan geldiğini bilip O'na teşekkür etmek, nimeti yerinde kullanmak.
- **Tövbe:** Yapılan günahtan pişman olup Allah'tan bağışlanma dilemek ve bir daha yapmamaya karar vermek. Kapı herkese açıktır.
- **Tevekkül:** Gereken sebeplere başvurduktan sonra sonucu Allah'a bırakmak.

## 4. Hidayet ve dalalet

- **Hidayet:** Doğru yolu bulmak, doğru yola iletilmek. Allah hidayeti nasip eder, insan da buna yönelmeli ve çaba göstermelidir.
- **Dalalet:** Doğru yoldan sapmak. İnsan iradesini kullanarak yanlış seçim yaparsa dalalete düşer.
- Kur'an hem Allah'ın dilemesini hem insanın çabasını vurgular.

## 5. Adalet, infak ve diğer kavramlar

- **Adalet:** Herkese hakkını vermek. Kur'an, düşmanlığa rağmen adaletten ayrılmamayı emreder (Maide suresi, 8. ayet).
- **İhsan, ihlas, iffet, emanet** gibi diğer ahlaki kavramlar.
- **İnfak:** Allah yolunda mal harcamak. Zekât (farz) ve sadaka (nafile) infakın biçimleridir.
- **Fısk:** Allah'ın emirlerinden çıkmak. **Zulüm:** Haksızlık, başkasının hakkını ihlal etmek.
- **Cihat:** Sözlükte "çaba ve gayret." İslam'da Allah yolunda çaba göstermek. Nefisle mücadele (büyük cihat), ilimle ve emekle iyiliği yaymak ile meşru savunma bu kavramın kapsamındadır.
- **Fitne, fesat:** Toplumsal düzeni bozmak.

## 6. Kavramların ahlaki ve toplumsal etkisi

- **Takva ve ihsan:** Gizli ve açıkta dürüstlük.
- **Adalet:** Toplumsal barışın temeli.
- **İnfak:** Toplumsal dayanışmayı güçlendirir.
- **Sabır ve şükür:** Bireyin ruhsal dengesini korur.
- **Şirk, nifak ve zulüm:** Hem bireyi hem toplumu yıpratır.

## 7. Sık yapılan hatalar

- Nifakı küfürle aynı sanmak. Nifak, görünüşte iman eden birinin içte inkârıdır.
- Küfür ile şirki karıştırmak. Küfür inkâr, şirk Allah'a ortak koşmaktır.
- İhsanı yalnızca para yardımı sanmak. İyilik, güzel davranış ve ibadette derinlik demektir.
- Sabrı pasif bekleyiş sanmak.
- Cihadı yalnızca savaş sanmak. Çaba ve gayret anlamına gelir, nefisle mücadeleyi de kapsar.

