## 3. Ahilik

- **Ahi Evran** önderliğinde 13. yüzyılda Anadolu'da kurulmuştur.
- **Amaç:** Esnaf ve zanaatkârları ahlaki ilkelerle teşkilatlandırmak. Kalite, dürüstlük, yardımlaşma ve usta-çırak ilişkisini düzenlemek.
