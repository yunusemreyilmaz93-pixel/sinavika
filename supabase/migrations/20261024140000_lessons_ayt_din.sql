## 1. Kur'an'a göre dünya hayatı

Kur'an dünya hayatını hem **geçici** hem de **değerli** görür. Dünya, insanın imtihana tabi tutulduğu yerdir.

- "O, hanginizin daha güzel davranacağını denemek için ölümü ve hayatı yarattı." (Mülk suresi, 2. ayet).
- Dünya nimetleri **helal yoldan** kullanılabilir. Dünyayı tamamen terk etmek ya da ona aşırı bağlanmak doğru değildir.
- Kur'an dünya hayatını ahiretin **tarlası** sayılır. Orada ekilen, ahirette biçilir.
- Başarı dünya malıyla değil **iman ve salih amelle** ölçülür.

## 2. Ölüm ve berzah

- **Ölüm:** Dünya hayatının sona ermesi. Herkes ölümü tadacaktır. Ecel Allah'ın takdirindedir.
- **Berzah:** Ölümle kıyamet arasındaki dönem. Kabir hayatı.
- **Kabir:** Bu dönemin başladığı yer. Ruhun bedenden ayrılması.

## 3. Kıyamet ve diriliş

- **Kıyamet:** Dünyanın sonu. **Sûr'a üfürülmesi** (İsrafil) ile kâinatın düzeni bozulur.
- **Kıyamet alametleri:** İlim azalması, ahlak bozulması, fitnelerin artması gibi hadislerde bildirilen işaretler. Kesin zamanı yalnızca Allah bilir.
- **Ba's (diriliş):** İkinci kez sûra üfürülünce herkesin yeniden dirilmesi.
- **Haşr ve mahşer:** İnsanların toplanması ve hesap için toplandıkları yer.

## 4. Hesap ve mizan

- **Hesap:** Kişinin dünyadaki amellerinin sorgulanması.
- **Amel defteri:** Yapılan iyi ve kötü işlerin kaydı. Sağdan alanlar kurtuluşa erer, soldan alanlar sıkıntıya düşer.
- **Mizan (terazi):** İyiliklerin ve kötülüklerin tartıldığı ölçü. Allah adalet esasına göre hükmeder.
- **Şefaat:** Allah'ın izniyle peygamberlerin ve salih kulların bağışlanmaya aracı olması.
- **Sırat:** Cehennem üzerinden geçilecek köprü.

## 5. Cennet ve cehennem

- **Cennet:** İnananların ve salih amel işleyenlerin ebedî mükâfat yurdu. En büyük nimet Allah'ın rızasıdır.
- **Cehennem:** İnkâr edenlerin ve zulüm yapanların cezalandırıldığı yer. Allah'ın adaletinin bir tecellisidir.
- **A'raf:** Cennet ile cehennem arası.
- Kur'an cennet ve cehennemi **maddi ve manevi** boyutlarıyla anlatır.

## 6. Ahiret inancının delilleri

- **Nakli deliller:** Kur'an ve hadisler ahiret hayatını kesin olarak bildirir. Kur'an'da birçok ayet ahireti konu edinir.
- **Akli deliller:**
  - **Adalet delili:** Dünyada her iyiliğin karşılığı görülmez ve her zulüm cezasız kalmaz. Adaletin tam gerçekleşmesi için ahiret gerekir.
  - **Yaratma delili:** İnsanı ilk kez yaratan Allah'ın yeniden yaratmaya gücü yeter.
  - **Hikmet ve amaç delili:** İnsan boş yere yaratılmamıştır. Hayatın bir amacı olmalıdır.
  - **Vicdan ve fıtrat:** İnsandaki ölümsüzlük özlemi.

## 7. Ahiret inancının etkileri

**Bireysel etkileri:**
- Sorumluluk bilinci kazandırır, kötülükten alıkoyar.
- Ölüm korkusunu ve kaygıyı azaltır, umut verir.
- Sabır ve dayanıklılık sağlar. Musibetlere karşı teselli olur.
- Hayata anlam katar.

**Toplumsal etkileri:**
- Adalet, dürüstlük ve güven ortamını güçlendirir.
- Yardımlaşma, paylaşma ve iyilik yapma davranışını teşvik eder.
- Hak ihlallerini ve suçları azaltır.

## 8. Sık yapılan hatalar

- Ahiret inancını dünyayı terk etmek sanmak. İslam dünya hayatını da önemser.
- Berzahı kıyametle karıştırmak. Berzah ölümden kıyamete kadar sürer.
- Mizanı yalnızca fiziksel bir terazi sanmak. Amellerin adaletle değerlendirilmesidir.
- Cennet ve cehenneme girişin yalnızca amele bağlı olduğunu sanmak. Allah'ın rahmeti ve affı da vardır.
- Kıyametin zamanını insanların bilebileceğini sanmak.

