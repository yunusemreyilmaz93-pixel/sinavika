## 4. Önemli bilim insanları

- **Harezmî (780-850):** **Cebirin kurucusu.** Hint rakamlarını tanıttı. "Algoritma" sözcüğü adından türemiştir. Hisab el-Cebr ve'l-Mukabele eseri.
- **İbn Heysem (965-1040):** **Optiğin kurucusu.** Kitabü'l-Menazır'da görmenin gözün içine gelen ışıkla olduğunu gösterdi. Deney yöntemini kullandı, karanlık oda deneyleri yaptı.
- **Razi (865-925):** Hekim ve kimyager. Çiçek ve kızamığı ayırt etti. El-Havi.
- **İbn Sina (980-1037):** Filozof ve hekim. **El-Kanun fi't-Tıb** yüzyıllarca Avrupa üniversitelerinde okutuldu.
- **Biruni (973-1048):** Matematik, astronomi, coğrafya ve tarih. Dünyanın çevresini hesapladı. Hindistan hakkındaki eseriyle bilinir.
- **Cezerî (1136-1206):** Otomatlar ve mekanik aletler. Mühendislik.
- **Ebu'l-Vefa, Battani, Ömer Hayyam:** Matematik ve astronomi.
- **Uluğ Bey (1394-1449):** Semerkant'ta rasathane kurdu. **Zic-i Cedid-i Sultani** yıldız cetveli.
- **Ali Kuşçu (1403-1474):** Uluğ Bey'in öğrencisi. Fatih Sultan Mehmed zamanında İstanbul'da ders verdi.
- **Takiyyüddin (1526-1585):** **İstanbul Rasathanesi.** Mekanik saat ve astronomi aletleri.

## 5. Bilimi destekleyen kurumlar

- **Beytülhikme:** Bağdat'ta çeviri ve araştırma merkezi.
- **Medreseler:** Nizamiye Medreseleri (Selçuklular), **Fatih ve Süleymaniye Medreseleri** (Osmanlı).
