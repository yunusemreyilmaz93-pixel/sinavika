## 1. Din ve laiklik

- **Laiklik:** Devlet işlerinin din kurallarına göre yürütülmemesi, devletin bütün inançlara eşit mesafede durması ve **vicdan, din ve ibadet özgürlüğünün** güvence altında olmasıdır.
- Türkiye'de laiklik 1937'de Anayasa'ya girdi. Din hizmetleri **Diyanet İşleri Başkanlığı** (1924) tarafından yürütülür. Din eğitimi MEB ve Diyanet çerçevesinde yürütülür.
- **İslam'a göre:** Kur'an'da "Dinde zorlama yoktur." (Bakara, 256). Herkes inancında ve ibadetinde özgürdür.
- Laiklik, dinsizlik değildir. Hem dindar hem dinsiz bireyin haklarını güvence altına alır.

## 2. Din, bilim ve teknoloji

- Din ve bilim farklı alanlara hitap eder. Bilim "nasıl?" sorusuna, din "neden ve ne için?" sorusuna odaklanır.
- İslam bilimsel araştırmayı teşvik eder. Teknoloji **insanlığın yararına** kullanıldıkça değerlidir.
- **Etik sınırlar:** Genetik müdahale, klonlama, yapay zekâ ve biyoteknolojide insan onuru, canlıların ve gelecek kuşakların haklarının korunması gerekir.
- **Medya ve internet:** Bilgi kirliliği, mahremiyet, siber zorbalık. Haber ve bilgi doğrulanmadan paylaşılmamalıdır (Hucurat suresi, 6. ayet).

## 3. Sağlık ve bağımlılıklar

- İslam **yaşamın ve sağlığın korunmasını** esas alır. Beden bir emanettir.
- **Tedavi olmak** teşvik edilir. Tevekkül, tedbiri dışlamaz.
- **Organ ve doku nakli:** Din alimleri ve Diyanet, hayat kurtaracak organ bağışını, bazı şartlarla uygun bulur.
- **Bağımlılık:** Alkol, uyuşturucu, kumar ve sigara gibi akla ve sağlığa zarar veren maddelerden sakınmak esastır. Kur'an içkiyi ve kumarı yasaklar (Maide suresi, 90. ayet). **Aklın korunması** İslam hukukunun amaçlarındandır.
- **Ruh sağlığı:** Psikolojik destek almak dinî tevekküle aykırı değildir.

## 4. Çevre

- İnsan yeryüzünde **halife** (sorumlu temsilci) konumundadır. Doğa **emanettir.**
- **İsraf** yasaktır. Su, enerji ve gıda israf edilmemelidir (Araf, 31).
- **Çevre kirliliği, ormansızlaşma ve canlı türlerinin yok edilmesi** Kur'an'ın "bozgunculuk" (fesat) uyarısıyla ilişkilendirilir.
- Hz. Peygamber ağaç dikmeyi teşvik etti. Hayvanlara şefkat gösterilmesini emretti.

## 5. Şiddet, terör ve barış

- Kur'an'a göre haksız yere bir insanı öldürmek bütün insanlığı öldürmek, bir insanı kurtarmak da bütün insanlığı kurtarmak gibidir (Maide suresi, 32. ayet).
- **İslam terörü ve masum insanın öldürülmesini yasaklar.** Terör hiçbir dine ya da inanca mal edilemez.
- **Barış ve adalet** temel değerlerdir. Savaş ancak meşru savunma amacıyla ve etik kurallar çerçevesinde söz konusudur. Kadın, çocuk, yaşlı ve sivillere zarar verilemez.
- **Radikalleşme:** Dinin yanlış ve aşırı yorumlanması. Sağlam dinî bilgi bu eğilime karşı koruyucudur.

## 6. Dinlerarası diyalog ve hoşgörü

- Kur'an farklı din ve kültürlerin varlığını bir **gerçeklik** olarak kabul eder: "Sizin dininiz size, benim dinim banadır." (Kâfirûn suresi, 6. ayet).
- **Medine Vesikası** ve **Osmanlı millet sistemi** farklı dinlerin bir arada yaşamasının tarihî örnekleridir.
- **Diyalog:** Karşılıklı anlayış, saygı ve ortak değerler üzerinde buluşma. Amaç inançları birleştirmek değil barış içinde birlikte yaşamaktır.
- **Önyargı, ayrımcılık ve nefret söylemi** dinin ahlak ilkelerine aykırıdır.

## 7. Dinî bilgi kaynakları

- **Birincil kaynaklar:** Kur'an ve sahih sünnet.
- **Din alimleri ve ilmî kurumlar:** Diyanet İşleri Başkanlığı, ilahiyat fakülteleri, Din İşleri Yüksek Kurulu.
- Güvenilir bilgi için **kaynak, uzmanlık ve ilmî birikim** esastır. Sosyal medyadaki yorumlar tek başına yeterli değildir.
- **İctihad, fetva, kelam, fıkıh:** Dinî hükümlerin anlaşılmasında kullanılan alanlar.

## 8. Sık yapılan hatalar

- Laikliği dine karşı olmak sanmak. İnanç özgürlüğünü güvence altına alır.
- Din ve bilimin çatıştığını sanmak.
- İslam'ın şiddeti ve terörü onayladığını sanmak. Masum canın korunması temel ilkedir.
- Bilgi kaynağı olarak anonim sosyal medya yorumlarını yeterli saymak.
- Tevekkülü tedavi olmamak sanmak.

