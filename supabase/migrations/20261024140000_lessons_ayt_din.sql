## 1. Yahudilik

**Tarihsel gelişim:**
- **Hz. İbrahim:** Ortak ata kabul edilir. Hz. Yakub (İsrail) soyundan gelenlere **İsrailoğulları** denir.
- **Hz. Musa:** İsrailoğullarını Mısır'dan çıkardı. **Tevrat** ve **On Emir** bu döneme bağlanır.
- **Hz. Davud ve Hz. Süleyman:** İsrail krallığı ve Kudüs'te Süleyman Mabedi (MÖ 1000 civarı).
- **Babil sürgünü (MÖ 586):** Kudüs yıkıldı, Yahudilerin önemli bölümü sürüldü. Tevrat metinleri bu dönemde derlendi.
- **Diaspora:** Yahudilerin dünyaya dağılması.

**Kutsal kitaplar:**
- **Tevrat (Tanah):** Hz. Musa'ya indirilen, ancak zamanla değişikliğe uğradığı kabul edilen kitap. Yahudilere göre kutsal kitabın tamamı (Tevrat, Neviim ve Ketuvim) Tanah'tır.
- **Talmud:** Sözlü geleneğin yazıya geçirilmiş hâli, yorum ve hukuk metinleri.

**İnanç esasları:** Tek Tanrı (Yehova) inancı, peygamberlik, Tevrat'ın vahiy olması, seçilmiş halk anlayışı ve Mesih bekleyişi, ahiret inancı.

**İbadet ve kurumlar:**
- **Sinagog:** İbadet yeri. **Haham:** Dinî lider ve âlim.
- **Şabat:** Cuma akşamından Cumartesi akşamına kadar süren haftalık dinlenme ve ibadet günü.
- **Bayramlar:** **Pesah** (Mısır'dan çıkış), **Roş Aşana** (yeni yıl), **Yom Kippur** (kefaret günü), **Purim**, **Hanuka.**

## 2. Hristiyanlık

**Tarihsel gelişim:**
- **Hz. İsa:** Hristiyanlık onun öğretisine dayanır. İslam'a göre Allah'ın peygamberidir.
- **İlk dönem:** Roma İmparatorluğu'nda zulüm gördü. **Pavlus** Hristiyanlığın Yahudi olmayanlara yayılmasında etkili oldu.
- **313 Milano Fermanı:** Roma'da Hristiyanlığa serbestlik. **325 İznik Konsili:** İnanç esasları tartışıldı. **380:** Roma'da resmî din oldu.
- **1054 Büyük ayrılık:** Katolik ve Ortodoks kiliseleri ayrıldı.
- **1517 Reform:** Martin Luther ile Protestanlık doğdu.

**Kutsal kitap:** **İncil** (Yeni Ahit). Hristiyanlar Eski Ahit'i (Tevrat) de kutsal sayar. Dört İncil (Matta, Markos, Luka, Yuhanna) kabul edilir.

**İnanç esasları:** Teslis (Baba, Oğul ve Kutsal Ruh), İsa'nın tanrısal niteliği, haç ve kurtuluş, ahiret.

**İbadet ve kurumlar:** **Kilise.** **Vaftiz** (dinî kabul töreni), **evharistiya** (ayin). **Pazar** haftalık ibadet günü. **Noel** ve **Paskalya** başlıca bayramlardır.

**Mezhepler:**
- **Katolik:** Merkezi Vatikan, lideri Papa.
- **Ortodoks:** Doğu kiliseleri. Merkezi yoktur, patrikhaneler vardır (İstanbul Fener Rum Patrikhanesi önde gelen patrikhanedir).
- **Protestan:** Reform sonucu doğdu. Kutsal metne ve kişisel imana vurgu. Papa'nın otoritesini kabul etmez.

## 3. Kur'an'ın Ehl-i kitaba bakışı

- Kur'an Yahudi ve Hristiyanlara **Ehl-i kitap** (kitap sahipleri) der. Tevrat, Zebur ve İncil'in Allah tarafından indirildiğini kabul eder.
- Bu kitapların **zamanla değişikliğe uğradığını** (tahrif) belirtir. Kur'an onları doğrulayıcı ve koruyucu olarak indirilmiştir.
- Ehl-i kitaba karşı **adalet, hoşgörü ve güzel davranış** emredilir. "Dinde zorlama yoktur." (Bakara suresi, 256. ayet).
- **Hz. İsa'nın** Allah'ın kulu ve peygamberi olduğunu, **teslis** inancının kabul edilmediğini vurgular.
- Ehl-i kitapla evlilik ve yiyecek gibi konularda özel hükümler vardır.
- **Medine Vesikası** ve Osmanlı **millet sistemi** farklı inançların bir arada yaşamasının tarihî örnekleridir.

## 4. İslam ile benzerlikler ve farklar

- **Benzerlikler:** Tek Tanrı inancı (Yahudilikte tam, Hristiyanlıkta teslis yorumuyla), peygamberler, vahiy, ahiret, ahlaki ilkeler.
- **Farklar:** Peygamber anlayışı, kutsal kitaplarının değişmeden korunup korunmadığı, teslis, Hz. Muhammed'in peygamberliği.

## 5. Sık yapılan hatalar

- Yahudilik ile Hristiyanlığı karıştırmak. Hristiyanlık Hz. İsa'nın öğretisine, Yahudilik Hz. Musa'ya ve Tevrat'a dayanır.
- Talmud'u Tevrat sanmak. Talmud sözlü geleneğin yorum ve hukuk metinleridir.
- Ortodoks ile Katolik'i aynı sanmak. 1054'te ayrılmışlardır.
- Protestanlığın İznik Konsili'nde doğduğunu sanmak. Reform ile 16. yüzyılda doğmuştur.
- Kur'an'ın Ehl-i kitaba düşman olduğunu sanmak. Adalet ve hoşgörü emredilir.

