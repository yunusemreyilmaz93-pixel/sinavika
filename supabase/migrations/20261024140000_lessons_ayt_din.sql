## 2. Anadolu'daki tasavvufi hareketler

- **Yesevilik:** **Ahmed Yesevi** (Türkistan, 12. yüzyıl). **Divan-ı Hikmet.** Türkçe, sade dil. Anadolu'ya alperen ve dervişlerle taşındı.
- **Mevlevilik:** **Mevlana Celaleddin Rumi** (1207-1273, Konya). **Mesnevi, Divan-ı Kebir, Fihi Mâ Fih.** Aşk, hoşgörü ve insan sevgisi. Oğlu **Sultan Veled** Mevlevilik tarikatını sistemleştirdi. **Sema** ayini.
- **Bektaşilik:** **Hacı Bektaş Veli** (1247-1337, Kırşehir civarı). **Makalat.** "Eline, beline, diline sahip ol." İnsan sevgisi, çalışma ve paylaşma.
- **Ahilik:** **Ahi Evran** (Kırşehir). Esnaf ve sanatkârları teşkilatlandıran, ahlaki ilkelere dayalı kurum.
- **Kadirilik, Rifailik, Halvetilik, Nakşibendilik, Bayramilik** gibi tarikatlar da Anadolu'da yayıldı.
- **Hacı Bayram Veli** (Ankara): Bayramilik tarikatının kurucusu. Ankara'daki külliyesiyle tanınır.
- **Yunus Emre** (1240-1320): Mürşidi Tapduk Emre'dir. Arı Türkçeyle yazdığı şiirlerde sevgi, hoşgörü ve insana değer verme. Divan ve Risaletü'n-Nushiyye.

