Deprem, sel, fırtına, yanardağ patlaması. Doğa olayları bazen büyük zarara yol açar ve hazırlıklı olmak canımızı kurtarabilir. Türkiye, depremlerin sık yaşandığı bir ülke olduğu için deprem ve afetle ilgili bilgi herkes için önemlidir. Bu konuda doğal afetlerle ilgili İngilizce kelimeleri, afet sırasında ne yapılması gerektiğini ve geçmişte yaşanan afetleri anlatmayı öğreneceksin.

:::hedefler
1. Doğal afetlerin adlarını ve sonuçlarını İngilizce söylemek.
2. Afet öncesinde, sırasında ve sonrasında yapılması gerekenleri emir cümleleri ve “should” ile anlatmak.
3. Geçmişte yaşanan bir afeti geçmiş zaman cümleleriyle anlatmak.
