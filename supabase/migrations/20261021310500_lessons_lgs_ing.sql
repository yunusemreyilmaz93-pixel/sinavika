## 2. Zorunluluk: have to ve must

**Have to (-meli, zorundayım):** Dışarıdan gelen kurallar, görevler. **Must:** İç kaynaklı ya da güçlü zorunluluk.

- I **have to** do my homework. (Ödevimi yapmak zorundayım.)
- She **has to** clean her room every Saturday.
- We **must** be quiet in the library.
- **Do** you **have to** wash the dishes? (Bulaşığı yıkamak zorunda mısın?)

| Olumlu | Olumsuz | Soru |
| --- | --- | --- |
| I have to | I don’t have to | Do I have to…? |
| He/She has to | He/She doesn’t have to | Does he/she have to…? |
| You must | You mustn’t | Must I…? |

