## 4. Past Continuous (-ing)

Geçmişte **belli bir anda devam eden** eylemleri anlatır.

**was / were + fiil + -ing**

- I **was walking** in the forest. (Ormanda yürüyordum.)
- They **were swimming** in the lake. (Gölde yüzüyorlardı.)
- **Were** you **sleeping**? (Uyuyor muydun?)
- She **wasn’t listening**. (Dinlemiyordu.)

### When ve While

- **While:** Uzun süren olayı bildirir. **While + past continuous**
- **When:** Kısa olayı bildirir. **When + past simple**

**Örnek:**

- **While** I **was walking** in the forest, I **saw** a bear.
- I **was swimming** **when** it **started** to rain.

| | Uzun olay (past continuous) | Kısa olay (past simple) |
| --- | --- | --- |
| Örnek | I was walking in the forest | when I saw a bear |
| Bağlaç | **while** + uzun olay | **when** + kısa olay |

:::neden-sonuc
- Bir olay devam ederken bir başka olay aniden olur => Uzun olay “was/were + -ing”, kısa olay “past simple”.
- Uzun olayın başına “while” getirilir => While we were camping, it started to rain.
- Kısa olayın başına “when” getirilir => We were camping when it started to rain.
:::

