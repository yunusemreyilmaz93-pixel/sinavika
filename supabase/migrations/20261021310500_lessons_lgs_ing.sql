## 2. Sevme, sevmeme ve tercih etme

### Sevme ve sevmeme kalıpları

| Kalıp | Anlamı | Örnek |
| --- | --- | --- |
| like / love + -ing | sevmek, çok sevmek | I **like playing** chess. |
| enjoy + -ing | zevk almak | She **enjoys drawing**. |
| be fond of + -ing | hoşlanmak | He **is fond of reading**. |
| be keen on + -ing | meraklı olmak | They **are keen on dancing**. |
| don’t mind + -ing | sakıncası yok | I **don’t mind helping** you. |
| dislike / don’t like + -ing | sevmemek | I **dislike waiting**. |
| hate + -ing | nefret etmek | He **hates getting** up early. |
| can’t stand + -ing | dayanamamak | I **can’t stand being** late. |

:::baglanti
Bu kalıpların hepsinde **fiil -ing** alır. “I enjoy **to swim**” yanlış, “I enjoy **swimming**” doğrudur. Seçeneklerde **to + fiil** ile **-ing** arasında seçim yapman gerekiyorsa bu kuralı hatırla.
