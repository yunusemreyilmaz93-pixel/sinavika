- You **mustn’t** share your password. (Yasak, güçlü)
- You **can** ask your teacher for help.

**Should ile must arasındaki fark:** “Should” tavsiyedir, “must” ise güçlü bir zorunluluktur.

## 5. If cümleleri (Birinci tip)

Gerçekleşebilecek bir durumun **sonucunu** anlatırken “if” cümlesi kullanırız.

**If + şimdiki zaman (present simple), will + yalın fiil**

- **If you share** your password, someone **will use** your account.
- **If you click** on unknown links, your computer **will get** a virus.
- **If you spend** too much time online, you **won’t have** time for homework.
- **If you study** with the internet, you **will find** many sources.

| If kısmı | Sonuç kısmı |
| --- | --- |
| If you chat with strangers, | you may get into trouble. |
| If you use a strong password, | your account will be safer. |
| If you don’t log out, | someone can use your account. |

:::neden-sonuc
- Şifreni paylaşırsın => Birisi hesabını kullanabilir (If you share it, someone will use it).
- Bilinmeyen bağlantılara tıklarsın => Bilgisayarına virüs girebilir.
- Güçlü şifre kullanırsın => Hesabın daha güvenli olur.
:::

## 6. Siber zorbalık

**Cyberbullying**, internet üzerinden birine kötü davranmak, onu incitmek ya da korkutmaktır. Mesajlarla hakaret etmek, utandırıcı fotoğraf paylaşmak, dışlamak gibi davranışlar siber zorbalık sayılır.

