## 2. Afet öncesi hazırlık

Bir afet olmadan önce yapılacaklar:

- **Prepare an emergency kit.** (Acil durum çantası hazırla.)
- **Learn** the safe places in your home and school.
- **Know** the emergency phone numbers.
- **Plan** a meeting place with your family.
- **Fix** heavy furniture to the wall.
- **Practice** emergency drills (tatbikat).

