Bir arkadaşını doğum günü partisine davet etmek, onun teklifini kibarca reddetmek ya da bir arkadaşının sana nasıl davrandığını anlatmak. Bunların hepsi **arkadaşlık** üzerine İngilizce konuşmaktır. LGS İngilizce sorularında bu ünite genellikle **diyalog tamamlama, davet etme, kabul etme, reddetme ve arkadaşlık özelliklerini anlatma** sorularıyla gelir. Bu konuda gerekli kelimeleri, kalıpları ve soru tiplerini öğreneceksin.

:::hedefler
1. Arkadaşlıkla ilgili temel kelimeleri ve sıfatları kullanmak.
2. Davet etme, kabul etme ve reddetme kalıplarını doğru kullanmak.
3. Arkadaşlık özelliklerini ve problemlerini İngilizce anlatmak.
4. Diyalog tamamlama sorularında doğru cevabı seçmek.
:::

:::ipucu
Diyalog tamamlama sorularında **önce karşılıklı konuşmanın havasına** bak. Davet ediliyorsa cevap “kabul” ya da “ret” olmalıdır. Cevap sorunun türüyle uyumlu olmalı. Soruyu anlamadan seçeneklere bakma.
:::

## 1. Arkadaşlık sözcükleri

| İngilizce | Türkçe |
| --- | --- |
| friend | arkadaş |
| close friend | yakın arkadaş |
| best friend | en iyi arkadaş |
| classmate | sınıf arkadaşı |
| neighbor | komşu |
| friendship | arkadaşlık |
| trust | güvenmek, güven |
| honest | dürüst |
| loyal | sadık, vefalı |
| helpful | yardımsever |
| kind | nazik, iyi kalpli |
| generous | cömert |
| reliable | güvenilir |
| supportive | destekleyici |
| share | paylaşmak |
| get along with | iyi geçinmek |
| argue | tartışmak |
| make up | barışmak |
| keep a secret | sır tutmak |
| miss | özlemek |

**Örnek cümleler:**

- A good friend is **honest** and **loyal**.
- My best friend always **supports** me.
- We **get along** very well.
- We argued yesterday, but we **made up** today.

## 2. İyi bir arkadaşın özellikleri

İyi bir arkadaşı anlatırken şu kalıpları kullanabilirsin.

- A good friend **should be** honest. (İyi bir arkadaş dürüst olmalıdır.)
- A true friend **never** lies to you. (Gerçek bir arkadaş sana asla yalan söylemez.)
- A good friend **listens** to you and **helps** you.
- You can **trust** him/her with a secret.

| Güzel bir arkadaşlık için | Arkadaşlığı bozan davranışlar |
| --- | --- |
| honesty (dürüstlük) | lying (yalan söylemek) |
| trust (güven) | gossiping (dedikodu yapmak) |
| respect (saygı) | being selfish (bencil olmak) |
| sharing (paylaşmak) | breaking promises (sözünü tutmamak) |

## 3. Davet etme (Invitations)

Bir arkadaşını bir etkinliğe çağırırken kullanılan kalıplar:

- **Would you like to** come to my birthday party? (Doğum günü partime gelmek ister misin?)
- **Do you want to** go to the cinema with me? (Benimle sinemaya gitmek ister misin?)
- **How about** playing basketball? (Basketbol oynamaya ne dersin?)
- **Why don’t we** go for a walk? (Yürüyüşe çıksak mı?)
- **Let’s** meet at the park. (Parkta buluşalım.)
- I’m **inviting you to** my house on Saturday.

:::baglanti
“Would you like to” kalıbından sonra **fiilin yalın hâli** gelir: Would you like to **go**? “How about” kalıbından sonra ise **-ing** takılı fiil gelir: How about **going**? Bu ayrım LGS’de sık sınanır.
:::

## 4. Daveti kabul etme (Accepting)

- **Yes, I’d love to.** (Evet, çok isterim.)
- **Sure, that sounds great.** (Tabii, harika görünüyor.)
- **That’s a great idea!** (Bu harika bir fikir!)
- **Okay, I’ll be there.** (Tamam, orada olacağım.)
- **I’d be happy to come.**
- **Thank you for inviting me.** (Beni davet ettiğin için teşekkürler.)

## 5. Daveti reddetme (Refusing)

Bir daveti reddederken kibar olmak ve bir **sebep** vermek önemlidir.

- **I’m sorry, I can’t.** (Üzgünüm, yapamam.)
- **I’d love to, but I have to study for my exam.** (İsterdim, ama sınavıma çalışmam gerek.)
- **Thanks for inviting me, but I’m busy.** (Davet için sağ ol, ama meşgulüm.)
- **I’m afraid I can’t make it.** (Maalesef gelemem.)
- **Maybe another time.** (Belki başka zaman.)

| Davet | Kabul | Ret |
| --- | --- | --- |
| Would you like to come to the party? | Yes, I’d love to! | I’d love to, but I have homework. |
| How about playing football? | Sure, why not? | Sorry, I’m not feeling well. |
| Why don’t we study together? | That’s a good idea! | I’m afraid I can’t. I have a plan. |

:::neden-sonuc
- Biri seni etkinliğe çağırıyor => “Would you like to…?” ile davet edilmiştir, kabul ya da ret cevabı vermelisin.
- Daveti reddedeceksin => Önce “I’m sorry” de, sonra bir sebep söyle (I have homework).
- Daveti kabul edeceksin => “I’d love to”, “Sure”, “That sounds great” gibi olumlu ifadeler seç.
:::

## 6. Örnek diyaloglar

**Diyalog 1 (Kabul):**

- **Ali:** Would you like to come to the cinema with me on Saturday?
- **Mert:** Yes, I’d love to! What time?
- **Ali:** At 6 o’clock.
- **Mert:** Great. See you then.

**Diyalog 2 (Ret):**

- **Zeynep:** Do you want to play volleyball after school?
- **Ece:** I’m sorry, I can’t. I have a piano lesson.
- **Zeynep:** That’s okay. Maybe another time.
- **Ece:** Sure, thanks for asking.

## 7. Arkadaşlık problemleri ve çözümleri

Arkadaşlar arasında bazen sorunlar olur. Bu durumda şu ifadeleri kullanabilirsin.

- **I’m sorry for what I said.** (Söylediğim şey için üzgünüm.)
- **Let’s talk about it.** (Bunu konuşalım.)
- **Can we make up?** (Barışabilir miyiz?)
- **I didn’t mean to hurt you.** (Seni incitmek istemedim.)
- **You should apologize to him/her.** (Ondan özür dilemelisin.)

**Tavsiye verirken** “should” kullanılır:

- You **should talk** to your friend.
- You **shouldn’t shout** at him.

