- **prefer A to B:** A’yı B’ye tercih etmek. I **prefer tea to coffee.** I **prefer reading to watching** TV.
- **prefer to + fiil:** I **prefer to stay** at home.
- **would rather + yalın fiil:** I **would rather play** football than play chess.
- **would prefer to + fiil:** I **would prefer to go** to the park.

