## 3. Afet sırasında ne yapılmalı?

**Deprem sırasında:**

- **Stay calm.** (Sakin ol.)
- **Drop, cover and hold on.** (Çök, kapan, tutun.)
- **Get under a strong table.** (Sağlam bir masanın altına gir.)
- **Stay away from windows** and tall furniture. (Pencerelerden ve uzun eşyalardan uzak dur.)
- **Don’t use the elevator.** (Asansör kullanma.)
- **Don’t run** outside during the shaking.

**Sel sırasında:**

- **Move to higher ground.** (Yüksek bir yere çık.)
- **Don’t walk or drive** through flood water.
- **Turn off** the electricity.

**Orman yangını sırasında:**

- **Leave the area** quickly.
- **Call the fire department.**
- **Stay away from** the smoke.

:::baglanti
Emir cümleleri (**imperative**) **özne olmadan, yalın fiille** başlar: “Stay calm.” “Don’t panic.” “Get under a table.” Güvenlik kuralları ve talimatlar genellikle bu yapıdadır. Olumsuzlar “**Don’t + yalın fiil**” biçimindedir.
:::

| Yapmalısın (Do) | Yapmamalısın (Don’t) |
| --- | --- |
| Stay calm | Panic |
| Get under a table | Use the elevator |
| Stay away from windows | Run outside |
| Follow instructions | Ignore the warnings |
| Help others | Go near broken buildings |

## 4. Tavsiye: should ve shouldn’t

- You **should** have an emergency kit.
- You **should** listen to the warnings.
- You **shouldn’t** panic.
- You **shouldn’t** stand near windows during an earthquake.

## 5. Geçmişte yaşanan afetleri anlatmak

Geçmiş zaman (past simple) kullanılır.

- A big earthquake **happened** in the city last night.
- It **destroyed** many buildings.
- Rescue teams **arrived** quickly.
- Many people **lost** their homes.
- The government **sent** help.

**Past continuous ile arka plan anlatma:**

- **While** we **were sleeping**, the earthquake **started**.
- I **was walking** home **when** the storm **began**.

**Örnek haber metni:**

> A strong earthquake **hit** the city at 3 a.m. yesterday. People **were sleeping** when the shaking **began**. Many buildings **collapsed**, but rescue teams **started** work immediately. They **saved** many people. The government **sent** tents and food to the victims.

:::neden-sonuc
- Büyük bir deprem olur => Binalar çöker, insanlar evsiz kalır, kurtarma ekipleri çalışır.
- Yoğun yağış olur => Dereler taşar, sel olabilir.
- Hazırlıklı olursan => Afet sırasında daha az zarar görürsün.
:::

## 6. Doğa olaylarının nedenleri

- **Earthquake:** Yer kabuğundaki fay hatlarının hareketi.
- **Volcano:** Dünyanın içindeki erimiş kayaç (magma) yeryüzüne çıkması.
- **Flood:** Çok yağmur yağması, kar erimesi ya da barajın taşması.
- **Tornado:** Sıcak ve soğuk havanın çarpışması sonucu dönen rüzgâr.
- **Drought:** Uzun süre yağmur yağmaması.

**Neden-sonuç kalıpları:**

- The river **overflowed because** it rained heavily. (Çok yağmur yağdığı için nehir taştı.)
- It rained heavily, **so** the river overflowed. (Çok yağmur yağdı, bu yüzden nehir taştı.)

