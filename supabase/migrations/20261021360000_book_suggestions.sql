create or replace function public.admin_book_suggestions()
returns table (id integer, title text, author text, votes integer, created_at timestamptz)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'Yetkiniz yok';
  end if;
  return query
    select s.id, s.title, s.author, (select count(*) from public.book_suggestion_votes v where v.suggestion_id = s.id)::int, s.created_at
    from public.book_suggestions s where s.status = 'pending'
    order by 4 desc, s.created_at desc;
end $$;

create or replace function public.review_book_suggestion(p_id integer, p_approve boolean, p_title text default null, p_author text default null)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  s public.book_suggestions;
begin
  if not private.is_admin() then
    raise exception 'Yetkiniz yok';
  end if;
  select * into s from public.book_suggestions where id = p_id and status = 'pending' for update;
  if s is null then
    raise exception 'Öneri bulunamadı';
  end if;
  if p_approve then
    insert into public.catalog_books (title, author) values (trim(coalesce(nullif(p_title, ''), s.title)), trim(coalesce(nullif(p_author, ''), s.author)))
    on conflict (public.fold_tr(title), public.fold_tr(author)) do nothing;
    update public.book_suggestions set status = 'approved' where id = p_id;
  else
    update public.book_suggestions set status = 'rejected' where id = p_id;
  end if;
end $$;

revoke all on function public.admin_book_suggestions(), public.review_book_suggestion(integer, boolean, text, text) from public, anon;
grant execute on function public.admin_book_suggestions(), public.review_book_suggestion(integer, boolean, text, text) to authenticated;
