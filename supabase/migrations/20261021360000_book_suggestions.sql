create or replace function private.suggest_catalog_book() returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  k text;
  sid integer;
  stat text;
  vote_count integer;
  cat_title text;
  cat_author text;
begin
  if new.author is null or char_length(trim(new.author)) < 2 or char_length(trim(new.title)) < 2 then
    return new;
  end if;
  if new.title ~* '(https?:|www\.|@)' or new.author ~* '(https?:|www\.|@)' then
    return new;
  end if;
  if exists (select 1 from public.catalog_books c where public.fold_tr(c.title) = public.fold_tr(new.title) and public.fold_tr(c.author) = public.fold_tr(new.author)) then
    return new;
  end if;
  cat_title := regexp_replace(trim(new.title), '\s+', ' ', 'g');
  cat_author := regexp_replace(trim(new.author), '\s+', ' ', 'g');
  k := public.fold_tr(cat_title) || '|' || public.fold_tr(cat_author);
  insert into public.book_suggestions (title, author, key) values (cat_title, cat_author, k) on conflict (key) do nothing;
  select s.id, s.status, s.title, s.author into sid, stat, cat_title, cat_author from public.book_suggestions s where s.key = k;
  if stat <> 'pending' then
    return new;
  end if;
  insert into public.book_suggestion_votes (suggestion_id, student_id) values (sid, new.student_id) on conflict do nothing;
  select count(*) into vote_count from public.book_suggestion_votes v where v.suggestion_id = sid;
  if vote_count >= 3
     and position(left(cat_title, 1) in 'ABCÇDEFGĞHIİJKLMNOÖPQRSŞTUÜVWXYZ0123456789') > 0
     and position(left(cat_author, 1) in 'ABCÇDEFGĞHIİJKLMNOÖPQRSŞTUÜVWXYZ') > 0 then
    insert into public.catalog_books (title, author) values (cat_title, cat_author)
    on conflict (public.fold_tr(title), public.fold_tr(author)) do nothing;
    update public.book_suggestions set status = 'approved' where id = sid;
  end if;
  return new;
end $$;
create trigger books_suggest after insert on public.books
