Çok çalışan bir öğrenci sınavda başarısız olabilir, çok hazırlıksız bir öğrenci beklenmedik biçimde başarılı olabilir. Bu durumlarda insan “Kader bu muydu?” diye sorar. Kader inancı, insanın **sorumluluğu ile Allah’ın bilgisi** arasındaki ilişkiyi anlatır. Bu konuda kader inancının ne olduğunu, insanın iradesiyle ilişkisini ve kader inancının günlük hayata etkisini öğreneceksin.

:::hedefler
