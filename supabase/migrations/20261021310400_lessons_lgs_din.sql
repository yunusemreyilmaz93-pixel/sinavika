## 1. Zekât nedir?

**Zekât**, belli bir miktarın üzerinde malı olan Müslümanların, **mallarının belli bir bölümünü ihtiyaç sahiplerine vermesidir**. Zekât, İslam’ın beş şartından biridir. Hem **malî** hem de **sosyal** bir ibadettir.

Zekât sözcüğü **temizlik** ve **artma** anlamlarına gelir. Zekât veren kişinin malı bereketlenir ve kalbi cimrilik gibi kötü duygulardan arınır.

### Zekât kimlere farzdır?

Bir kişiye zekât vermenin farz olması için şu şartlar aranır.

- **Müslüman, akıllı ve ergen** olması.
- **Nisap miktarı mala sahip olması:** Zekâtın farz olması için gereken asgari mal varlığıdır. Altın cinsinden **yaklaşık 80 gram** değerindedir. (Güncel miktar için Diyanet’e bakılır.)
- Bu malın **temel ihtiyaçlar ve borçlar dışında** kalması.
- Malın üzerinden **bir yıl geçmesi** (kameri yıl).

### Zekât oranı

- Para, altın, gümüş ve ticaret mallarında **kırkta bir** (yüzde 2,5).
- Tarım ürünlerinde farklı oran uygulanır (öşür).
- Hayvanlarda belli bir sayıdan sonra farklı oranlar vardır.

**Örnek:** Nisabı aşan ve bir yılı dolan 20 000 TL birikimi olan kişi $20\,000 \cdot \dfrac{1}{40} = 500$ TL zekât verir.

:::dene
1. Zekâtın farz olması için gereken şartlardan ikisini yaz. => Nisap miktarı mala sahip olmak ve malın üzerinden bir yıl geçmesi.
2. Bir tüccar 80 000 TL ticaret malına ve birikime sahiptir ve bir yıl geçmiştir. Zekât oranı kırkta bir ise ne kadar verir? => $80\,000 / 40 = 2\,000$ TL.
:::

## 2. Zekât kimlere verilir?

Kur’an’da (Tevbe suresi, 60. ayet) zekâtın verileceği sekiz grup sayılmıştır.

| Zekât verilecek grup | Kimler? |
| --- | --- |
| Fakirler | Hiçbir geliri olmayan ya da çok az geliri olanlar |
| Miskinler | Geliri ihtiyacını karşılamayanlar |
| Zekât toplayan görevliler | Zekâtı toplama ve dağıtma görevi yapanlar |
| Kalpleri İslam’a ısındırılacaklar | Müslüman olmak isteyenler ya da İslam’a ısınması beklenenler |
| Köle ve esirler | Özgürlüğüne kavuşturulacak insanlar |
| Borçlular | Borcunu ödeyemeyenler |
| Allah yolunda olanlar | Hayırlı hizmetlerde, Allah rızası için çalışanlar |
| Yolda kalmışlar | Yolculuk sırasında yardıma ihtiyaç duyanlar |

### Zekât verilmeyecek kişiler

- **Anne-baba, dede-nine** (usul) ve **çocuk, torun** (füru) ile **eş**: Çünkü bu kişilerin bakım yükümlülüğü zaten kişinin üzerindedir.
- **Zengin kişiler**.
- Gösteriş amacıyla ve **karşılık beklenerek** verilen yardım zekât sayılmaz. Zekât, **Allah rızası** için verilmelidir.

:::baglanti
Zekât, **yardım edilen kişinin onurunu zedelemeden** verilmelidir. Bir kişiye yardım ederken minnet altında bırakmamak, ona karşı üstünlük taslamamak İslam ahlakının gereğidir. Gizlice verilen yardım da daha değerli kabul edilir.
:::

## 3. Sadaka

**Sadaka**, Allah rızası için, karşılık beklemeden yapılan her türlü iyilik ve yardımdır. Sadaka sözcüğü “doğruluk” kökünden gelir. Zekâttan farklı olarak sadakada **nisap ve süre şartı yoktur**. Herkes, gücü ölçüsünde sadaka verebilir.

**Sadakanın çeşitleri:**

- **Mal ile yapılan yardım:** Para, yiyecek, giyecek vermek.
- **Güzel söz söylemek:** İyi bir söz sadakadır.
- **Gülümsemek:** “Kardeşinin yüzüne gülümsemen sadakadır.” (Hadis)
- **Yola engel olan şeyi kaldırmak:** Bir taşı yoldan çekmek bile sadakadır.
- **Bilgi paylaşmak:** İlim öğretmek, birine yol göstermek.

### Sadaka-i fıtır (fitre)

Ramazan ayı sonunda, **bayram namazından önce** verilen sadakadır. Yoksulların bayramı sevinçle geçirmesini sağlamayı amaçlar. Her Müslüman, kendisi ve bakmakla yükümlü olduğu kişiler için fitre verir.

### Kurban

**Zilhicce ayında** belirli şartları taşıyan kişilerin, **Allah rızası için** hayvan kesip etini paylaştırmasıdır. Etin bir bölümü yoksullara dağıtılır. Böylece toplumda paylaşma ve dayanışma güçlenir.

### Sadaka-i câriye

**Sadaka-i câriye**, kişinin ölümünden sonra da **sevabı devam eden** hayırlardır. Okul, çeşme, köprü, kütüphane yaptırmak, ağaç dikmek, faydalı bir kitap yazmak bunlara örnektir.

Hz. Muhammed şöyle buyurmuştur (anlamı): “İnsan ölünce üç şey dışında amel defteri kapanır: Sadaka-i câriye, kendisinden faydalanılan ilim ve kendisine hayır dua eden hayırlı evlat.”

**Vakıf:** Kişinin malını, **belli bir amaç için** (okul, hastane, çeşme gibi) kalıcı olarak ayırmasıdır. Selçuklu ve Osmanlı’da vakıflar, eğitim, sağlık ve sosyal yardım alanında büyük hizmet verdi. Bugün de birçok vakıf faaliyetini sürdürüyor.

