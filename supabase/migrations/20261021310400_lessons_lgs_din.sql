- 632 | Hz. Muhammed vefat etti, vahiy tamamlandı
- 633 | Yemame Savaşı, Hz. Ebubekir döneminde toplama
- 650 | Hz. Osman döneminde çoğaltma (Mushaf-ı Osmani)
:::

## 4. Kur’an’ın korunması

Kur’an’da, Allah’ın onu koruyacağı belirtilmiştir: **“Kur’an’ı biz indirdik, onu koruyacak olan da elbette biziz.”** (Hicr suresi, 9. ayet) Bu koruma bir kısmı insanlar aracılığıyla gerçekleşmiştir.

- **Hafızlık geleneği:** Her çağda milyonlarca insan Kur’an’ı ezberlemiştir.
- **Yazılı nüshalar:** Mushaflar çoğaltılarak korunmuştur.
- **Tecvid ve kıraat ilimleri:** Okunuşun doğru korunmasını sağlar.
- **Aynı metin:** Bugün dünyanın her yerindeki Kur’an aynı metindir.

## 5. Kur’an’ın özellikleri

