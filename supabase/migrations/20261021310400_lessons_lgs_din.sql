## 3. Kur’an’ın yazılması ve toplanması

### Hz. Muhammed döneminde

- Hz. Muhammed vahiy geldikçe ayetleri **ashabına** okur, kâtipler (Zeyd b. Sabit, Hz. Ali, Hz. Osman gibi) ayetleri **kemik, deri, hurma dalı** gibi malzemelere yazardı.
- Pek çok sahabi Kur’an’ı **ezberledi**. Bunlara **hafız** denir.
- Hz. Muhammed her yıl Ramazan’da Cebrail’e Kur’an’ı okuyup **kontrol ettirirdi**.

### Hz. Ebubekir döneminde (632-634)

**Yemame Savaşı**’nda çok sayıda hafız şehit oldu. Bunun üzerine Kur’an’ın **bir araya toplanması** kararlaştırıldı. **Zeyd b. Sabit** başkanlığında bir kurul ayetleri toplayıp **sayfalar hâlinde** yazdırdı.

### Hz. Osman döneminde (644-656)

Farklı bölgelerde okunuşta ayrılıklar ortaya çıkınca Hz. Osman, Hz. Ebubekir döneminde toplanan nüshayı esas alarak **çoğaltıp** Medine, Kûfe, Basra, Şam ve Mekke gibi merkezlere gönderdi. Böylece Müslümanlar **tek bir metin etrafında** birleşti. Bu nüshaya **Mushaf-ı Osmani** denir.

