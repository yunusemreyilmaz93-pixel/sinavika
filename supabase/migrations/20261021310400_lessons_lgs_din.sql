- **Korunmuştur:** İndiği günden bugüne değişmemiştir.
- **Mucizedir:** Dili ve anlatımı eşsizdir. Hz. Muhammed’in en büyük mucizesi Kur’an’dır.
- **Kolay anlaşılır:** “Biz Kur’an’ı öğüt almak için kolaylaştırdık.” (Kamer suresi, 17. ayet)
