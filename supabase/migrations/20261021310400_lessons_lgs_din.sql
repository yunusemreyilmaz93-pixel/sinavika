## 1. Hz. Muhammed’in hayatından kesitler

Hz. Muhammed, **570 yılında Mekke’de** doğdu. Babası Abdullah, doğumundan önce vefat etmişti. Annesi Âmine ile dedesi **Abdülmuttalib** onu büyüttü. Küçük yaşta annesini ve dedesini kaybetti. Daha sonra amcası **Ebu Talib** ona baktı.

Gençliğinde **dürüstlüğü ve güvenilirliği** ile tanındı. Mekkeliler ona **“el-Emin”** (güvenilir kişi) adını verdi. Hz. Hatice ile evlendi (yaklaşık 25 yaşında).

| Yıl | Olay |
| --- | --- |
| 570 | Mekke’de doğdu |
| 610 | **Hira Mağarası’nda ilk vahiy** (Alak suresi) |
| 622 | **Hicret**: Mekke’den Medine’ye göç, İslam takviminin başlangıcı |
| 628 | **Hudeybiye Barışı** |
| 630 | **Mekke’nin fethi** |
| 632 | **Veda Hutbesi** ve vefat |

Önemli olaylar:

- **İlk vahiy (610):** Hira Mağarası’nda Cebrail aracılığıyla ilk ayetler indi: “Oku!”
- **Mekke dönemi (610-622):** Müşrikler Müslümanlara baskı yaptı. İnananlar işkence gördü. Hz. Muhammed sabırla davetine devam etti.
- **Hicret (622):** Zulüm artınca Müslümanlar Medine’ye göç etti. Medine’de ilk **Medine Sözleşmesi** yapıldı. Bu sözleşme, farklı din ve kabilelerin bir arada barış içinde yaşamasını düzenleyen belge olarak kabul edilir.
- **Hudeybiye Barışı (628):** Müslümanlar ile Mekkeliler arasında yapılan barış antlaşmasıdır. Barışın yolunu açtı.
- **Mekke’nin fethi (630):** Hz. Muhammed Mekke’ye kan dökmeden girdi.
- **Veda Hutbesi (632):** Son hac sırasında yaptığı konuşmadır. İnsan hakları, adalet, kadın ve çocuk hakları gibi temel ilkeleri içerir.

## 2. Hz. Muhammed’in ahlak özellikleri

### Doğruluk ve güvenilirlik

Peygamber olmadan önce de **“el-Emin”** diye anılırdı. Mekkelilerin değerli eşyaları ona emanet edilirdi. Hicret gecesi bile, düşmanı olan kişilerin emanetlerini **iade etmek için** Hz. Ali’yi Mekke’de bıraktı.

### Merhamet ve şefkat

Hz. Muhammed için Kur’an’da şu anlama gelen bir ifade yer alır: “Biz seni ancak âlemlere rahmet olarak gönderdik.” (Enbiya suresi, 107. ayet) Çocukları, yaşlıları, yoksulları, hayvanları ve bitkileri korurdu.

- Çocukları severdi, onlarla ilgilenirdi.
- Hayvanlara eziyet edilmesini yasakladı.
- Hasta ziyaret eder, yetimlere sahip çıkardı.

### Hoşgörü ve affedicilik

**Mekke’nin fethi** hoşgörünün en büyük örneklerindendir. Yıllarca kendisine ve inananlara zulmeden Mekkelilere şöyle dedi: **“Bugün size kınama yok. Gidin, hepiniz serbestsiniz.”** İntikam almadı, hepsini affetti.

- **Taif olayı:** Taif’e İslam’a davet etmek için gitti, taşlandı ve yaralandı. Ama taşlayanlara beddua etmedi, “Belki onların soyundan Allah’a inanacak kimseler çıkar” diyerek dua etti.

:::baglanti
Hz. Muhammed, **gücü eline geçtiğinde** kötülük yapanları affetti. Kendini kontrol etmek ve intikam almamak, gerçek bir güçtür. Bu yüzden Mekke’nin fethi, sadece askerî bir zafer değil, **ahlaki bir zaferdir**.
:::

### Adalet

Kimseye ayrımcılık yapmaz, zengin-fakir, soylu-köle farkı gözetmezdi. “Fatma bile çalsa, onun da elini keserdim” diyerek **hukukun herkes için eşit olduğunu** vurguladı.

### Alçakgönüllülük ve sadelik

Kendisini ayrıcalıklı göstermez, halkın arasında otururdu. Evinde işlere yardım eder, ayakkabısını kendisi tamir ederdi. Gösterişten kaçınır, sade yaşardı.

### Cömertlik ve yardımseverlik

İhtiyaç sahiplerine yardım eder, kendi ihtiyacı olsa bile verirdi. Kendisinden bir şey isteyene “hayır” demezdi.

### Çalışkanlık ve sorumluluk

Gençliğinde çobanlık ve ticaret yaptı. Çalışmayı ve helal kazancı teşvik etti. “Kimse, elinin emeğinden daha hayırlı bir yiyecek yememiştir.” (Hadis)

### Komşuluk ve arkadaşlık

Komşu haklarına büyük önem verirdi. “Komşusu aç iken tok yatan bizden değildir.” sözü bunu gösterir. Arkadaşlarına danışır (istişare), onların görüşlerine değer verirdi.

| Ahlak özelliği | Örnek olay |
| --- | --- |
| Güvenilirlik | “El-Emin” unvanı, emanetleri iade etmesi |
| Merhamet | Çocuklara, yetimlere ve hayvanlara şefkat |
| Hoşgörü | Mekke’nin fethinde affetmesi |
| Sabır | Taif olayı, Mekke dönemi baskıları |
| Adalet | Hukukun herkes için eşit uygulanması |
| Alçakgönüllülük | Halkın arasında sade yaşaması |

## 3. Medine Sözleşmesi ve toplumsal barış

Medine’de Müslümanlar, Yahudiler ve diğer kabileler birlikte yaşıyordu. **Medine Sözleşmesi** ile şu ilkeler belirlendi.

- Herkesin **dinî özgürlüğü** korunur.
- Dışarıdan bir saldırı olursa **birlikte savunma** yapılır.
- Herkes **hukuk karşısında** eşittir.
- Birbirinin haklarına saygı gösterilir.

Bu sözleşme, **çok kültürlü toplumda barış içinde bir arada yaşamanın** ilk örneklerinden biri kabul edilir.

## 4. Veda Hutbesi

Hz. Muhammed, vefatından önce 632’de yaptığı **Veda Hacı** sırasında Arafat’ta bir konuşma yaptı. Bu konuşmanın bazı ilkeleri şunlardır.

- Herkesin **canı, malı ve namusu** dokunulmazdır.
- **Irk, renk ve soy** farkı yoktur. “Arabın Arap olmayana, beyazın siyaha üstünlüğü yoktur. Üstünlük ancak takvadadır (Allah’a karşı sorumluluk bilinci).”
- Faiz kaldırılmıştır, haksız kazanç yasaktır.
- **Kadınlara iyi davranılması** ve onların haklarının gözetilmesi istenir.
- Kur’an ve sünnet insanlığa yol gösteren kaynaklardır.

Veda Hutbesi, **evrensel insan haklarının** ilk önemli belgelerinden biri sayılır.

:::neden-sonuc
- Mekkeliler Müslümanlara zulmeder => Hz. Muhammed ve arkadaşları Medine’ye hicret eder.
- Hz. Muhammed, güç elindeyken Mekkelileri affeder => İslam’ın hoşgörü ve merhamet ilkesi güçlü biçimde gösterilir.
- Medine Sözleşmesi yapılır => Farklı inançtan topluluklar barış içinde yaşar.
:::

