## 1. Vahiy ve Kur’an

**Vahiy**, Allah’ın peygamberlerine, **kendi iradesiyle ve özel bir yolla** bildirdiği mesajdır. Vahiy genellikle **Cebrail adlı melek aracılığıyla** gelir.

