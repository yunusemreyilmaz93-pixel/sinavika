## 5. Yardımlaşmanın faydaları

**Bireye faydaları:**

- Cimrilik, bencillik gibi kötü huylardan arınır.
- Paylaşmanın verdiği manevi huzuru yaşar.
- Allah’ın rızasını kazanmayı hedefler.

**Topluma faydaları:**

- **Yoksulluk azalır**, gelir dağılımı dengelenir.
- Zengin ile yoksul arasındaki mesafe kısalır, **kıskançlık ve kin azalır**.
- Toplumsal **dayanışma ve kardeşlik** güçlenir.
- Ekonomide mal dolaşıma girer, atıl kalmaz.

:::neden-sonuc
- Zenginler zekâtlarını verir => Yoksullar temel ihtiyaçlarını karşılar, toplumda kıskançlık azalır.
- İnsanlar yardımlaşır => Toplumsal dayanışma ve barış güçlenir.
- Sadaka-i câriye yapılır => Yapan kişi öldükten sonra da topluma faydası ve sevabı sürer.
:::

