:::

:::ipucu
Kader sorularında **“insan sorumlu mu, değil mi?”** sorusu çok önemlidir. İslam inancına göre insan, **iradesiyle seçim yapar ve yaptıklarından sorumludur**. Kader, insanı tembelliğe ya da sorumsuzluğa değil, çalışmaya ve güvenle hareket etmeye çağırır.
:::

## 1. Kader ve kaza nedir?

**Kader**, Allah’ın evrendeki her şeyi **ilmiyle bilmesi, planlaması ve takdir etmesidir**. Kısaca, her şeyin Allah’ın bilgisi ve takdiri dâhilinde olmasıdır.

**Kaza**, Allah’ın takdir ettiği şeyin, **zamanı geldiğinde yaratılmasıdır**.

| Kavram | Anlamı |
| --- | --- |
| Kader | Allah’ın her şeyi önceden bilmesi ve takdir etmesi |
| Kaza | Takdir edilenin zamanı gelince meydana gelmesi |

Kaza ve kader, İslam’ın iman esasları arasında yer alır. Kur’an’da şu anlama gelen ayetler vardır: Allah, her şeyi bir ölçüye göre yaratmıştır (Kamer suresi, 49. ayet).

## 2. İnsan iradesi ve sorumluluk

Allah, insanı **akıl ve irade** sahibi olarak yaratmıştır. İnsan, iyi ya da kötü davranışı **seçme özgürlüğüne** sahiptir. Bu özgürlük, kader inancı ile çelişmez.

- **Allah’ın ilmi:** Allah olacak her şeyi bilir. Bu bilgi, insanın seçimini zorlamaz. Bir öğretmenin “Bu öğrenci çalışmazsa kalır” demesi, öğrencinin çalışmamasının sebebi olmaz.
- **İnsanın iradesi:** İnsan seçimini kendi iradesiyle yapar. Yaptığı seçimlerden **sorumludur**.

Kur’an’da insanın sorumluluğuna dair şu anlama gelen ifadeler yer alır: “Allah kimseye gücünün yeteceğinden fazlasını yüklemez.” (Bakara suresi, 286. ayet)

:::neden-sonuc
- İnsan iyi ya da kötüyü seçmekte özgürdür => Seçimlerinden sorumludur. İyiliğin ödülünü, kötülüğün sonucunu görür.
- Allah olacak her şeyi bilir => Bu bilgi, insanın seçimlerini ortadan kaldırmaz.
- İnsan çalışmadan sonuç bekler => Kader inancıyla bağdaşmaz. İslam, çalışmayı teşvik eder.
:::

### Cüz’i irade

İnsanın seçim yapabilmesine **cüz’i irade** denir. İnsan, kendi sınırları içinde karar verir. Allah’ın sonsuz iradesi ise evrenin tamamını kapsar. İnsanın davranışlarından sorumlu tutulması, bu irade sayesindedir.

## 3. Kader inancı ve sorumluluk

Kader inancını yanlış anlamak, bazı kişileri **sorumsuzluğa** götürebilir. Örneğin “Ne olacaksa olur” diyerek çalışmamak ya da ders çalışmayıp “kaderimde yoksa olmaz” demek, **yanlış bir anlayıştır**.

Kur’an’da şu anlama gelen bir ayet vardır: “Bir toplum kendini değiştirmedikçe Allah onların durumunu değiştirmez.” (Ra’d suresi, 11. ayet) Bu ayet, insanın **çaba göstermesinin** önemini vurgular.

:::baglanti
İnsan, kaderi **bilmediği** için çalışmak zorundadır. Sınavda ne çıkacağını, sonucun ne olacağını bilmeyen öğrenci, elinden gelen en iyi hazırlığı yapmalıdır. Sonuçta “çabam yeterli olmadı” diyebilirse kaderine razı olması kolay olur, “hiç çalışmadım” demek ise sorumluluk gerektirir.
:::

## 4. Tevekkül, sabır ve dua

### Tevekkül

**Tevekkül**, insanın **elinden gelen çabayı gösterdikten sonra sonucu Allah’a bırakmasıdır**. Tevekkül, tembellik değildir. Önce **çalışmak**, sonra **güvenmek** esastır.

- Çiftçi tohumu eker, çalışır, sonra yağmuru Allah’tan bekler.
- Öğrenci ders çalışır, sınava girer, sonucu Allah’tan bekler.

### Sabır

**Sabır**, zorluk ve sıkıntılar karşısında **dayanmak, isyan etmemek** ve doğru yoldan ayrılmamaktır. Sabır pasif beklemek demek değildir. Zorluğa karşı **çaba göstermeye** devam etmektir.

### Dua

**Dua**, insanın Allah’a yönelmesi, O’ndan yardım ve iyilik dilemesidir. Dua, **çalışmanın yerini tutmaz**, ama çalışmaya manevi güç verir. İnsan dua ederken çabasından vazgeçmez.

## 5. Kader inancının insana kazandırdıkları

Kader inancı doğru anlaşıldığında insana şunları kazandırır.

- **Ruhsal huzur:** İnsan, çabasından sonra sonuca razı olur.
- **Sorumluluk bilinci:** Yaptıklarından hesap vereceğini bilir.
- **Sabır ve dayanıklılık:** Zorluklar karşısında yılmaz.
- **Şükür:** Başarıda kibirlenmez, Allah’a şükreder.
- **Cesaret:** Gelecek korkusunu yenmeye yardımcı olur.

Kader inancının yanlış anlaşılması ise şu zararlara yol açabilir.

| Yanlış anlayış | Zararı |
| --- | --- |
| “Ne olacaksa olur” diyerek çalışmamak | Tembellik, başarısızlık |
| Başkalarının hatalarını kadere yüklemek | Sorumluluktan kaçmak |
| Her kötülüğü kadere bağlamak | Haksızlıklara ve kötülüklere karşı çıkmamak |

