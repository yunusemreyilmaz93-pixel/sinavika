-- Kitap kataloğu: öğrenci kitap eklerken ad ve yazar önerisi için -------------------------
-- Sayfa sayısı baskıdan baskıya değiştiği için kataloğa konmaz, öğrenci girer.

create extension if not exists pg_trgm with schema extensions;

create or replace function public.fold_tr(p text) returns text
language sql immutable parallel safe set search_path = ''
as $$ select trim(regexp_replace(translate(lower(translate(p, 'İI', 'iı')), 'ığüşöçâîû', 'igusocaiu'), '\s+', ' ', 'g')) $$;

create table public.catalog_books (
  id integer generated always as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  author text not null check (char_length(author) between 1 and 80),
  search text generated always as (public.fold_tr(title || ' ' || author)) stored
);
create unique index catalog_books_unique on public.catalog_books (public.fold_tr(title), public.fold_tr(author));

alter table public.catalog_books enable row level security;
create policy "catalog read" on public.catalog_books for select to authenticated using (true);
revoke all on public.catalog_books from anon, authenticated;
grant select on public.catalog_books to authenticated;

create or replace function public.search_catalog_books(p_query text)
returns table (id integer, title text, author text)
language sql stable security invoker set search_path = ''
as $$
  with q as (select public.fold_tr(left(coalesce(p_query, ''), 80)) as v),
  p as (select v, replace(replace(replace(v, '\', '\\'), '%', '\%'), '_', '\_') as pattern from q)
  select b.id, b.title, b.author
  from public.catalog_books b, p
  where char_length(p.v) >= 2
    and (b.search like '%' || p.pattern || '%' or extensions.word_similarity(p.v, b.search) >= 0.45)
  order by (b.search like p.pattern || '%') desc, (b.search like '%' || p.pattern || '%') desc, extensions.word_similarity(p.v, b.search) desc, b.title
  limit 8
$$;
grant execute on function public.search_catalog_books(text) to authenticated;
revoke execute on function public.search_catalog_books(text) from anon, public;

