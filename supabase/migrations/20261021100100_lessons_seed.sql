## 1. Avrupa değişiyor, Osmanlı zorlanıyor

Mustafa Kemal 1881’de doğduğunda Osmanlı Devleti eski gücünü kaybetmişti. Bunun en önemli sebebi, Avrupa’da birkaç yüzyıl içinde yaşanan büyük değişimlerdi.

**Fikir alanındaki değişim.** Rönesans ve Reform hareketleriyle Avrupa’da insanlar kiliseye ve geleneklere bağlı kalmadan düşünmeye başladı. Aydınlanma Çağı’nda akıl ve bilim her şeyin ölçüsü oldu.

**Fransız İhtilali (1789).** Bu ihtilal milliyetçilik, eşitlik, özgürlük ve adalet fikirlerini bütün dünyaya yaydı. Milliyetçilik, “her millet kendi devletini kurmalı” düşüncesidir. Bu fikir, içinde pek çok milleti barındıran Osmanlı için büyük bir tehlikeydi.

**Sanayi İnkılabı.** 18. yüzyılın sonunda İngiltere’de başlayan bu dönüşümle üretim el emeğinden makineye geçti. Fabrikalar çok fazla mal üretiyordu. Avrupa devletleri bu fabrikalar için **ham madde** ve ürettiklerini satacak **pazar** aramaya başladı. Bu ihtiyaç, sömürgeciliği hızlandırdı.

:::neden-sonuc
- Milliyetçilik fikri => Devletteki farklı milletler bağımsızlık için ayaklandı. Sırplar 1804’te isyan etti, Yunanistan 1830’da bağımsız oldu.
- Sanayi İnkılabı => Ucuz Avrupa malları Osmanlı pazarını doldurdu, yerli üreticiler zarar gördü. Devlet borçlandı, 1881’de borçları yönetmek için Duyun-u Umumiye kuruldu.
- Aydınlanma ve özgürlük fikirleri => Osmanlı aydınları anayasa ve meclis istedi. 1876’da Kanun-i Esasi ilan edildi, I. Meşrutiyet başladı.
:::

**Osmanlı ne yaptı?** Devleti kurtarmak için yenilikler yapıldı: Tanzimat Fermanı (1839), Islahat Fermanı (1856), I. Meşrutiyet (1876) ve II. Meşrutiyet (1908). Aydınlar da devleti kurtarmak için farklı fikirler ileri sürdü: Osmanlıcılık, İslamcılık, Türkçülük ve Batıcılık. Ama 20. yüzyılın başında Osmanlı hâlâ toprak kaybediyor, ekonomisi dışa bağlı kalıyordu.

:::cizelge{baslik="Osmanlı’nın yenilik adımları"}
- 1839 | Tanzimat Fermanı
- 1856 | Islahat Fermanı
- 1876 | I. Meşrutiyet
- 1908 | II. Meşrutiyet
:::

:::baglanti
Mustafa Kemal, devletin yıkılmak üzere olduğu bu dönemde büyüdü. İleride yaptığı inkılapların çoğu, bu dönemin sorunlarına verilmiş cevaplardır.
:::

## 2. Selanik’te bir çocuk: Çocukluk ve okul yılları

Mustafa, 1881’de Selanik’te doğdu. Babası Ali Rıza Efendi önce gümrük memuruydu, sonra kereste ticaretiyle uğraştı. Annesi Zübeyde Hanım’dı. Kardeşlerinden yalnızca Makbule yaşadı.

![Makbule Hanım, Zübeyde Hanım ve Mustafa Kemal’in portreleri yan yana](/lessons/bir-kahraman-doguyor/aile.webp "Soldan sağa: Kız kardeşi Makbule, annesi Zübeyde Hanım ve Mustafa Kemal. | Wikimedia Commons, CC0")

**Selanik neden önemli?** Selanik, Osmanlı’nın Avrupa’daki en gelişmiş şehirlerinden biriydi. Limanı ve demiryolu sayesinde Avrupa ile bağlantısı güçlüydü. Farklı dinlerden ve milletlerden insanlar bir arada yaşıyordu. Avrupa’daki yeni fikirler buraya çok çabuk ulaşıyordu. Mustafa, dünyaya açık bir şehirde büyüdü.

![Selanik’te Mustafa Kemal’in doğduğu üç katlı pembe ev](/lessons/bir-kahraman-doguyor/selanik-ev.webp "Mustafa Kemal’in doğduğu ev, Selanik. Bugün müze olarak ziyaret ediliyor. | Fotoğraf: CeeGee, Wikimedia Commons, CC BY-SA 4.0")

**İlk karar: Hangi okul?** Annesi onun mahalle mektebinde okumasını istiyordu. Babası ise yeni yöntemlerle eğitim veren Şemsi Efendi Okulu’nu tercih ediyordu. Mustafa önce Hafız Mehmet Efendi’nin mahalle mektebine başladı, kısa süre sonra Şemsi Efendi Okulu’na geçti. Babasının bu tercihi, ailenin yeniliğe açık olduğunu gösterir.

**Erken gelen sorumluluk.** Babası öldüğünde Mustafa yedi yaşındaydı. Bir süre dayısının Rapla Çiftliği’nde yaşadı, burada çalışarak büyüdü. Okula dönmek için Selanik’e geldi ve Selanik Mülkiye Rüştiyesi’ne başladı. Burada bir öğretmeninden haksız yere dayak yiyince okulu bıraktı.

**Kendi yolunu seçmek.** Komşularının oğlunun askeri öğrenci kıyafetine özeniyordu. Annesi istemese de 1893’te sınava girdi ve Selanik Askeri Rüştiyesi’ni kazandı. Matematik öğretmeni Mustafa Sabri Bey, onun başarısını görünce adına **“Kemal”** adını ekledi. Bu ad “olgunluk, mükemmellik” anlamına gelir.

![Harp Okulu öğrencileri üniformalarıyla toplu fotoğrafta](/lessons/bir-kahraman-doguyor/harp-okulu.webp "İstanbul Harp Okulu’nda arkadaşlarıyla, yaklaşık 1902. Mustafa Kemal ön sırada, soldan ikinci oturan. Bilinen en eski fotoğrafıdır. | Askeri Müze arşivi, renklendirilmiş. Wikimedia Commons, kamu malı")

| Okul | Yıl | Onun hakkında ne söyler? |
| --- | --- | --- |
| Şemsi Efendi Okulu | 1880’ler | Ailesi yeni eğitim yöntemlerine açıktı. |
| Selanik Askeri Rüştiyesi | 1893 | Kendi kararını verdi, matematikte çok başarılıydı. |
| Manastır Askeri İdadisi | 1896 | Edebiyata, tarihe ve hitabete ilgi duydu. |
| İstanbul Harp Okulu | 1899 | 1902’de teğmen olarak mezun oldu. |
| Harp Akademisi | 1902-1905 | 1905’te kurmay yüzbaşı rütbesiyle mezun oldu. |

:::baglanti
Erken yaşta babasını kaybetmesi onu sorumluluk sahibi yaptı. Askeri okulu kendi seçmesi, kararlı ve bağımsız bir kişiliği olduğunu gösterir. LGS’de bu tür olaylar, “Mustafa Kemal’in hangi özelliğini gösterir?” diye sorulur.
:::

## 3. Fikirler nasıl oluştu: Gençlik yılları

Mustafa Kemal’in düşünce dünyası, okuduğu kitaplardan, öğretmenlerinden ve gördüğü olaylardan beslendi.

| Öğretmenler | Yazarlar | Olaylar |
| --- | --- | --- |
| Ömer Naci ile edebiyat ve hitabet, Mehmet Tevfik Bey ile tarih merakı. | Namık Kemal, Tevfik Fikret, Ziya Gökalp, Voltaire, Montesquieu, Rousseau. | Balkan milletlerinin örgütlenmesi, yönetimi eleştiren okul gazetesi. |

**Manastır’daki öğretmenleri.** Manastır Askeri İdadisi’nde arkadaşı Ömer Naci ile edebiyata ve güzel konuşmaya (hitabet) ilgi duydu. Tarih öğretmeni Mehmet Tevfik Bey, onun tarihe olan merakını artırdı. Bu ilgi, ileride etkili konuşmalar yapan bir lider olmasında pay sahibidir.

**Okuduğu yazarlar.** Namık Kemal’in vatan ve hürriyet şiirlerini severek okudu. Tevfik Fikret’in ve Ziya Gökalp’in eserlerinden etkilendi. Fransızca öğrenerek Voltaire, Montesquieu ve Rousseau gibi Aydınlanma düşünürlerini okudu. Bu yazarların ortak noktası vatan sevgisi, özgürlük ve aklın önemiydi.

**Gözlemlediği olaylar.** Manastır’da Balkan milletlerinin bağımsızlık için nasıl örgütlendiğini yakından gördü. Milliyetçilik fikrinin bir devleti nasıl parçalayabileceğini burada anladı. Harp Okulu’nda arkadaşlarıyla yönetimin hatalarını eleştiren bir gazete çıkardı.

**İlk örgüt.** Okuldan sonra fikirleri yüzünden bir süre tutuklandı ve Şam’a görevlendirildi. 1906’da burada arkadaşlarıyla **Vatan ve Hürriyet Cemiyeti**’ni kurdu. Amacı, vatanı kurtarmak ve meşrutiyet yönetimini getirmekti.

:::baglanti
Okuduğu yazarlardaki vatan, özgürlük ve akıl fikirleri ileride Cumhuriyet’in, milli egemenliğin ve laikliğin temelini oluşturacaktır.
:::

## 4. Cephede bir subay: Askerlik hayatı

Mustafa Kemal’in liderlik özellikleri, ilk görevlerinde ve savaşlarda ortaya çıktı.

**Ordu ve siyaset.** 1909’da İstanbul’da 31 Mart Olayı çıktı. Meşrutiyete karşı çıkan bu ayaklanmayı bastırmak için Selanik’ten bir ordu yola çıktı. Mustafa Kemal bu ordunun kurmay başkanıydı ve orduya **Hareket Ordusu** adını verdi. Aynı yıllarda askerlerin siyasetten uzak durması gerektiğini savundu. Bu fikir, Cumhuriyet döneminde de önemsediği bir ilke oldu.

**Trablusgarp Savaşı (1911).** İtalya, Osmanlı’ya ait Trablusgarp’a (bugünkü Libya) saldırdı. Osmanlı’nın buraya kara ve deniz yoluyla asker göndermesi çok zordu. Mustafa Kemal, gazeteci kimliğiyle Mısır üzerinden gizlice bölgeye geçti. **Tobruk** ve **Derne**’de yerel halkı örgütleyerek İtalyanlara karşı başarılı savaştı. Ancak Balkan Savaşları başlayınca Osmanlı, 1912’de Uşi Antlaşması ile Trablusgarp’ı İtalya’ya bırakmak zorunda kaldı.

![Mustafa Kemal çölde çadırın önünde, yanında yerel savaşçılar](/lessons/bir-kahraman-doguyor/derne-1912.webp "Kurmay Binbaşı Mustafa Kemal (solda), Derne’de yerel savaşçıların önünde emirlerini yazdırıyor, 1912. | Anıtkabir arşivi. Wikimedia Commons, kamu malı")

**Balkan Savaşları (1912-1913).** Balkan devletleri birleşerek Osmanlı’ya saldırdı. Mustafa Kemal, Gelibolu Yarımadası’nda Bolayır’daki kolordunun kurmay başkanıydı. Bu savaşlarda Osmanlı Balkanlar’daki topraklarının büyük bölümünü kaybetti. Mustafa Kemal’in doğduğu şehir Selanik de elden çıktı. II. Balkan Savaşı’nda Edirne geri alındı.

**Sofya’da ataşemiliter (1913).** Savaştan sonra Sofya’ya askeri ataşe olarak gönderildi. Burada Bulgaristan’ın meclisini, demokratik kurumlarını ve toplum hayatını yakından gözlemledi. Bu gözlemler, ileride kuracağı yeni devlete dair fikirlerini zenginleştirdi.

| Olay | Gösterdiği özellik |
| --- | --- |
| Hareket Ordusu adını vermesi | Öncülük, sorumluluk alma |
| Ordunun siyasete karışmamasını savunması | İleri görüşlülük, ilkeli olma |
| Trablusgarp’a gizlice gitmesi | Vatanseverlik, cesaret, fedakârlık |
| Yerel halkı örgütlemesi | Teşkilatçılık, liderlik |
| Sofya’daki gözlemleri | Yeniliğe açıklık, çok yönlülük |

:::baglanti
Trablusgarp’ta yerel halkı örgütleme deneyimi, Milli Mücadele’de halkı örgütlerken çok işine yarayacaktır. Bu konu bir sonraki ünitenin temelidir.
:::

