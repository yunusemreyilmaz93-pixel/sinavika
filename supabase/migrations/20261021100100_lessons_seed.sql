## LGS’de nasıl sorulur

Fiilimsi soruları genellikle bir cümledeki sözcüğün türünü ya da görevini sorar. Çoğu zaman ek tanımanı değil, sözcüğün cümledeki işine bakmanı ister.

:::soru{cevap="C"}
Aşağıdaki cümlelerin hangisinde altı çizili sözcük **sıfat-fiildir**?

- A) [Okumak](#altcizgi) insanı geliştirir.
- B) Çocuk [gülerek](#altcizgi) yanımıza geldi.
- C) [Yırtılmış](#altcizgi) kitabı çöpe attı.
- D) Dün akşam erken [uyudum](#altcizgi).

---

1. Her seçenekte altı çizili sözcüğün cümledeki görevini sor.
2. A seçeneğinde okumak isim gibi kullanılmış ve özne olmuş. İsim-fiildir.
3. B seçeneğinde gülerek, geldi fiilinin nasıl yapıldığını anlatıyor. Zarf-fiildir.
4. C seçeneğinde yırtılmış, kitabı sözcüğünü niteliyor. Hangi kitap? Yırtılmış kitap. Sıfat-fiildir.
5. D seçeneğinde uyudum çekimli fiildir ve cümlenin yüklemidir.
:::

:::soru{cevap="D"}
Aşağıdaki cümlelerin hangisinde **fiilimsi yoktur**?

- A) Çocuklar koşa koşa geldi.
- B) Gelecek hafta sınav olacağız.
- C) Kitabı bitirince bana haber ver.
- D) Akşam yemeğini erkenden yedik.

---

1. Önce her cümlenin yüklemini bul. Sonra yüklem dışındaki fiil kökenli sözcüklere bak.
2. A seçeneğinde “koşa koşa” zarf-fiildir.
3. B seçeneğinde “gelecek” hafta sözcüğünü niteleyen sıfat-fiildir.
4. C seçeneğinde “bitirince” zarf-fiildir.
5. D seçeneğinde “yedik” çekimli fiildir. “Erkenden” ise zarftır, fiil kökünden gelmez. Bu cümlede fiilimsi yoktur.
:::

:::ipucu{baslik="İpucu"}
“Fiilimsi yoktur” diyen sorularda önce yüklemi ayır. Geriye kalan sözcüklerde fiil kökünden gelen bir sözcük kalmıyorsa cevap odur.
:::

## Kendini dene

Cevaplara bakmadan önce her soruyu kendi cümlelerinle cevaplamaya çalış. Hatırlamaya zorlamak, tekrar okumaktan daha kalıcı öğretir.

:::dene
1. Koşmak, koşan ve koşarak sözcüklerinin ortak noktası nedir? Farkları nedir? => Üçü de koş- fiilinden türemiş fiilimsidir. Koşmak isim gibi, koşan sıfat gibi ve ismi niteler, koşarak zarf gibi ve fiili niteler.
2. “Gelecek hafta sınava gireceğiz.” cümlesinde hangi sözcük fiilimsidir? Neden? => Gelecek. Hafta sözcüğünü niteleyen sıfat-fiildir. Gireceğiz çekimli fiildir ve cümlenin yüklemidir.
3. “Dün okuduğum kitabı sana vereyim.” cümlesindeki okuduğum sözcüğünü eklerine ayır. => oku + duğ + um. -duğ sıfat-fiil ekidir, -um iyelik ekidir. Kişi eki değildir.
4. “Çalışmak başarının anahtarıdır.” cümlesinde çalışmak hangi fiilimsidir? Cümledeki görevi nedir? => İsim-fiildir. Cümlenin öznesidir.
5. “Sınıfa girer girmez sessizlik oldu.” cümlesinde girer girmez hangi türdür? Neyi niteler? => Zarf-fiildir. Oldu yüklemini zaman bakımından niteler.
:::

