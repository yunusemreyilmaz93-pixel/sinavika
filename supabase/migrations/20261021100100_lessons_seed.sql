## 1. Fiilimsi nedir?

Fiilimsi, fiil kök ya da gövdesine bazı eklerin gelmesiyle oluşur. Fiilden doğar ama cümlede fiil gibi iş görmez. İsim, sıfat ya da zarf gibi kullanılır. Aynı fiil kökünden üç farklı fiilimsi türetebilirsin:

:::formul
- koş | mak | koşmak | İsim-fiil | yesil
- koş | an | koşan | Sıfat-fiil | mavi
- koş | arak | koşarak | Zarf-fiil | sari
:::

### Fiilimsi, çekimli fiilden nasıl ayrılır?

Çekimli fiil zaman ve kişi bildirir, cümlede yüklem olur. Fiilimsi zaman ve kişi bildirmez. Cümlede tek başına yüklem görevi görmez.

| Özellik | Çekimli fiil | Fiilimsi |
| --- | --- | --- |
| Cümledeki görevi | Yüklem olur. | İsim, sıfat ya da zarf görevi görür. |
| Zaman ve kişi | Bildirir. (geldi, gelirim) | Bildirmez. (gelmek, gelen, gelerek) |
| Olumsuz yapılabilir mi? | Evet. (gelmedi) | Evet. (gelmemek, gelmeyen, gelmeden) |
| Örnek cümle | Çocuk koştu. | Koşan çocuk yoruldu. |

### Fiil özelliklerini korurlar

Fiilimsiler olumsuz yapılabilir. Nesne ve zarf da alabilirler. “Kitap okumak” ifadesinde “kitap”, okumak fiilimsisinin nesnesidir. Fiilimsiyle bu sözcükler bir araya gelince **fiilimsi grubu** oluşur.

:::baglanti
Bir sözcüğün fiilimsi olup olmadığını anlamak için şunu sor: Bu sözcük cümlede yüklem mi, yoksa başka bir sözcüğe bağlı mı? Yüklem değil de başka bir sözcüğe bağlıysa fiilimsi olabilir.
:::

## 2. İsim-fiiller: İsim gibi kullanılan fiilimsiler

İsim-fiiller cümlede isim gibi kullanılır. Özne, nesne ya da tümleç olabilirler. İsim gibi davrandıkları için çoğul, iyelik ve hâl eki alabilirler.

Örnek ekler: [-mak / -mek](#ek) [-ma / -me](#ek) [-ış / -iş / -uş / -üş](#ek)

| Cümledeki görevi | Örnek cümle |
| --- | --- |
| Özne | [Koşmak](#altcizgi) sağlığa yararlıdır. |
| Nesne | Ali [kitap okumayı](#altcizgi) çok sever. |
| Dolaylı tümleç | Çocuk [yüzmekten](#altcizgi) korkuyor. |

:::ipucu
“Okumayı” sözcüğüne bak: Okuma isim-fiilinin sonuna belirtme hâl eki (-yı) gelmiş. İsim gibi hâl eki alması, bu sözcüğün isim görevinde olduğunu gösterir.
:::

:::baglanti
“Kitap okumak” gibi bir fiilimsi grubunu cümlenin ögesini bulurken tek parça say. Özneyi ya da nesneyi ararken grubun tamamını al.
:::

## 3. Sıfat-fiiller: İsmi niteleyen fiilimsiler

Sıfat-fiiller bir ismin önüne gelir ve onu niteler. “Nasıl?” ya da “Hangi?” sorusuna cevap verirler.

Örnek ekler: [-an / -en](#ek) [-ası / -esi](#ek) [-ar / -er](#ek) [-maz / -mez](#ek) [-dık / -dik](#ek) [-acak / -ecek](#ek) [-mış / -miş](#ek)

| Sıfat-fiil | Niteledikleri | Örnek cümle |
| --- | --- | --- |
| koşan | çocuk | [Koşan](#altcizgi) çocuk yoruldu. |
| görülesi | manzara | Burası [görülesi](#altcizgi) bir manzara. |
| akar | su | [Akar](#altcizgi) su yolunu bulur. |
| bitmez | enerji | Onun [bitmez](#altcizgi) bir enerjisi var. |
| okuduğum | kitap | [Okuduğum](#altcizgi) kitap çok güzeldi. |
| gelecek | hafta | [Gelecek](#altcizgi) hafta tatil başlıyor. |
| yorulmuş | yolcu | [Yorulmuş](#altcizgi) yolcu bir bankta oturdu. |

:::ipucu
**“Okuduğum” sözcüğünü parçala:** oku + [-duğ](#ek) + [-um](#ek). -duğ sıfat-fiil ekidir. Sondaki -um ise iyelik ekidir, kişi eki değildir. “Gördüğüm” ve “okuduğumuz” gibi sözcüklerde de aynı durum var.
:::

:::baglanti
-acak, -mış ve -dık ekleri hem sıfat-fiil eki hem de kip eki olabilir. Eke değil, görevine bak. Bir ismin önünde onu niteliyorsa sıfat-fiildir. Cümlenin sonunda yüklem olarak duruyorsa kip ekidir.
:::

## 4. Zarf-fiiller: Fiili niteleyen fiilimsiler

Zarf-fiiller cümlede zarf gibi kullanılır ve yüklemi niteler. İş nasıl yapıldı, ne zaman yapıldı gibi soruların cevabını verirler.

| Soru | Ekler | Örnekler |
| --- | --- | --- |
| Nasıl? | [-arak](#ek) [-ıp](#ek) [-madan](#ek) [-a / -e](#ek) [-esiye](#ek) | gülerek, koşup, yapmadan, koşa koşa |
| Ne zaman? | [-ınca](#ek) [-ken](#ek) [-dıkça](#ek) [-ır -maz](#ek) | görünce, dönerken, okudukça, gelir gelmez |

| Zarf-fiil | Örnek cümle | Sorusu |
| --- | --- | --- |
| gülerek | Çocuk [gülerek](#altcizgi) odaya girdi. | Nasıl girdi? |
| koşa koşa | Çocuklar [koşa koşa](#altcizgi) geldi. | Nasıl geldi? |
| yapmadan | Kahvaltı [yapmadan](#altcizgi) çıktı. | Nasıl çıktı? |
| görünce | Seni [görünce](#altcizgi) sevindim. | Ne zaman sevindim? |
| dönerken | Eve [dönerken](#altcizgi) yağmura yakalandık. | Ne zaman yakalandık? |
| gelir gelmez | Eve [gelir gelmez](#altcizgi) ödevine başladı. | Ne zaman başladı? |

:::baglanti
Zarf-fiil yüklemi niteler, yüklemin kendisi değildir. “Çocuk koşarak okula geldi.” cümlesinde yüklem **geldi**. Koşarak, geldi fiilinin nasıl yapıldığını anlatan zarf-fiildir.
:::

