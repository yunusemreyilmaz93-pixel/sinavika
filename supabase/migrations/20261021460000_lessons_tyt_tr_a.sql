2. Yapım ekini çekim ekinden ayırt etmek.
3. Sözcüğü yapısına göre basit, türemiş ya da birleşik olarak sınıflandırmak.
4. İsimden isim, isimden fiil, fiilden isim ve fiilden fiil yapan ekleri tanımak.
5. Birleşik sözcüğün oluşum türlerini bilmek.
:::

:::ipucu
Ek soruları için **tek bir ölçüt** yeter: Ek, sözcüğün anlamını ya da türünü değiştirip yeni bir sözcük yapıyorsa yapım ekidir. Yalnızca sözcüğün cümledeki göreviyle ya da ilişkisiyle ilgili bir bilgi veriyorsa (çoğul, hâl, iyelik, kişi, zaman) çekim ekidir.
:::

## 1. Kök, gövde, ek

**Kök:** Sözcüğün **anlam taşıyan en küçük parçasıdır**. Daha küçük parçaya bölünemez. göz, ev, gel-, yaz-.

**Gövde:** Çekim eki almadan önceki hâlidir. Kök, yapım eki alırsa gövde olur: göz → **gözlük** (gövde).

**Ek:** Köke ya da gövdeye eklenen ses ya da hecedir. İki gruba ayrılır.

| Ek türü | Görevi | Örnek |
| --- | --- | --- |
| **Yapım eki** | Yeni sözcük türetir, anlamı ya da türü değiştirir | göz-**lük**, kitap-**lık**, gül-**ümse** |
| **Çekim eki** | Sözcüğü cümlede başka sözcüklerle ilişkilendirir, anlamı değiştirmez | kitap-**lar**, ev-**de**, gel-**di** |

**Dizilişi:** Önce yapım ekleri, sonra çekim ekleri gelir. göz-lük-çü-**ye** (yapım-yapım-çekim).

## 2. Yapım ekleri

**İsimden isim yapan ekler:**

| Ek | Örnek |
| --- | --- |
| -lık, -lik, -luk, -lük | kitaplık, gözlük, öğretmenlik |
| -cı, -ci, -cu, -cü, -çı, -çi | aşçı, kitapçı, balıkçı |
| -lı, -li, -lu, -lü | akıllı, tuzlu, evli |
| -sız, -siz, -suz, -süz | akılsız, tuzsuz, evsiz |
| -cık, -cik, -cuk, -cük | evcik, kitapçık |
| -ca, -ce | Türkçe, güzelce |

**İsimden fiil yapan ekler:** -la/-le (göz-le-mek, ütü-le-mek), -laş/-leş (güzel-leş-mek), -lan/-len (ev-len-mek), -al/-el (az-al-mak).

**Fiilden isim yapan ekler:** -ma/-me (oku-ma, yaz-ma), -ış/-iş/-uş/-üş (gül-üş, bak-ış), -im/-ım/-um/-üm (bil-im, ol-um), -gı/-gi/-gu/-gü (bil-gi, say-gı), -ak/-ek (kon-ak), -ıcı/-ici/-ucu/-ücü (oku-yucu, çal-ıcı).

**Fiilden fiil yapan ekler:** Fiil çatı ekleri yapım ekidir. -dır, -t, -ıl, -ın, -ış: yap-ıl-mak, yaz-dır-mak.

## 3. Çekim ekleri

| Çekim eki | Örnek |
| --- | --- |
| Çoğul eki | kitap-**lar** |
| İyelik ekleri | kitab-**ım**, kitab-**ın** |
| Durum (hâl) ekleri | ev-**e**, ev-**i**, ev-**de**, ev-**den**, ev-**in** (ilgi) |
| Kişi ekleri | gel-di-**m**, gel-ir-**sin** |
| Zaman ekleri | gel-**di**, gel-**ecek**, gel-**iyor** |
| Ek fiil | öğrenci-**ydi**, güzel-**miş** |

Çekim eki sözcüğün türünü ve anlamını değiştirmez. Sözcük hâlâ aynı sözcüktür, yalnızca cümledeki **görevi** ya da **ilişkisi** değişir.

## 4. Yapıca sözcük türleri

**Basit sözcük:** Hiç ek almamış sözcük ya da **yalnızca çekim eki almış** sözcük. masa, evler, kitaptan, geldim.

**Türemiş sözcük:** Kök ya da gövdeye **yapım eki** getirilerek oluşmuştur. gözlük, aşçı, akıllı, bilgi. Bir ya da birden çok yapım eki alabilir: **göz-lük-çü**.

**Birleşik sözcük:** **İki ya da daha fazla sözcüğün birleşmesiyle** oluşur. Birleşik sözcükler çoğu zaman yeni bir kavram anlatır.

| Birleşik sözcük çeşidi | Örnek |
| --- | --- |
| Kaynaşmış (ses değişimi ile) | kaynana, kahvaltı, pazartesi |
| Anlamca kalıplaşmış (ses değişimi yok) | akşamüstü, başkent, gökdelen, hanımeli |
| Sıfat tamlaması kalıplaşan | karabiber, akciğer |

Birleşik sözcük sayılmayanlar: **İkilemeler** (ağır ağır, gide gele) ve **pekiştirmeler** (masmavi) kendilerine özgü yapıdadır.

## 5. Sözcüğün parçalarını bulma

Sözcüğün parçalarını bulmak için **sondan başa** doğru ayır.

**Örnek: gözlükçülerden**

- **-den**: çekim eki (ayrılma durumu)
- **-ler**: çekim eki (çoğul)
- **-çü**: yapım eki (isimden isim)
- **-lük**: yapım eki (isimden isim)
- **göz**: kök

Sözcük: **kök + yapım + yapım + çekim + çekim**. Türemiş yapılıdır.

:::neden-sonuc
- Ek, sözcüğün anlamını ya da türünü değiştiriyor => Yapım ekidir.
- Ek, sözcüğün cümledeki ilişkisini gösteriyor => Çekim ekidir.
- Sözcük yalnızca çekim eki almış => Basit yapılıdır.
- Sözcük yapım eki almış => Türemiş yapılıdır.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Çoğul, iyelik ve hâl eklerini yapım eki sanmak** sık yapılan bir hatadır. Bunlar çekim ekidir. Bir de birleşik sözcükle türemiş sözcüğü karıştırırsın: “Akşamüstü” iki sözcüğün birleşimidir, içinde yapım eki yoktur.
:::

:::baglanti
Sözcüğün yapısı “İsim ve Sıfat”, “Fiiller ve Ek Fiil” konularında ek türlerinin nasıl çalıştığını anlamanın temelidir. “Fiilimsiler” ve “Fiil Çatısı” konularındaki ekler de yapım ekidir. Bu konudaki çekim ekleri ise “Cümlenin Ögeleri” konusunda ögelerin belirlenmesine yardım eder.
:::

