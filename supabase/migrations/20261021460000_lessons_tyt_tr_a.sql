## 1. Paragrafın yapısı

**Paragraf**, tek bir düşünceyi ya da duyguyu anlatan, birbirine bağlı cümlelerden oluşan yazı birimidir. Bir paragrafta üç bölüm vardır:

| Bölüm | Görevi |
| --- | --- |
| Giriş | Konuyu tanıtır, soruyu ya da düşünceyi ortaya koyar |
| Gelişme | Düşünceyi açıklar, örneklerle ve kanıtlarla destekler |
| Sonuç | Düşünceyi toparlar, yargıyı bildirir |

Birçok paragrafta ana düşünce **ilk ya da son cümlededir**. İlk cümlede olan ana düşünceyi “yargı ile başlayan” paragraf, son cümlede olanı “sonuca varan” paragraf olarak düşünebilirsin.

## 2. Konu, ana düşünce, yardımcı düşünce

**Konu:** Parçanın **neyi** anlattığıdır. “Kitap okumak”, “çevre kirliliği”, “zaman yönetimi”. Konu genellikle **bir sözcük ya da kısa bir öbekle** söylenir.

**Ana düşünce:** Yazarın konu hakkında **söylemek istediği asıl yargıdır**. Konunun üzerine bir şey söyler. “Kitap okumak, insanın bilgisini ve bakış açısını geliştirir.” Tam bir cümledir ve genellikle öğüt, yargı ya da çıkarım içerir.

**Yardımcı düşünce:** Ana düşünceyi destekleyen ve açıklayan diğer düşüncelerdir.

**Örnek:** “Kitap okumak, yalnızca bilgi edinmek demek değildir. Okuyan kişi, başka insanların hayatına girer ve kendi düşüncelerini yeniden sorgular. Bu yüzden iyi bir okur, hem daha çok bilen hem de daha geniş düşünen biridir.”

- **Konu:** Kitap okumanın faydası.
- **Ana düşünce:** Kitap okumak insanın hem bilgisini hem bakış açısını geliştirir.
- **Yardımcı düşünce:** Okuyan kişi başka insanların hayatına girer.

**Ana düşünceyi bulmak için:** Parçayı bir cümleyle özetle. “Bu yazar neden yazmış?” sorusuna cevap ara. Ana düşünce, **parçanın tamamını kapsayan** cümledir. Yalnızca bir kısmını anlatan seçenek yardımcı düşüncedir.

## 3. Anlatım biçimleri

| Biçim | Amacı | Anlatımın özelliği |
| --- | --- | --- |
| Açıklayıcı | Bilgi vermek, açıklamak | Sade, net, nesnel. Bilimsel yazılarda sık görülür |
| Öyküleyici | Bir olayı anlatmak | Olaylar sırayla anlatılır, kişi ve yer vardır, fiiller çoktur |
| Betimleyici | Görüntüyü gözümüzde canlandırmak | Sıfatlar ve duyu organlarına seslenen sözcükler çoktur |
| Tartışmacı | Karşı görüşü çürütmek, görüşü savunmak | Karşı görüşe cevap verilir, kanıt gösterilir |

Bir parça birden çok biçimde olabilir ama **ağırlıklı** olan biçim sorulur.

**Örnek (betimleyici):** “Köyün girişindeki yaşlı çınar, dalları yere kadar sarkan koca bir gölgeye benziyordu. Yaprakları sabah güneşinde yeşilin binlerce tonuna bürünüyordu.” Burada sıfatlar çoktur ve parçada bir olay anlatılmamıştır, bir **görüntü** anlatılmıştır.

## 4. Düşünceyi geliştirme yolları

Yazarın bir düşünceyi nasıl desteklediği sorulur:

| Yol | İpucu |
| --- | --- |
| Tanımlama | Bir kavramın ne olduğunu söyler: “…dır, denir” |
| Karşılaştırma | İki şeyi benzerlik ya da farklılık bakımından kıyaslar |
| Örnekleme | Genel bir yargıyı örnekle somutlaştırır: “örneğin, mesela” |
| Tanık gösterme | Bir otoriteden ya da ünlü bir kişiden söz alır |
| Sayısal verilerden yararlanma | Rakam, yüzde, istatistik kullanır |
| Benzetme | Anlatılanı başka bir şeye benzeterek anlatır |
| Neden-sonuç gösterme | Bir durumun sebebini ve sonucunu açıklar |

## 5. Sık görülen soru türleri

**Akışı bozan cümle.** Parçanın konusundan ve akışından **kopuk** olan cümleyi bulursun. Konuyla ilgisi olmayan, başka bir konuyu anlatan ya da önceki cümleyle bağ kurulamayan cümle akışı bozar. Önce parçanın konusunu bul, sonra ona uymayan cümleyi seç.

**Paragraf tamamlama.** Boş bırakılan cümle, parçanın **konusuna ve anlatım akışına** uygun olmalıdır. Boşluktan önceki ve sonraki cümlelerin bağlaçlarına bak.

**Paragraf oluşturma (cümleleri sıralama).** İlk cümle genelde konuyu tanıtır, başka cümleye bağlı bir ifade (“bu yüzden, ayrıca, ancak”) taşımaz. Son cümle sonucu verir. Zamirler (bu, şu, onlar) ve bağlaçlar, önceki cümleye bağlanır.

**Paragrafı ikiye bölme.** İkinci paragrafın **başlayacağı cümle**, konunun değiştiği ya da yeni bir yönünün anlatıldığı cümledir.

**Başlık bulma.** Başlık, parçanın tamamını kapsar ve kısa söylenir.

:::ipucu{baslik="Sık yapılan hata"}
**Yardımcı düşünceyi ana düşünce sanmak** sık yapılan bir hatadır. Seçenekte parçanın yalnızca bir kısmını anlatan bir cümle varsa ana düşünce değildir. Aşırı genelleme yapan (“tek yol”, “her zaman”, “asla”) seçeneklere de dikkat et: Parçada böyle bir kesinlik yoksa seçenek yanlıştır.
:::

:::baglanti
Paragraf, “Sözcükte Anlam” ve “Cümlede Anlam” konularının uygulama alanıdır. Parçadaki her cümleyi doğru yorumlayamazsan ana düşünceyi bulamazsın. “Noktalama İşaretleri” ve “Anlatım Bozuklukları” da paragraf sorularında akıcı okumanın yardımcılarıdır.
:::

