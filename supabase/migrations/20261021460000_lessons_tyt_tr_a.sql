## 1. Ünlüler ve ünsüzler

Türkçede **8 ünlü** (sesli) ve **21 ünsüz** (sessiz) vardır.

| Grup | Ünlüler |
| --- | --- |
| Kalın | a, ı, o, u |
| İnce | e, i, ö, ü |
| Düz | a, e, ı, i |
| Yuvarlak | o, ö, u, ü |
| Geniş | a, e, o, ö |
| Dar | ı, i, u, ü |

**Sert (süreksiz) ünsüzler:** f, s, t, k, ç, ş, h, p. “Fıstıkçı Şahap” cümlesiyle akılda tutulur. Diğer ünsüzler yumuşaktır.

## 2. Ünlü uyumları

**Büyük ünlü uyumu.** Bir sözcükteki ünlüler hepsi kalın (a, ı, o, u) ya da hepsi ince (e, i, ö, ü) olmalıdır. Sözcüğün **ilk hecesindeki ünlü** diğerlerini belirler.

- Uyar: **ağaç** (a-a), **balık** (a-ı), **çocuk** (o-u), **kuzu** (u-u), **gelir** (e-i), **gözlük** (ö-ü)
- Uymaz: **kitap** (i-a), **kalem** (a-e), **elma** (e-a), **anne** (a-e)

Yabancı kökenli sözcüklerin çoğu ve birleşik sözcükler büyük ünlü uyumuna uymaz. Türkçe ekler, kalın sözcüklere kalın, ince sözcüklere ince ünlülü olarak eklenir: **kitap-lar, ev-ler**.

**Küçük ünlü uyumu.** Düz ünlüden (a, e, ı, i) sonra düz ünlü gelir. Yuvarlak ünlüden (o, ö, u, ü) sonra ya **dar yuvarlak** (u, ü) ya da **düz geniş** (a, e) ünlü gelir.

- Uyar: **kalem** (a-e), **elma** (e-a), **kuzu** (u-u), **okul** (o-u), **kulak** (u-a), **gözlük** (ö-ü)
- Uymaz: **sabun** (a-u), **limon** (i-o), **doktor** (o-o), **otobüs** (o-o-ü)

Kural şu: ilk hece düzse tüm heceler düz olur, ilk hece yuvarlaksa sonrakiler yuvarlak dar ya da düz geniş olur.

## 3. Ünsüz benzeşmesi

Sert ünsüzle (f, s, t, k, ç, ş, h, p) biten sözcüklere **c, d, g** ile başlayan ek geldiğinde ekin başındaki ünsüz sertleşerek **ç, t, k** olur.

- sokak + da → sokak**ta**
- kitap + cı → kitap**çı**
- ağaç + dan → ağaç**tan**
- toprak + da → toprak**ta**

Yumuşak ünsüzle ya da ünlüyle biten sözcüklerde ek yumuşak kalır: **ev-de, okul-da, göz-den**.

## 4. Ses olayları

**Ünsüz yumuşaması.** Çok heceli sözcüklerin sonundaki **p, ç, t, k** ünsüzleri, **ünlüyle başlayan bir ek** gelince **b, c, d, ğ** olur.

| Sözcük | Ek alınca |
| --- | --- |
| kitap | kitabı |
| ağaç | ağacı |
| kanat | kanadı |
| çocuk | çocuğu |
| yaprak | yaprağı |

Tek heceli sözcüklerin çoğunda yumuşama olmaz: **at - atı, top - topu, saç - saçı, süt - sütü**. Ayrıca bazı çok heceli sözcüklerde de olmaz: **millet - milleti**.

**Ünlü düşmesi.** Bazı sözcüklere ünlüyle başlayan ek gelince **ikinci hecedeki ünlü düşer**.

- omuz → **omzu**
- ağız → **ağzı**
- burun → **burnu**
- gönül → **gönlü**
- fikir → **fikri**

**Ünlü daralması.** **-yor** eki, **a** ya da **e** ile biten fiil köklerine gelince kökteki geniş ünlü daralır.

- bekle-yor → **bekliyor** (e → i)
- anla-yor → **anlıyor** (a → ı)
- oyna-yor → **oynuyor** (a → u)
- söyle-yor → **söylüyor** (e → ü)

**Ünsüz türemesi.** Arapçadan geçen bazı sözcüklere ek gelince son ünsüz **çift yazılır**: his → **hissetmek**, af → **affetmek**, zan → **zannetmek**, ret → **reddetmek**.

**Ulama.** Ünsüzle biten sözcük, ünlüyle başlayan sözcükle birlikte okunurken ünsüz, ikinci sözcüğün ilk hecesine bağlanır: “çok acı” → ço-kacı, “yarım ekmek” → ya-rı-mek-mek.

## 5. Heceler

Türkçede **her hecede tek ünlü** bulunur. Ünlü sayısı hece sayısını verir.

- **Açık hece:** Ünlüyle biten hece (a, o, ka, de).
- **Kapalı hece:** Ünsüzle biten hece (at, kul, kal).

Hece ayırırken ünlüden önceki ünsüz, o ünlüye bağlanır: **o-ku-lu-muz, ka-lem, ki-tap**. İki ünsüz yan yana gelirse ilk ünsüz önceki heceye, ikincisi sonraki heceye gider: **kar-deş, ak-şam**.

:::ipucu{baslik="Sık yapılan hata"}
**Ünlü düşmesi ile ünlü daralmasını** karıştırırsın. Düşmede ünlü yok olur (omuz - omzu), daralmada ünlünün **niteliği değişir** (bekle - bekliyor). Ayrıca “kitapçı” ve “kitabı” arasındaki farkı da hatırla: ‘cı’ eki sert ünsüzle bitene ‘çı’ olur (benzeşme), ünlüyle başlayan ek ise ‘p’yi ‘b’ye çevirir (yumuşama).
:::

:::baglanti
Ses bilgisi “Yazım Kuralları” konusunun temelidir: Hangi sesin yazıda nasıl gösterileceği ses olaylarına bağlıdır. “Sözcükte Yapı” konusunda eklerin neden farklı biçimlerde geldiğini de bu konudan anlarsın.
:::

