| Başlık | Kısa not |
| --- | --- |
| Kök | Anlamlı en küçük parça |
| Yapım eki | Yeni sözcük türetir |
| Çekim eki | İlişki kurar, anlamı değiştirmez |
| Basit | Ek almamış ya da yalnız çekim eki almış |
| Türemiş | Yapım eki almış |
| Birleşik | İki sözcüğün birleşimi |
| Sıralama | Önce yapım, sonra çekim |

