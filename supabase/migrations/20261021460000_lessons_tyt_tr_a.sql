## 1. Nokta ve virgül

**Nokta ( . )** şu yerlerde kullanılır:

- Tamamlanmış cümlenin sonunda.
- Bazı kısaltmaların sonunda: Dr., Prof., vb.
- Sıra bildiren sayılardan sonra: 1., 2., 3.
- Tarihlerde: 29.10.1923
- Saatlerde: 14.30
- Bin ayracı olarak: 1.250

**Nokta kullanılmaz:** Büyük harflerle yazılan kısaltmalarda (TBMM, TDK, TRT), ölçü birimlerinde (kg, cm, km), başlıklarda.

**Virgül ( , )** en çok kullanılan işarettir:

| Kullanım yeri | Örnek |
| --- | --- |
| Eş görevli sözcükler arasında | Sepete elma, armut, üzüm koydu. |
| Sıralı cümleler arasında | Kapı açıldı, içeri girdi, oturdu. |
| Hitap sözcüklerinden sonra | Ali, buraya gel. |
| Ara sözlerden ve ara cümlelerden önce ve sonra | Ahmet, benim arkadaşım, geldi. |
| “Ama, fakat, ancak, lakin” öncesinde | Çok çalıştı, ama başaramadı. |
| Cümle başındaki “evet, hayır, peki, yani” sonrasında | Evet, haklısın. |
| Tarihlerde ay ile gün/yıl arasında | 10 Kasım 1938, Perşembe |

**Virgül kullanılmaz:** Özne ile yüklem arasında, nesne ile yüklem arasında, sıfat ile isim arasında (tek sıfat varsa), cümleyi bölmek için gereksiz yerlerde.

- Yanlış: Dün akşam kitabı, okudum.
- Doğru: Dün akşam kitabı okudum.

## 2. Noktalı virgül ve iki nokta

**Noktalı virgül ( `;` )** virgüllerle ayrılmış ögeler arasında daha **güçlü bir ara** vermek için kullanılır. Sıralı cümleler anlam bakımından birbirine yakın ve uzunsa noktalı virgülle ayrılır. “Ama, fakat, ancak” ile başlayan uzun cümlelerin önünde de kullanılabilir.

**İki nokta ( : )** şu yerlerde kullanılır:

- **Açıklama yapılacak** bir cümlenin sonunda: “Şu bilinen bir gerçek: Emek, değerin kaynağıdır.”
- **Örnek ya da sıralama** vereceğinde: “Sepette şu meyveler vardı: elma, armut, üzüm.”
- **Konuşmayı başlatırken**: “Annem şöyle dedi: ‘Hava soğuk, mont giy.’”
- Karşılıklı konuşmada kişi adından sonra, anlık notlarda.

Dikkat: İki nokta, cümlenin kesintisiz akışını bozacak yerlere konmaz. “Dün akşam: arkadaşlarımla sinemaya gittim” yanlıştır.

## 3. Soru işareti, ünlem, üç nokta

**Soru işareti ( ? ):** Soru bildiren cümlelerin sonunda. Ayrıca bilinmeyen tarih ya da sayıların yerine (1930?) kullanılabilir. **Dolaylı anlatımda soru işareti kullanılmaz:** “Bana kim olduğunu söylemedi.” (soru değil, haber veren cümle).

**Ünlem ( ! ):** Sevinç, öfke, şaşkınlık, seslenme, emir bildiren cümlelerin sonunda. “Ne güzel bir gün!”, “Dur!”

**Üç nokta ( … ):** 

- Cümlenin tamamlanmadığını, söylenmek istenenin söylenmediğini gösterir: “Gelmeyeceğini biliyordum…”
- Alıntılarda **atlanan kısım** yerine konur.
- Duyguları ya da çekingenliği yansıtır.

## 4. Tırnak, yay ayraç, kısa çizgi, eğik çizgi

**Tırnak işareti ( “ ” ):**

- Başkasından **aynen alınan sözlerde**: Annem “Hava soğuk” dedi.
- Vurgulanmak istenen sözcüğü gösterir.
- Eser, gazete, dergi adlarında kullanılabilir.

**Yay ayraç ( ( ) ):** Cümlede **açıklama ya da ek bilgi** için kullanılır. “Ankara (Türkiye’nin başkenti) büyük bir kenttir.” Yaşam yıllarında ve kaynakça numaralarında da kullanılır: Nazım Hikmet (1902-1963).

**Kısa çizgi ( - ):**

- Satır sonunda sözcüğü hecelerden ayırırken.
- Birleşik ögeleri bağlarken: İstanbul-Ankara hattı, yedi-sekiz yaşında.
- Tarih ve yıl aralıklarında: 1914-1918.

**Eğik çizgi ( / ):** Tarihlerde, alternatif seçeneklerde, dizelerin satır sonlarında kullanılır.

**Uzun çizgi:** Karşılıklı konuşmalarda konuşma başlangıcını göstermek için ya da ara sözleri ayırmak için kullanılır.

