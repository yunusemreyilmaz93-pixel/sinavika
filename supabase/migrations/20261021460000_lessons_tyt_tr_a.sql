“Kalın bir kitap”, “kalın bir ses”, “kalın kafalı biri”. Üç cümlede de aynı sözcük var ama her seferinde başka bir şey anlatıyor. Türkçe sorularının büyük kısmı, bir sözcüğün **o cümlede hangi anlamda** kullanıldığını bulmaya dayanır. Bu konuda sözcüğün anlam türlerini, anlam ilişkilerini ve deyim ile atasözlerini öğreneceksin.

:::hedefler
1. Sözcüğün gerçek, yan, mecaz ve terim anlamını ayırt etmek.
2. Somut ve soyut anlamlı sözcükleri ayırt etmek.
3. Eş sesli, eş anlamlı ve zıt anlamlı sözcükleri bulmak.
4. Deyim ile atasözünü birbirinden ayırmak.
5. Bir sözcüğün cümledeki anlamını bağlamdan çıkarmak.
:::

:::ipucu
Sözcüğün anlamını **tek başına değil, cümlenin içinde** düşün. “Ağır” sözcüğünü sözlükte bulabilirsin ama hangi anlamda kullanıldığını yalnızca yanındaki sözcükler söyler. “Ağır çanta” ile “ağır söz” aynı sözcüğü farklı anlamlarda kullanır.
:::

## 1. Gerçek, yan, mecaz ve terim anlam

**Gerçek (temel) anlam.** Sözcüğün akla ilk gelen, en yaygın anlamıdır. Sözcüğü hiç bilmeyen birine ilk olarak bu anlamı söylersin.

**Yan anlam.** Sözcüğün temel anlamıyla bağlantılı olarak kazandığı ek anlamdır. Temel anlamla yan anlam arasında bir benzerlik ya da ilişki vardır. Sözlükte aynı maddenin altında 2., 3. anlam olarak sıralanır.

**Mecaz anlam.** Sözcüğün gerçek anlamından uzaklaşıp **benzetme yoluyla** kazandığı anlamdır. Cümlenin bağlamı olmadan anlaşılmaz.

**Terim anlam.** Sözcüğün bir bilim, sanat ya da meslek dalında kazandığı özel anlamdır. Terim anlamlı sözcük, o alanda tek bir anlam taşır.

| Anlam | “ayak” sözcüğüyle örnek | “kök” sözcüğüyle örnek |
| --- | --- | --- |
| Gerçek | Ayağına taş battı. | Ağacın kökü toprağa uzandı. |
| Yan | Masanın ayağı kırılmış. | Dişin kökü iltihaplanmış. |
| Mecaz | Her işe ayak uyduramıyor. | Sorunun kökünü bulmalısın. |
| Terim | Şiirde ayak, ölçü birimidir. | Dokuzun karekökü üçtür. |

**Nasıl ayırırsın?** Önce cümlede sözcüğü **gerçek anlamıyla** okumayı dene. Anlam akıyorsa gerçek anlamdır. Anlamsız kalıyorsa mecaz ya da yan anlam vardır. Sözcüğün, gerçek anlamıyla **ilişkisi görünen ama yeni bir şeyi adlandıran** kullanımı yan anlamdır. Hiç alakası kalmamış, benzetmeye dayanan kullanım ise mecazdır.

:::neden-sonuc
- “Soğuk su içti.” cümlesinde sıcaklık ölçülebiliyor => Gerçek anlam.
- “Soğuk bir tavırla karşıladı.” cümlesinde tavır ısıya sahip değil => Mecaz anlam.
- “Çaydanlığın ağzı” ifadesinde bir şeyin açıklığı adlandırılıyor => Yan anlam.
:::

## 2. Somut ve soyut anlam

**Somut anlam:** Beş duyu organından biriyle (görme, işitme, koklama, tatma, dokunma) algılanabilen kavramlardır. Masa, ışık, ses, koku, yağmur, çay.

**Soyut anlam:** Duyu organlarıyla algılanamayan, akılla ve duyguyla kavranan kavramlardır. Sevgi, adalet, özlem, korku, düşünce.

Aynı sözcük farklı cümlelerde somut ya da soyut olabilir. “Kırık bir bardak” cümlesinde “kırık” somuttur, “kırık bir gönül” cümlesinde soyuttur. Sorularda “hangisinde soyut anlamlı sözcük **kullanılmıştır**” diye sorulursa koyu yazılan sözcüğün cümledeki kullanımına bak.

## 3. Sözcükler arasındaki anlam ilişkileri

**Eş sesli (sesteş) sözcükler.** Yazılışları ve okunuşları aynı, anlamları **birbiriyle ilgisiz** sözcüklerdir.

- **yüz:** 100 sayısı, surat, yüzmek eylemi
- **çay:** içecek, küçük akarsu
- **al:** renk adı, almak eyleminin emri
- **yaz:** mevsim, yazmak eyleminin emri

Dikkat: Yan anlamda anlamlar arasında bağlantı vardır, sesteşlikte yoktur. “Ayak” (organ) ile “masanın ayağı” yan anlam ilişkisindedir. “Yüz” (sayı) ile “yüz” (surat) arasında hiçbir bağ yoktur, bunlar sesteştir.

**Eş anlamlı (anlamdaş) sözcükler.** Yazılışları farklı, anlamları aynı ya da çok yakın sözcüklerdir: okul-mektep, öğretmen-hoca, güzel-hoş, sevgi-muhabbet. Tam eş anlamlı sözcük azdır, çoğu birbirine **yakın anlamlıdır**.

**Zıt (karşıt) anlamlı sözcükler.** Anlamca birbirinin karşıtı olan sözcüklerdir: iyi-kötü, ışık-karanlık, gelmek-gitmek, alçak-yüksek. Bir sözcüğün her anlamının zıddı aynı değildir. “Açık” sözcüğünün karşıtı “kapalı”, “açık renk” için “koyu”, “açık sözlü” için “kapalı” olmayabilir.

| İlişki | Örnek |
| --- | --- |
| Eş sesli | Yüz (100) - yüz (surat) |
| Eş anlamlı | Cesur - yürekli |
| Zıt anlamlı | Doğru - yanlış |
| Yakın anlamlı | Çabuk - hızlı |

## 4. Deyim ve atasözü

**Deyim:** Gerçek anlamından ayrı, **kalıplaşmış** ve çoğunlukla mecaz anlam taşıyan söz öbeğidir. Bir durumu, davranışı ya da özelliği anlatır. “Gözden düşmek”, “ağzı kulaklarına varmak”, “eli açık olmak”, “kulak vermek”.

**Atasözü:** Uzun deneyimlerden doğan, **yargı bildiren**, öğüt veren ya da genel bir gerçeği anlatan kalıplaşmış sözlerdir. “Damlaya damlaya göl olur”, “Ağaç yaşken eğilir”, “Sakla samanı gelir zamanı”.

| Ayrım | Deyim | Atasözü |
| --- | --- | --- |
| Anlam | Çoğunlukla mecaz | Gerçek, mecaz ya da ikisi birlikte |
| Yargı | Yargı bildirmez | Yargı bildirir, öğüt verir |
| Cümle durumu | Çoğu zaman cümleyi tamamlamaz | Genelde cümle özelliğindedir |
| Kalıp | Değişmez | Değişmez |

:::ipucu{baslik="Sık yapılan hata"}
**Sözcüğün tek bir anlamı olduğunu** sanmak en sık yapılan hatadır. Soruda “bu cümlede şu anlamdadır” diyorsa o cümleye bak, sözlükteki ilk anlama değil. Ayrıca yan anlamı mecaz anlamla karıştırırsın: Yan anlamda temel anlamla bağ **görünür**, mecazda ise sözcük benzetme yoluyla başka bir kavrama taşınmıştır.
:::

:::baglanti
Bu konudaki anlam türleri “Cümlede Anlam” ve “Paragraf” konularında her cümlenin yorumunda kullanılır. “Söz sanatları” da mecaz anlamın bir uzantısıdır: Benzetme ve kişileştirme, sözcüğün mecaz yoluyla kullanılmasına dayanır.
:::

