## 2. de/da, ki ve mi

**“de/da” bağlaç.** Cümlede “bile, ayrıca” anlamı taşır ve **ayrı yazılır**. Ünlü uyumuna uyar (da/de). Atılsa cümlenin anlamı bozulmaz.

- Sen **de** gel. (Sen bile)
- Ben **de** okula gidiyorum.

**“-de/-da” ek (bulunma eki).** Sözcüğe **bitişik** yazılır, yer bildirir ve ünsüz benzeşmesine uğrar (-te, -ta).

- Ev**de** kal. Sokak**ta** oynuyorlar. Sen**de** bu kitaptan var mı?

**Ayırma ölçütü:** “de/da”yı çıkarınca cümle anlamlıysa bağlaçtır, ayrı yazılır. Çıkarınca anlam bozuluyorsa ektir, bitişik yazılır.

**“ki” bağlaç.** Ayrı yazılır, genellikle iki cümleyi bağlar.

- Biliyorum **ki** yarın gelecek.
- Öyle bir yorgundum **ki** ayakta duramıyordum.

**“-ki” ek.** Sözcüğe bitişik yazılır, ek olarak “bulunma, ait olma” bildirir.

- Sınıf**taki** öğrenciler. Bugün**kü** ders. Masa**daki** kitap.

**Bitişik yazılan kalıplaşmış “ki”ler:** halbuki, oysaki, mademki, sanki, çünkü.

**Soru eki “mi”.** Her zaman **ayrı** yazılır. Önündeki sözcüğün son ünlüsüne uyar (mı, mi, mu, mü).

- Geldi **mi**? Okudun **mu**? Bu senin **mi**?

Soru ekinden sonra gelen ek bitişik yazılır: gelmiş **miydi**, okudun **mu**ydu.

