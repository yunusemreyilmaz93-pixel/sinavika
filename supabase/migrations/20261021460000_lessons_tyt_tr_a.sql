## 1. Neden-sonuç, amaç-sonuç, koşul-sonuç

**Neden-sonuç.** Bir olayın sebebini ve sonucunu bildirir. Sebep zaten olmuştur, sonuç ona bağlıdır. İpuçları: “çünkü, için, -dığı için, -dığından, yüzünden, sebebiyle, -diğinden dolayı”.

- Yağmur yağdığı için maç ertelendi. (Sebep: yağmur, sonuç: erteleme)
- Çünkü ders çalışmamıştı, sınavdan düşük aldı.

**Amaç-sonuç.** Bir iş **belli bir amaçla** yapılır. Amaç henüz gerçekleşmemiştir, iş onu gerçekleştirmek için yapılır. İpuçları: “için, diye, amacıyla, -mek üzere, -sin diye, -mesi için”.

- Sınavı kazanabilmek için gece gündüz çalıştı. (Amaç: sınavı kazanmak)
- Erken yetişsin diye yola önceden çıktı.

**Koşul-sonuç.** Bir olayın gerçekleşmesi başka bir olaya bağlıdır. İpuçları: “-se, -sa, eğer, -mediği sürece, -diği takdirde”.

- Erken kalkarsan otobüse yetişirsin.
- Hava güzel olursa pikniğe gideceğiz.

:::neden-sonuc
- “Yağmur yağdığı için yollar kapandı.” cümlesinde sebep önce gerçekleşmiş => Neden-sonuç.
- “Yollar kapanmasın diye tedbir aldılar.” cümlesinde amaç henüz gerçekleşmemiş => Amaç-sonuç.
- “Tedbir alırlarsa yollar kapanmaz.” cümlesinde kapanmama alınan tedbire bağlı => Koşul-sonuç.
:::

## 2. Karşılaştırma, tanım, örnekleme

**Karşılaştırma:** İki ya da daha fazla varlığın, durumun, özelliğin bir bakımdan kıyaslanmasıdır. İpuçları: “-den daha, kadar, gibi, ise, ama, oysa”. Bu kitap ötekinden daha ilginç.

**Tanım:** Bir kavramın ne olduğunu açıklayan cümledir. “… …dır” kalıbıyla kurulur ve çoğunlukla “denir” ile biter. Çember, bir noktadan eşit uzaklıktaki noktaların kümesidir.

**Örnekleme:** Genel bir yargıyı somut bir durumla göstermektir. İpuçları: “örneğin, mesela, söz gelişi”. Sebzeler vitamin kaynağıdır, örneğin havuç A vitamini bakımından zengindir.

**Benzetme:** İki şey arasında ortak bir özellik kurmaktır. “Gibi, sanki, kadar” sözcükleriyle yapılır.

## 3. Öznel ve nesnel yargı

**Öznel yargı:** Kişiden kişiye, zamandan zamana **değişen**, kanıtlanamayan görüştür. Duygu, beğeni, tahmin içerir. “En güzel, en iyi, harika, sıkıcı, muhteşem” gibi sözcükler genelde öznel yargı işaretidir.

- Bu şehrin en güzel mevsimi sonbahardır.
- Roman okumak insanı en çok dinlendiren uğraştır.

**Nesnel yargı:** Herkes için aynı olan, **ölçülebilen ya da kanıtlanabilen** bilgidir.

- Su, deniz seviyesinde 100 derecede kaynar.
- Ankara, Türkiye’nin başkentidir.

Basit bir ölçüt: “Birisi bunu **yanlışlayabilir mi?**” Evet ve nasıl yanlışlayacağı belli ise nesneldir. “Bence” ile başlatabiliyorsan öznel yargıdır.

## 4. Kesinlik ve olasılık

**Kesinlik:** Yargının kesin ve değişmez olduğunu bildirir. İpuçları: “kesinlikle, mutlaka, muhakkak, hiç, asla” ve yüklemin kesin kipleri.

**Olasılık:** Yargının gerçekleşme ya da doğru olma ihtimalini bildirir. İpuçları: “belki, galiba, sanırım, herhalde, muhtemelen, -ebilir, -miş olmalı”.

| Cümle | Anlam |
| --- | --- |
| Yarın sabah toplantı başlayacak. | Kesinlik |
| Dedem yine vapura yetişememiş olabilir. | Olasılık |
| Bu takım kesinlikle şampiyon olacak. | Kesinlik, ama öznel yargı |

## 5. Çıkarım yapmak

Çıkarım, cümlede **söylenenden mantıkla elde edilen** sonuçtur. Cümlede doğrudan yazılı olmayan ama yazılandan kesin çıkan bilgi çıkarımdır. Cümlede yazılmayan, olabileceği düşünülen ya da yazar tarafından hiç söylenmemiş bir bilgi ise çıkarım değildir, tahmindir.

**Yöntem:** Seçeneği cümlede bir **dayanak** göstererek doğrulayabiliyorsan doğrudur. Dayanak gösteremiyorsan ya da cümlenin söylediğinin **ötesine geçiyorsa** yanlıştır.

:::ipucu{baslik="Sık yapılan hata"}
**Cümlede olmayan bir bilgiyi doğru saymak** en sık yapılan hatadır. “Ece her gün kütüphaneye gelir” cümlesinden “Ece sınavlara çok çalışır” çıkarılamaz, çünkü kütüphanede ne yaptığı belli değildir. Ayrıca “neden” ile “amaç” karışır: Neden olmuş olanı, amaç ise henüz olmamış olanı söyler.
:::

