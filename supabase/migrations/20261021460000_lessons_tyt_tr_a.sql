“Bu güzel kitabı çok sevdim.” cümlesinde “kitap” bir **isimdir**, “güzel” ve “bu” o ismi tanıtan **sıfatlardır**. Cümlenin yapı taşları olan isim ve sıfat, TYT’de her yıl sorulan konulardır. Bir sözcüğün isim mi sıfat mı olduğu **cümledeki göreviyle** belirlenir. Bu konuda isimlerin türlerini, isim tamlamalarını, sıfat çeşitlerini ve adlaşmış sıfatı öğreneceksin.

:::hedefler
1. İsimleri anlamlarına göre (özel, cins, somut, soyut, topluluk) ayırt etmek.
2. İsim tamlamalarını (belirtili, belirtisiz, zincirleme) tanımak.
3. Sıfat türlerini (niteleme, işaret, sayı, belgisiz, soru) ayırt etmek.
4. Adlaşmış sıfatı belirlemek.
5. Sıfat tamlaması ile isim tamlamasını ayırt etmek.
