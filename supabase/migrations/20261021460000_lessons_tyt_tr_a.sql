:::

## 1. İsim

Varlıkları, kavramları ve olayları karşılayan sözcüklere **isim (ad)** denir. İsimler anlamlarına göre gruplanır.

| Tür | Anlamı | Örnek |
| --- | --- | --- |
| Cins ismi | Aynı türdeki varlıkların ortak adı | kitap, kalem, şehir, öğrenci |
| Özel isim | Tek bir varlığa verilen ad | Ankara, Ali, Karadeniz, Çalıkuşu |
| Somut isim | Duyu organlarıyla algılanır | masa, yağmur, çay |
| Soyut isim | Duyu organlarıyla algılanamaz | sevgi, korku, adalet |
| Topluluk ismi | Biçimce tekil, anlamca çoğul | sürü, ordu, millet, halk, orman |
| Tekil | Tek varlık | kitap |
| Çoğul | Birden çok varlık (-lar, -ler) | kitaplar |

**Kafa karıştıran noktalar:**

- **Topluluk ismi** tekil görünür ama anlamı çoğuldur. Sürü, çok sayıda hayvandan oluşur. “Sürü geldi” cümlesinde yüklem tekil gelir.
- **Özel ad** olmak için tek varlığa ait olmalıdır. “Deniz” sözcüğü “Mavi deniz” cümlesinde cins ismidir, “Karadeniz” özel isimdir.
- Çoğul eki “-ler”, çekim ekidir ve ismin türünü değiştirmez.

## 2. İsim tamlamaları

Bir ismin başka bir isimle sahiplik ya da ilgi ilişkisi kurduğu söz öbeğidir. İki parçası vardır: **tamlayan** ve **tamlanan**.

**Belirtili isim tamlaması:** Tamlayan **ilgi eki** (-ın, -in, -un, -ün) alır, tamlanan **iyelik eki** alır. “Okulun bahçesi”, “Ali’nin kalemi”, “annemin eli”.

**Belirtisiz isim tamlaması:** Tamlayan ek almaz, tamlanan **iyelik eki** alır. “Okul bahçesi”, “kapı kolu”, “çay bardağı”.

**Zincirleme isim tamlaması:** İkiden fazla isim bir arada tamlama oluşturur. “Türkiye Cumhuriyeti Devleti” ya da “okulun bahçe kapısı”.

| Tamlama | Tamlayan | Tamlanan |
| --- | --- | --- |
| Belirtili | okul**un** | bahçe**si** |
| Belirtisiz | okul | bahçe**si** |
| Zincirleme | okul**un** | bahçe kapı**sı** |

## 3. Sıfat

İsimleri **niteleyen ya da belirten** sözcüklere sıfat denir. Sıfat, ismin **önünde** gelir ve onun hangi özelliğe sahip olduğunu ya da hangisi olduğunu söyler.

**Niteleme sıfatları:** İsmin rengini, biçimini, durumunu ya da niteliğini bildirir. Soru: “nasıl?” → **güzel** kız, **kırmızı** elma, **uzun** yol, **eski** ev.

**Belirtme sıfatları:** İsmin hangi, kaç ya da hangisi olduğunu belirtir.

| Tür | Soru | Örnek |
| --- | --- | --- |
| İşaret sıfatı | Hangi? | **Bu** kitap, **şu** adam, **o** kız, **öyle** bir gün |
| Sayı sıfatı | Kaç? | **Üç** arkadaş, **ikişer** elma, **üçüncü** gün |
| Belgisiz sıfat | Nasıl bir belirsizlik? | **Bazı** öğrenciler, **birkaç** kişi, **her** gün, **hiçbir** şey |
| Soru sıfatı | Hangi, kaç, ne? | **Hangi** yol? **Kaç** kitap? **Ne** zaman? |

**Sıfat tamlaması:** Sıfat + isim. “Güzel kız”, “kırmızı elma”. İsim tamlamasından farkı, tamlananın iyelik eki almamasıdır.

## 4. Adlaşmış sıfat

Sıfat, ismin önünde gelir. **İsim düşerse sıfat tek başına kalır ve isim görevi görür.** Buna **adlaşmış sıfat** denir. Adlaşmış sıfat çekim eki alır.

- **Yaşlı** adam bastonunu aldı. (Sıfat, “adam”ı niteliyor)
- **Yaşlılara** yer verelim. (Adlaşmış sıfat, isim yerine kullanılmış, çekim eki almış)

**Ölçüt:** Sözcüğü bir isim niteliyor mu? Niteliyorsa sıfattır. Niteleyecek isim yoksa ve sözcük çekim eki almışsa adlaşmış sıfattır.

:::neden-sonuc
- “Güzel” ismin önünde ve onu niteliyor => Sıfattır (güzel kız).
- “Güzel” ismin yerine kullanılmış ve ek almış => Adlaşmış sıfattır (güzeller geldi).
- Tamlanan iyelik eki almış => İsim tamlamasıdır (okul bahçesi).
- Tamlanan iyelik eki almamış => Sıfat tamlamasıdır (güzel kız).
:::

:::ipucu{baslik="Sık yapılan hata"}
**Sıfat tamlaması ile isim tamlamasını karıştırmak** en sık yapılan hatadır. “Okul bahçesi”nde “bahçe” iyelik eki almıştır, bu bir isim tamlamasıdır. “Güzel kız”da “kız” ek almamıştır, bu bir sıfat tamlamasıdır. Bir de **topluluk ismini çoğul** sanırsın. Çoğul olmak için “-lar, -ler” gerekir, “sürü” tekil bir isimdir ama anlamı çoğuldur.
:::

:::baglanti
Sıfat konusu “Zamir ve Zarf” ile yakından ilgilidir: “Çok güzel kız” cümlesinde “çok”, sıfatı niteleyen bir **zarf**tır. “Fiilimsiler”deki sıfat-fiil de sıfat görevindedir. Bu konudaki isim tamlamaları, “Cümlenin Ögeleri” konusunda öznenin ve nesnenin tamlama olarak gelmesini anlamanı sağlar.
:::

## 5. Konuyu toparla

| Başlık | Kısa not |
| --- | --- |
| Cins isim | Ortak ad |
| Özel isim | Tek varlığın adı |
| Topluluk ismi | Biçimi tekil, anlamı çoğul |
| Belirtili tamlama | Tamlayan -ın, tamlanan iyelik |
| Belirtisiz tamlama | Tamlayan eksiz, tamlanan iyelik |
| Niteleme sıfatı | Nasıl? |
| Belirtme sıfatları | İşaret, sayı, belgisiz, soru |
| Adlaşmış sıfat | İsim yerine kullanılan, ek almış sıfat |

