Roma’nın çöküşünden Rönesans’a kadar geçen bin yıldan fazla süre boyunca felsefe, tek tanrılı dinlerin gölgesinde gelişti. Bu dönemde en çok tartışılan konu **akıl ile inanç (iman)** ilişkisiydi. Hem Hristiyan Batı’da hem İslam dünyasında Yunan felsefesi yeniden yorumlandı. Bu konuda **Hristiyan felsefesini** (Patristik ve Skolastik), **İslam felsefesini** (Kindi, Farabi, İbn Sina, Gazali, İbn Rüşd), bu dönemin **temel sorunlarını** ve **tümeller tartışmasını** öğreneceksin.

:::hedefler
1. MS 2. yüzyıldan 15. yüzyıla kadar felsefenin genel özelliklerini ve dönemlerini sıralamak.
2. Patristik ve Skolastik felsefenin önemli düşünürlerini ve görüşlerini eşleştirmek.
3. İslam felsefesinin doğuşunu ve önemli filozoflarını açıklamak.
4. Akıl-iman ilişkisi hakkındaki farklı yaklaşımları karşılaştırmak.
5. Tümeller tartışmasındaki görüşleri (realizm, nominalizm) ayırt etmek.
:::

## 1. Genel özellikler

Bu dönemde felsefe:

- **Din merkezlidir.** “Felsefe teolojinin hizmetçisidir (ancilla theologiae)” anlayışı Batı’da yaygındır.
- **Akıl-iman ilişkisi** temel sorundur. İnanç ile akıl nasıl bağdaşır? Hangisi önce gelir?
- **Tek tanrılı din** (Hristiyanlık, İslam, Yahudilik) esasına dayanır. Evren ve insan **Tanrı’nın yaratması** olarak ele alınır.
- **Yunan felsefesi, özellikle Platon ve Aristoteles, yeniden yorumlanır.**
- **Tanrı’nın varlığına dair deliller** geliştirilir.

**Dönemler:**

- **Hristiyan Felsefesi:** Patristik (MS 2. yüzyıldan 8. yüzyıla) ve **Skolastik** (9. yüzyıldan 15. yüzyıla).
- **İslam Felsefesi:** 8. yüzyıldan 12. yüzyıla, en parlak dönemi 9 ile 12. yüzyıl.
- **Yeni Platonculuk** (3. yüzyıl, Plotinos) ve **Yahudi felsefesi** (Maimonides).

## 2. Hristiyan felsefesi

### Patristik felsefe (Kilise babaları)

**Kilise babaları**, Hristiyan inancını felsefeyle savunan ve temellendiren düşünürlerdir. Felsefe, Hristiyanlığı akılla savunmak için kullanılır. En önemli temsilcisi **Augustinus**’tur.

**Augustinus (354 ile 430):**

- **Platon ve Yeni Platonculuktan** etkilenmiştir.
- **İman akıldan önce gelir:** “**Anlamak için inanıyorum.**” İman, akla yol gösterir.
- **Kötülük sorunu:** **Kötülük, iyiliğin yokluğudur**, kendi başına bir varlığı yoktur. Kötülük **insanın özgür iradesinin kötüye kullanılmasıdır.**
- **Zaman:** Zaman Tanrı’nın yaratmasıdır, insanın bilincinde (geçmiş, şimdi, gelecek) vardır.
- **Eserleri:** İtiraflar, Tanrı Devleti.

**Yeni Platonculuk (Plotinos, MS 3. yüzyıl):** Her şey “**Bir**”den (Tek) taşar (**sudur**). Ruh Bir’e dönmek ister. Hristiyan ve İslam düşüncesini etkilemiştir.

### Skolastik felsefe

**Skolastik**, “okul felsefesi” demektir. **Kilise ve manastır okullarında** yetişen düşünürler. Platon ve Aristoteles’in felsefesi, Hristiyan öğretisiyle uyumlu hale getirilmeye çalışılır. 12 ve 13. yüzyılda **İslam felsefesinden** (özellikle İbn Rüşd ve İbn Sina’nın çevirilerinden) etkilenmiştir.

- **Anselmus (11. yüzyıl):** “Anlamak için inanıyorum.” **Ontolojik delil:** Tanrı, “kendisinden daha büyüğü düşünülemeyen varlık”tır, bu yüzden gerçekte vardır.
- **Abelardus (12. yüzyıl):** **Tümeller tartışmasında** ılımlı bir görüş (kavramcılık). Aklın inanç konusunda kullanılmasını savundu.
- **Thomas Aquinas (13. yüzyıl, 1225 ile 1274):** Skolastiğin en büyük düşünürü. **Akıl ile iman uyumludur**, **çelişmez.** Aristoteles felsefesini Hristiyanlıkla uzlaştırır. **Tanrı’nın varlığı için beş yol (delil)**, özellikle **kozmolojik** delil. **Doğa ile doğaüstü**, **akıl ile vahiy** birbirini tamamlar. Eseri: Summa Theologiae.
- **Duns Scotus** ve **William of Ockham (14. yüzyıl):** **Ockham nominalizmi savundu.** “**Gereksiz varsayımlar yapma**” (Ockham’ın usturası). Akıl ile inancı birbirinden ayırdı. Skolastiğin çözülmesine katkıda bulundu.
- **Roger Bacon (13. yüzyıl):** Deneyin önemini vurguladı, deneysel bilimin habercisidir.

### Tümeller tartışması

Soru: **Tümel kavramlar** (insan, ağaç, güzellik) gerçekten var mıdır, yoksa yalnızca zihnimizde ya da isim olarak mı?

- **Realizm (gerçekçilik):** Tümeller **gerçekten vardır**, tek tek nesnelerden önce ya da onlardan bağımsızdır (Platon çizgisi, Anselmus, Aquinas’ın ılımlı biçimi).
- **Nominalizm (adcılık):** Gerçekte **yalnızca tek tek nesneler vardır**, tümeller yalnızca **isimlerdir (ses)**. (Roscelin, Ockham).
- **Kavramcılık (konseptüalizm):** Tümeller **zihinde kavram olarak** vardır. (Abelardus).

## 3. İslam felsefesi

**Doğuşu:** Abbasiler döneminde (8 ile 9. yüzyıl) **Beytü’l-Hikme**’de Yunanca, Süryanice, Farsça ve Sanskritçe eserler Arapçaya çevrildi. **Aristoteles, Platon ve Yeni Platonculuk** etkili oldu. Kur’an ve hadislerin akılla anlaşılması isteği, felsefe ile dinin ilişkisini **bir sorun haline getirdi.**

**Temsilciler:**

- **Kindi (801 ile 873):** **İlk İslam filozofu**, “Arap filozofu” olarak anılır. Felsefe ile dinin **uyumlu** olduğunu savundu. Yunan felsefesini Arapçaya kazandırdı. Matematik, astronomi, tıp, müzik.
- **Farabi (870 ile 950):** “**Muallim-i Sani (İkinci Öğretmen)**” (Birinci Öğretmen Aristoteles). Mantık ve metafizik. **Din ile felsefe uyumludur**, farklı yollarla aynı hakikate ulaşır. **Siyaset felsefesi:** “**Erdemli Şehir (el-Medinetü’l-Fazıla)**” Mutluluğu hedefleyen, aklı güçlü yöneticinin başında olduğu şehir. Müzikte de önemlidir.
- **İbn Sina (980 ile 1037):** **Felsefe, tıp** ve matematik. **“Şifa”** (felsefe ansiklopedisi), **“el-Kanun fi’t-Tıb”** (tıp kitabı, yüzyıllarca Avrupa’da okutuldu). **“Uçan adam” deneyi:** Duyulardan yalıtılmış bir insan kendi varlığını yine de bilir, ruh bedenden ayrıdır. **Zorunlu varlık (Vacibü’l-vücud):** Varlığı kendinden olan Tanrı, mümkün varlıkların nedenidir. **Aklın ve vahyin uyumu.**
- **Gazali (1058 ile 1111):** **“Tehafütü’l-Felasife” (Filozofların Tutarsızlığı):** Filozofların (Farabi, İbn Sina) bazı görüşlerini (evrenin ezeliliği, Tanrı’nın cüzileri bilmemesi, bedenin dirilmemesi) **eleştirir.** Nedensellikte Tanrı’nın rolünü vurgular. **İhya-u Ulumi’d-Din:** Tasavvuf ve ahlak.
- **İbn Rüşd (1126 ile 1198):** **Aristoteles şârihi** (yorumcusu). **“Tehafütü’t-Tehafüt”** adlı eseriyle Gazali’ye cevap verdi. **Din ile felsefe aynı hakikate götürür**, akıl ile vahiy çelişmez. Latin Batı’da **Aristoteles’in** tanınmasını ve skolastiği etkiledi (**Averroesçilik**).
- **İbn Haldun (1332 ile 1406):** **“Mukaddime”**. **Toplum ve tarih felsefesi, asabiyet**, devletlerin doğuşu ve çöküşü. Sosyolojinin öncüsü sayılır.
- Diğer: **İhvan-ı Safa**, **İbn Bacce, İbn Tufeyl** (Endülüs, “Hayy bin Yakzan”).

**Türk-İslam düşüncesi:** **Yusuf Has Hacib**, **Ahmed Yesevi**, **Mevlana**, **Yunus Emre** (tasavvuf ve ahlak).

## 4. Yahudi felsefesi ve Rönesans’a geçiş

- **Maimonides (İbn Meymun, 12. yüzyıl):** Yahudi felsefesinin büyük temsilcisi. **Din ile aklı uzlaştırmaya** çalıştı. “Şaşkınların Kılavuzu.” İbn Rüşd’den etkilenmiştir.
- **İslam ve Hristiyan felsefesinin etkileşimi:** İspanya’da Toledo gibi merkezlerde **Arapçadan Latince**ye çeviriler yapıldı. Böylece Aristoteles ve İslam bilginlerinin eserleri Avrupa’ya ulaştı.
- 14 ve 15. yüzyılda **Rönesans** ve **hümanizm**: İnsan merkezli düşünce, antik felsefeye dönüş, bilim ve deney.

:::neden-sonuc
- Din felsefenin merkezine geçiyor => Akıl-iman ilişkisi temel sorun olur.
- Beytü’l-Hikme’de çeviriler yapılıyor => İslam dünyasında felsefe gelişir.
- Gazali filozofları eleştiriyor => İbn Rüşd “Tehafütü’t-Tehafüt” ile cevap verir.
- İslam bilginlerinin eserleri Latinceye çevriliyor => Aristoteles Avrupa’da yeniden etkili olur.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Gazali ile İbn Rüşd’ün eserlerini karıştırma.** “Tehafütü’l-Felasife” Gazali’nin, “Tehafütü’t-Tehafüt” İbn Rüşd’ündür. Bir de **Augustinus ile Thomas Aquinas’ı karıştırma**: Augustinus Platoncu ve Patristik, Aquinas Aristotelesçi ve Skolastiktir. **Kindi’yi ilk, Farabi’yi İkinci Öğretmen** olarak hatırla: Kindi “ilk İslam filozofu”, Farabi “Muallim-i Sani”dir.
:::

:::baglanti
Bu konu, “İlk Çağ Felsefesi” konusundaki Platon ve Aristoteles’in sonraki yüzyıllardaki etkisini gösterir. “Din Felsefesi” konusundaki Tanrı’nın varlığı delilleri (ontolojik, kozmolojik) ve akıl-iman ilişkisi bu dönemde geliştirilmiştir. “Bilgi Felsefesi” ve “Varlık Felsefesi” konularındaki nominalizm-realizm ve rasyonalizm tartışmasının kökleri buradadır. Tarihte “İslam Medeniyetinin Doğuşu”, “İlk Türk İslam Devletleri” ve “Orta Çağ’da Dünya” konularındaki Beytü’l-Hikme, bilim ve düşünce hayatı bu konuyla bütünleşir. Din kültüründe “İslam Düşüncesinde Yorumlar” da ilişkilidir.
:::

