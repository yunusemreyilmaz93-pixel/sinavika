## 1. Din felsefesi nedir

**Din felsefesi**, dini **felsefi yöntemle**, yani **akıl yürütme, eleştiri ve kavram analiziyle** inceleyen felsefe alanıdır. **Dini savunmak ya da çürütmek amacı taşımaz**, dinle ilgili temel soruları tartışır.

**Din felsefesinin soruları:**

- Din nedir? İnsan neden dine ihtiyaç duyar?
- **Tanrı var mıdır?** Varlığı nasıl gösterilebilir?
- **Tanrı’nın özellikleri** (sonsuzluk, kudret, bilgi, iyilik) nelerdir?
- **Kötülük sorunu:** Tanrı varsa kötülük neden vardır?
- **Mucize ve vahiy** mümkün müdür?
- **Ruh, ölümden sonra yaşam** ve ahiret.
- **Din ile akıl**, **din ile bilim**, **din ile ahlak** ilişkisi nasıldır?
- **Dinî dil** (kutsal metinlerin dili) nasıl anlaşılır?

**Din felsefesi ile din bilimleri (teoloji, kelam) farkı:** Kelam ve teoloji **belli bir dinin inanç esaslarını** temel alarak o dini açıklar ve savunur. Din felsefesi ise **herhangi bir dinin inanç esasına bağlı olmadan** tarafsız bir bakışla inceler.

## 2. Tanrı’nın varlığına ilişkin deliller

**Ontolojik (varlıkbilimsel) delil:** **Anselmus**: Tanrı, “kendisinden daha büyüğü düşünülemeyen varlık”tır. Eğer yalnızca düşüncede olsaydı, hem düşüncede hem gerçekte var olan bir varlık ondan daha büyük olurdu. Bu yüzden Tanrı gerçekte de vardır. **Descartes** benzer bir delil kullanmıştır. **Tanrı kavramından** varlığına geçilir.

**Kozmolojik (evrenbilimsel) delil:** Evrendeki her şeyin bir nedeni vardır. Nedenler zinciri **sonsuza kadar gidemez**, bu zincirin bir **ilk nedeni** olmalıdır. Bu ilk neden **Tanrı**dır. **Aristoteles** (“ilk hareket ettirici”), **Thomas Aquinas**, **Farabi, İbn Sina, Gazali**’nin delillerine temel olmuştur.

**Teleolojik (gaye, amaç, düzen) delil:** Evrendeki **düzen, uyum ve amaçlılık** bir **akıllı yaratıcıya** işaret eder. Bir saatin varlığı nasıl saatçiyi gerektiriyorsa evrenin düzeni de bir tasarımcıyı gerektirir. **William Paley** gibi düşünürler.

**Ahlaki delil:** **Kant:** Ahlak yasası ve ödev bilinci, adaletin sonunda gerçekleşmesi için **Tanrı’nın varlığını** gerektirir. Kant’a göre Tanrı’nın varlığı **kuramsal akılla kanıtlanamaz** ama **pratik akıl (ahlak)** için bir **postulattır**.

**Dinî deneyim delili:** İnsanın yaşadığı manevi tecrübeler, vicdan ve sezgi.

Bu delillerin her biri **eleştiri** de almıştır. Delillerin **kesin ispat** değil, **akıl yürütme yoluyla gerekçelendirme** olduğu söylenebilir.

## 3. Tanrı ve evren ilişkisi

| Görüş | Anlamı | Temsilci |
| --- | --- | --- |
| **Teizm** | Tanrı vardır, evreni yaratmıştır ve **evrene müdahil** olmaya devam eder (mucize, vahiy, dua). Tanrı evrenden ayrıdır | İbrahimî dinler (Müslümanlık, Hristiyanlık, Yahudilik) |
| **Deizm** | Tanrı evreni **yaratmış** ama sonra **kendi yasalarına bırakmıştır**, müdahale etmez. Vahiy ve mucizeye gerek görmez | Voltaire, Rousseau, Newton |
| **Panteizm** | **Tanrı ile evren aynıdır.** Tanrı evrenin dışında değil, içindedir | Spinoza |
