## 1. Felsefe nedir

**Felsefe** sözcüğü Yunanca **philosophia** sözcüğünden gelir. **Philo** (sevgi) ve **sophia** (bilgelik) birleşimidir. Yani **bilgelik sevgisidir**. İlk felsefecilere **filozof** denir.

Felsefe, varlığı, bilgiyi ve değeri **akıl** yoluyla **sorgulayan**, eleştiren ve temellendirmeye çalışan bir **düşünme etkinliğidir**. Kesin ve herkesçe kabul edilen cevapları vermekten çok, **doğru soruyu sormayı** önemser.

### Felsefenin ortaya çıkışı

Felsefenin ilk ortaya çıktığı yer, **MÖ 6. yüzyılda Anadolu’nun Ege kıyısındaki İyonya** bölgesinin **Milet** kentidir. İlk filozof olarak **Thales** (Tales) kabul edilir. Bu dönem felsefenin **mitolojiden akla** geçişi olarak bilinir. Daha önce evren, tanrılar ve efsanelerle açıklanırken Thales gibi düşünürler doğayı **akıl ve gözlemle** açıklamaya çalıştı.

Felsefenin Anadolu’da doğmasında rol oynayan etkenler: Ticaret ve kültürel etkileşim, farklı uygarlıkların (Mısır, Babil) bilgilerinin kaynaşması, merak ve araştırma isteği, **özgür düşünce ortamı**.

## 2. Felsefi düşüncenin özellikleri

- **Sorgulayıcı ve eleştirel:** Hiçbir şeyi olduğu gibi kabul etmez, “neden?” diye sorar.
- **Akla dayanır.** Gerekçelendirmeye çalışır, kanıt ve tutarlılık ister.
- **Evrensel ve tümeldir.** Tek tek olaylar yerine bütünü, genel ilkeleri araştırır.
- **Sistemli (düzenli) ve tutarlıdır.**
- **Yeni sorular açar.** Bir soruya cevap verilirken başka sorular doğar.
- **Dogmatik değildir.** Her görüş tartışmaya açıktır.
- **Önyargılardan kurtulmaya çalışır.** Kişisel çıkar ve alışkanlıklarla düşünmez.
- **Kendi içinde bağımsızdır.** Bilgi arayışında başka bir otoriteye bağlı değildir.
- **Felsefe kimsenin tekelinde değildir.** Her insan felsefe yapabilir.

## 3. Felsefi sorunun özellikleri

Her soru felsefi değildir. Bir felsefi sorunun şu özellikleri vardır:

- **Evrenseldir:** Herkesi ilgilendirir, her yerde ve her zaman sorulabilir (“Özgürlük nedir?”).
- **Cevapları kesin ve herkesçe kabul edilen cevaplar değildir.** Farklı felsefeciler farklı cevaplar verir.
- **Tartışmaya açıktır.**
- **Düşündürür ve yeni sorular doğurur.**
- **Kavram analizine dayanır.** “Adalet nedir?” sorusu adalet kavramının anlamını çözümlemeyi gerektirir.
- **Gündelik bilgiyle ya da deneyle cevaplanamaz.**

**Örnek.** “Su kaç derecede kaynar?” sorusu bilimseldir, deneyle cevaplanır. “Gerçek nedir?”, “Mutluluk nedir?” sorusu felsefidir, deneyle kesin cevaplanamaz.

## 4. Felsefe ile bilim, din ve sanat

| | Felsefe | Bilim | Din | Sanat |
| --- | --- | --- | --- | --- |
| Dayanak | Akıl, sorgulama | Akıl, gözlem ve deney | İnanç ve vahiy | Duygu, hayal, yaratıcılık |
| Konu | Varlık, bilgi, değer (bütün) | Belli bir alan | Kutsal, inanç | Güzel, duygular |
| Yöntem | Sorgulama, akıl yürütme | Bilimsel yöntem | İnanç | Estetik ifade |
| Sonuç | Tartışmaya açık | Genellikle kanıtlanabilir | İnanç esaslıdır | Estetik değer |

- Felsefe, **bilimin temellerini** sorgular (bilim nedir, bilimsel yöntem nasıldır?). Bilimler felsefeden ayrılarak ortaya çıkmıştır.
- Felsefe ve din ilişkisi tarihte tartışılmıştır. **Din Felsefesi** dinle ilgili kavramları akıl yoluyla inceler.
- Sanat ve felsefe de insanı ve dünyayı anlamaya çalışır, ancak **dili** farklıdır.

