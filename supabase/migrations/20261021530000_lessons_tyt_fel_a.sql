## 1. Bilim nedir

**Bilim**, evreni ve olayları **sistemli, akla ve gözleme dayalı, test edilebilir yöntemlerle** inceleyen, **genel geçer, nesnel bilgi** üretmeye çalışan etkinliktir.

**Bilimsel bilginin özellikleri:**

- **Nesneldir.** Kişiden kişiye değişmez, kişisel yargı taşımaz.
- **Akla ve olgulara (gözlem ve deneye) dayanır.**
- **Test edilebilir (sınanabilir)** ve **tekrarlanabilir.**
- **Genellemelidir (evrenseldir).** Tek tek olaylardan genel yasalar çıkarır.
- **Sistemlidir ve tutarlıdır.**
- **Eleştiriye açıktır.** Her bilimsel bilgi yeni kanıtlarla **değişebilir, düzeltilebilir** (kesin ve mutlak değildir).
- **Birikimlidir.** Önceki bilgiler üzerine kurulur.
- **Amacı:** Olayları **açıklamak** ve **öngörmek**.
- **Evrensel ve bağımsızdır:** Kimsenin otoritesine bağlı değildir.

**Bilimsel bilgi ile günlük bilgi farkı:** Günlük bilgi kişisel tecrübelere dayanır, sistemsiz ve test edilmemiş olabilir. Bilimsel bilgi sistemli ve sınanmıştır.

## 2. Bilimlerin sınıflandırılması

- **Formal (biçimsel) bilimler:** **Mantık ve matematik.** Konusu soyut kavramlardır. Deneyden bağımsız, **tutarlılık** esaslıdır.
- **Doğa bilimleri:** **Fizik, kimya, biyoloji, astronomi.** Doğayı gözlem ve deneyle inceler.
- **Sosyal ve beşeri bilimler:** **Tarih, sosyoloji, psikoloji, ekonomi, siyaset bilimi.** İnsanı ve toplumu inceler. Deney sınırlı, gözlem ve anket önemlidir.

## 3. Bilimsel yöntem ve kavramlar

**Bilimsel yöntemin aşamaları:**

1. **Problemin belirlenmesi** (soru)
2. **Gözlem ve bilgi toplama**
3. **Hipotez kurma**
4. **Deney ve test etme**
5. **Sonuçları değerlendirme**
6. **Kuram ya da yasaya ulaşma, rapor yazma**

**Temel kavramlar:**

- **Olgu:** Gözlemlenen, doğruluğu sınanabilen gerçek durum.
- **Hipotez:** Olguyu açıklamak için ileri sürülen, **henüz sınanmamış açıklama önerisi.**
- **Yasa:** Olgular arasındaki **değişmez ve genel ilişkiyi** ifade eden önerme. (Isınan metal genleşir.)
- **Kuram (teori):** Birçok olgu ve yasayı **bir arada açıklayan** sistemli açıklamadır.
- **Deney:** Değişkenleri kontrol ederek hipotezi sınama.

**Yöntemler:**

- **Tümevarım (indüksiyon):** **Tek tek gözlemlerden** genel yargılara varma. **Francis Bacon.** Eleştiri: Sınırlı sayıda gözlemden genel yargıya ulaşmak kesin kanıt değildir (kara kuğu örneği).
- **Tümdengelim (dedüksiyon):** **Genel ilkelerden** özel sonuçlara varma. **Descartes.** Matematikte kullanılır.
- **Hipotetik-dedüktif yöntem:** Hipotez kurulur, ondan çıkarımlar yapılır ve **deneyle sınanır.**

## 4. Bilim felsefesinde yaklaşımlar

**Mantıksal pozitivizm (Viyana Çevresi):** Bir önermenin anlamlı olması için **gözlem ya da deneyle doğrulanabilir** olması gerekir. Metafizik önermeler anlamsızdır.

**Karl Popper (yanlışlanabilirlik):**

- Bir kuramın bilimsel olması, **doğrulanabilir olmasından çok, yanlışlanabilir olmasına** bağlıdır.
- **Yanlışlanabilirlik ölçütü:** Bir kuram, **gözlem ya da deneyle çürütülebilecek** biçimde ifade edilmelidir.
- Çürütülemeyen (her sonuçla uyumlu olan) kuramlar **bilimsel değildir** (sözde bilim: astroloji).
- Bilim **sınama ve çürütme (eleştirel akılcılık)** yoluyla ilerler.

**Thomas Kuhn (paradigma ve bilimsel devrim):**

- Bilim **sürekli birikimle değil, devrimlerle** ilerler.
- **Paradigma:** Bilim insanlarının belli bir dönemde ortak kabul ettiği **kuram, yöntem ve soru çerçevesi.**
- **Normal bilim:** Mevcut paradigma içinde çalışma.
- **Kriz:** Paradigmanın açıklayamadığı olaylar birikir.
- **Bilimsel devrim:** Eski paradigma yerini **yeni paradigmaya** bırakır (Kopernik, Newton, Einstein). Farklı paradigmalar **kıyaslanamazdır.**

**Paul Feyerabend (anarşist yaklaşım):** Bilimde **tek bir yöntem** yoktur. “**Her şey olabilir.**” Bilimsel gelişim farklı yöntemlere açıktır.

**Bilimsel gerçekçilik:** Bilimsel kuramlar dünyanın gerçek yapısını anlatır. **Araççılık:** Kuramlar yalnızca olayları öngörmeye yarayan araçlardır.

## 5. Bilim ve değerler

- **Bilimin nesnelliği:** Bilim insanı önyargılarından kurtulmaya çalışır. Yine de her bilim insanı bir **bakış açısına** sahiptir.
- **Bilim ve etik:** Bilimsel bulguların kullanımı **ahlaki sorumluluk** doğurur (atom enerjisi, genetik mühendisliği, yapay zekâ). **Bilimsel araştırma etiği:** Gönüllü onayı, veri doğruluğu, hayvan hakları.
- **Bilim ve toplum:** Bilimin gelişimi **toplumsal, ekonomik ve siyasi** koşullardan etkilenir.
- **Bilimin sınırları:** Bilim **olanı** açıklar, **olması gerekeni** (değerleri) belirlemez. Bilimin kesin cevap veremediği sorular (hayatın anlamı gibi) felsefe, din ve sanatın alanına girer.
- **Sözde bilim:** Bilimsel görünümlü ama bilimsel yönteme uymayan iddialar (astroloji, kehanet).

:::neden-sonuc
- Tek tek gözlemlerden genel yargıya varılıyor => Tümevarım.
- Genel ilkelerden özel sonuç çıkarılıyor => Tümdengelim.
- Kuram yanlışlanamıyor, her sonucu açıklıyor => Popper’a göre bilimsel değildir.
- Eski paradigma açıklayamadığı olaylar nedeniyle terk ediliyor => Bilimsel devrim (Kuhn).
:::

:::ipucu{baslik="Sık yapılan hata"}
**Bilimsel bilginin kesin ve değişmez olduğunu sanma.** Bilimsel bilgi eleştiriye açıktır, yeni kanıtlarla değişebilir. Bir de **hipotezle yasayı karıştırma**: Hipotez sınanmamış öneri, yasa sınanmış ve genel ilişkidir. **Popper’ı doğrulamaya dayalı sanma**: Popper için ölçüt yanlışlanabilirliktir.
