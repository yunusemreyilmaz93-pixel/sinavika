## 1. Ahlak ve etik

- **Ahlak (moral):** Bir toplumda neyin iyi, neyin kötü olduğunu belirleyen, davranışları yönlendiren **kurallar, değerler ve alışkanlıklardır.** Toplumdan topluma değişebilir.
- **Etik (ahlak felsefesi):** Ahlakı **felsefi olarak inceleyen** disiplindir. “İyi nedir?”, “Ödev nedir?”, “İnsan özgür müdür?” gibi sorulara cevap arar.
- **Hukuk:** Devletin koyduğu ve **yaptırımı yasalarla** (ceza, para) uygulanan kurallardır. Ahlak kurallarının yaptırımı ise **vicdan ve toplumun tepkisidir.**

| | Ahlak | Hukuk |
| --- | --- | --- |
| Kaynak | Vicdan, gelenek, değerler | Devlet, yasa |
| Yaptırım | Vicdan azabı, toplum dışlaması | Ceza ve yasal yaptırım |
| Alan | İç dünya ve davranış | Dışa vuran davranış |
| Zorlama | Gönüllüdür | Zorlayıcıdır |

## 2. Ahlaki eylemin özellikleri

Bir davranışın **ahlaki eylem** sayılabilmesi için:

- **Bilinçli** olmalıdır (ne yaptığını bilerek).
- **Özgür iradeyle** yapılmalıdır (zorla değil, seçerek).
- **Sorumluluk** yüklemelidir (sonuçlarını üstlenmek).
- Bir **değer yargısı** içermelidir (iyi ya da kötü, doğru ya da yanlış olarak değerlendirilebilmelidir).

**Örnek.** Zorla bir şey yaptırılan kişiye ya da refleks hareketlere ahlaki sorumluluk yüklenmez. Çocuk ve akıl hastası bilinçli ve özgür karar veremediği için sınırlı sorumludur.

**Ahlaki yargılar** “iyi”, “kötü”, “doğru”, “yanlış” gibi değer bildirir ve **olması gerekeni** belirtir (normatif). Bilimsel yargılar ise **olanı** anlatır (betimleyici).

**Vicdan:** Kişinin eylemlerini iyi ya da kötü olarak değerlendiren **iç yargı gücüdür.** Kişiye ahlaki doğruyu hatırlatır, yanlış eylem sonrası **pişmanlık** duyurur.

## 3. Ahlaki özgürlük ve sorumluluk

Ahlaki sorumluluk, **özgürlüğe** dayanır. İnsan eylemlerinde **özgür** değilse (tamamen zorunlu ve belirlenmişse) sorumluluktan söz edilemez. Bu yüzden **özgür irade** ile **determinizm** tartışması etikle iç içedir.

- **Sartre:** İnsan **özgürlüğe mahkûmdur.** Seçimlerinden tamamen sorumludur. Kendini bahane edemez.
- Sorumluluk **bireysel** (kendi eyleminden), **toplumsal** (çevreden) ve **evrensel** olabilir.

## 4. Başlıca ahlak görüşleri

### Erdem etiği (Sokrates, Platon, Aristoteles)

- **Sokrates:** “**Erdem bilgidir.**” Doğruyu bilen kişi kötülük yapmaz, kötülük bilgisizlikten gelir.
- **Platon:** Dört temel erdem: **Bilgelik, cesaret, ölçülülük (itidal), adalet.**
- **Aristoteles:** Amaç **mutluluk (eudaimonia)**tur. Mutluluk **erdemli yaşamla** elde edilir. **Erdem, iki aşırı uç arasında bir orta yoldur** (cesaret, korkaklık ile gözü karalık arasında, cömertlik, cimrilik ile savurganlık arasında). Erdem **alışkanlıkla** kazanılır.

### Ödev ahlakı (Kant)

**Immanuel Kant**’a göre ahlaki değer eylemin **sonucunda** değil, **niyetinde ve ödeve uygunluğundadır.**

- Dünyada **koşulsuz iyi olan tek şey iyi niyettir** (iyi irade).
- **Kategorik buyruk:** “**Öyle davran ki, davranışının ilkesi aynı zamanda evrensel bir yasa olabilsin.**” Bir eylem, herkesin aynı şekilde yapmasını isteyebileceğin biçimdeyse ahlakidir.
- **İnsanı hiçbir zaman yalnızca araç olarak görme**, her zaman **amaç** olarak gör.
- Ahlaki eylem **ödev bilinciyle** yapılır, çıkar, haz ya da ceza korkusuyla değil.

**Örnek.** Bir kişi, borcunu kimse görmese ve bunun için ceza almasa bile, **ödev olduğu için** öder. Kant’a göre bu ahlaki eylemdir.

### Faydacılık (Utilitarizm: Bentham, Mill)

Ahlaki değer eylemin **sonucuna** bağlıdır. **Doğru eylem, en çok sayıda insan için en çok mutluluğu (faydayı) sağlayan eylemdir.** Bentham mutluluğu nicel, Mill nitel (zihinsel hazlar daha değerli) ele alır. **Sonuç önemlidir, niyet değil.**

### Hazcılık (Hedonizm: Aristippos, Epikuros)

**İyi, hazdır.** Aristippos bedensel hazza önem verirken **Epikuros** zihinsel hazzı ve **ruh dinginliğini (ataraksia)** öne çıkarır. Aşırı haz acıya yol açıyorsa kaçınılmalıdır.

### Sofistler ve ahlaki görecelik

Sofistler ahlaki değerlerin **toplumdan topluma değiştiğini** savunur (rölativizm). Mutlak, herkes için geçerli ahlak yoktur.

### Stoacılık

**Doğaya ve akla uygun yaşamak** ahlakın temelidir. **Tutkulara değil, akla** göre davranmak erdemdir. Kaderi sakin kabul etmek (**apatheia**) önemlidir.

