## 1. Sanat felsefesi (estetik) nedir

**Estetik** sözcüğü Yunanca “**aisthesis**” (duyum, algı) sözcüğünden gelir. **Baumgarten** 18. yüzyılda felsefe terimi olarak kullanmıştır. **Sanat felsefesi**, **güzeli, sanat eserini ve sanatsal yaratıcılığı** inceler.

**Temel sorular:**

- **Sanat nedir?** Doğadan farkı nedir?
- **Güzel nedir?** Güzellik nesnede mi, bakanda mı?
- **Sanatçı kimdir?** Yaratıcılık nedir?
- **Sanat eserinin değeri** neye göre belirlenir?
- **Sanatın işlevi nedir?** Ne amaçla yapılır?
- **Sanat ve ahlak, sanat ve toplum** ilişkisi nedir?

## 2. Güzel kavramı

**Nesnel görüş:** Güzellik **nesnenin kendisindedir**, ölçülebilir niteliklerle (**simetri, uyum, oran, denge**) belirlenir. Güzellik herkes için geçerlidir. **Pythagoras**, **Platon**, **Aristoteles** bu görüşe yaklaşır (güzel, uyum ve oran).

**Öznel görüş:** Güzellik **bakanın zevkine ve duygusuna** bağlıdır. “Güzellik bakanın gözündedir.” **Hume** ve bazı çağdaş düşünürler.

**Kant:** Güzel, **çıkardan bağımsız beğeniyi** doğuran şeydir. Güzel yargısı **öznel** gözükür ama herkesin paylaşabileceği bir **evrensellik** iddiası taşır.

**Güzel ile sanat aynı değildir.** Doğada da güzellikler (gün batımı, çiçek) vardır, fakat bunlar **insanın yaratmadığı** güzelliklerdir. **Sanat insan yapımıdır.** Sanat eseri güzel olmak zorunda mıdır? Bazı sanat eserleri çirkini ya da acıyı da konu eder (Picasso’nun Guernica’sı).

## 3. Sanat nedir

**Sanat**, insanın **duygu, düşünce ve hayallerini estetik bir biçimde ifade ettiği yaratıcı etkinliktir.**

**Sanatın özellikleri:**

- **Yaratıcıdır, özgündür.** Sanatçı yeni bir şey ortaya koyar.
- **Estetik değer taşır.**
- **Duygu ve hayal gücüne dayanır** (duyguları harekete geçirir).
- **Kişiseldir ve evrenseldir.** Sanatçının kendi dünyasını yansıtır ama başka insanlara da seslenir.
- **Amaç dışı olabilir:** Çoğu sanat eseri kendi başına bir değere sahiptir.
- **Bir biçim ve anlatım aracı** (renk, ses, söz, taş) kullanır.
- **Toplumsal ve kültürel bir bağlamda** üretilir.

**Sanatçı** (sanat yaratıcısı) farklı bakış açısı ve yaratıcı güç taşır. **Dehâ** (yetenek ve ilham) önemli kabul edilir.

### Sanat, zanaat ve bilim

| | Sanat | Zanaat | Bilim |
| --- | --- | --- | --- |
| Amaç | Güzel ve ifade | Fayda, kullanışlı ürün | Bilgi, doğruluk |
| Yaratıcılık | Çok yüksek, özgün | Kalıba ve tekniğe bağlı | Yöntem |
| Ürün | Tek, özgün eser | Benzer çok ürün | Genel yasalar |
| Örnek | Resim, şiir | Çömlekçilik, marangozluk | Fizik yasası |

**Sanat ile doğa:** Doğa kendiliğinden vardır, sanat **insan eliyle** yaratılır.

## 4. Sanat kuramları

- **Taklit (mimesis) kuramı:** Sanat **doğayı ve gerçekliği taklit eder.** **Platon:** Sanat gerçeğin (idea) taklidinin taklididir, bu yüzden değeri düşüktür. **Aristoteles:** Taklit, **insanın doğal bir eğilimidir**, sanat gerçeği **olması gerektiği gibi** yansıtır. **Tragedya** insanı **arındırır (katharsis)**.
- **İfade (dışavurum) kuramı:** Sanat, sanatçının **duygusunu dışa vurmasıdır.** **Croce**, **Tolstoy**. Romantik sanatçılar.
- **Biçimcilik (formalizm):** Sanat eserinin değeri **biçiminde** (renk, çizgi, uyum, düzen) yatar. İçerik ya da konu önemsizdir.
- **“Sanat için sanat”:** Sanatın **kendi dışında bir amacı** (ahlaki, siyasi, toplumsal) yoktur. Sanat **kendi başına** değerlidir.
- **Toplumsal gerçekçilik ve toplum için sanat:** Sanat **toplumu yansıtmalı ve değiştirmelidir.**
- **Dinî ve ahlaki amaç:** Orta Çağ’da sanat dinî öğretiyi anlatma aracıydı.

## 5. Sanatın işlevleri

- **Estetik zevk verme.**
- **Duygu ve düşünceleri ifade etme.**
- **Bilgi ve farkındalık kazandırma:** Toplumun sorunlarını ve değerlerini yansıtır.
- **Arınma (katharsis):** Duyguların boşalması.
- **Toplumsal ve kültürel kimlik.** Kültürel mirası aktarır.
- **Eğitici ve ahlaki:** İnsanı iyiye yöneltmek.
- **Eğlendirme ve dinlendirme.**

## 6. Sanat eserinin değeri

Bir eserin değeri **yaratıcılığı, özgünlüğü, estetik niteliği**, ifade gücü ve **kalıcılığı** ile ilgilidir. Fakat **kimin güzel kabul edeceği** zamana, topluma ve kültüre göre değişir. Bazı eserler yaşadıkları dönemde anlaşılmamış, sonradan değer kazanmıştır.

**Sanat eleştirisi:** Eserleri **sanat ölçütleriyle** değerlendiren çalışmadır. Eleştirmen estetik bakımdan akıl yürütür.

:::neden-sonuc
- Sanat eseri insan yaratıcılığıyla ortaya çıkıyor => Doğa güzelliğinden ayrılır.
- Eserin değeri biçimine bağlanıyor => Biçimcilik.
- Sanat toplumu yansıtmalı deniyor => Toplumsal sanat anlayışı.
- Sanat yalnızca kendi için yapılıyor => “Sanat için sanat” görüşü.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Güzel ile sanatı aynı sanma.** Doğanın da güzelliği vardır ama sanat insan yapımıdır. Bir de **estetiği yalnızca “güzel” ile sınırlama**: Sanat çirkini ve acıyı da konu edebilir. **Sanat ile zanaatı karıştırma**: Zanaat kalıba bağlı ve işlevseldir, sanat özgünlük ve yaratıcılığa dayanır.
:::

:::baglanti
Bu konu, “Felsefeyi Tanıma” konusundaki değer felsefesi alanlarından estetiği ayrıntılandırır. “Ahlak Felsefesi” konusundaki sanat-ahlak ilişkisi bu konuyla kesişir. “İlk Çağ Felsefesi” konusundaki Platon ve Aristoteles, taklit kuramının kurucularıdır. Edebiyatta “Edebi Sanatlar” ve “Edebi Akımlar” sanat kuramlarıyla yakından ilişkilidir. Din kültüründe “Gençlik ve Değerler” ve tarihte “Dünya Gücü Osmanlı” konusundaki mimari ve sanat örnekleri bu konuya örnektir.
