## 6. Felsefenin faydaları

- **Eleştirel ve bağımsız düşünmeyi** geliştirir.
- **Önyargıyı** azaltır, farklı görüşleri anlamayı kolaylaştırır.
- Doğru **soru sorma** becerisi kazandırır.
- **Kavramları** doğru ve açık kullanmayı öğretir.
- Hayata ve topluma daha **bilinçli** bakmayı sağlar.
- Bilimin, sanatın, hukukun ve siyasetin temellerini anlamaya yardım eder.

:::neden-sonuc
- Olaylar akılla sorgulanıyor => Felsefi düşünce ortaya çıkar.
- İlk filozof Milet’te çıkıyor => Felsefe Anadolu’da, mitolojiden akla geçişle doğmuştur.
- Soru deneyle cevaplanamıyor ve tartışmaya açık => Felsefi sorudur.
- Her cevap yeni soru doğuruyor => Felsefe bitmeyen bir sorgulama etkinliğidir.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Felsefe cevap vermez, tartışma sanma.** Felsefe de cevap verir ama bunlar **akla dayalı, gerekçeli ve tartışmaya açık** cevaplardır. Bir de **felsefi sorunun kesin cevabı yoktur** diyerek felsefenin boş olduğunu düşünme: Felsefi cevaplar **gerekçelendirilir**. **Felsefi soru ile bilimsel soruyu ayır**: Deneyle sınanabiliyorsa bilimseldir.
:::

:::baglanti
Bu konu, felsefenin diğer bütün konularına girişidir. “Bilgi Felsefesi”, “Varlık Felsefesi” ve “Ahlak Felsefesi” gibi alanlar buradaki soruları ayrıntılandırır. “İlk Çağ Felsefesi” konusunda Thales ve Milet okulunu bu çerçevede inceleyeceksin. “Bilim Felsefesi” konusunda bilimin felsefeyle ilişkisi derinleşir. Din kültüründe “Bilgi ve İnanç” konusu da bilgi, akıl ve inanç ilişkisini ele alır.
