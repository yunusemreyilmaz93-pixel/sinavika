## 1. Siyaset felsefesi nedir

**Siyaset felsefesi**, **devleti, iktidarı, otoriteyi, adaleti, özgürlüğü ve hakları** felsefi biçimde inceler. Siyasetin **nasıl olduğundan** çok **nasıl olması gerektiğiyle** ilgilenir.

**Temel sorular:**

- **Devlet neden vardır?** Devletin kaynağı ve amacı nedir?
- **İktidarın kaynağı** nedir, **meşru yönetim** nasıl olur?
- **Bireyin devlet karşısındaki özgürlüğü** nerede biter?
- **Adalet nedir?** Adil bir toplum nasıl kurulur?
- **En iyi yönetim biçimi** hangisidir?
- İnsan **neden yasalara uymalıdır?** Haksız yasalara karşı gelinebilir mi?

## 2. Temel kavramlar

- **Siyaset:** Toplumsal yaşamı düzenleme, kamusal kararları verme ve yönetme faaliyeti.
- **Devlet:** Belli bir ülkede, belli bir halk üzerinde **egemenlik** kullanan siyasi örgüt.
- **İktidar (güç):** Başkalarını kendi iradesine uydurma, davranışlarını yönlendirme gücü. **Zor kullanma** yetkisini de içerir.
- **Otorite:** **Meşru kabul edilen** güç. İtaat, korkudan değil, otoriteye **saygı ve onaydan** doğar.
- **Meşruiyet:** Yönetimin **halk tarafından haklı ve kabul edilebilir** görülmesi. Hukuka uygunluk ve rıza ile ilgilidir.
- **Egemenlik:** Devletin en yüksek, bağımsız karar verme yetkisi. **Halk egemenliği:** Egemenliğin halka ait olması.
- **Hak:** İnsanın doğuştan ya da yasalarla sahip olduğu yetkiler (yaşam hakkı, mülkiyet, özgürlük).
- **Adalet:** Herkese hak ettiğini vermek, eşit durumlarda eşit davranmak.

## 3. Devletin kaynağı

**Doğal görüş (Aristoteles):** İnsan **doğası gereği siyasal bir varlıktır** (“zoon politikon”). Devlet **doğal bir kurumdur**. İnsan ancak toplum ve devlet içinde kendini gerçekleştirir, **mutlu** olur.

**Toplum sözleşmesi:** Devlet, insanların **aralarında yaptıkları bir sözleşmeyle** kurulur. Doğa durumundan toplum durumuna geçilir.

- **Hobbes (“Leviathan”):** Doğa durumunda “**insan insanın kurdudur**”, herkes herkesle savaş halindedir. Güvenlik için insanlar tüm haklarını **mutlak yetkili bir egemene** devreder. **Mutlak otorite** gerekir.
- **Locke:** Doğa durumunda insanlar **yaşam, özgürlük, mülkiyet** gibi **doğal haklara** sahiptir. Devlet bu hakları korumak için kurulur. **Sınırlı devlet.** Devlet hakları çiğnerse halk **direnme hakkına** sahiptir. **Liberalizmin** temelidir.
- **Rousseau (“Toplum Sözleşmesi”):** İnsan doğuştan iyi ve özgürdür, toplum onu bozar. Meşru devlet **genel irade**ye dayanır. **Halk egemenliği.** “İnsan özgür doğar, ama her yerde zincirler içindedir.”

**Kuvvetler ayrılığı (Montesquieu):** Gücün kötüye kullanılmaması için **yasama, yürütme ve yargı** birbirinden ayrı ve bağımsız olmalıdır. Modern demokrasilerin temelidir.

## 4. Siyasi düşünürler

- **Platon (“Devlet”):** İdeal devlet, **filozofların yönettiği** devlettir. Toplum üç sınıftan oluşur: Yöneticiler (filozof-krallar, bilgelik), askerler (cesaret), üreticiler (ölçülülük). **Adalet**, herkesin kendi görevini yapmasıdır.
- **Aristoteles:** Yönetimleri **iyi** (monarşi, aristokrasi, politeia) ve **bozulmuş** (tiranlık, oligarşi, demokrasi) olarak ayırır. **Orta sınıfın** güçlü olduğu yönetim dengelidir.
- **Farabi (“Erdemli Şehir”):** **Erdemli şehir**, aklı ve ahlakı güçlü bir yöneticinin başında olduğu, halkın mutluluğunu amaçlayan şehirdir.
- **İbn Haldun:** Devletin ortaya çıkışında **asabiyet** (grup dayanışması) rolü büyüktür. Devletler doğar, gelişir ve çöker.
- **Makyavelli (“Prens”):** Siyasette **amaç** (devletin korunması ve gücü) **araçları** haklı kılabilir. Siyaset ahlaktan ayrı değerlendirilir, **gerçekçi** bir yaklaşım.
- **Hobbes, Locke, Rousseau, Montesquieu:** Yukarıda.
- **John Stuart Mill (“Özgürlük Üzerine”):** Devletin ve toplumun bireyin özgürlüğüne **başkasına zarar vermediği sürece** karışmaması gerekir.

## 5. Adalet, özgürlük ve eşitlik

**Adalet türleri (Aristoteles):**

- **Dağıtıcı adalet:** Toplumsal kaynak ve onurların kişilerin **liyakatine ve katkısına** göre dağıtılması.
- **Düzeltici (giderici) adalet:** Haksızlığın giderilmesi, zararın karşılanması.

**Özgürlük:**

- **Negatif özgürlük:** Dışarıdan **engelin ve baskının olmaması**.
- **Pozitif özgürlük:** Kişinin **kendi iradesiyle karar verip hayatını şekillendirebilmesi**.

**Eşitlik:** Kanun önünde eşitlik, **fırsat eşitliği** ve sonuçta eşitlik arasında ayrım yapılır.

**Sivil itaatsizlik:** Haksız ya da adaletsiz bulunan bir yasaya **şiddetsiz ve açık biçimde** karşı gelmek (**Thoreau**).

## 6. Yönetim biçimleri ve ideolojiler

**Yönetim biçimleri:** Monarşi (tek kişi), aristokrasi (seçkinler), **demokrasi** (halk yönetimi), cumhuriyet, otoriter ve totaliter rejimler.

| İdeoloji | Temel fikir |
| --- | --- |
| **Liberalizm** | Birey özgürlüğü, mülkiyet, sınırlı devlet, piyasa serbestisi (Locke, Mill) |
| **Sosyalizm** | Eşitlik, toplumsal adalet, üretim araçlarında ortak mülkiyet (Marx) |
| **Muhafazakârlık** | Gelenek, kurumlar, aile ve toplumsal düzenin korunması |
| **Anarşizm** | Devletin gereksiz olduğu, ortadan kaldırılması gerektiği |
| **Milliyetçilik** | Ulusun ortak kimlik, kültür ve çıkarlarını esas alma |

**Demokrasi:** Halkın yönetimde söz sahibi olması. **Temsili demokraside** halk temsilcilerini seçer. Demokrasinin koşulları: **Hukukun üstünlüğü, kuvvetler ayrılığı, özgür seçim, temel hak ve özgürlükler, çoğulculuk.**

:::neden-sonuc
- Doğa durumunda herkes herkesle savaşıyor => Hobbes’a göre mutlak yetkili bir devlet gerekir.
- Devlet doğal hakları korumak için kuruluyor => Locke’a göre sınırlı devlet ve direnme hakkı vardır.
- Yasama, yürütme ve yargı ayrılıyor => Güç dengelenir, özgürlük korunur (Montesquieu).
- Yönetim halkça onaylanıyor => Otorite meşru olur.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Hobbes ile Locke’u karıştırma.** Hobbes mutlak, Locke sınırlı devlet ister. Bir de **iktidar ile otoriteyi aynı sanma**: İktidar zora da dayanabilir, otorite meşru kabul edilen güçtür. **Montesquieu’nun yasama, yürütme ve yargıyı ayırdığını** ve bunun **kuvvetler ayrılığı** olduğunu unutma.
:::

