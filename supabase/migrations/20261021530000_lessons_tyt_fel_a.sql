| **Agnostisizm** | Tanrı’nın varlığı **bilinemez**, ne var ne yok denilemez | Huxley |

## 4. Kötülük sorunu

Bir yanda Tanrı’nın **sonsuz iyi, güçlü ve bilen** olduğu inancı, öte yanda dünyada **acı, haksızlık ve kötülüğün varlığı** vardır. “Tanrı iyi ise kötülüğü neden engellemiyor?” sorusu **kötülük problemi**dir. Bu sorunun cevabı arayışına **teodise** (Tanrı’yı savunma) denir (**Leibniz**).

**Verilen cevaplardan bazıları:**

- **İnsanın özgür iradesi:** İnsan özgür bırakıldığı için kötülük yapabilir.
- **Kötülük göreceli ve geçicidir.** Kötülük, iyiliğin yokluğudur. Büyük bir bütünün parçasıdır.
- **İmtihan:** Kötülük insanı geliştirir ya da sınar.
- **Tanrı’nın amacını bilemeyiz.**
- **Kötülük sorunu, ateistler** tarafından Tanrı’nın olmadığına dair bir delil olarak da kullanılır.

## 5. Din, akıl ve bilim

**Din ile akıl ilişkisi:**

- **Akıl ve iman uyumludur.** Akıl, dini anlamaya yardımcıdır. **Farabi, İbn Rüşd, Thomas Aquinas** bu görüştedir.
- **İman akıldan önce gelir** (fideizm): Din aklın ötesindedir, akılla doğrulanamaz. **Tertullianus** ve **Kierkegaard** bu yönde düşünür.
- **Akıl iman için tek ölçüttür** (rasyonalizm): Akla aykırı dini inançlar kabul edilmemelidir.

**Din ile bilim:** Bilim, **doğadaki olayları gözlem ve deneyle**, **neden ve nasıl** sorularıyla inceler. Din ise **anlam, değer, amaç, ahlak ve kutsal** üzerine kuruludur. Bu ilişki hakkında iki yaklaşım vardır:

- **Çatışma:** Din ve bilim birbirine aykırıdır.
- **Uyum ya da farklı alanlar:** Din ve bilim farklı sorulara cevap verir, çatışmak zorunda değildir.

