Felsefe Anadolu’nun Ege kıyısında, Milet’te doğduğunda ilk sorulardan biri şuydu: “Her şeyin ilk maddesi, kökeni nedir?”. Bu soru bin yılı aşkın bir süre boyunca düşünürleri meşgul etti. Bu konuda **İlk Çağ felsefesinin dönemlerini** (MÖ 6. yüzyıldan MS 2. yüzyıla), **doğa filozoflarını**, **Sofistleri**, **Sokrates, Platon ve Aristoteles**’i ile **Helenistik dönem okullarını** (Epikurosçuluk, Stoacılık, Septisizm) öğreneceksin.

