## 1. Bilgi felsefesinin soruları

Bilgi felsefesi şu sorular üzerinde durur:

- **Bilgi nedir?** Doğru ve temellendirilmiş inanç mıdır?
- **Bilgi mümkün müdür?** İnsan gerçeği bilebilir mi? (**Bilginin imkânı**)
- **Bilginin kaynağı nedir?** Akıl mı, duyu mu, sezgi mi? (**Bilginin kaynağı**)
- **Bilginin sınırı var mı?** İnsan neleri bilebilir, neleri bilemez?
- **Bilginin doğruluğunu neye göre anlarız?** (**Doğruluk ölçütü**)

**Bilgi türleri:** Günlük (sağduyu) bilgi, bilimsel bilgi, felsefi bilgi, dinî bilgi, sanatsal bilgi. Her tür bilgi farklı yöntem ve ölçüte dayanır.

## 2. Bilginin imkânı

**Dogmatizm (kuşkuculuğa karşı, kesin bilgicilik):** İnsan gerçeği **kesin olarak** bilebilir. Kuşkuya yer yoktur. Duyularımız ve aklımız doğru bilgi verir. Bu görüş, gerçeği olduğu gibi bildiğini düşünür.

**Septisizm (kuşkuculuk):** **Kesin ve evrensel bilgi imkânsızdır.** Her bilgi kuşkuludur, bu yüzden **yargıdan kaçınılmalıdır.** Temsilcileri **Pyrrhon** (Pironcular) ve **Gorgias**’tır. Duyularımız yanıltıcıdır.

**Rölativizm (görecelik):** Bilgi **kişiye, topluma, zamana göre değişir.** Mutlak ve herkes için geçerli doğru yoktur. **Protagoras:** “İnsan her şeyin ölçüsüdür.” Sofistler bu görüştedir.

**Kritisizm (eleştiricilik):** Bilgi **mümkündür ama sınırlıdır.** Aklın bilgisini önce **eleştirmek** gerekir. **Kant**’ın görüşüdür. Kant’a göre bilgi hem **deneyden** (duyu verileri) hem **akıldan** (kavramlar) gelir. İnsan **şeylerin kendisini (numen)** değil, **görünüşlerini (fenomen)** bilebilir.

**Fenomenalizm:** Yalnızca görünüşler bilinebilir, şeylerin gerçek yapısı bilinemez.

## 3. Bilginin kaynağı

**Rasyonalizm (akılcılık):** Bilginin tek ya da asıl kaynağı **akıldır.** Duyular yanıltabilir, kesin bilgiyi akıl verir. **Doğuştan fikirler** vardır.

- **Descartes:** Her şeyden kuşku duyar ama kuşku duyduğundan kuşku duyulamaz. **“Düşünüyorum, öyleyse varım” (Cogito)**. Doğru bilgi akılla, **açık ve seçik** düşüncelerle bulunur.
- **Spinoza, Leibniz** de akılcıdır.

**Empirizm (deneycilik):** Bilginin kaynağı **deneyim ve duyulardır.** Doğuştan fikir yoktur. İnsan zihni doğuşta **“boş bir levhadır” (tabula rasa)**.

- **Locke, Hume, Berkeley** (İngiliz deneycileri), **Francis Bacon.**
- **Locke:** Bütün bilgi duyum ve düşünme (iç deneyim) yoluyla gelir. **Hume:** Neden-sonuç ilişkisi alışkanlıktır.

**Kritisizm (Kant):** Rasyonalizm ile empirizmi uzlaştırır. “**Kavramsız algı kördür, algısız kavram boştur.**” Bilgi **deney** (içeriği) ve **akıl** (biçimi) birlikteliğiyle oluşur.

**Sezgicilik (entüisyonizm):** Gerçek bilgi **sezgi** ile edinilir. **Bergson**. Mantıksal akıl bilgiyi parçalar, sezgi bütünü kavrar.

**Pozitivizm (olguculuk):** Yalnızca **gözlem ve deneyle doğrulanabilen** bilgi geçerlidir. **Comte.** Metafizik bilgiyi reddeder.

**İdealizm ve Realizm:** Bilginin nesnesi üzerine görüşlerdir (düşünce mi, nesne mi önce?).

## 4. Doğruluk ölçütleri

Bir bilginin **doğru** olup olmadığına neye göre karar vereceğimizi ele alan görüşlerdir:

| Ölçüt | Görüş | Örnek |
| --- | --- | --- |
| **Tutarlılık (Mantıksal tutarlılık)** | Bilgi, **bildiğimiz diğer bilgilerle çelişmiyorsa** doğrudur | Matematiksel bir ispat, bilimsel kuram sistemi |
| **Uygunluk (Yazışma, Karşılık)** | Bilgi **gerçekliğe (olgulara) uygunsa** doğrudur | “Yağmur yağıyor” önermesi gerçekten yağmur yağıyorsa doğrudur |
| **Faydacılık (Pragmatizm)** | Bilgi **işe yarıyorsa, sonuç veriyorsa** doğrudur. **William James, Dewey** | Bir ilacın hastayı iyileştirmesi |
| **Apaçıklık (Açıklık ve seçiklik)** | Zihne **açık ve seçik** görünen bilgi doğrudur. **Descartes** | “İki ile iki dörttür” |
| **Uzlaşım (Konsensüs)** | **Toplumun ya da bilim çevresinin uzlaştığı** bilgi doğrudur | Bilimsel topluluğun kabulü |

Hiçbir ölçüt tek başına her bilgi için yeterli olmayabilir. Matematikte **tutarlılık**, doğa bilimlerinde **uygunluk**, günlük yaşamda **fayda** daha çok kullanılır.

## 5. Bilgi ve yanılgı

- **Doğru bilgi** gerçeğe uygun ve temellendirilmiş bilgidir.
- **Yanılgı:** Doğru sanılan ama yanlış olan bilgidir. Duyuların yanıltması, acele karar, önyargı yanılgı kaynağıdır.
- **Kuşku:** Doğruya ulaşmak için yöntemli bir araç olarak kullanılabilir (Descartes’ın metodik kuşkusu).
- Bilgi ile **inanç** farklıdır: İnanç kanıtsız olabilir, bilgi **gerekçelendirilmiş** olmalıdır.

:::neden-sonuc
- Bilginin tek kaynağı deneyim sayılıyor => Empirizm (deneycilik).
- Bilginin kaynağı akıl sayılıyor => Rasyonalizm (akılcılık).
- Hiçbir bilginin kesin olmadığı savunuluyor => Septisizm (kuşkuculuk).
- Bilginin kişiye ve topluma göre değiştiği savunuluyor => Rölativizm (görecelik).
:::

:::ipucu{baslik="Sık yapılan hata"}
**Septisizmi rölativizmle karıştırma.** Septisizm hiçbir bilginin kesin olmadığını, rölativizm bilginin göreceli olduğunu söyler. Bir de **kritisizmi (Kant) empirizmle karıştırma**: Kant’a göre bilgi hem deneyden hem akıldan gelir. **Doğruluk ölçütünü bilginin kaynağı ile karıştırma**: Kaynak “bilgi nereden gelir”, ölçüt “doğruluğu nasıl anlarız” sorusunun cevabıdır.
