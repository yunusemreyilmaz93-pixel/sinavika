## 1. Dönemler

- **Doğa (Sokrates Öncesi) Dönemi (MÖ 6. ve 5. yüzyıl):** Evrenin **ilk ilkesi (arkhe)** araştırıldı.
- **Sofistler ve Sokrates (MÖ 5. yüzyıl):** İlgi **insana, bilgiye ve ahlaka** yöneldi.
- **Klasik Dönem (MÖ 4. yüzyıl):** Platon ve Aristoteles.
- **Helenistik ve Roma Dönemi (MÖ 4. yüzyıl sonundan MS 2. yüzyıla):** Epikuros, Stoa, Septisizm. Felsefe **bireyin mutluluğu ve huzuru** üzerinde yoğunlaştı.

## 2. Doğa filozofları

**Milet Okulu (İyonya)**

- **Thales (Tales):** İlk filozof. **Arkhe sudur.** Her şey sudan oluşur ve suya döner. Evreni mitlerle değil, tek bir doğal maddeyle açıklaması önemlidir.
- **Anaksimandros:** Arkhe **apeiron** (sınırsız, belirsiz, nitelikçe sınırlandırılmamış). Evren bu sonsuz ve belirsiz maddeden doğar.
- **Anaksimenes:** Arkhe **havadır.** Yoğunlaşıp seyrelmekle her şey ortaya çıkar.

**Diğerleri**

- **Pythagoras:** **Sayıların** evrenin özü olduğunu söyledi. Evren sayısal ilişkilerle uyum içindedir. Müziğe ve matematiğe katkı.
- **Herakleitos (Efes):** Arkhe **ateş**, evrenin özü **sürekli değişim.** “**Aynı ırmakta iki kez yıkanılmaz.**” Evrene hükmeden yasa **logos**’tur. Karşıtların birliği.
- **Parmenides (Elea):** **Varlık tektir, değişmez ve sonsuzdur.** Değişim ve çokluk duyuların yanılgısıdır. “Varlık vardır, yokluk yoktur.” Gerçeği **akıl** bulur. **Zenon** (Elea) hocasını savunmak için paradokslar öne sürdü.
- **Empedokles:** **Dört element** (toprak, su, hava, ateş) ve iki güç (**sevgi ve nefret**). Çoğulcu.
- **Anaksagoras:** Evreni düzenleyen **nous (akıl)**. Her şeyde her şeyden bir parça vardır.
- **Demokritos:** **Atomculuk.** Evren **boşluk içinde hareket eden bölünemez atomlardan** oluşur. Materyalist. Ruh da atomlardan oluşur.

## 3. Sofistler

**Sofistler** MÖ 5. yüzyılda ücretle **hitabet (retorik) ve bilgi** öğreten gezgin öğretmenlerdi. Dikkat doğadan **insana** çevrildi.

- **Protagoras:** “**İnsan her şeyin ölçüsüdür.**” **Bilgi ve ahlak göreceldir**, kişiye ve topluma göre değişir (**rölativizm**). Mutlak doğru yoktur.
- **Gorgias:** “Hiçbir şey yoktur. Olsa bile bilinemez. Bilinse bile başkasına aktarılamaz.” (septik görüş)
- **Eleştiri:** Sofistler doğruyu araştırmaktan çok **ikna etmeye** önem verdiği için eleştirilmiştir. Sokrates ve Platon karşı çıkmıştır.

## 4. Sokrates (MÖ 470 ile 399)

- **Yazı yazmamıştır.** Görüşlerini öğrencisi Platon’dan öğreniyoruz.
- Dikkati **insanın ahlaki ve bilgi sorunlarına** çevirmiştir. “**Kendini bil.**” (Delphi tapınağındaki söz)
- **Bilgi ve erdem:** “**Erdem bilgidir.**” Doğruyu bilen kötülük yapmaz.
- **Yöntemi:** **Diyalog (karşılıklı konuşma).** Önce **ironi** (karşıdakinin bilgisizliğini sorularla ortaya çıkarma), sonra **ebelik (doğurtma, maiyetik)** yoluyla doğru bilgiyi **kişinin kendisinin** bulmasını sağlar. “**Bildiğim tek şey hiçbir şey bilmediğimdir.**”
- **Evrensel kavramlar:** Adalet, cesaret gibi kavramların **tanımını** arar, evrensel bilgiyi savunur. Sofistlerin göreceliğine karşıdır.
- **Ölümü:** Gençleri yoldan çıkarmak ve tanrıları inkâr suçlamasıyla yargılandı, baldıran zehri içerek öldü (MÖ 399).

## 5. Platon (MÖ 427 ile 347)

Sokrates’in öğrencisi, **Akademia**’nın kurucusudur.

- **İdealar kuramı:** Gerçek varlık **idealar âlemindedir** (değişmez, sonsuz, evrensel formlar). Duyularla gördüğümüz **duyular âlemi** idealarının **gölgesi ya da kopyasıdır.** İkici anlayış. En yüksek ide **İyi ideasıdır.**
- **Mağara alegorisi:** Zincirli insanlar mağarada duvardaki gölgeleri gerçek sanır. Filozof mağaradan çıkıp gerçek ışığı (idealar) görür.
- **Bilgi:** Gerçek bilgi **idealar hakkındaki akıl bilgisidir** (episteme). Duyu bilgisi (doksa) yanıltıcıdır. **Anımsama:** Ruh idealar âlemini daha önce görmüştür, öğrenme **hatırlamadır.**
- **Ahlak ve devlet:** **Dört erdem:** Bilgelik, cesaret, ölçülülük, adalet. İdeal devlette toplum üç sınıftır (yöneticiler-filozof krallar, askerler, üreticiler). **Filozoflar yönetmelidir.**
- **Sanat:** Taklidin taklidi olarak değerini düşük görür.
- **Önemli eserleri:** Devlet, Phaidon, Sofist, Şölen.

## 6. Aristoteles (MÖ 384 ile 322)

Platon’un öğrencisi, **Lykeion**’un kurucusudur. Büyük İskender’in hocasıdır.

- **Platon’u eleştirir:** İdealar duyular âleminden **ayrı değildir**, nesnelerin **içindedir**. Gerçek varlık **tek tek nesnelerdir** (töz = madde + biçim).
- **Madde ve form:** Her varlık **madde** (neyden) ve **biçim (form)**’den (ne olduğu) oluşur.
- **Dört neden:** Maddi, biçim, etkin, erek (amaç). **Teleolojik** evren anlayışı.
- **İlk hareket ettirici:** Evrenin ilk nedeni, **hareket etmeyen ilk hareket ettirici** (Tanrı).
- **Mantık:** **Mantığın kurucusu.** Kıyas (tasım) teorisi. “Organon”.
- **Bilgi:** **Deney ve gözlemi** önemser. Bilgi duyulardan başlar, akıl işler.
- **Ahlak:** **Erdem etiği.** Mutluluk (eudaimonia), erdem iki aşırı uç arasında **orta yoldur.**
- **Siyaset:** İnsan **siyasal bir varlıktır** (zoon politikon).
- **Sanat:** Taklit (mimesis) doğal bir eğilimdir, tragedya katharsis sağlar.
- **Önemli eserleri:** Metafizik, Nikomakhos’a Etik, Politika, Poetika.

## 7. Helenistik ve Roma dönemi

- **Epikurosçuluk (Epikuros):** Amaç **haz** ve **ruh dinginliğidir (ataraksia).** Ölüm korkusu yersizdir. Atomculuğu benimser. Aşırı hazdan kaçınır.
- **Stoacılık (Zenon, Epiktetos, Marcus Aurelius):** **Doğaya ve akla uygun yaşa.** Tutkulardan arınmak, kaderi sükûnetle kabul etmek, **apatheia**. Dünya vatandaşlığı.
- **Septisizm (Pyrrhon):** Kesin bilgi imkânsızdır, **yargıdan kaçınılmalıdır** (epokhe). Ruh huzuru böyle bulunur.
- **Yeni Platonculuk (Plotinos):** Platon’un görüşlerinin yeniden yorumu (MS 3. yüzyıl).

:::neden-sonuc
- Evrenin ilk maddesi aranıyor => Doğa filozofları arkhe’yi (su, hava, ateş, atom) araştırır.
