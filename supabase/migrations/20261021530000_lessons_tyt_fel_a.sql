## 1. Varlık felsefesi nedir

**Varlık felsefesi (ontoloji)**, **“Var olan nedir?”**, **“Gerçeklik nedir?”**, **“Var olmak ne demektir?”** sorularına cevap arar. Varlığı **bir bütün olarak** inceler. Bilimler ise varlığın belli bir kısmını ele alır (fizik madde ve enerjiyi, biyoloji canlıyı).

**Metafizik:** Varlığın duyularla bilinemeyen, deneyin ötesindeki ilk nedenlerini ve ilkelerini araştıran bölümdür. Aristoteles’in “**Birinci Felsefe**” dediği alandır.

**Varlık felsefesinin temel soruları:**

- Var olan nedir, nasıl vardır? (**Varlığın doğası**)
- Evren **tek bir şeyden mi** yoksa **birden çok şeyden mi** oluşur? (**Varlığın sayısı**)
- Varlık **değişir mi** değişmez mi? (**Değişim**)
- Olaylar **zorunlu bir nedenle mi** olur, yoksa **rastlantısal mı**? (**Nedensellik**)
- Evrenin bir **amacı** var mı? (**Amaçlılık**)
- Varlığın **ilk nedeni** (arkhe) nedir?

## 2. Varlığın doğası

**Materyalizm (maddecilik):** Var olan her şey **maddedir.** Ruh, düşünce, bilinç de maddenin bir ürünüdür ya da ondan bağımsız değildir. **Demokritos** (atom), **Epikuros**, **Marx** bu görüştedir. Evren maddenin hareketiyle açıklanır.

**İdealizm (ülkücülük, fikircilik):** Gerçek varlık **ruh, düşünce ya da ideadır.** Madde ya düşüncenin ürünüdür ya da ikinci derecededir.

- **Platon:** Gerçek varlık **idealar âlemindedir.** Duyularla gördüğümüz âlem idealarının gölgesidir.
- **Berkeley:** “**Var olmak, algılanmaktır.**” Algılayan bir zihin olmadıkça madde yoktur.
- **Hegel:** Gerçek varlık “mutlak ruh”tur.

**Realizm (gerçekçilik):** Varlık, **insanın algısından ve düşüncesinden bağımsız olarak** vardır. Nesneler algılanmasak da vardır. **Aristoteles** realist kabul edilir. Realizm, nesnel gerçekliği kabul eder.

**Düalizm (ikicilik):** Evren **iki ayrı ve birbirine indirgenemez** töz üzerine kurulmuştur. **Descartes:** **Madde** (yer kaplayan töz) ve **ruh** (düşünen töz). Platon’un idealar ve duyular âlemi ayrımı da ikiciliktir.

**Varoluşçuluk:** **Sartre** “**varoluş özden önce gelir**” der. İnsan önce vardır, sonra seçimleriyle kendini oluşturur. İnsanın özü önceden belirlenmemiştir.

## 3. Varlığın sayısı

- **Monizm (tekçilik):** Evren **tek bir ilke** ya da özden oluşur. **Thales** (su), **Anaksimenes** (hava), **Herakleitos** (ateş). Hem materyalist hem idealist monizm vardır.
- **Düalizm (ikicilik):** İki farklı töz. Madde ve ruh. **Descartes.**
- **Plüralizm (çoğulculuk):** Evren **birden çok** temel öğeden oluşur. **Empedokles** (toprak, su, hava, ateş), **Anaksagoras**, **Leibniz** (monadlar).

## 4. Değişim ve değişmezlik

- **Herakleitos:** Her şey sürekli **akar ve değişir.** “**Aynı ırmakta iki kez yıkanılmaz.**” Gerçeklik **oluştur (becoming)**. Evrenin yasası **logos**’tur.
- **Parmenides:** Gerçek varlık **değişmez, tektir, sonsuzdur.** Değişim duyuların yanıltmasıdır. “Varlık vardır, yokluk yoktur.” Gerçek **akılla** kavranır.

Bu tartışma, “varlığın özü **değişmez** midir, **değişir** mi?” sorusuna yol açmıştır.

## 5. Nedensellik ve amaçlılık

- **Determinizm (zorunluluk, belirlenimcilik):** Bütün olaylar **önceki nedenlerle zorunlu olarak** belirlenmiştir. Aynı koşullarda aynı sonuç olur. Evren bir **neden-sonuç zinciridir**. İnsanın eylemleri bile nedenlere bağlıdır.
- **İndeterminizm (belirlenmemezlik, rastlantısallık):** Olaylar zorunlu olarak belirlenmemiştir. **Rastlantı ve özgürlük** için yer vardır.
- **Mekanizm:** Evren **bir makine gibi** işler, olaylar fizik yasalarıyla açıklanır.
- **Teleoloji (amaççılık):** Evrendeki her şey **bir amaca** yöneliktir. **Aristoteles** her şeyin bir **ereği** (hedef nedeni) olduğunu söyler.

### Aristoteles’in dört nedeni

- **Maddi neden:** Neyden yapıldığı (heykelin mermeri)
- **Biçim nedeni:** Şekli (heykelin biçimi)
- **Etkin neden:** Kim yaptı (heykeltıraş)
- **Erek (ereksel) neden:** Ne için yapıldı (heykelin amacı)

