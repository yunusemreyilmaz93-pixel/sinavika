Bir ülkenin dünya siyasetindeki ağırlığı yalnızca askerî gücüne mi bağlıdır? Boğazlar, kanallar ve enerji hatları devletlerin kaderini nasıl etkiler? **Jeopolitik**, coğrafi konumun, yer şekillerinin, kaynakların ve sınırların bir devletin **siyasetine ve gücüne etkisini** inceler. Bu konuda **mutlak ve göreceli konumu**, **jeopolitik kuramları**, **dünyanın stratejik boğaz ve kanallarını**, **Türkiye'nin jeopolitik konumunu** ve **jeopolitik konumun sonuçlarını** öğreneceksin.

:::hedefler
1. Mutlak ve göreceli konum kavramlarını ayırt etmek.
2. Mahan, Mackinder ve Spykman kuramlarını karşılaştırmak.
3. Önemli boğaz ve kanalları (Hürmüz, Malakka, Süveyş, Panama, Cebelitarık) yerleriyle eşleştirmek.
4. Türkiye'nin jeopolitik avantaj ve risklerini yorumlamak.
5. Konumun ekonomik ve siyasi sonuçlarını söylemek.
:::

:::ipucu
