## 1. Çatışmaların nedenleri

- **Siyasi:** Sınır anlaşmazlıkları, bağımsızlık talepleri, rejim değişikliği, iç savaşlar.
- **Ekonomik:** Doğal kaynakların (petrol, doğal gaz, su, maden) paylaşımı, yoksulluk, eşitsizlik.
- **Etnik ve dinî:** Farklı etnik, mezhepsel ve dinî grupların siyasi ve toplumsal rekabeti.
- **Tarihî:** Sömürge dönemi sınırları, geçmişten kalan sorunlar.
- **Uluslararası rekabet:** Büyük güçlerin etki alanı mücadelesi.

## 2. Orta Doğu

Dünyanın en gergin bölgelerinden biridir. Petrol ve doğal gaz zenginliği, stratejik konum, farklı dinî ve etnik gruplar etkili olmuştur.

- **Filistin-İsrail sorunu:** 1948'den beri süren, toprak, sınır, Kudüs'ün statüsü ve mülteci sorunları etrafında yoğunlaşan çatışma.
- **Suriye iç savaşı (2011-):** Milyonlarca kişi yerinden oldu, çok sayıda Suriyeli komşu ülkelere sığındı.
- **Irak:** 2003 müdahalesi sonrası istikrarsızlık.
- **Yemen:** İç savaş ve insani kriz.
- **Körfez bölgesi:** Enerji kaynakları ve güç dengesi.

## 3. Balkanlar ve Kafkasya

**Balkanlar:**
- **Yugoslavya'nın dağılması (1990'lar):** Etnik ve dinî temelli savaşlar. **Bosna Savaşı (1992-1995)** ve **Kosova çatışması (1998-1999).**
- NATO müdahalesi, Dayton Barış Anlaşması (1995).

**Kafkasya:**
- **Dağlık Karabağ sorunu:** Azerbaycan ile Ermenistan arasında. 1990'lardan beri süren gerginlik, 2020'de ve 2023'te yeniden yaşanan çatışmalarla yeni bir aşamaya girdi.
- **Abhazya ve Güney Osetya:** Gürcistan'ın toprak bütünlüğüyle ilgili sorun.
- **Çeçenistan:** Rusya'nın iç çatışması.

## 4. Afrika

- **Darfur (Sudan), Somali, Sahel bölgesi, Kongo.**
- **Nedenleri:** Sömürge sınırlarının etnik gerçekliği yansıtmaması, yoksulluk, zayıf devlet yapıları, doğal kaynak rekabeti.
- **Sonuçları:** Kıtlık, salgın, kitlesel göç.

## 5. Asya ve diğer bölgeler

- **Keşmir:** Hindistan ve Pakistan arasında.
- **Afganistan:** Uzun süren savaş ve iç çatışma.
- **Güney Çin Denizi:** Deniz yetki alanları ve ticaret yollarında anlaşmazlık. Çin, Vietnam, Filipinler ve diğerleri.
- **Kore Yarımadası:** Kuzey ve Güney Kore arasındaki gerilim.
- **Doğu Ukrayna:** 2014'ten sonra Kırım ve Donbas, 2022'de geniş çaplı savaşa dönüştü.
- **Kıbrıs:** 1974'ten beri bölünmüş durumda.

## 6. Çatışmaların sonuçları

- **İnsani:** Ölümler, yaralanmalar, açlık, sağlık hizmetlerinin çökmesi.
- **Göç:** Mülteciler ve yerinden edilmiş kişiler. Komşu ülkelere ve Avrupa'ya göç.
- **Ekonomik:** Altyapının yıkımı, üretimin ve ticaretin durması, yoksulluk.
- **Çevresel:** Ormanların ve tarım alanlarının yok olması, kirlilik.
- **Siyasi:** Bölgesel dengesizlik, terör, silahlanma.

## 7. Barışı koruma ve çözüm yolları

- **Diplomasi ve müzakere.**
- **BM barış gücü operasyonları.**
- **Uluslararası Adalet Divanı, arabuluculuk.**
- **İnsani yardım.**
- **Ekonomik yaptırımlar.**
- **Bölgesel iş birliği ve kalkınma.**

## 8. Sık yapılan hatalar

- Çatışmaları tek bir nedene bağlamak. Genellikle birden çok neden iç içedir.
- Yugoslavya'nın dağılmasını Soğuk Savaş öncesine yerleştirmek. 1990'larda yaşandı.
- Keşmir'i Orta Doğu çatışması sanmak. Güney Asya'dadır.
- Çatışmaların sonuçlarını yalnızca yerel sanmak. Göç ve ekonomi yoluyla bölge dışına taşar.
- BM barış gücünün her sorunu çözeceğini sanmak.

