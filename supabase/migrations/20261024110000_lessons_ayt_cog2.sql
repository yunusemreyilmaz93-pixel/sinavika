## 1. Kültür ve kültür bölgesi

**Kültür:** İnsanların toplum olarak ürettiği maddi ve manevi değerlerin tümü.

**Kültürün ögeleri:** Dil, din, gelenek ve görenekler, sanat, mimari, yemek, giyim, hukuk, değer yargıları.

**Kültür bölgesi:** Ortak dil, din, tarih ve yaşam biçimi gibi özelliklerle birbirine yakın toplumların yaşadığı geniş alan.

## 2. Doğal çevre ve kültür

- **Kurak bölgelerde** göçebe hayvancılık ve vaha tarımı.
- **Kutup bölgelerinde** Eskimoların hayvan derisi giysileri ve kar evleri.
- **Muson Asya'sında** pirinç tarımı ve çok nüfus. Çatılı, açık evler.
- **Dağlık bölgelerde** taş evler ve yaylacılık.
- **Ormanlık bölgelerde** ahşap yapılar.

Aynı zamanda kültür de çevreyi dönüştürür. Terasla tarım, baraj, kanal, yapay adalar.

## 3. Başlıca kültür bölgeleri

- **Batı (Avrupa) kültür bölgesi:** Hristiyanlık, Latin ve Cermen kökenli diller, demokrasi ve sanayi gelenekleri. Avrupa, Kuzey Amerika, Avustralya.
- **Latin Amerika kültür bölgesi:** İspanyol ve Portekiz etkisi, Katolik inancı, yerli ve Afrika kökenli kültürlerin karışımı.
- **İslam kültür bölgesi:** Kuzey Afrika, Orta Doğu, Orta Asya ve Güneydoğu Asya'nın bir kısmı. Arapça, Türkçe, Farsça ve diğer diller. Ortak din ve gelenekler.
- **Hint kültür bölgesi:** Hinduizm, Budizm, kast sistemi, Güney Asya.
- **Çin (Doğu Asya) kültür bölgesi:** Konfüçyüsçülük, Budizm, Çin yazısı etkisi. Çin, Kore, Japonya, Vietnam.
- **Slav (Rus) kültür bölgesi:** Ortodoks Hristiyanlık, Slav dilleri. Rusya, Doğu Avrupa.
- **Afrika (Sahra altı) kültür bölgesi:** Yerel diller, geleneksel inançlar, topluluk yaşamı.
- **Türk kültür bölgesi:** Anadolu'dan Orta Asya'ya uzanan, ortak dil ailesi, tarih ve gelenekleri paylaşan Türk toplulukları.

## 4. Türk dünyası

- **Ortak unsurlar:** Türkçe'nin lehçeleri, ortak tarihî geçmiş, gelenekler (Nevruz, Ergenekon), halk edebiyatı (destanlar, Dede Korkut), müzik, el sanatları.
- **Bağımsız Türk devletleri:** Türkiye, Azerbaycan, Kazakistan, Kırgızistan, Özbekistan, Türkmenistan. Kuzey Kıbrıs Türk Cumhuriyeti.
- **Türk Devletleri Teşkilatı** gibi iş birliği yapıları.
- **Dil:** Alfabe farklılığı (Latin, Kiril, Arap) iletişimi zorlaştırabilir.

## 5. Kültürel etkileşim ve küreselleşme

**Etkileşimi artıran etkenler:**
- Göç, ticaret, savaş, turizm.
- İletişim araçları (internet, televizyon).
- Eğitim, uluslararası kuruluşlar.

**Sonuçlar:**
- **Kültürel zenginleşme:** Yemek, müzik, sanat alışverişi.
- **Kültürel benzeşme:** Küreselleşme ile yerel kültürlerin yok olma riski.
- **Kültürel çatışma:** Farklı değerlerin karşılaşması.
- **Kültürel mirasın korunması:** UNESCO Somut Olmayan Kültürel Miras listesi (Mevlevi Sema Törenleri, Karagöz, Âşıklık geleneği gibi Türkiye'den öğeler).

## 6. Sık yapılan hatalar

- Kültür bölgelerinin sınırlarının kesin olduğunu sanmak.
- Kültürü yalnızca sanat ve müzik sanmak. Dil, din, mimari, beslenme de kültürdür.
- İslam kültür bölgesini yalnızca Arapça ile sınırlamak.
- Küreselleşmenin kültürleri tamamen aynılaştırdığını sanmak.
- Türk kültür bölgesinin yalnızca Türkiye'den oluştuğunu sanmak.

