## 1. Birleşmiş Milletler (BM, 1945)

- **Amaç:** Dünya barışı ve güvenliğini korumak, uluslararası iş birliğini geliştirmek, insan haklarını korumak.
- **Merkez:** New York. 193 üye.
- **Ana organlar:**
  - **Genel Kurul:** Bütün üyelerin temsil edildiği organ. Her ülkenin bir oyu vardır.
  - **Güvenlik Konseyi:** 15 üye. **5 daimi üye (ABD, Rusya, Çin, İngiltere, Fransa)** veto hakkına sahiptir. Barış ve güvenlikle ilgili bağlayıcı karar alabilir.
  - **Ekonomik ve Sosyal Konsey.**
  - **Uluslararası Adalet Divanı (Lahey).**
  - **Sekreterlik.**
- **Uzmanlık kuruluşları:** UNESCO (eğitim, bilim, kültür), UNICEF (çocuk), WHO (sağlık), FAO (tarım ve gıda), ILO (çalışma), IMF ve Dünya Bankası (ekonomi).
- **Türkiye** 1945'in kurucu üyelerindendir.

## 2. Askerî ve siyasi örgütler

- **NATO (1949):** Kuzey Atlantik Antlaşması Örgütü. Kolektif savunma (5. madde). Merkez Brüksel. **Türkiye 1952'de üye oldu.**
- **AGİT (Avrupa Güvenlik ve İş Birliği Teşkilatı):** Helsinki Nihai Senedi (1975) ile başlayan süreç. Güvenlik, insan hakları. Merkez Viyana.
- **Avrupa Konseyi (1949):** İnsan hakları ve hukukun üstünlüğü. Avrupa İnsan Hakları Mahkemesi. Merkez Strazburg. **Türkiye kurucu üyedir.**
- **Şanghay İş Birliği Örgütü:** Çin, Rusya, Orta Asya ülkeleri ve diğerleri. Güvenlik ve ekonomi.
- **Arap Birliği (1945):** Arap ülkeleri.
- **Afrika Birliği (2002):** Afrika devletleri.
- **İslam İş Birliği Teşkilatı (İİT, 1969):** İslam ülkelerinin iş birliği. Merkez Cidde.

## 3. Ekonomik örgütler

- **Avrupa Birliği (AB):** Ekonomik ve siyasi birlik. Ortak pazar, Avro. Maastricht Antlaşması (1992).
- **DTÖ (1995):** Dünya Ticaret Örgütü. Merkez Cenevre.
- **IMF ve Dünya Bankası (1944):** Para sistemi ve kalkınma finansmanı.
- **OECD:** Ekonomik İş Birliği ve Kalkınma Örgütü. Gelişmiş ve yükselen ekonomiler. Türkiye kurucu üyedir.
- **G20:** Büyük ekonomilerin forumu. Türkiye üyedir.
- **OPEC (1960):** Petrol İhraç Eden Ülkeler Örgütü. Petrol arz ve fiyat politikasını koordine eder. Merkez Viyana. Kurucuları İran, Irak, Kuveyt, Suudi Arabistan ve Venezuela.
- **ASEAN (1967):** Güneydoğu Asya Ülkeleri Birliği. Merkez Cakarta.
- **NAFTA (1994):** ABD, Kanada, Meksika. Yerini USMCA aldı.
- **Mercosur:** Güney Amerika.
- **KEİ (Karadeniz Ekonomik İş Birliği, 1992)** ve **ECO (Ekonomik İş Birliği Teşkilatı).**

## 4. Türk dünyası örgütleri

- **Türk Devletleri Teşkilatı (TDT):** Türkiye, Azerbaycan, Kazakistan, Kırgızistan, Özbekistan ve gözlemci üyeler. Kültürel, siyasi ve ekonomik iş birliği.
- **TÜRKSOY:** Ortak Türk Kültürü Uluslararası Teşkilatı.
- **TİKA:** Türkiye'nin kalkınma ve kültür iş birliği kurumu.

## 5. Türkiye'nin üyelikleri

BM, NATO, OECD, Avrupa Konseyi, AGİT, İİT, G20, KEİ, DTÖ. AB ile Gümrük Birliği ve aday ülke statüsü. Türk Devletleri Teşkilatı'nda aktif.

## 6. Örgütlerin rolü ve eleştiriler

**Olumlu:**
- Barışın korunması, barış gücü operasyonları.
- Ticaretin ve kalkınmanın desteklenmesi.
- İnsan hakları, sağlık ve eğitim programları.
- İklim ve çevre iş birliği.

**Eleştiriler:**
- Güvenlik Konseyi'nde veto hakkı, kararların kilitlenmesine neden olabilir.
- Büyük güçlerin etkisi.
- Uygulama gücü ve yaptırımın yetersizliği.

## 7. Sık yapılan hatalar

- NATO'yu ekonomik örgüt sanmak. Askerî ittifaktır.
- Türkiye'nin AB üyesi olduğunu sanmak. Aday ülkedir.
- OPEC'in tüm petrol üreticilerini kapsadığını sanmak.
- Güvenlik Konseyi'nde tüm üyelerin veto hakkı olduğunu sanmak. Yalnızca 5 daimi üye.
- BM merkezini Cenevre sanmak. New York'tur (Avrupa merkezi Cenevre).

