## 1. Etkileşim türleri

- **Ekonomik:** Ticaret, yatırım, enerji alışverişi, turizm, işgücü göçü.
- **Siyasi:** İttifaklar, diplomasi, uluslararası kuruluşlar, anlaşmalar.
- **Kültürel:** Dil, sanat, eğitim, medya, göç.
- **Askerî:** Savunma iş birlikleri, ortak tatbikatlar, çatışmalar.

Etkileşimi artıran etkenler: Ulaşım ve iletişimin gelişmesi, küreselleşme, komşuluk, ortak sınırlar ve kaynaklar.

## 2. Sınır aşan su kaynakları

Birden fazla ülkeden geçen nehirlerin paylaşımı önemli bir etkileşim alanıdır.

- **Fırat ve Dicle:** Türkiye'de doğar, Suriye ve Irak'a akar. Türkiye'nin GAP barajları su paylaşımı tartışmalarını gündeme getirir.
- **Asi Nehri:** Lübnan, Suriye ve Türkiye.
- **Nil:** Mısır, Sudan, Etiyopya ve diğerleri. Etiyopya'nın Büyük Rönesans Barajı gerilim kaynağıdır.
- **Meriç:** Türkiye, Yunanistan ve Bulgaristan.
- **Tuna:** On ülkeden geçerek Karadeniz'e ulaşır.
- **Mekong, Ürdün, Amu Derya ve Siri Derya.**

**Sorunlar:** Su kıtlığı, kirlilik, baraj yapımı, tarımsal sulama. **Çözümler:** İkili ve çok taraflı su anlaşmaları, ortak yönetim.

## 3. Deniz yetki alanları

BM Deniz Hukuku Sözleşmesi (1982) ile belirlenmiştir.

- **Karasuları:** Kıyıdan en çok 12 deniz miline kadar. Kıyı devleti tam egemenlik kullanır. Türkiye Karadeniz ve Akdeniz'de 12 mil, **Ege'de 6 mil** uygular.
- **Bitişik bölge:** 24 mile kadar. Gümrük, vergi ve sağlık denetimi.
- **Münhasır ekonomik bölge (MEB):** 200 mile kadar. Balıkçılık, petrol ve doğal gaz gibi kaynakları işletme hakkı.
- **Kıta sahanlığı:** Kıyıdan itibaren denizin altındaki doğal uzantı. Ege'de ve Doğu Akdeniz'de uyuşmazlık konusudur.
- **Açık deniz:** Hiçbir devletin egemenliğinde değildir.

![Kıyıdan açığa doğru karasuları, bitişik bölge, münhasır ekonomik bölge ve açık deniz](/lessons/ayt-cog2/deniz-yetki-alanlari.svg "Deniz yetki alanları ve kıta sahanlığı")

Türkiye, BM Deniz Hukuku Sözleşmesi'ne taraf değildir. Ege Denizi'nde Yunan adalarının kıta sahanlığı ve MEB hakkı üzerinden anlaşmazlık vardır.

## 4. Enerji ilişkileri

- **Üretici ülkeler:** Rusya, Azerbaycan, İran, Irak, Katar, Suudi Arabistan.
- **Tüketici ve transit ülkeler:** Avrupa ülkeleri, Çin, Hindistan, Türkiye.
- **Boru hatları ve LNG:** Enerji tedariki ve güvenliği.
- **Bağımlılık:** Tek ülkeye bağımlılık siyasi baskıya yol açabilir. Çözüm tedarik çeşitlendirmesidir.
- **OPEC** petrol üreticilerinin arz ve fiyat politikalarını koordine eder.

## 5. Türkiye ve komşuları

- **Yunanistan:** Ege'de kıta sahanlığı, karasuları, hava sahası ve Kıbrıs uyuşmazlıkları. Aynı zamanda NATO üyesidir ve ticaret yapılır.
- **Bulgaristan ve Gürcistan:** İyi komşuluk ve ekonomik iş birliği.
- **Azerbaycan:** Yakın siyasi ve ekonomik ilişkiler. BTC, TANAP ve Bakü-Tiflis-Kars demiryolu.
- **Ermenistan:** Sınır kapısı uzun süredir kapalıydı. Normalleşme görüşmeleri sürmektedir.
- **İran:** Doğal gaz ticareti ve sınır ticareti.
- **Irak ve Suriye:** Su paylaşımı, güvenlik, göç ve ticaret.

## 6. İş birliği ve uyuşmazlık

**İş birliği alanları:** Ticaret, enerji, ulaşım koridorları, turizm, eğitim, kültür.

**Uyuşmazlık nedenleri:** Sınır ve toprak, su ve enerji kaynakları, etnik ve dinî ayrılıklar, deniz yetki alanları, siyasi ittifaklar.

**Çözüm yolları:** Diplomasi, uluslararası hukuk ve mahkemeler (Uluslararası Adalet Divanı), arabuluculuk, uluslararası kuruluşlar.

## 7. Sık yapılan hatalar

- Karasuları ile kıta sahanlığını karıştırmak. Karasuları su yüzeyi ve sütunu, kıta sahanlığı deniz tabanıdır.
- Türkiye'nin her denizde 12 mil karasuyu uyguladığını sanmak. Ege'de 6 mil uygular.
- Açık denizde bir devletin egemenlik hakkı olduğunu sanmak.
- Fırat ve Dicle'nin yalnızca Türkiye'den geçtiğini sanmak.
- Etkileşimin hep iş birliği olduğunu sanmak. Uyuşmazlık da içerir.

:::baglanti
