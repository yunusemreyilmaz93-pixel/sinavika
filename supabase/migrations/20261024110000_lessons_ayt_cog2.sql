## 1. Kıtalar ve okyanuslar

**Kıtalar (alan sıralaması):** Asya, Afrika, Kuzey Amerika, Güney Amerika, Antarktika, Avrupa, Okyanusya (Avustralya).

- **Asya:** En büyük kıta. Dünya nüfusunun yaklaşık %60'ı burada yaşar. Çin ve Hindistan.
- **Afrika:** İkinci büyük kıta. Nüfus artış hızı yüksek. Gelişmişlik düzeyi düşük ülkeler çok.
- **Avrupa:** Nispeten küçük ama nüfusu ve ekonomisi gelişmiş. Çok sayıda ülke.
- **Kuzey Amerika:** ABD, Kanada, Meksika.
- **Güney Amerika:** Amazon Havzası. Brezilya en büyük ülke.
- **Antarktika:** Kalıcı nüfusu yoktur. Bilim istasyonları.
- **Okyanusya:** Avustralya, Yeni Zelanda ve Pasifik adaları.

**Okyanuslar:** Pasifik (en büyük ve en derin), Atlas, Hint, Kuzey Buz, Güney Okyanusu.

## 2. Ülkeleri sınıflandırma ölçütleri

- **GSYH (Gayri Safi Yurt İçi Hasıla):** Bir ülkenin bir yılda ürettiği mal ve hizmetlerin toplam değeri. **Kişi başına GSYH** ortalama gelir düzeyini gösterir.
- **İnsani Gelişme Endeksi (İGE):** Sağlık (yaşam beklentisi), eğitim (okullaşma, okuryazarlık) ve gelir düzeyini birlikte ölçer. Birleşmiş Milletler hazırlar.
- Diğer göstergeler: Bebek ölüm hızı, okuryazarlık, sanayi ve hizmet payı, kentleşme, teknoloji düzeyi.

## 3. Ülke grupları

**Gelişmiş ülkeler:**
- Yüksek gelir, yüksek İGE.
- Sanayi ve hizmet sektörü baskın, Ar-Ge güçlü.
- Nüfus artışı yavaş veya durağan, yaşlı nüfus fazla.
- Örnekler: ABD, Almanya, Japonya, Birleşik Krallık, Kanada.

**Gelişmekte olan ülkeler:**
- Orta gelir, hızla sanayileşme.
- Nüfus artışı yüksek, kentleşme hızlı.
- Örnekler: Türkiye, Brezilya, Hindistan, Meksika, Çin (yükselen ekonomi).

**Az gelişmiş ülkeler:**
- Düşük gelir, düşük İGE.
- Birincil sektör (tarım) baskın, nüfus artışı yüksek.
- Sağlık, eğitim ve altyapı yetersiz.
- Örnekler: Afrika'nın büyük bölümü, bazı Asya ülkeleri.

**Kuzey-Güney ayrımı:** Gelişmiş ülkeler çoğunlukla kuzeyde (Kuzey Amerika, Avrupa, Japonya, Avustralya), gelişmekte olan ve az gelişmiş ülkeler güneyde yer alır.

::sim{tur="koordinat"}

## 4. Büyük bölgeler ve özellikleri

- **Kuzey Amerika:** Gelişmiş ekonomiler, geniş tarım alanları ve zengin madenler.
- **Latin Amerika:** İspanyolca ve Portekizce konuşulur. Brezilya Portekizce konuşur. Zengin tarım ve maden. Gelir eşitsizliği yüksek.
- **Avrupa:** Gelişmiş sanayi ve hizmet, yaşlı nüfus, Avrupa Birliği.
- **Afrika:** Doğal kaynak zenginliği, nüfus artışı yüksek, gelişmişlik düşük. Sahra altı Afrika.
- **Orta Doğu:** Petrol ve doğal gaz zenginliği, kurak iklim, siyasi gerilim.
- **Güney Asya:** Hindistan, Pakistan, Bangladeş. Nüfus yoğun.
- **Doğu ve Güneydoğu Asya:** Çin, Japonya, Güney Kore. Hızlı sanayileşme, ihracata dayalı büyüme.
- **Orta Asya ve Kafkasya:** Türk cumhuriyetleri, enerji kaynakları.
- **Okyanusya:** Avustralya ve Yeni Zelanda gelişmiş, Pasifik adaları küçük ekonomiler.

## 5. Bölgeler arası farklar

- **Kaynak dağılımı:** Petrol Orta Doğu, tarım Kuzey Amerika ve Güney Amerika'da yoğun.
- **Nüfus:** Asya'da çok, Antarktika'da hiç.
- **Gelişmişlik:** Kuzeyde yüksek, güneyde düşük.
- **Teknoloji ve eğitim:** Gelişmiş ülkelerde yüksek.

Farkların nedenleri: Tarihî süreç (sömürgecilik), doğal kaynak dağılımı, eğitim düzeyi, siyasi istikrar ve ekonomik politikalar.

## 6. Sık yapılan hatalar

- Gelişmişliği yalnızca kişi başına gelire bağlamak. İGE sağlık ve eğitimi de içerir.
- Brezilya'nın İspanyolca konuştuğunu sanmak. Portekizce konuşulur.
- Kuzey-Güney ayrımını yarım küre ayrımıyla karıştırmak.
- Çin ve Hindistan'ı gelişmiş ülke saymak. Yükselen ya da gelişmekte olan ekonomilerdir.
- Antarktika'da kalıcı nüfus olduğunu sanmak.

