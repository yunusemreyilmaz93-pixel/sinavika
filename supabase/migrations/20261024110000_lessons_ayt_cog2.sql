## 1. İnsan ve çevre ilişkisi

- **Çevre insanı etkiler:** İklim, yer şekilleri ve kaynaklar yerleşme, tarım ve ekonomiyi belirler.
- **İnsan çevreyi etkiler:** Tarım, sanayi, ulaşım, yerleşme ve nüfus artışı çevreyi değiştirir.
- Teknoloji geliştikçe doğaya etki gücü de arttı. Sorun, doğal kaynak tüketimi ile atık üretiminin doğanın **yenilenme hızını aşmasıdır.**
- **Ekolojik ayak izi:** Bir kişinin ya da toplumun tükettiği kaynağı ve ürettiği atığı karşılamak için gereken biyolojik üretken alan.

## 2. Başlıca çevre sorunları

- **Hava kirliliği:** Fosil yakıtlar, sanayi, taşıt egzozları, ısınma. Asit yağmurları, solunum hastalıkları, görüş kaybı. Kentlerde **smog.**
- **Su kirliliği:** Evsel ve sanayi atıkları, gübre ve ilaç kalıntıları, petrol sızıntıları. **Ötrofikasyon** (göl ve denizde alg patlaması).
- **Toprak kirliliği ve erozyon:** Ormansızlaşma, yanlış tarım, aşırı otlatma.
- **Ormansızlaşma:** Tarım ve yerleşme için orman tahribi. Amazon.
- **Çölleşme:** Kurak ve yarı kurak alanlarda aşırı otlatma, yanlış sulama, iklim değişikliği. Sahel kuşağı.
- **Biyolojik çeşitlilik kaybı:** Habitat kaybı, aşırı avlanma, kirlilik.
- **Ozon tabakasının incelmesi:** Klor ve brom içeren gazlar (CFC). Morötesi ışın artışı, cilt kanseri riski. Antarktika üzerinde "ozon deliği".
- **Atık sorunu:** Plastik kirliliği, çöp.

## 3. Küresel ısınma ve iklim değişikliği

- **Sera etkisi:** Atmosferdeki bazı gazlar (karbondioksit, metan, su buharı, azot oksitler) yer yüzeyinden yayılan ısıyı tutar. Doğal sera etkisi hayatı mümkün kılar.
- **Sorun:** Fosil yakıt kullanımı ve ormansızlaşma sera gazlarını artırır. Atmosfer **aşırı ısınır.**
- **Sonuçlar:**
  - Kutup buzulları ve dağ buzullarının erimesi.
  - Deniz seviyesinin yükselmesi, kıyı yerleşimlerinin tehlikesi.
  - Kuraklık, sel, orman yangını gibi aşırı hava olaylarının artması.
  - Tarımsal üretimin değişmesi, su kıtlığı.
  - İklim göçleri.
  - Biyomların kayması.

## 4. Doğal afetler

- **Deprem:** Levha hareketleri. Türkiye'de Kuzey Anadolu ve Doğu Anadolu fay hatları. **Korunma:** Depreme dayanıklı yapı, zemin etüdü, afet bilinci.
- **Sel ve taşkın:** Aşırı yağış, dere yatakları ve yamaçlarda yapılaşma.
- **Heyelan ve çığ:** Eğimli, killi, ormansız yamaçlar.
- **Kuraklık:** Yağış azlığı. Su yönetimi gerektirir.
- **Orman yangını:** Sıcak, kurak yaz, insan kaynaklı ihmal.
- **Volkanik patlama, tsunami, kasırga.**

**Afet yönetimi:** Önleme, hazırlık, müdahale, iyileştirme. Erken uyarı sistemleri, afet planları, sigorta, eğitim.

## 5. Uluslararası çevre anlaşmaları

- **Stockholm Konferansı (1972):** İlk BM çevre konferansı.
- **Montreal Protokolü (1987):** Ozon tabakasına zarar veren maddelerin (CFC) kullanımını azaltır. Başarılı kabul edilir.
- **Rio Zirvesi (1992):** Çevre ve kalkınma. Biyolojik çeşitlilik, iklim değişikliği çerçeve sözleşmesi, Gündem 21.
- **Kyoto Protokolü (1997):** Gelişmiş ülkeler için sera gazı salımı azaltma hedefleri.
- **Paris İklim Anlaşması (2015):** Küresel sıcaklık artışını sanayi öncesine göre 2 °C'nin altında, mümkünse 1,5 °C ile sınırlama hedefi. Türkiye anlaşmayı 2021'de onayladı.
- **Basel, Ramsar, Bern, Barselona sözleşmeleri:** Tehlikeli atıklar, sulak alanlar, yaban hayatı, Akdeniz'in korunması.

## 6. Çözümler

- Yenilenebilir enerji, enerji verimliliği.
- Toplu taşıma, bisiklet, yürüyüş.
- Geri dönüşüm ve atık azaltma.
- Ağaçlandırma, orman koruma.
- Çevre dostu tarım ve üretim.
- Eğitim, farkındalık ve yasal düzenlemeler.
- Uluslararası iş birliği.

## 7. Sık yapılan hatalar

- Ozon incelmesini küresel ısınmanın nedeni sanmak. İki ayrı sorundur.
- Sera etkisinin yalnızca zararlı olduğunu sanmak. Doğal sera etkisi hayat için gereklidir.
- Küresel ısınmayı yalnızca kutuplarda etkili sanmak. Dünya genelini etkiler.
- Kyoto'yu ozon anlaşması sanmak. Montreal ozon, Kyoto sera gazıdır.
- Çevre sorunlarını yalnızca gelişmiş ülkelerin sorunu sanmak.

