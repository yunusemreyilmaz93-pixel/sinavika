## 1. Mutlak ve göreceli konum

- **Mutlak (matematik) konum:** Enlem ve boylam ile belirlenir. Değişmez. Türkiye yaklaşık 36°-42° kuzey enlemleri ile 26°-45° doğu boylamları arasındadır.
- **Göreceli (bağıl) konum:** Çevresindeki bölgelere, denizlere, ülkelere göre konumdur. Zamanla değerini değiştirebilir. Örneğin Süveyş Kanalı'nın açılması Akdeniz'in önemini artırmıştır.
- **Jeopolitik konum:** Göreceli konumun siyasi, ekonomik ve askerî açıdan önemidir.

## 2. Jeopolitik kuramlar

- **Alfred Mahan (Deniz Gücü Kuramı):** Denizlere hâkim olan dünyaya hâkim olur. Güçlü donanma, limanlar ve üsler.
- **Halford Mackinder (Kalpgâh / Heartland Kuramı):** Doğu Avrupa'ya hâkim olan kalpgâhı, kalpgâha hâkim olan dünya adasını (Avrupa-Asya-Afrika), dünya adasına hâkim olan dünyayı yönetir.
- **Nicholas Spykman (Kıyı Kuşağı / Rimland Kuramı):** Avrasya'nın kıyı kuşağına hâkim olan dünyayı yönetir.
- **Giulio Douhet:** Hava gücünün belirleyiciliği.
- **Günümüz:** Enerji, su, uzay ve siber güç de jeopolitik rekabetin parçasıdır.

## 3. Stratejik boğaz ve kanallar

- **İstanbul ve Çanakkale Boğazları:** Karadeniz'i Akdeniz'e bağlar. Rusya, Ukrayna, Romanya, Bulgaristan ve Gürcistan'ın Akdeniz'e çıkış yolu. **Montrö Sözleşmesi (1936)** geçişi düzenler.
- **Cebelitarık Boğazı:** Atlas Okyanusu ile Akdeniz'i bağlar. İspanya ve Fas arasında.
- **Süveyş Kanalı (1869):** Akdeniz ile Kızıldeniz'i bağlar. Avrupa-Asya deniz yolunu çok kısaltır. Mısır'da.
- **Panama Kanalı (1914):** Atlas ve Pasifik okyanuslarını bağlar.
- **Hürmüz Boğazı:** Basra Körfezi'ni Umman Denizi'ne bağlar. Dünya petrol ticaretinin önemli bir bölümü buradan geçer.
- **Malakka Boğazı:** Hint Okyanusu ile Pasifik'i (Güney Çin Denizi) bağlar. Çin ve Japonya'nın enerji ve ticaret yolu.
- **Bab-ül Mendep:** Kızıldeniz ile Aden Körfezi arasında.

## 4. Türkiye'nin jeopolitik konumu

**Avantajlar:**
- **Üç kıtanın (Asya, Avrupa, Afrika) kesişim noktasına** yakın, Avrupa ile Asya arasında köprü.
- **Boğazlara** sahiptir. Karadeniz'in Akdeniz'e açılan kapısıdır.
- **Enerji koridoru:** Hazar, Orta Asya ve Orta Doğu enerjisini Avrupa'ya taşıyan hatların geçiş noktası (BTC, TANAP, TürkAkım).
- **Etki alanları:** Balkanlar, Kafkasya, Orta Doğu, Akdeniz, Karadeniz ve Orta Asya ile tarihî ve kültürel bağlar.
- **Üç yanı denizlerle çevrili** uzun kıyı şeridi.
- **Su zengini:** Fırat, Dicle ve Kuzey Kafkasya.

**Riskler:**
- Çevresindeki **istikrarsız bölgeler** (Orta Doğu, Kafkasya, Doğu Akdeniz).
- Göç ve güvenlik sorunları.
- Su, enerji ve sınır uyuşmazlıkları (Ege kıta sahanlığı, Kıbrıs, Doğu Akdeniz hidrokarbon kaynakları).
- Enerji ithalatına bağımlılık.

## 5. Jeopolitik konumun sonuçları

- Büyük güçlerin ilgisi ve rekabeti.
- Ticaret, ulaşım ve enerji koridorlarında avantaj.
- Diplomasi ve ittifaklara yön verir (NATO, AB).
- Askerî stratejiyi ve savunma harcamalarını etkiler.
- Çatışma ve gerilim riski taşır.

## 6. Sık yapılan hatalar

- Mutlak konumun zamanla değiştiğini sanmak. Mutlak konum sabittir.
- Mahan'ı kara gücü kuramıyla karıştırmak. Deniz gücüdür.
- Süveyş Kanalı'nı Pasifik ve Atlas'ı bağlayan kanal sanmak. Akdeniz ile Kızıldeniz'i bağlar.
- Hürmüz Boğazı'nı Karadeniz'in çıkışı sanmak.
- Türkiye'nin konumunun yalnızca avantajlı olduğunu sanmak. Riskler de vardır.

:::baglanti
Bu konu, **Küresel Ortam** konusundaki ülke gruplarının jeopolitik boyutudur. **Ulaşım ve Ticaret** (Coğrafya-1) konusundaki boğaz ve koridor bilgisi buraya taşınır. **Ülkeler Arası Etkileşim** ve **Çatışma Bölgeleri** konuları bu konumların siyasi sonuçlarını işler. **Tarih** dersinde Boğazlar Sorunu, Montrö, Soğuk Savaş ve Truman Doktrini bu başlıkla doğrudan ilişkilidir.
:::

