Dünyayı tek bir bütün olarak anlamak zor. Bu yüzden coğrafyacılar onu **bölgelere ve ülke gruplarına** ayırır. Hangi ülke gelişmiş, hangisi gelişmekte olan? Kıtaların hangi özellikleri öne çıkıyor? Ülkeleri sınıflandırırken hangi ölçütlere bakılıyor? Bu konuda **kıtaları ve okyanusları**, **ülkelerin gelişmişlik ölçütlerini**, **dünya ülkelerinin gruplandırılmasını**, **büyük bölgeleri** ve **bölgelerin başlıca özelliklerini** öğreneceksin.

:::hedefler
1. Kıtaların ve okyanusların temel özelliklerini söylemek.
2. Gelişmişlik göstergelerini (GSYH, İGE) açıklamak.
3. Gelişmiş, gelişmekte olan ve az gelişmiş ülke gruplarını karşılaştırmak.
4. Büyük dünya bölgelerini ve başlıca ülkelerini eşleştirmek.
5. Ülkelerin bölgesel özelliklerini (iklim, kaynak, nüfus) yorumlamak.
:::

:::ipucu
Bir ülkenin gelişmişliği tek bir ölçütle belirlenmez. **GSYH (kişi başına gelir)** ekonomik gücü, **İnsani Gelişme Endeksi (İGE)** ise **sağlık, eğitim ve gelir** üçlüsünü birlikte ölçer. Soruda "birden çok boyut" geçiyorsa İGE'ye bak.
:::

