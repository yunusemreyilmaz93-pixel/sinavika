2. Başlıca çevre sorunlarını (kirlilik, çölleşme, küresel ısınma, ozon incelmesi) nedenleriyle eşleştirmek.
3. Sera etkisi ile küresel ısınma arasındaki ilişkiyi yorumlamak.
