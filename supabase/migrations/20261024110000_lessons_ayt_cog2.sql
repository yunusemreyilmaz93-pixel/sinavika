Barışı korumak, ticareti kolaylaştırmak, sağlık krizlerine birlikte çözüm üretmek tek bir devletin gücünü aşar. Bu nedenle devletler bir araya gelerek **uluslararası örgütler** kurar. Bu konuda **küresel ve bölgesel örgütleri** (BM, NATO, AB, AGİT, İİT, OPEC, ASEAN, Arap Birliği, Afrika Birliği, Şanghay İş Birliği, G20 ve diğerleri), **kuruluş amaçlarını**, **üye yapılarını** ve **Türkiye'nin bu örgütlerdeki yerini** öğreneceksin.

