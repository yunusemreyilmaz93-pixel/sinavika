İnsan, doğduğu andan itibaren öğrenmeye ve anlam aramaya yönelir. “Ben nereden geldim, nereye gidiyorum, hayatın anlamı nedir?” sorularına cevap ararken hem **bilgiye** hem **inanca** ihtiyaç duyar. Bilgi, gerçeği doğru olarak kavramaktır. İnanç ise insanın kalbinde bir şeyi doğru kabul etmesidir. Bu konuda **bilgi kaynaklarını**, **din ile bilgi ilişkisini**, **inanç kavramını**, **İslam’da iman esaslarını** ve **akıl ile vahiy ilişkisini** öğreneceksin.

:::hedefler
1. Bilgi kaynaklarını (duyu, akıl, doğru haber, vahiy) sıralamak.
2. Din, inanç ve iman kavramlarını açıklamak.
3. İslam’da bilgi ve ilme verilen önemi örneklerle anlatmak.
4. İman esaslarını (altı esas) ve temel anlamlarını söylemek.
5. Akıl ile vahiy arasındaki ilişkiyi ve vahyin özelliklerini yorumlamak.
:::

## 1. Bilgi ve bilgi kaynakları

**Bilgi**, insanın gerçeği doğru olarak kavramasıdır. Bilgi edinmenin başlıca kaynakları şunlardır:

- **Duyular (algı):** Gözle görme, kulakla işitme, dokunma, koklama, tatma. Çevreyle ilk temas bu yolla kurulur. Duyular zaman zaman yanıltabilir.
- **Akıl:** Çıkarım yapma, düşünme, sebep-sonuç ilişkisi kurma yeteneği. Matematik ve mantık bilgisinin temelidir.
- **Doğru haber (güvenilir bilgi aktarımı):** Başkalarından, kitaplardan ve güvenilir kaynaklardan öğrenilen bilgi. Tarih bilgisi, coğrafya bilgisi büyük ölçüde bu yolla edinilir.
- **Vahiy:** Allah’ın, peygamberlerine bildirdiği bilgi. Dinî bilginin temel kaynağıdır.
- **İlham ve sezgi:** İnsanın kalbine doğan bilgi.

Bilginin güvenilir olması için **doğruluğu kontrol edilmelidir.** Bilgi kirliliği ve dezenformasyonun yaygın olduğu bir dönemde, bilginin **kaynağını sorgulamak** önemlidir.

## 2. İslam’da bilgi ve ilim

İslam dini bilgiye ve öğrenmeye büyük önem verir:

- Kur’an’ın ilk inen ayeti “**Oku**” emriyle başlar (Alak suresi). Okumak, öğrenmek ve düşünmek ilk emirdir.
- Kur’an insanı **akletmeye, düşünmeye, evrendeki olayları incelemeye** çağırır. Evren, “**ayet**” (işaret) olarak anılır.
- Hz. Muhammed’in ilim hakkındaki sözleri, **beşikten mezara kadar öğrenmeyi** teşvik eder.
- Müslümanlar tarih boyunca **tıp, matematik, astronomi, felsefe** gibi alanlarda ilim üretmiştir.
- İslam’da **faydalı ilim** önemlidir. Bilgi, **amelle (davranışla)** birleşmelidir.

**Bilgi ile ahlak:** Bilgi, ahlakla birleşmediğinde zarar verebilir. Bu yüzden İslam, **ilim ile ahlakı bir arada** ister.

## 3. Din, inanç ve iman

- **Din:** Allah tarafından konulmuş, insanları dünya ve ahiret mutluluğuna ulaştıran **inanç, ibadet ve ahlak ilkelerinin bütünüdür.**
- **İnanç:** İnsanın bir şeyin doğruluğuna **kalpten kesin olarak bağlanmasıdır.** Dinî inançlar da, bilimsel bilgi gibi, insan hayatında rol oynar.
- **İman:** Kelime anlamı “güvenmek, tasdik etmek”tir. Terim olarak, Hz. Muhammed’in Allah’tan getirdiği esasları **kalp ile tasdik edip dil ile ikrar etmektir.**
- **İslam:** Allah’a teslim olmak, bağlanmak. Hem dinin adı hem de Müslümanların yaşayışıdır.
- **Müslüman olmanın temel şartı:** Kelime-i şehadet getirerek iman etmektir.

**İnsanın inanç ihtiyacı:** İnsan, ölüm, acı, adalet ve anlam gibi konularda **tutunacak bir değere** ihtiyaç duyar. İnanç, insana **huzur, umut ve ahlaki rehberlik** sağlar.

**Bilgi ile inanç ilişkisi:** İkisi birbirini **tamamlar**. Bilgi, evreni anlamayı sağlar. İnanç, anlam ve değer verir. Gerçek inanç **bilinçli ve araştırarak** edinilir, **taklit ve körü körüne** olmamalıdır.

## 4. İmanın esasları

İslam’da iman esasları **altı**dır:

| İman esası | Anlamı |
| --- | --- |
| **Allah’a iman** | Allah’ın bir ve eşsiz olduğuna, yaratıcı ve her şeyin sahibi olduğuna inanmak |
| **Meleklere iman** | Allah’ın nurdan yarattığı, emirlerini yerine getiren varlıklara inanmak (Cebrail, Mikail, İsrafil, Azrail) |
| **Kitaplara iman** | Allah’ın peygamberlerine gönderdiği kitaplara inanmak (Tevrat, Zebur, İncil, Kur’an) |
| **Peygamberlere iman** | Allah’ın insanlara gönderdiği peygamberlere inanmak (Hz. Muhammed son peygamberdir) |
| **Ahiret gününe iman** | Ölümden sonra yeniden dirilmeye, hesap gününe, cennet ve cehenneme inanmak |
| **Kadere iman** | Allah’ın her şeyi bilmesine, dilemesine ve yaratmasına inanmak, insanın iradesiyle sorumlu olduğuna inanmak |

**İmanın şartlarından birine inanmayan** kişi imanın bütünlüğünü bozar. İman **kalpte** yerleşir, **ameller** (davranışlar) imanın gereğidir.

## 5. Akıl ve vahiy

**Akıl:** Allah’ın insana verdiği, **iyiyi ve kötüyü ayırt etme** ve düşünme yeteneğidir. İslam, aklı **önemli bir nimet** olarak görür. Kur’an defalarca “aklınızı kullanmaz mısınız?” diye sorar.

**Vahiy:** Allah’ın, **peygamberlerine** onlar aracılığıyla insanlara **dinî bilgileri** bildirmesidir. Vahyin kaynağı **Allah**’tır, melek (Cebrail) aracılığıyla ya da başka yollarla gelir. Vahyin özellikleri:

- Allah’tan gelir, **hatasız ve güvenilirdir.**
- **Hakikati**, yani insanın tek başına bilemeyeceği konuları (ahiret, Allah’ın sıfatları, ibadet biçimleri) bildirir.
- İnsanın **akıl ile ulaşabileceği** bilgilerle **çelişmez.**

**Akıl ile vahyin ilişkisi:** Akıl, **vahyi anlamada, yorumlamada ve değerlendirmede** kullanılır. Vahiy, aklın **ulaşamadığı alanlarda** rehberlik eder. İkisi birbirini **destekler.** Akıl dini anlamak için gereklidir, ancak akıl tek başına dinî hükümleri koyamaz.

**Kur’an’ın indirilmesi:** Hz. Muhammed’e **yaklaşık 23 yılda** (610 ile 632) parça parça indirilmiştir. **114 sure** vardır.

