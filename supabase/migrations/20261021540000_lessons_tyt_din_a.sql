## 1. Dinin işlevleri

**Dinin bireye işlevleri:**

- **Anlam ve amaç** kazandırır: Hayatın, ölümün ve acının anlamını açıklar.
- **Huzur ve umut** verir. Zor zamanlarda teselli kaynağıdır.
- **Ahlaki rehberlik** sağlar: İyi ve kötü hakkında ölçü verir.
- **Kimlik ve aidiyet duygusu** kazandırır.

**Dinin topluma işlevleri:**

- **Birlik ve bütünleşme** sağlar. Ortak inanç ve ibadetler (cemaatle namaz, cuma, bayramlar) insanları yakınlaştırır.
- **Toplumsal düzen ve ahlak** için ortak değerler oluşturur.
- **Dayanışma ve yardımlaşmayı** teşvik eder.
- **Kültürü ve sanatı** besler (mimari, edebiyat, müzik, hat).
- **Eğitim ve ilmi** destekler (medreseler, vakıflar).

## 2. İslam’da yardımlaşma ve dayanışma

İslam, Müslümanları **kardeşliğe, yardımlaşmaya ve paylaşmaya** çağırır. “Müminler ancak kardeştirler.” (Hucurat suresi) Hz. Muhammed şöyle buyurmuştur: “**Müminler, birbirini sevmede, birbirine merhamet etmede bir vücut gibidir. Bir organı rahatsız olunca diğer organları da uykusuzluk ve ateşle ona iştirak eder.**”

**Yardımlaşma ibadet ve kurumları:**

- **Zekât:** Zengin Müslümanın malından belli oranda fakire vermesi. Toplumsal adaleti sağlar.
- **Sadaka:** Gönüllü yardım. Sadaka-i câriye, yararı sürekli olan hayırdır (çeşme, okul, kitap).
- **Fitre ve kurban:** Bayramlarda paylaşım.
- **İnfak:** Allah yolunda harcama.
- **Vakıf:** Bir malın gelirini **hayır işine** (okul, hastane, çeşme, kütüphane, aşevi) süresiz ayırmak. **Osmanlı’da** vakıflar eğitim, sağlık, su ve kervansaray hizmetlerinin büyük kısmını yürütmüştür.
- **Komşuluk ve akraba hakları (sıla-i rahim):** Hz. Peygamber komşunun hakkını çok vurgulamıştır: “**Komşusu açken tok yatan bizden değildir.**”
- **İmece ve ahilik:** Toplumsal dayanışma gelenekleridir.

**Faydaları:** Fakirliği azaltır, **sosyal adaleti** sağlar, **kıskançlık ve kini** önler, **toplumsal barışı** güçlendirir.

## 3. Toplumsal barış, hoşgörü ve farklı inançlara saygı

- **İslam’da inanç hürriyeti:** “**Dinde zorlama yoktur.**” (Bakara suresi). Kimse inanç konusunda zorlanamaz. Herkes inancını yaşamakta özgürdür.
- **Hoşgörü ve saygı:** Başkalarının inançlarına, kutsallarına saygı gösterilir. Hakaret ve alay edilmez.
- **Medine Vesikası:** Hz. Muhammed’in Medine’de **Müslümanlar, Yahudiler ve diğer topluluklarla** yaptığı, farklı inançlara hak, özgürlük ve güvence veren **yazılı toplum sözleşmesidir.**
- **Osmanlı’da hoşgörü:** **Millet sistemi** farklı inançtaki toplulukların kendi inanç ve gelenekleriyle yaşamasına olanak verdi.
- **Barış:** İslam adı bile **selam, barış, esenlik** köküyle ilişkilidir. “Selam”, Müslümanların birbirine verdiği esenlik temennisidir.
- **Adalet ve eşitlik:** Irk, dil, renk ve sınıf üstünlüğü yoktur. “Arabın Arap olmayana, Arap olmayanın Arap’a üstünlüğü yoktur, üstünlük takvadadır.” (Veda Hutbesi)
- **Hukuk:** Hak ve sorumluluklar herkes için eşittir, **adalet toplumun temelidir.**

**Çatışmanın nedenleri:** Önyargı, bilgisizlik, taassup, ayrımcılık, çıkar, istismar. **Çözüm:** Eğitim, diyalog, anlayış, hoşgörü.

## 4. Din ve kültür, sanat

Din, sanat ve kültürle yakından ilişkilidir:

- **Mimari:** Cami, medrese, köprü, çeşme, kervansaray. **Mimar Sinan** (Süleymaniye, Selimiye).
- **Hat (yazı), tezhip, ebru, minyatür** ve **çini** sanatları.
- **Edebiyat ve müzik:** İlahi, nefes, kasîde, mevlit, ezan okuma (güfte ve beste), Mevlevi mûsikisi. **Yunus Emre, Mevlana.**
- **Gelenek ve bayramlar:** Bayramlaşma, kandil geceleri, mevlit, Ramazan davulu, iftar sofraları, hatim.
- **Dil:** Dinî kavramlar Türkçeye girmiştir (selam, dua, şükür, hayır).

Bu zenginlik **kültürel mirasın** bir parçasıdır ve **korunması** gerekir.

## 5. Din istismarı

**Din istismarı**, dinî duyguların ve değerlerin **kişisel, siyasi ya da maddi çıkar için** kullanılmasıdır. Zararları:

- **İnsanları aldatır**, güvenilir bir dinî otoriteye duyulan **güveni zedeler.**
- **Toplumda ayrışma ve kutuplaşma** doğurur.
- **Dine olan inancı zedeler**, insanları dinden soğutabilir.
- **Terör ve şiddet** için kullanıldığında din ile ilgisi yoktur. Din, **can ve mal güvenliğini** korur. “**Bir insanı haksız yere öldüren bütün insanlığı öldürmüş gibidir.**” (Maide suresi)

**Korunma yolları:** **Doğru dinî bilgi**, güvenilir kaynaklar (Diyanet, ilahiyat fakülteleri), eleştirel düşünme, bilinçli olmak, dinî bilgiyi kişisel çıkarlar için kullanan kişilere karşı uyanık olmak.

## 6. Din ve laiklik

Laiklik, **din ve devlet işlerinin ayrılması** ve **din ve vicdan özgürlüğünün güvence altına alınmasıdır.** Anayasamızda laiklik ilkesi vardır ve **herkes inancını yaşama, değiştirme ve ibadet özgürlüğüne** sahiptir. Devlet bütün inançlara **eşit mesafededir.**

:::neden-sonuc
