Din yalnızca kişinin vicdanında yaşayan bir inanç değildir. Aynı zamanda aile kurmayı, komşuluk ilişkilerini, ticareti, yardımlaşmayı, bayramlaşmayı ve toplumun birlikte yaşama biçimini etkiler. Din ile toplum arasındaki bu karşılıklı ilişkiyi **din sosyolojisi** inceler. Bu konuda **dinin toplumsal işlevlerini**, **dayanışma ve yardımlaşma kurumlarını** (zekât, sadaka, vakıf), **toplumsal barış ve hoşgörüyü**, **farklı inançlara saygıyı**, **din istismarını** ve **dinî ve kültürel hayatın birlikteliğini** öğreneceksin.

