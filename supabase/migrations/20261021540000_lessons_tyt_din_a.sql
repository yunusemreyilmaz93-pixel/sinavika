## 1. Gençlik dönemi

**Gençlik (ergenlik ve sonrası)**, çocukluktan yetişkinliğe geçiş dönemidir. Bu dönemde şu gelişmeler yaşanır:

- **Fiziksel gelişim:** Boy uzar, bedensel değişimler olur. Beden imajı önem kazanır.
- **Zihinsel gelişim:** Soyut düşünme, sorgulama, eleştirel bakış gelişir. “Neden?” sorusu çoğalır.
- **Duygusal gelişim:** Duygu değişimleri, hassasiyet, kimlik arayışı, sevgi ve aidiyet ihtiyacı.
- **Sosyal gelişim:** Akranlarla bağ güçlenir, bağımsızlık isteği artar, geleceğe dair plan yapılır.
- **Ahlaki ve dinî gelişim:** Din ve değerleri sorgulama, anlam arayışı, inanç ve ibadet bilinci.

**Dinî sorumluluk:** İslam’da bir kişi **akıl ve ergenlik (büluğ)** çağına geldiğinde dinî sorumluluk (teklif) başlar.

## 2. Gençlerin karşılaştığı sorunlar

- **Kimlik arayışı:** “Ben kimim?” sorusunun cevabını bulma, kendini tanıma.
- **Akran baskısı:** Arkadaş grubuna uymak için yanlış davranışlara yönelmek.
- **Bağımlılıklar:** Sigara, alkol, uyuşturucu gibi **madde bağımlılığı** ile **teknoloji, oyun ve sosyal medya bağımlılığı.**
- **Medya ve sanal ortam etkisi:** Yanlış bilgi, özendirme, kendini başkalarıyla kıyaslama, siber zorbalık.
- **Gelecek kaygısı:** Sınav, meslek seçimi, işsizlik.
- **Aile ve okul ile iletişim sorunları.**
- **Boş zamanı değerlendirememe.**

**Çözüm yolları:**

- **Aile ve arkadaşlarla** sağlıklı iletişim kurmak, **güvendiğin bir yetişkinden** destek almak.
- **Bilinçli** olmak, **hayır diyebilmek**.
- **Spor, sanat, okuma, gönüllülük** gibi olumlu etkinliklerle ilgilenmek.
- **Hedef belirlemek** ve planlı çalışmak.
- **Dinî ve ahlaki değerlerle** yaşamı anlamlandırmak.

**İslam ve bağımlılıklar:** İslam, aklı, sağlığı ve nesli koruma ilkelerine göre alkol ve uyuşturucu gibi akıl ve bedene zarar veren maddeleri yasaklar. **İnsanın kendine zarar vermesi** de doğru görülmez.

## 3. Değer kavramı

**Değer**, bir toplumun ve bireyin **önemli saydığı, korunması gerektiğini düşündüğü** ilke, ölçü ve inançlardır. Davranışlarımıza yön verir.

**Değerlerin türleri:**

- **Manevi değerler:** Dürüstlük, sevgi, saygı, merhamet, adalet, fedakârlık, vefa, hoşgörü, yardımseverlik.
- **Sosyal ve kültürel değerler:** Aile, komşuluk, misafirperverlik, geleneksel bayramlar.
- **Evrensel değerler:** Yaşam hakkı, adalet, özgürlük, barış. Bütün insanlıkça kabul edilen değerler.
- **Dinî değerler:** İnanç, ibadet, ahlak.

**Değerler nasıl kazanılır?** Aile, okul, çevre, arkadaşlar, din, medya aracılığıyla. Değer, **bilmek kadar yaşamayı** da gerektirir. Değerlerin **model alınarak** öğrenilmesi önemlidir.

**Değer ve karar verme:** Değerlerin net olması, zor kararlarda **doğruyu seçmeni** sağlar.

## 4. Kur’an’da gençler

Kur’an, gençlerin imanını, dürüstlüğünü ve kararlılığını örnek gösterir:

- **Ashab-ı Kehf (Mağara Arkadaşları):** Zalim bir yönetimde inançlarını korumak için mağaraya sığınan **birkaç genç**. “**Onlar Rablerine iman eden gençlerdi, biz de onların hidayetini artırdık.**” (Kehf suresi). **İnançta sebat, doğruluk ve cesaret** örneği.
- **Hz. Yusuf:** Gençliğinde **iffet, güvenilirlik ve sabır** gösterdi. Kıskanç kardeşleri tarafından kuyuya atıldı, haksız yere zindana girdi ama Allah’a güvenini kaybetmedi, sonunda sorumluluk sahibi bir yönetici oldu.
- **Hz. İbrahim:** Gençlik çağında **toplumun putlarına** karşı akılla, **tevhid** (Allah’ın birliği) fikrini savundu.
- **Hz. İsmail:** Allah’a **teslimiyet** ve babasına saygı örneğidir.

**Çıkarılacak dersler:** Gençlik, inancı ve değerleri koruma, **doğruluktan ayrılmama**, **haksızlığa karşı durma** ve **Allah’a güvenme** dönemidir.

## 5. İslam’da gençliğin değeri

- Gençlik **büyük bir nimet ve emanettir.** Allah’ın verdiği bu güç ve zaman **hesabı sorulacak** bir imkândır.
- Hz. Muhammed’in öğüdü: “**Beş şeyi beş şeyden önce değerlendir:** Gençliğini ihtiyarlıktan önce, sağlığını hastalıktan önce, zenginliğini fakirlikten önce, boş zamanını meşguliyetten önce, hayatını ölümden önce.”
- **Gençlik:** İlim öğrenme, ibadet, güzel ahlak ve topluma yarar sağlama dönemidir. Gençlere verilen sorumluluk ve güven önemlidir.
- **Gençlerin topluma katkısı:** **Gönüllü çalışmalar, eğitim, yardımlaşma, çevre koruma, bilim ve sanat.**

:::neden-sonuc
- Gençlik dönemi kimlik arayışı dönemidir => Değer ve model seçimi çok önemlidir.
- Akran baskısı ve bağımlılık riskleri artıyor => Bilinçli olmak ve hayır diyebilmek gerekir.
- Değerler aile ve çevreden öğreniliyor => Güzel örnek ve model değer edinmede etkilidir.
