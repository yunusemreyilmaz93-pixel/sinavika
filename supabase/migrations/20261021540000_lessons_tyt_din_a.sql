## 1. Ahlak nedir

**Ahlak**, insanın **huy ve karakteridir.** Doğru ve yanlış, iyi ve kötü davranışlar hakkında kabul edilen ilkelerdir. **Hulk** (yaratılış) ve **hulûk** (huy) sözcüklerinden gelir. İslam’a göre **güzel ahlak** (hüsn-i hulk), **imanın bir gereğidir.**

- **Hz. Muhammed** güzel ahlakın en güzel örneğidir. Kur’an “**Sen elbette büyük bir ahlak üzerindesin.**” (Kalem suresi) diyerek Peygamber’in ahlakını över.
- Hz. Peygamber’in ahlakla ilgili buyrukları: “**Müminlerin iman bakımından en olgunu ahlakı en güzel olanıdır.**”
- İbadetler **ahlakı güçlendirmek** için de vardır: Namaz **kötülükten alıkoyar**, oruç **sabır** öğretir, zekât **cömertlik**, hac **eşitlik ve kardeşlik** kazandırır.
- **Ahlak ve hukuk farkı:** Ahlak vicdana, hukuk yaptırıma dayanır. **Ahlaki sorumluluk** kişinin iç dünyasında başlar.

## 2. Güzel ahlak örnekleri

- **Doğruluk (sıdk):** Doğru söylemek, sözde ve davranışta doğru olmak. Hz. Peygamber: “**Doğruluk iyiliğe, iyilik cennete götürür.**” Yalan ise kötülüğe götürür.
- **Güvenilirlik (emanet):** Emanete ve verilen sözlere sadık olmak, bırakılan şeyi korumak. **El-Emin** olan Peygamber örnektir. Sözünde durmak (**vefa**), ahde vefa.
- **Adalet:** Herkese hak ettiğini vermek, **sevdiğin kişiye de sevmediğin kişiye de** adil davranmak.
- **Merhamet ve şefkat:** İnsana, hayvana, çevreye şefkat. “**Merhamet etmeyene merhamet olunmaz.**” Yetim, yaşlı ve yoksulları gözetmek.
- **Sabır:** Zorluk ve sıkıntıda dayanmak, **öfke anında kendini tutmak**. Hz. Peygamber: “**Güçlü kişi, güreşte yenen değil, öfke anında kendine hâkim olan kişidir.**”
- **Tevazu (alçak gönüllülük):** Kendini başkalarından üstün görmemek. Kibrin zıddıdır.
- **Cömertlik ve yardımseverlik:** Mal ve zamanını başkalarıyla paylaşmak. **İsraftan kaçınmak, cimri olmamak.**
- **Af ve hoşgörü:** Kötülüğe iyilikle karşılık vermek, bağışlayıcı olmak.
- **Haya (utanma duygusu):** Edep ve ölçülülük. “Hayâ imandandır.”
- **Şükür ve kanaat:** Elindekine şükretmek, hırs ve açgözlülükten uzak durmak.
- **Çalışkanlık ve sorumluluk:** Helal kazanç, işini en iyi şekilde yapmak (**itkan**).
- **Komşuluk ve akrabalık:** Komşu ve akrabanın hakkını gözetmek.
- **Temizlik:** “Temizlik imandandır.” Beden, çevre ve kalp temizliği.

## 3. Kötü ahlaki davranışlar

- **Yalan:** Gerçeğe aykırı söz söylemek. Güveni yok eder. Hz. Peygamber, yalanı **münafığın alametlerinden** saymıştır.
- **Gıybet:** Bir kimsenin **arkasından, hoşlanmayacağı bir şeyi söylemek.** Hz. Peygamber: “**Gıybet, kardeşini hoşlanmadığı bir şeyle anmandır.**” Eğer söylenen doğruysa gıybet, yalansa **iftira** (daha büyük günah) olur. Dedikodu, koğuculuk da buna benzer.
- **Hased (kıskançlık):** Başkasının nimetinin yok olmasını istemek. **Gıpta** (özenme) ise ondan farklıdır, başkasının iyiliğine özenip kendisi de çalışmaktır.
- **Kibir (kendini beğenmişlik):** Kendini başkalarından üstün görmek.
- **İsraf ve cimrilik:** İsraf, gereksiz harcamadır. Cimrilik, vermemektir. **İkisi de kötü**, doğrusu **orta yol (ölçülülük)**tür.
- **Haksızlık ve zulüm:** Başkasının hakkını yemek, **kul hakkı.**
- **Hırsızlık, rüşvet, haksız kazanç.**
- **Öfke ve kötü söz:** Kırıcı sözler, hakaret, alay etmek.
- **Başkasını incitmek:** “**Müslüman, elinden ve dilinden diğer insanların güvende olduğu kişidir.**”

**Kul hakkı:** Başkasına zarar verildiğinde, bu hak **Allah** tarafından bağışlanmaz, **hak sahibi razı olmalıdır.** Tövbe ile birlikte **helalleşmek** gerekir.

## 4. Toplumsal ahlak ilkeleri

- **Adalet ve eşitlik.** Ayrımcılık yapmamak.
- **Barış ve uzlaşma:** Kavga edenleri barıştırmak.
- **Yardımlaşma:** İyilikte ve takvada yardımlaşmak, kötülükte ve düşmanlıkta yardımlaşmamak (Maide suresi).
- **İyiliği emredip kötülükten sakındırmak (emr-i bi’l-maruf ve nehy-i ani’l-münker):** Doğru ve iyi davranışı özendirmek, kötülüğe karşı çıkmak, ama **güzel söz ve nezaketle**.
- **Çevre ve hayvanlara karşı sorumluluk:** Doğayı korumak, israf ve kirlilikten kaçınmak.
- **Haklara saygı:** Kamu malına ve başkasının mülküne zarar vermemek.
- **Selam vermek, güler yüz, güzel söz.**

## 5. Dijital ortamda ahlaki tutum

Sosyal medya ve internette de ahlak ilkeleri geçerlidir:

- **Doğruluk:** Doğrulanmamış bilgiyi paylaşma, **dedikodu ve iftira** yayma.
- **Saygı:** Hakaret, siber zorbalık ve nefret söyleminden uzak durma.
- **Mahremiyet:** Başkalarının özel hayatını ve fotoğraflarını izinsiz paylaşma.
- **Zaman ve bağımlılık:** Zamanı ve sağlığı korumak.
- **Sorumluluk:** Yazdığın ve paylaştığın her şeyden **sorumlu olduğunu** bil.

:::neden-sonuc
- Kişi doğruyu söylüyor ve sözünde duruyor => Güven oluşur, toplumda saygı kazanır.
