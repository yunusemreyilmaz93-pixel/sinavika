## 1. İbadet nedir

**İbadet**, kulun Allah’a olan **saygı, bağlılık ve şükrünü** Allah’ın emrettiği ve Hz. Muhammed’in öğrettiği biçimde göstermesidir. Kelime anlamı “kulluk etmek, boyun eğmek”tir.

**İbadetin türleri:**

- **Bedenî ibadetler:** Beden ile yapılan ibadetler. Namaz, oruç.
- **Malî ibadetler:** Mal ile yapılan ibadetler. Zekât, sadaka, kurban.
- **Hem bedenî hem malî ibadetler:** **Hac.**
- **Kalbî ve diğer ibadetler:** Dua, zikir, tövbe, Kur’an okuma.

**İbadetin esasları:** İbadet **niyetle** yapılır, **Allah’ın rızası** için yapılır, **gösteriş (riya) için olmaz.** İbadetin biçimi **Hz. Peygamber’in öğrettiği şekildedir.**

## 2. İslam’ın şartları

İslam’ın temel ibadet ve uygulama esasları **beştir:**

1. **Kelime-i şehadet:** “Eşhedü en lâ ilâhe illallah ve eşhedü enne Muhammeden abdühû ve resûlüh.” Allah’ın bir olduğuna ve Hz. Muhammed’in O’nun kulu ve elçisi olduğuna şahitlik etmek. Müslüman olmanın temel şartıdır.
2. **Namaz:** Günde beş vakit kılınan ibadet.
3. **Oruç:** Ramazan ayında tutulan ibadet.
4. **Zekât:** Zengin Müslümanların malından fakirlere verdiği hak.
5. **Hac:** Gücü yeten Müslümanın ömründe bir kez Kâbe’yi ziyaret edip yapması gereken ibadet.

## 3. Namaz

- Günde **beş vakit** kılınır: **Sabah, öğle, ikindi, akşam, yatsı.**
- Her vaktin **farz** rekât sayısı: Sabah 2, öğle 4, ikindi 4, akşam 3, yatsı 4. Toplam $2 + 4 + 4 + 3 + 4 = 17$ rekâttır.
- **Cuma namazı** haftada bir cuma günü cemaatle kılınır, hutbe dinlenir. **Bayram namazları** yılda iki kez kılınır.
- Namazın **şartları:** Temizlik (abdest, gusül), temiz elbise ve yer, avret yerlerini örtme, kıbleye yönelme, vaktinde kılma, niyet.
- Namaz **kıble (Kâbe)** yönüne dönülerek kılınır. **Ezan** vakti bildirir.
- **Faydaları:** Allah ile bağ kurar, **disiplin ve düzen** kazandırır, kötülüklerden korur, huzur verir. Cemaatle kılmak **birlik ve eşitlik** duygusunu güçlendirir.

## 4. Oruç

- **Ramazan ayında** imsak vaktinden akşam ezanına kadar yeme, içme ve cinsel ilişkiden uzak durmaktır.
- **Müslüman, akıllı, ergenlik çağına gelmiş ve sağlıklı olan** kişiye farzdır. Hasta, yolcu ve diğer mazeretliler sonra tutabilir ya da fidye verir.
- **Ramazan bayramı** orucun sonunda kutlanır. **Fitre** (fıtır sadakası) verilir.
- **Faydaları:** **Sabrı, irade eğitimini** ve **empati yeteneğini** artırır. Aç kalanın halini anlamayı sağlar. Sağlık ve **dayanışma** (iftar sofraları) yönünden faydalıdır.

## 5. Zekât

- **Nisap** denen belli miktarı aşan mala sahip ve üzerinden **bir yıl geçmiş** zengin Müslümanlar, malının **kırkta birini** (%2,5) fakirlere ve Kur’an’da sayılan yerlere verir.
- **Zekât alanlar:** Fakirler, yoksullar, borçlular, yolda kalmışlar gibi sekiz sınıf.
- **Örnek.** Nisabı aşan ve üzerinden bir yıl geçen 40 000 TL birikmiş para için verilecek zekât $\dfrac{40\,000}{40} = 1000\ \text{TL}$’dir.
- **Sadaka:** Gönüllü yardım, miktar sınırı yoktur. **Fitre**, **kurban**, **infak** da yardımlaşma ibadetleridir.
- **Faydaları:** **Cimrilik ve bencillikten** arındırır, **zengin ile fakir arasındaki mesafeyi** azaltır, **toplumsal dayanışma ve sosyal adaleti** sağlar. Nimetin şükrüdür.

## 6. Hac ve umre

- **Hac:** Zilhicce ayında, **Mekke’de** belirli yerlerde (Kâbe, Arafat, Müzdelife, Mina) yapılan ibadettir. **Gücü yetene ömründe bir kez** farzdır. Arafat’ta bulunmak (**vakfe**) haccın en önemli ibadetidir.
- **Umre:** Yılın her zamanında yapılabilen, haccın küçüğü sayılan ziyaret.
- **Kurban bayramı** haccın bitimiyle birlikte kutlanır. **Kurban** kesmek malî ibadettir.
- **Faydaları:** Dünyanın her yerinden Müslümanları bir araya getirir. **Eşitlik, kardeşlik, sabır ve fedakârlık** duygusunu pekiştirir. Herkes aynı ihramı giyer.

## 7. Diğer ibadetler

- **Dua:** Allah’a yalvarmak, dilekte bulunmak. Kulun Allah’a yakınlığını gösterir.
- **Zikir:** Allah’ı sürekli anmak (tesbih, hamd, tekbir).
- **Tövbe:** Günahtan pişmanlık duyup Allah’a dönmek, aynı günahı bir daha işlememeye karar vermek.
- **Kur’an okumak:** Anlamını düşünerek ve kurallarına uygun okumak.
- **Kurban:** Kurban bayramında Allah’ın adıyla hayvan kesmek ve etini paylaşmak.
- **Kandiller, bayramlar, Cuma:** Dinî günler ve geceler.

