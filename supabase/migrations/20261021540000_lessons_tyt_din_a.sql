## 1. Doğumu ve çocukluğu

- Hz. Muhammed yaklaşık **570** yılında **Mekke**’de doğdu. Babası **Abdullah** doğumundan önce, annesi **Âmine** altı yaşında iken vefat etti. Önce dedesi **Abdülmuttalib**, sonra amcası **Ebu Talib** himayesinde büyüdü.
- Çocukluğunda **Halime** adlı bir süt anne yanında kaldı.
- Gençliğinde **çobanlık** ve **ticaret** yaptı. Amcasıyla ticaret kervanlarına katılarak **Şam**’a gitti.

## 2. Gençliğinde güzel ahlakı: “el-Emin”

Hz. Muhammed gençliğinde **doğruluğu, güvenilirliği, dürüstlüğü ve ahlakı** ile tanındı. Mekkeliler ona “**el-Emin**” (güvenilir kişi) dedi. Peygamberlikten önce de **putlara tapmadı**, kötü alışkanlıklardan uzak durdu.

**Gençliğindeki önemli olaylar:**

- **Hilfü’l-Fudul (Erdemliler Cemiyeti):** Gençlik yıllarında katıldığı, haksızlığa uğrayan ve zulme maruz kalanları korumayı amaçlayan antlaşmadır. Hz. Peygamber, peygamber olduktan sonra da bu antlaşmayı **övgüyle** anmıştır.
- **Hacerülesved olayı:** Kâbe yeniden inşa edilirken Kâbe’nin kutsal Hacerülesved taşını yerine koyma konusunda kabileler arasında anlaşmazlık çıktı. Hz. Muhammed’in **akıllıca çözümü**, taşı bir örtüye koyup her kabile liderinin bir ucundan tutmasını sağlamak oldu. Böylece **kan dökülmeden** barış sağlandı.
- **Hz. Hatice ile evlilik:** 25 yaşındayken ticaret ortağı **Hatice**’yle evlendi. Hz. Hatice, onun ahlakına güvenmişti. Evlilikleri sevgi, vefa ve güvene dayanır.

## 3. Peygamberliği ve gençlerin İslam’a katılması

- **40 yaşında**, Mekke yakınlarındaki **Hira Mağarası**’nda ilk vahiy geldi. İlk ayetler “**Oku**” emriyle başlar (Alak suresi). Peygamberlik görevi başladı.
- İslam’ı ilk kabul edenler arasında **gençler** çoktu: **Hz. Ali** (yaklaşık 10 yaşlarında çocuk), **Zeyd b. Harise**, **Hz. Ebubekir**, **Talha, Zübeyr, Sa’d b. Ebi Vakkas, Abdurrahman b. Avf** gibi gençler ilk Müslümanlar arasındaydı.
- Mekke dönemi (610 ile 622) zor geçti. Müslümanlar baskı ve eziyet gördü. **Habeşistan’a** hicret edildi, sonra **622’de Medine’ye hicret** gerçekleşti.

## 4. Peygamber’in gençlere verdiği önem

Hz. Muhammed gençleri **önemser, güvenir ve sorumluluk verir:**

- **Mus’ab b. Umeyr:** Mekke’nin zengin ve zarif bir genciydi. İslam’ı kabul etti, Medine’ye **ilk öğretmen ve elçi** olarak gönderildi. Orada İslam’ı yaydı, Medine’de İslam’ın yayılmasında büyük rol oynadı.
- **Hz. Ali:** Genç yaşta İslam’ı kabul etti. **Hicret gecesi** Peygamber’in yatağında yattı ve Mekkelilerin emanetlerini sahiplerine ulaştırdı. Sonra güvenilir bir komutan oldu.
- **Üsame b. Zeyd:** Henüz **18-20 yaşlarında** iken Hz. Peygamber onu, **Bizans’a karşı gönderilen büyük bir ordunun komutanı** yaptı. Bu ordunun içinde yaşlı ve deneyimli sahabiler de vardı. Peygamber’in gençlere güveninin açık örneğidir.
- **Muaz b. Cebel:** Genç bir sahabi olarak **Yemen’e** gönderilerek **halkı eğitmek ve yönetmek** için görevlendirildi. Peygamber ona sorarak “Hükmü neye göre vereceksin?” dedi, o da “Kur’an’a, bulamazsam Sünnet’e, bulamazsam kendi görüşüme (içtihat)” diye cevap verdi, Peygamber bundan memnun oldu.
- **Zeyd b. Sabit:** Genç yaşta Kur’an’ı yazan **vahiy katipleri** arasındaydı. Kur’an’ın toplanmasında da önemli görev aldı. Aynı zamanda yabancı dilleri öğrenmekle görevlendirildi.
- **Abdullah b. Abbas (ibn Abbas):** Peygamber’in amcasının oğludur. Genç yaşta ilme düşkündü, Kur’an tefsirinin (yorumunun) önemli isimlerindendir.

## 5. Peygamber’in gençlere öğütleri

- **“Beş şeyi beş şeyden önce değerlendir:** Gençliğini ihtiyarlıktan önce, sağlığını hastalıktan önce, zenginliğini fakirlikten önce, boş zamanını meşguliyetten önce, hayatını ölümden önce.”
- Kıyamet gününde **Allah’ın gölgesinde gölgelenecek yedi kişiden biri**, “**Rabbine ibadet ederek yetişen genç**”tir.
- **Doğruluk, dürüstlük, güvenilirlik** (emanet), **söz tutmak**, **güler yüzlü olmak** ve **kolaylaştırmak.**
- **İlim öğrenmek:** İlim öğrenmek her Müslümana farzdır.
- **Anne babaya iyilik, büyüklere saygı ve küçüklere merhamet.**
- **Zararlı alışkanlıklardan uzak durmak**, **iffet** ve temiz hayat.
- **Güzel örnek olmak:** Gençler, **model** alınacak kişiler arasındadır.

**Hz. Peygamber’den gençlere dersler:**

- Gençlik, **ilim, ahlak ve hizmet** için değerlendirilmeli.
- **Güven kazanmak** karakterle olur (el-Emin).
- **Haksızlığa karşı çıkmak** ve mazlumu korumak (Hilfü’l-Fudul).
- **Sorumluluk almak ve görev üstlenmek.**
- **Barış ve uzlaşma** arayışı (Hacerülesved olayı).

