## 1. Allah inancı ve tevhid

**Tevhid**, Allah’ın **bir ve tek** olduğuna, **eşi ve benzeri bulunmadığına** inanmaktır. İslam’ın temel esasıdır. Kelime-i tevhid: “**Lâ ilâhe illallah**” (Allah’tan başka ilah yoktur). Kur’an’da İhlas suresi tevhidi özetler: “De ki, O Allah bir tektir. Allah sameddir (hiçbir şeye muhtaç değildir, her şey O’na muhtaçtır). Doğurmamış ve doğmamıştır. Hiçbir şey O’na denk değildir.”

**Şirk**, Allah’a ortak koşmaktır. İslam’da **en büyük günahtır.**

**Allah’ın varlığı:** Evrendeki **düzen, uyum ve incelik**, bir yaratıcının varlığına işaret eder. Kur’an, insanı **kâinatı incelemeye** çağırır. Allah’ın varlığı **kalbi** ve **aklı** ile bilinir.

## 2. Allah’ın isim ve sıfatları

**Esmâü’l-hüsnâ:** Allah’ın **güzel isimleri**dir. Geleneksel olarak **99 isim** sayılır (Rahman, Rahim, Rezzak, Gaffar, Adl, Kerim, Semi, Basir gibi). Allah’ı bu isimlerle anmak ve dua etmek tavsiye edilir.

**Sıfatları:** Allah’ın vasıfları iki ana gruba ayrılır:

- **Zâtî (selbi) sıfatlar:** Allah’ın zatına ait. **Vücûd** (var olması), **Kıdem** (başlangıçsız olması), **Bekâ** (sonsuz olması), **Vahdâniyet** (birliği), **Muhalefetün li’l-havâdis** (yaratılmışlara benzememesi), **Kıyam bi-nefsihî** (varlığının kendinden olması).
- **Subûtî sıfatlar:** **Hayat, İlim, Semi (işitme), Basar (görme), İrade, Kudret, Kelam, Tekvin** (yaratma).

Allah **her şeyi bilen, her şeye gücü yeten, merhametli ve adil**dir. Bu bilinç, insanı **sorumlu davranmaya** yöneltir.

## 3. İnsanın yaratılış amacı ve sorumluluğu

- **İnsan Allah’ın yarattığı en şerefli varlıklardandır.** Akıl, irade, vicdan ve konuşma yeteneği verilmiştir.
- **Yaratılış amacı:** Allah’a **kulluk** etmek (Zariyat suresi). Kulluk, yalnızca ibadet değil, **ahlaklı ve sorumlu bir hayat yaşamak** demektir.
- **Halifelik:** İnsan yeryüzünde **Allah’ın halifesidir**, yani yeryüzünü **imar etmek, adaleti sağlamak, doğayı korumak** ile sorumludur.
- **İmtihan:** Dünya hayatı bir **imtihandır.** Nimetler ve sıkıntılar insanı sınar.
- **Sorumluluk:** İnsan iradesiyle yaptığından sorumludur. **Hesap günü** her insan yaptıklarının karşılığını görür.
- **Kul hakkı:** İnsanların birbiri üzerindeki hakkı. Kul hakkı bağışlanması için **hak sahibinin razı olmasını** gerektirir.

## 4. Özgür irade ve kader

**Kader:** Allah’ın **ezelî ilmi**, her şeyi **bilmesi, takdir etmesi** ve yaratmasıdır. **Kaza:** Takdir edilenin zamanı gelince yerine getirilmesidir.

- **Allah her şeyi önceden bilir** ama bu bilgi insanı **zorlamaz.** İnsan **kendi iradesiyle seçer**, Allah da onun ne seçeceğini bilir.
- **Cüz’î irade:** Allah’ın insana verdiği sınırlı **seçme gücü.** İnsan seçimlerinden sorumludur. İnsan **iyi ya da kötü** yolu seçebilir.
- **Kader inancı:** İnsana **güven, sabır ve umut** verir. Başarıda şımartmaz, kayıpta yıkmaz. Ama **tembellik ve çalışmama bahanesi** değildir. İnsan, **çalışmak, tedbir almak** ile yükümlüdür.
- **Hz. Peygamber:** “Önce deveni bağla, sonra tevekkül et.”

## 5. Allah ile ilişkiyi güçlendiren tutumlar

- **Dua:** Allah’a yalvarmak, dilekte bulunmak. **Kulun Allah’a muhtaç olduğunun** ifadesidir. İçten, güvenle ve Allah’ın kabulüne inanarak yapılır. **Allah dua edenin duasını işitir.**
- **Zikir ve şükür:** **Şükür**, Allah’ın nimetlerini hatırlayıp O’na teşekkür etmek ve nimeti **iyi yolda kullanmaktır.** Şükreden nimetini artırır.
- **Sabır:** Zorluk ve sıkıntılara **dayanmak**, tepkisiz kalmak değil, **doğru davranmaya devam etmektir.** Sabır, güçlü bir ahlaki erdemdir.
- **Tevekkül:** Gerekli **tedbiri alıp** sonucu **Allah’a bırakmaktır.** Tembellik değildir.
- **Tövbe:** Günahtan **pişmanlık duymak**, o günahı terk etmek, bir daha yapmamaya karar vermek, kul hakkı varsa **helalleşmek.** Allah **tövbeleri kabul eden ve merhametlidir** (Tevvab, Rahim).
- **Havf ve reca:** Allah’tan **korkmak (saygı)** ve **ümit etmek.** İkisi dengelenir.
- **İhlas:** İbadet ve davranışlarda **yalnız Allah rızasını gözetmek.**
- **Takva:** Allah’a saygı duyup **günahlardan sakınmak** ve emirlerine uymak.

**İhsan:** “Allah’ı görüyormuş gibi ibadet etmek, sen O’nu görmesen de O seni görmektedir” bilinciyle yaşamak.

:::neden-sonuc
- Allah’ın bir olduğuna inanılıyor => Tevhid, şirkten uzak durulur.
- İnsan iradesiyle sorumlu tutuluyor => Eylemlerinin hesabını vereceği bilinci doğar.
- Kader tembellik gerekçesi yapılmıyor => İnsan çalışır, tedbir alır.
- Sıkıntıda sabır, nimette şükür gösteriliyor => Kul Allah’a güven ve bağlılığını kuvvetlendirir.
:::

