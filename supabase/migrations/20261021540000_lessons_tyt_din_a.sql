## Mini test

:::soru{cevap="A"}
Aşağıdaki mezheplerden hangisi itikadî (inanç) alanda sistemleştirilmiş bir mezheptir?

- A) Maturidîlik
- B) Hanefî mezhebi
- C) Şâfiî mezhebi
- D) Mâlikî mezhebi
- E) Hanbelî mezhebi

---

1. Maturidîlik ve Eş'arîlik inanç esaslarını yorumlayan itikadî mezheplerdir.
2. Hanefî, Şâfiî, Mâlikî ve Hanbelî ise amelî (fıkhî) mezheplerdir. Doğru cevap A.

Diğer şıklar: **Hanefî mezhebi** Hanefî amelî (fıkhî) bir mezheptir / **Şâfiî mezhebi** Şâfiî amelî (fıkhî) bir mezheptir / **Mâlikî mezhebi** Mâlikî amelî (fıkhî) bir mezheptir / **Hanbelî mezhebi** Hanbelî amelî (fıkhî) bir mezheptir.
:::

:::soru{cevap="D"}
İmam Mâtürîdî’nin yaşadığı ve akla geniş yer veren itikadî mezhebi sistemleştirdiği şehir aşağıdakilerden hangisidir?

- A) Basra
- B) Medine
- C) Bağdat
- D) Semerkant
- E) Küfe

---

1. İmam Mâtürîdî Semerkant'ta yaşamış ve mezhebini orada sistemleştirmiştir.
2. Doğru cevap D.

Diğer şıklar: **Basra** Basra Eş’arî ve Mutezile ile ilişkilidir / **Medine** Medine İmam Mâlik’in şehridir / **Bağdat** Bağdat İmam Ahmed b. Hanbel’in şehridir / **Küfe** Küfe İmam Ebû Hanîfe’nin şehridir.
:::

:::soru{cevap="B"}
“Divan-ı Hikmet” adlı eserin yazarı olan, Orta Asya’da yaşayan ve Türk tasavvufunun öncüsü kabul edilen mutasavvıf aşağıdakilerden hangisidir?

- A) Mevlânâ
- B) Ahmed Yesevî
- C) Yunus Emre
- D) Hacı Bektaş-ı Velî
- E) Abdülkadir Geylanî

---

1. Divan-ı Hikmet Ahmed Yesevî'nin eseridir ve sade Türkçe ile yazılmıştır.
2. Doğru cevap B.

Diğer şıklar: **Mevlânâ** Mevlânâ’nın eseri Mesnevî’dir / **Yunus Emre** Yunus Emre’nin eseri Divan ve Risaletü’n-Nushiyye’dir / **Hacı Bektaş-ı Velî** Hacı Bektaş’ın eseri Makalât’tır / **Abdülkadir Geylanî** Abdülkadir Geylanî Kadirîliğin kurucusudur.
:::

:::soru{cevap="E"}
Aşağıdakilerden hangisi mezheplerin ortaya çıkışındaki nedenlerden biridir?

- A) Dinin temel esaslarının farklı olması
- B) Peygamberin farklı kişiler olması
- C) Kur’an’ın farklı metinlerinin bulunması
- D) İbadetlerin bütünüyle terk edilmesi
- E) Ayet ve hadislerin farklı yorumlanması

---

1. Mezhepler dinin temel esaslarında ortaktır, ayrıntıda yorum farkı vardır.
2. Ayetlerin ve hadislerin farklı yorumlanabilmesi bu farkın nedenlerindendir. Doğru cevap E.

Diğer şıklar: **Dinin temel esaslarının farklı olması** mezhepler temel esaslarda ortaktır / **Peygamberin farklı kişiler olması** tüm mezhepler aynı peygamberi kabul eder / **Kur’an’ın farklı metinlerinin bulunması** Kur’an’ın metni tektir / **İbadetlerin bütünüyle terk edilmesi** mezhepler ibadetleri yorumlar, terk etmez.
:::

