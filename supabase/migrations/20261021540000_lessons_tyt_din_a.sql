2. Yardımlaşma ve dayanışma kurumlarını (zekât, sadaka, vakıf) örneklerle anlatmak.
3. Hoşgörü, barış ve farklı inançlara saygı ilkelerini yorumlamak.
4. Din ile kültür ve sanat ilişkisini örneklemek.
