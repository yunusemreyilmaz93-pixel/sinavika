- Hz. Muhammed dürüstlüğüyle tanınıyor => “el-Emin” unvanını alır.
- Peygamber gençlere görev ve güven veriyor => Gençler topluma hizmette önemli roller üstlenir.
- Hacerülesved olayında kabileler çatışmak üzereyken akıllı çözüm bulunuyor => Barış sağlanır, kan dökülmez.
- Gençlik emanet kabul ediliyor => Zamanı ve gücü ilme, ibadete, hizmete harcamak gerekir.
:::

:::ipucu{baslik="Sık yapılan hata"}
**Hz. Muhammed’in gençliğini yalnızca “çocukluk ve peygamberlik” arasında bir boşluk sanma.** Bu dönemde **güvenilirlik, ticaret, adalet ve barış** çabalarıyla örnek bir hayat yaşadı. Bir de **Üsame b. Zeyd ile Zeyd b. Harise’yi** karıştırma: Zeyd, Hz. Peygamber’in azatlı kölesi ve evlatlığıdır. Üsame onun oğludur. **Hacerülesved olayı** Peygamber’in peygamberlikten önceki bir olayıdır.
:::

:::baglanti
Bu konu, “Gençlik ve Değerler” konusundaki gençliğin değerini Hz. Peygamber örneği ile tamamlar. “Ahlaki Tutum ve Davranışlar” konusundaki doğruluk ve güvenilirlik değerleri onun hayatında örnek bulur. Tarihte “İslam Medeniyetinin Doğuşu” konusundaki Hz. Muhammed dönemi olayları (hicret, Medine Vesikası) bu konuyla ilişkilidir. “Din ve Toplumsal Hayat” konusu barış ve dayanışma değerlerini toplumsal boyutta işler.
